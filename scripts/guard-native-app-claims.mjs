#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// Η ΕΦΑΡΜΟΓΗ ΚΙΝΗΤΟΥ ΔΕΝ ΕΧΕΙ ΚΥΚΛΟΦΟΡΗΣΕΙ — ΚΑΝΕΝΑ ΚΕΙΜΕΝΟ ΔΕΝ ΛΕΕΙ ΟΤΙ ΥΠΑΡΧΕΙ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΠΕΡΙΣΤΑΤΙΚΟ, ΜΕΤΡΗΜΕΝΟ. Ολόκληρο το προϊόν λέει με συνέπεια ότι η εφαρμογή
// κινητού ΔΕΝ έχει βγει: η αρχική γράφει «λίστα αναμονής για εφαρμογή κινητού,
// δεν υπάρχει εφαρμογή κινητού» (app/page.tsx), υπάρχει συνάρτηση
// notify-mobile-launch για ΟΤΑΝ βγει, ο βοηθός είναι ρητά κλειδωμένος με δοκιμή
// («μην πεις ποτέ ότι υπάρχει native app», assistantPersona.test.ts).
//
// ΕΝΑ ΣΗΜΕΙΟ ΤΟ ΕΣΠΑΓΕ, ΚΑΙ ΗΤΑΝ ΤΟ ΧΕΙΡΟΤΕΡΟ. Οι Οροι Χρήσης —δεσμευτικό
// κείμενο— έγραφαν ότι οι συνδρομητές «αποκτούν πρόσβαση στην εφαρμογή κινητού
// (App Store και Google Play) δεκαπέντε ημέρες νωρίτερα», σε ενεστώτα, σαν να
// υπάρχει. Υπόσχεση επί πληρωμή για προϊόν που δεν κυκλοφορεί: ακριβώς το είδος
// ανακρίβειας που ο αγοραστής νιώθει ως εξαπάτηση. Ο βοηθός φυλασσόταν με
// δοκιμή· το δημοσιευμένο νομικό κείμενο από κανέναν.
//
// ΤΙ ΕΛΕΓΧΕΤΑΙ, ΑΚΡΙΒΩΣ. Σε κάθε αποδιδόμενη σελίδα (app/**/*.tsx), κάθε γραμμή
// που ονομάζει «App Store» ή «Google Play» ΠΡΕΠΕΙ να κουβαλά και μια λέξη που
// δηλώνει ότι η εφαρμογή δεν έχει βγει ακόμη (όταν κυκλοφορήσει, λίστα αναμονής,
// δεν υπάρχει, δεν έχει βγει). Αλλιώς το κείμενο λέει ότι υπάρχει — και δεν
// υπάρχει. Ελέγχονται ΜΟΝΟ τα ονόματα των stores: είναι το ισχυρό, μονοσήμαντο
// σημάδι «η εφαρμογή είναι εκεί, κατέβασέ τη τώρα».
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { projectFiles } from './lib/git-files.mjs'

const STORE = /App Store|Google Play/
const GATE = /δεν έχει κυκλοφορήσει|όταν κυκλοφορήσει|θα κυκλοφορήσει|λίστα αναμονής|δεν υπάρχει|δεν έχει βγει|μόλις (βγει|κυκλοφορήσει)/

const files = projectFiles("'app/**/*.tsx'")
const provlimata = []
for (const arxeio of files) {
  const lines = readFileSync(arxeio, 'utf8').split('\n')
  lines.forEach((line, i) => {
    if (STORE.test(line) && !GATE.test(line)) {
      provlimata.push({ arxeio, grammi: i + 1, ti: line.trim().slice(0, 60) })
    }
  })
}

if (provlimata.length) {
  console.error(`\n✗ ${provlimata.length} κείμενα δηλώνουν την εφαρμογή κινητού στα stores σαν να υπάρχει:\n`)
  for (const p of provlimata.slice(0, 30)) console.error(`  ${p.arxeio}:${p.grammi}  «${p.ti}»`)
  console.error(`\n  ΤΙ ΝΑ ΚΑΝΕΙΣ: γράψε την πρόσβαση ως μελλοντική — «όταν κυκλοφορήσει`)
  console.error(`  (App Store και Google Play)…» — όπως λέει η αρχική και όπως φυλάει ο βοηθός.`)
  console.error(`  Η εφαρμογή δεν έχει βγει· κανένα κείμενο δεν πρέπει να λέει ότι υπάρχει.\n`)
  process.exit(1)
}
console.log(`✓ κανένα κείμενο δεν δηλώνει την εφαρμογή κινητού στα stores ως υπαρκτή (${files.length} αρχεία)`)
