#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΚΑΜΙΑ ΟΘΟΝΗ ΔΕΝ ΥΠΟΣΧΕΤΑΙ ΣΥΧΝΟΤΗΤΑ ΑΝΑΝΕΩΣΗΣ ΠΟΥ Η ΠΗΓΗ ΔΕΝ ΔΙΝΕΙ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ, ΠΙΑΣΜΕΝΟ ΣΤΗΝ ΠΑΡΑΓΩΓΗ. Ο υπολογιστής δανείου έγραφε, ακριβώς
// κάτω από την τιμή του Euribor:
//
//     «Αυτόματη ενημέρωση από την ΕΚΤ κάθε πρωί»
//
// Η ΕΚΤ ΔΕΝ δημοσιεύει ημερήσιο Euribor. Το `lib/market/ecb.ts` το έχει
// μετρήσει: ο κατάλογος του Data Portal, ρωτημένος με μπαλαντέρ στη συχνότητα,
// απαντά «A | M | Q» — ετήσια, μηνιαία, τριμηνιαία· και οι τέσσερις ημερήσιες
// υποψήφιες γύρισαν 404 στην πρώτη αληθινή εκτέλεση. Η τιμή που έβλεπε ο
// χρήστης ήταν ο μέσος όρος του ΠΡΟΗΓΟΥΜΕΝΟΥ μήνα, με λεζάντα που έλεγε
// «κάθε πρωί».
//
// ΓΙΑΤΙ ΠΕΡΑΣΕ ΑΠΟ ΟΛΟΥΣ ΤΟΥΣ ΑΛΛΟΥΣ. Η τιμή ήταν σωστή. Ο τύπος σωστός. Τα
// τεστ πράσινα. Λάθος ήταν μόνο η ΥΠΟΣΧΕΣΗ γύρω από την τιμή — και καμία
// υπόθεση δοκιμής δεν κοιτά υποσχέσεις.
//
// ΚΑΙ ΓΙΑΤΙ ΔΕΝ ΑΡΚΕΙ Η ΔΙΟΡΘΩΣΗ. Η λεζάντα ξαναγράφεται κάθε φορά που κάποιος
// φτιάχνει νέα οθόνη με επιτόκιο, γιατί «κάθε πρωί» ακούγεται σαν χαρακτηριστικό.
// Οσο δεν υπάρχει έλεγχος, θα ξαναμπεί.
//
// ΤΙ ΕΛΕΓΧΕΤΑΙ. Γραμμή ΟΘΟΝΗΣ που μιλά για επιτόκιο ή για την ΕΚΤ και
// ταυτόχρονα υπόσχεται συχνότητα. Δύο συνθήκες μαζί, ποτέ μία: μια οθόνη που
// λέει «κάθε πρωί» για ειδοποιήσεις είναι σωστή και μια που λέει «Euribor»
// χωρίς υπόσχεση επίσης.
//
// Η ΣΩΣΤΗ ΛΥΣΗ ΔΕΝ ΕΙΝΑΙ ΑΛΛΗ ΛΕΞΗ, ΕΙΝΑΙ ΑΛΛΗ ΠΗΓΗ: η λεζάντα διαβάζεται από
// το `basis` της ίδιας της τιμής, με την `greekWhen` του `lib/market/ecb.ts`.
// Οποιος αλλάξει συχνότητα, αλλάζει τη λεζάντα στο ίδιο σημείο.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { projectFiles } from './lib/git-files.mjs'

const files = projectFiles("'app/**/*.tsx' 'components/**/*.tsx'")

// ── ΓΙΑΤΙ ΤΟ ΘΕΜΑ ΕΙΝΑΙ ΤΟΣΟ ΣΤΕΝΟ ──────────────────────────────────────────
// Η πρώτη γραφή δεχόταν και τη λέξη «επιτόκι». Κοκκίνισε σε δύο σημεία που
// είναι ΣΩΣΤΑ και αυτό είναι χειρότερο από το να μην έπιανε τίποτα:
//
//   · «Ανάλυση κόστους σε πραγματικό χρόνο» στον υπολογιστή δανείου — μιλά για
//     τον ΥΠΟΛΟΓΙΣΜΟ που ξανατρέχει καθώς πληκτρολογείς, όχι για δεδομένα.
//   · «η βάση αφορά καθημερινή» στο Τιμολόγιο — «καθημερινή» εκεί είναι το
//     είδος της μίσθωσης, όχι συχνότητα ανανέωσης. Σε εφαρμογή ακινήτων η λέξη
//     ανήκει στο λεξιλόγιο του προϊόντος.
//
// Ο φύλακας που κοκκινίζει σε σωστό κώδικα παρακάμπτεται την τρίτη μέρα και
// τότε δεν φυλάει τίποτα. Το θέμα είναι πλέον ΟΝΟΜΑΣΤΙΚΟ: μόνο γραμμή που
// ονομάζει την πηγή, δηλαδή την ΕΚΤ ή το Euribor.
const THEMA = /Euribor|euribor|ΕΚΤ|ecb_rate/

/** Υπόσχεση συχνότητας. Το «live» μόνο ως λέξη — όχι μέσα σε «lively». */
const YPOSXESI = [
  { re: /κάθε πρωί/i, anti: 'κάθε πρωί' },
  { re: /κάθε μέρα|κάθε ημέρα/i, anti: 'κάθε μέρα' },
  { re: /σε πραγματικό χρόνο/i, anti: 'σε πραγματικό χρόνο' },
  { re: /(?<![\p{L}])live(?![\p{L}])/iu, anti: 'live' },
  { re: /ανά λεπτό|κάθε ώρα/i, anti: 'ανά λεπτό ή ώρα' },
]

/** Το σχόλιο εξηγεί· η δήλωση προς τον χρήστη υπόσχεται. Κρίνεται η δεύτερη. */
const dixosSxolia = (src) => {
  const out = []
  let inBlock = false
  for (const line of src.split('\n')) {
    let code = line
    const open = line.indexOf('/*')
    const close = line.indexOf('*/')
    if (inBlock) {
      if (close >= 0) { code = line.slice(close + 2); inBlock = false } else { code = '' }
    } else if (open >= 0) {
      if (close > open) code = line.slice(0, open) + line.slice(close + 2)
      else { code = line.slice(0, open); inBlock = true }
    }
    out.push(code.replace(/\/\/.*$/, ''))
  }
  return out
}

const provlimata = []
for (const file of files) {
  dixosSxolia(readFileSync(file, 'utf8')).forEach((code, i) => {
    if (!THEMA.test(code)) return
    for (const y of YPOSXESI) {
      if (!y.re.test(code)) continue
      provlimata.push({ file, gr: i + 1, anti: y.anti, line: code.trim().slice(0, 100) })
      break
    }
  })
}

if (provlimata.length) {
  console.error(`\n✗ ${provlimata.length} οθόνες υπόσχονται συχνότητα ανανέωσης δίπλα σε επιτόκιο:\n`)
  for (const p of provlimata.slice(0, 20)) {
    console.error(`  ${p.file}:${p.gr}  «${p.anti}»`)
    console.error(`     ${p.line}`)
  }
  if (provlimata.length > 20) console.error(`  … και άλλες ${provlimata.length - 20}`)
  console.error(`
  Η ΣΥΧΝΟΤΗΤΑ ΔΕΝ ΓΡΑΦΕΤΑΙ, ΔΙΑΒΑΖΕΤΑΙ. Κάθε τιμή αγοράς κουβαλά \`basis\` —
  «μέσος όρος μήνα», «ισχύει από την τελευταία μεταβολή» και τα λοιπά. Η οθόνη
  το δείχνει με την \`greekWhen(asOf, basis)\` του lib/market/ecb.ts, όπως ήδη
  κάνει η σύγκριση επιτοκίων στο TabLoan.tsx.

  Η ΕΚΤ δεν δημοσιεύει ημερήσιο Euribor: ο κατάλογος του Data Portal απαντά
  «A | M | Q» και οι ημερήσιες σειρές γυρίζουν 404. Οποια λεζάντα υπόσχεται
  ημερήσια ανανέωση είναι ψέμα προς τον χρήστη, με τη σωστή τιμή από πάνω.
`)
  process.exit(1)
}

console.log(`✓ καμία υπόσχεση συχνότητας δίπλα σε επιτόκιο, σε ${files.length} οθόνες`)
