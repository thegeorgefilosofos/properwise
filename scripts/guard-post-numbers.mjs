#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ ΚΕΙΜΕΝΟ ΔΙΠΛΑ ΣΤΗΝ ΑΝΑΡΤΗΣΗ ΔΕΝ ΓΡΑΦΕΙ ΨΗΦΙΑ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ ΕΧΕΙ ΗΔΗ ΓΙΝΕΙ, ΚΑΙ ΕΙΝΑΙ ΓΡΑΜΜΕΝΟ ΣΤΟ ΙΔΙΟ ΤΟ scripts/marketing/posts.ts:
//
//     «Στο πρώτο σχέδιο περιεχομένου έγραψα "ενοίκιο 9.600 €, χάνεις 480 € τον
//      χρόνο". ΛΑΘΟΣ: τα 480 € είναι η έκπτωση που χάνεται, όχι ο φόρος. Ο
//      φόρος είναι 15% αυτής, δηλαδή 72 €.»
//
// Ανθρωπος που ξέρει το προϊόν έκανε λάθος με παράγοντα 6,7 σε δύο γραμμές. Η
// λύση ήταν να μη γράφεται κανένα νούμερο με το χέρι: το `npm run posts` βγάζει
// τις εικόνες από τις ΙΔΙΕΣ συναρτήσεις που υπολογίζουν τον φόρο στην εφαρμογή.
//
// ── ΓΙΑΤΙ Ο ΦΥΛΑΚΑΣ ΔΕΝ ΚΟΙΤΑΖΕΙ ΤΟΝ ΦΑΚΕΛΟ ΤΩΝ ΑΝΑΡΤΗΣΕΩΝ ────────────────
// Η πρώτη εκδοχή τον κοίταζε — και ΕΜΕΙΝΕ ΠΡΑΣΙΝΗ στη μετάλλαξη. Ο λόγος είναι
// στο .gitignore:63: ολόκληρο το `docs/marketing/posts/*` αγνοείται, γιατί οι
// αναρτήσεις είναι παραγόμενες και γερνούν την ίδια μέρα. Αρχείο που δεν μπαίνει
// ποτέ στο αποθετήριο δεν φυλάγεται ποτέ από φύλακα του αποθετηρίου.
//
// ΑΡΑ Η ΕΡΩΤΗΣΗ ΑΛΛΑΖΕΙ: πού γράφεται κείμενο που θα διαβάσει κοινό και ΜΠΑΙΝΕΙ
// στο αποθετήριο; Στις λεζάντες. Η εικόνα δημοσιεύεται με κείμενο από πάνω —
// λεζάντα, νήμα, απάντηση σε σχόλιο — και αυτό το κείμενο, για να το δει
// άνθρωπος πριν φύγει, δεσμεύεται στο `docs/marketing/keimena/`.
//
// ── Ο ΚΑΝΟΝΑΣ, ΚΑΙ ΓΙΑΤΙ ΕΙΝΑΙ ΤΟΣΟ ΑΥΣΤΗΡΟΣ ─────────────────────────────
// Η λεζάντα δεν γράφει ψηφίο. Κανένα. Ο αριθμός ζει στην εικόνα, που τον πήρε
// από τη μηχανή· η λεζάντα λέει τη γωνία.
//
// Θα μπορούσε ο φύλακας να δέχεται όσα ψηφία υπάρχουν στο ευρετήριο που γράφει
// η μηχανή (`docs/marketing/posts/README.md`) — και τα δέχεται, ΟΤΑΝ υπάρχει,
// δηλαδή τοπικά, αμέσως μετά το `npm run posts`. Στο CI δεν υπάρχει: είναι κι
// αυτό παραγόμενο και αγνοημένο. Εκεί η λευκή λίστα είναι άδεια και ο κανόνας
// γίνεται απόλυτος. Αυτό ΔΕΝ είναι ατέλεια· είναι το σωστό προεπιλεγμένο, γιατί
// ένα ψηφίο που δεν μπορεί να διασταυρωθεί με τίποτα δεν πρέπει να φύγει προς
// τα έξω με το όνομα του προϊόντος από πάνω.
//
// ΣΕ ΦΟΡΟΛΟΓΙΚΟ ΠΕΡΙΕΧΟΜΕΝΟ ΕΝΑ ΛΑΘΟΣ ΝΟΥΜΕΡΟ ΔΕΝ ΕΙΝΑΙ ΛΕΠΤΟΜΕΡΕΙΑ: σβήνει
// την εμπιστοσύνη ολόκληρου του λογαριασμού και το προϊόν πουλά ακριβώς αυτό —
// «είμαστε η ανεξάρτητη απόδειξη που ελέγχει την πρώτη».
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync, existsSync } from 'node:fs'
import { projectFiles } from './lib/git-files.mjs'

const LEZANTES = 'docs/marketing/keimena'
const EVRETIRIO = 'docs/marketing/posts/README.md'

/** Κείμενο που γράφει άνθρωπος ή bot και ταξιδεύει προς τα έξω. */
const KEIMENO = /\.(md|txt)$/i

/** Το ίδιο το README του φακέλου εξηγεί τον κανόνα· δεν κρίνεται από αυτόν. */
const ODIGIES = new Set([`${LEZANTES}/README.md`])

const ypopsifia = projectFiles(`'${LEZANTES}/*' '${LEZANTES}/**/*'`)
  .filter(f => KEIMENO.test(f) && !ODIGIES.has(f))

// Η λευκή λίστα: ό,τι ψηφίο έγραψε η μηχανή, όταν η έξοδός της υπάρχει εδώ.
const egkekrimena = existsSync(EVRETIRIO)
  ? new Set(readFileSync(EVRETIRIO, 'utf8').match(/\d+/g) || [])
  : new Set()

if (!ypopsifia.length) {
  console.log('✓ καμία λεζάντα δεσμευμένη — κανένα ψηφίο να ελεγχθεί')
  process.exit(0)
}

const provlimata = []
for (const f of ypopsifia) {
  readFileSync(f, 'utf8').split('\n').forEach((line, i) => {
    for (const n of line.match(/\d+/g) || []) {
      if (egkekrimena.has(n)) continue
      provlimata.push({ f, gr: i + 1, n, line: line.trim().slice(0, 90) })
    }
  })
}

if (provlimata.length) {
  console.error(`\n✗ ${provlimata.length} ψηφία σε λεζάντα, που δεν τα παρήγαγε ο κώδικας:\n`)
  for (const p of provlimata.slice(0, 30)) {
    console.error(`  ${p.f}:${p.gr}  «${p.n}»`)
    console.error(`     ${p.line}`)
  }
  if (provlimata.length > 30) console.error(`  … και άλλα ${provlimata.length - 30}`)
  console.error(`
  Η ΛΕΖΑΝΤΑ ΓΡΑΦΕΙ ΤΗ ΓΩΝΙΑ, Η ΕΙΚΟΝΑ ΓΡΑΦΕΙ ΤΟΝ ΑΡΙΘΜΟ. Οι αριθμοί βγαίνουν
  από το \`npm run posts\`, που τους υπολογίζει με τις ΙΔΙΕΣ συναρτήσεις που
  υπολογίζουν τον φόρο μέσα στην εφαρμογή.

  Αν ο αριθμός πρέπει οπωσδήποτε να ειπωθεί σε κείμενο, δεν γράφεται εδώ: μπαίνει
  στη μηχανή, ξανατρέχει το \`npm run posts\` και η λεζάντα παραπέμπει στην
  εικόνα που τον δείχνει.

  Το ίδιο το scripts/marketing/posts.ts κουβαλά το περιστατικό: «έγραψα χάνεις
  480 € τον χρόνο. ΛΑΘΟΣ. Ο φόρος είναι 15% αυτής, δηλαδή 72 €.»
`)
  process.exit(1)
}

console.log(`✓ καμία λεζάντα δεν γράφει ψηφίο εκτός μηχανής (${ypopsifia.length} αρχεία)`)
