// ΤΙ ΓΙΝΟΤΑΝ. Το φύλλο δηλώνει `url('/fonts/inter-greek.woff2')`: απόλυτη
// διαδρομή, σωστή όταν σερβίρει το Next. Ο πάγκος όμως ανοίγει από τον δίσκο,
// οπότε η ίδια διαδρομή γινόταν `file:///fonts/…`, που δεν υπάρχει. Ο
// περιηγητής έπεφτε σιωπηλά στην εφεδρική γραμματοσειρά του συστήματος και
// ΚΑΘΕ σάρωση του πάγκου (διάταξη, στοίχιση, ετικέτες, στιγμιότυπα) μετρούσε
// άλλα πλάτη λέξεων από αυτά που βλέπει ο χρήστης με την Inter.
//
// ΤΙ ΚΑΝΕΙ. Αντιγράφει το public/fonts δίπλα στο φύλλο και γράφει τις
// διαδρομές σχετικές (`./fonts/…`). Ενας τόπος για τους τρεις πάγκους που
// γράφουν το ίδιο .perf-bench/globals.css, ώστε να μην ξαναγράψει κανείς το
// απόλυτο αντίγραφο πάνω από το διορθωμένο.
// ═══════════════════════════════════════════════════════════════════════════
import { cpSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Γράφει το `<out>/globals.css` με σχετικές διαδρομές γραμματοσειρών και
 * αντιγράφει τα αρχεία τους στο `<out>/fonts`.
 *
 * @param root η ρίζα του αποθετηρίου
 * @param out  ο φάκελος του πάγκου (.perf-bench)
 * @returns {string} το κείμενο του φύλλου όπως γράφτηκε
 */
export function writeBenchCss(root, out) {
  cpSync(join(root, 'public/fonts'), join(out, 'fonts'), { recursive: true });
  const css = readFileSync(join(root, 'app/globals.css'), 'utf8')
    .replace(/url\((['"]?)\/fonts\//g, 'url($1./fonts/');
  writeFileSync(join(out, 'globals.css'), css);
  return css;
}
