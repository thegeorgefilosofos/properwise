import { fakeAtak } from '@/lib/myaade/fixtures';

export interface FakeE9Row {
  n: number;
  /** Νομός, δήμος, διαμέρισμα. Με δύο τιμές, όπως όταν ο δήμος δεν τυπώνεται. */
  place?: string[];
  /** Η οδός: πάνω γραμμή, κύρια, κάτω γραμμή (όταν τυλίγεται). */
  street?: [string, string, string];
  num?: string;
  tk?: string;
  floor?: string;
  sqm?: string;
  aux?: string;
  built?: string;
  cat?: string;
  right?: string;
  /** Τα τρία κομμάτια του ποσοστού· `null` = δεν τυπώθηκε (κομμένη σελίδα). */
  pct?: [string, string, string] | null;
  /** Ο ΑΤΑΚ σε μία γραμμή αντί για δύο. */
  atakOneLine?: boolean;
}

const E9_HEADER_NOISE = [
  'Ο', 'ΥΠΟΛΟΙΠΟΙ ΔΡΟΜΟΙ ΟΙΚΟΔΟΜΙΚΟΥ ΤΕΤΡΑΓΩΝΟΥ\tΝ\tΟΣ', 'ΔΙΕΥΘΥΝΣΗ ΑΚΙΝΗΤΟΥ\tΚΤΙΣΜΑ\tΟΙΚΟΠΕΔΟ\tΤ', 'ΠΡΟΣΟΨΕΙΣ\tΜΕ',
  'Τ\tΟ- ΟΥ\tΤ\tΩΝ\tΕΠΙΦΑΝΕΙΑ\tΣ\tΣ\tΕ\tΗ\tΙΑ\tΟΠ', 'ΓΩΝ Π\tΘΗ\tΣ\tΣ\tΗ\tΣ\tΗ\tΙΦ\tΡ\tΓΟΡ',
  'ΙΝ\tΔΗΜΟΤΙΚΟ ή\tΤ Ε\tΣΚ\tΙΩΜΑ\tΙΚ\tΙΩΜΑ\tΙΚ\tΙΚ\tΗ', '. / Κ\tΔΗΜΟΣ ή\tΟΔΟΣ\tΔ\tΩΝ\tΟΡ\tΩΡ\tΟΣΟΨΗ\tΑ\tΙΔ',
  'Α\t.Κ\tΝΟΜΟΣ\tΚΟΙΝΟΤΙΚΟ\tΤ.Κ. Π\tΟΔΟΣ\tΠ\tΟΔΟΣ\tΠ\tΟΔΟΣ\tΠ ΘΟΣ Π ΙΘΜΟΣ ΟΙΚ ΟΥ Ν', 'ΚΟΙΝΟΤΗΤΑ\tΑΡΙΘΜΟΣ\tΡ\tΕ\tΗ\tΑ\tΙΚ',
  'ΔΙΑΜΕΡΙΣΜΑ\tΛ Α\tΙΔ\tΡ\tΠ\tΕ\tΚ', 'ΟΗ\tΟΣΟΣΤ\tΕ\tΟΣΟΣΤ\tΕ\tΕ', 'Ο Α\tΗ', 'Τ',
];

/** Αριθμός παροχής των fixtures: εννιαψήφιο που ΔΕΝ περνά τον έλεγχο ΑΦΜ. */
const FAKE_SUPPLY = '123456789';

/** Οι γραμμές ενός συνθετικού Ε9. `land` = γραμμές στον Πίνακα 2. */
export function fakeE9Lines(rows: readonly FakeE9Row[], o: { year?: number; afm?: string; land?: number } = {}): string[] {
  const afm = o.afm ?? FAKE_SUPPLY;
  const footer = (page: number) => `Ημερομηνία εκτύπωσης: 09/11/2026 18:44\tΣελίδα ${page} από 3`;
  const out = [
    'ΒΕΒΑΙΩΣΗ ΔΗΛΩΘΕΙΣΑΣ', 'Ε9\tΠΕΡΙΟΥΣΙΑΚΗΣ ΚΑΤΑΣΤΑΣΗΣ', `όπως έχει δηλωθεί την 1η Ιανουαρίου ${o.year ?? 2026}`,
    'ΣΤΟΙΧΕΙΑ ΤΟΥ ΥΠΟΧΡΕΟΥ', 'ΑΦΜ\tΕΠΩΝΥΜΟ ή ΕΠΩΝΥΜΙΑ\tΟΝΟΜΑ\tΠΑΤΡΩΝΥΜΟ', `${afm}\tΠΑΠΑΔΟΠΟΥΛΟΣ\tΓΕΩΡΓΙΟΣ\tΙΩΑΝΝΗΣ`,
    footer(1), `ΑΦΜ υπόχρεου : ${afm}`,
    'ΠΙΝΑΚΑΣ 1: ΣΤΟΙΧΕΙΑ ΟΙΚΟΠΕΔΩΝ (ΕΝΤΟΣ ΣΧΕΔΙΟΥ ή ΟΙΚΙΣΜΟΥ)', 'ΚΑΙ ΚΤΙΣΜΑΤΩΝ (ΕΝΤΟΣ ΚΑΙ ΕΚΤΟΣ ΣΧΕΔΙΟΥ)',
    ...E9_HEADER_NOISE,
  ];
  for (const r of rows) {
    const atak = fakeAtak(r.n);
    const [top, street, bottom] = r.street ?? ['', `ΠΑΡΑΔΕΙΓΜΑΤΟΣ`, ''];
    const pct = r.pct === undefined ? ['100,', '0000', '0'] : r.pct;
    const place = r.place ?? ['ΑΤΤΙΚΗΣ', 'ΑΘΗΝΑΙΩΝ', 'ΑΘΗΝΑΙΩΝ'];
    const area = [r.floor ?? String(r.n % 5), r.sqm ?? `${40 + r.n},50`, r.aux].filter(Boolean).join(' ');
    // Ο αναγνώστης δεν δίνει κενές γραμμές: χωρίς οδό και ποσοστό η γραμμή λείπει.
    out.push(...[
      [top, pct?.[0]].filter(Boolean).join('\t'),
      r.atakOneLine ? atak : atak.slice(0, 6),
      [...place, `${street} ${r.num ?? String(10 + r.n)} ${r.tk ?? '10000'} X ΔΟΚΙΜΗΣ X`, 'ΦΑΝΤΑΣΤΙΚΗΣ', 'ΑΛΛΗΣ',
        `2 100 1 ${r.cat ?? '1'}`, area, [r.built ?? '1990', r.right ?? '1', pct?.[1]].filter(Boolean).join(' '), `ΝΑΙ ${FAKE_SUPPLY}`].join('\t'),
      r.atakOneLine ? '' : atak.slice(6),
      [bottom, pct?.[2]].filter(Boolean).join('\t'),
    ].filter(Boolean));
  }
  out.push(footer(2), `ΑΦΜ υπόχρεου : ${afm}`, 'ΠΙΝΑΚΑΣ 2: ΣΤΟΙΧΕΙΑ ΓΗΠΕΔΩΝ', 'ΔΙΕΥΘΥΝΣΕΙΣ ΑΚΙΝΗΤΩΝ\tΡ\tΕΠΙΦΑΝΕΙΑ ΣΕ ΤΕΤΡΑΓΩΝΙΚΑ ΜΕΤΡΑ', 'Α\tΔΗΜΟΣ ή\tΟΔΟΣ\tΤ\tΚ');
  for (let k = 0; k < (o.land ?? 0); k++) {
    out.push(fakeAtak(900 + k).slice(0, 6), `ΑΤΤΙΚΗΣ\tΑΘΗΝΑΙΩΝ\tΘΕΣΗ ΔΟΚΙΜΗΣ 10000\t1.200,00\t1`, fakeAtak(900 + k).slice(6));
  }
  out.push(footer(3));
  return out;
}
