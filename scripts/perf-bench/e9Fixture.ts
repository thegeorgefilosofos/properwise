// Οι γραμμές όπως τις δίνει ο αναγνώστης κειμένου (lib/pdf/pdfText.ts) για το
// Ε9 του myAADE: κάθετες επικεφαλίδες κομματιασμένες, πέντε γραμμές ανά
// ακίνητο, ΑΤΑΚ σε δύο γραμμές (6 + 5 ψηφία), ποσοστό σε τρία κομμάτια
// («100,» / «0000» / «0»), κεφαλαία, υποδιαστολή με κόμμα. ΚΑΘΕ ΤΙΜΗ ΕΙΝΑΙ
// ΦΑΝΤΑΣΤΙΚΗ: ΑΤΑΚ 999…, ΑΦΜ και αριθμός παροχής που δεν περνούν τον έλεγχο
// ψηφίου ΑΦΜ, «ΠΑΡΑΔΕΙΓΜΑΤΟΣ», Τ.Κ. 10000. Τη χρησιμοποιούν η δοκιμή
// (lib/myaade/bulk.test.ts) και ο πάγκος διάταξης (scripts/perf-bench/mobile.tsx).
// Ζει εδώ και όχι στο lib/: η εφαρμογή δεν το καλεί ποτέ.
