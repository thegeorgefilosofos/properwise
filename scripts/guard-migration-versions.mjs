#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΚΑΘΕ ΜΕΤΑΝΑΣΤΕΥΣΗ ΕΧΕΙ ΔΙΚΗ ΤΗΣ ΕΚΔΟΣΗ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΠΕΡΙΣΤΑΤΙΚΟ. Στις 20/10/2026 δύο κλάδοι έγραψαν παράλληλα μετανάστευση με
// την ίδια ώρα, 20261020120000: η υπαναχώρηση (#414) και οι αυτόματες
// προθεσμίες (#415). Η βάση κρατά ΜΙΑ γραμμή ανά έκδοση στο
// `supabase_migrations.schema_migrations`. Η πρώτη που εφαρμόστηκε πήρε τη
// γραμμή· η δεύτερη έσκαγε σε κάθε deploy με διπλό κλειδί στο INSERT και
// σταματούσε τον αγωγό. Κάθε deploy της παραγωγής από εκεί και πέρα απέτυχε
// και καμία από τις επόμενες μεταναστεύσεις δεν έφτασε: ούτε ο
// `withdrawal_requests` (η φόρμα υπαναχώρησης δεν μπορούσε να γράψει) ούτε ο
// `accountant_invites` των προσκλήσεων του λογιστή.
//
// ΓΙΑΤΙ ΔΕΝ ΤΟ ΠΙΑΝΕΙ ΤΙΠΟΤΑ ΑΛΛΟ. Το CI ξαναχτίζει τη βάση με `psql`, αρχείο
// προς αρχείο, χωρίς πίνακα ιστορικού: εκεί δύο αρχεία με ίδια ώρα τρέχουν
// και τα δύο καθαρά. Το git δεν βλέπει σύγκρουση, γιατί τα ονόματα διαφέρουν
// μετά την ώρα. Το σφάλμα φαίνεται μόνο στο `supabase db push` της παραγωγής.
//
// ΤΙ ΕΛΕΓΧΕΤΑΙ. Τα 14 πρώτα ψηφία κάθε αρχείου `.sql` του
// supabase/migrations/ είναι μοναδικά. Καμία εξαίρεση.
// ═══════════════════════════════════════════════════════════════════════════
import { readdirSync } from 'node:fs'

const DIR = 'supabase/migrations'
const files = readdirSync(DIR).filter(f => f.endsWith('.sql')).sort()
const byVersion = new Map()
const badName = []
for (const f of files) {
  const m = /^(\d{14})_/.exec(f)
  if (!m) { badName.push(f); continue }
  byVersion.set(m[1], [...(byVersion.get(m[1]) ?? []), f])
}
const dupes = [...byVersion].filter(([, fs]) => fs.length > 1)

if (dupes.length || badName.length) {
  if (dupes.length) {
    console.error(`\n✗ ${dupes.length} εκδόσεις μετανάστευσης με περισσότερα από ένα αρχεία:\n`)
    for (const [v, fs] of dupes.slice(0, 30)) console.error(`  ${v}:  ${fs.map(f => `${DIR}/${f}`).join('  ·  ')}`)
  }
  if (badName.length) {
    console.error(`\n✗ ${badName.length} αρχεία χωρίς έκδοση 14 ψηφίων στην αρχή:\n`)
    for (const f of badName.slice(0, 30)) console.error(`  ${DIR}/${f}`)
  }
  console.error(`\n  ΤΙ ΝΑ ΚΑΝΕΙΣ: δώσε στο νεότερο αρχείο άλλη ώρα (π.χ. +100 στα τελευταία ψηφία)`)
  console.error(`  και ενημέρωσε όσα αρχεία το αναφέρουν με το όνομά του. Αν η παλιά έκδοση έχει`)
  console.error(`  ήδη γραφτεί στην παραγωγή, μένει στο αρχείο που εφαρμόστηκε πρώτο.\n`)
  process.exit(1)
}
console.log(`✓ migration-versions: ${files.length} μεταναστεύσεις, όλες με δική τους έκδοση`)
