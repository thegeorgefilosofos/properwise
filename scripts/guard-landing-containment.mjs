#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// Ο ΠΕΡΙΟΡΙΣΜΟΣ ΤΗΣ ΑΡΧΙΚΗΣ, ΚΑΙ Η ΜΙΑ ΕΝΟΤΗΤΑ ΠΟΥ ΔΕΝ ΤΟΝ ΑΝΤΕΧΕΙ
// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΦΥΛΑΕΙ. Η αρχική είναι 12.053 εικονοστοιχεία ύψος — δεκατέσσερις οθόνες —
// και ο περιηγητής τις έστρωνε ΟΛΕΣ πριν ζωγραφίσει την πρώτη: μία διάταξη
// 313ms με 1.111 από 1.111 αντικείμενα βρόμικα. Το `content-visibility: auto`
// στις έντεκα ενότητες `.lp-reveal` το έριξε στα μισά: μπλοκάρισμα 820 → 438ms,
// FCP 1.296 → 904ms. Ο κανόνας ζει στο app/globals.css.
//
// ΓΙΑΤΙ ΧΡΕΙΑΖΕΤΑΙ ΦΥΛΑΚΑΣ ΚΑΙ ΔΕΝ ΦΤΑΝΕΙ ΤΟ ΣΧΟΛΙΟ. Δύο τρόποι να χαθεί,
// κανένας τους θορυβώδης:
//
//   1. ΣΒΗΝΕΙ Ο ΚΑΝΟΝΑΣ. Η κλάση `lp-reveal` έμεινε κάποτε ΧΩΡΙΣ κανέναν
//      ορισμό CSS — ήταν κίνηση με transform, ο κανόνας αφαιρέθηκε, το όνομα
//      έμεινε σε έντεκα ενότητες. Ακριβώς αυτό μπορεί να ξανασυμβεί: κανείς
//      δεν βλέπει διαφορά στην οθόνη, μόνο το κινητό ξαναμπλοκάρει 380ms.
//
//   2. ΜΠΑΙΝΕΙ Η ΚΛΑΣΗ ΣΤΗ ΛΑΘΟΣ ΕΝΟΤΗΤΑ. Το scrollytelling κρατά το πάνελ
//      με `position: sticky`· ο περιορισμός σε πρόγονο ΣΠΑΕΙ το sticky —
//      το ίδιο ακριβώς που έσπαγε και ο παλιός transform. Η ενότητα είναι
//      επίτηδες χωρίς την κλάση, με τον λόγο γραμμένο δίπλα της. Οποιος
//      «τακτοποιήσει» τις ενότητες να έχουν όλες την ίδια κλάση σπάει το
//      καρφίτσωμα σιωπηλά: η σελίδα δείχνει σωστή, το πάνελ απλώς κυλάει.
//
// ΤΟ ΣΧΟΛΙΟ ΤΟ ΕΞΗΓΕΙ ΗΔΗ ΣΕ ΤΡΙΑ ΣΗΜΕΙΑ ΚΑΙ ΔΕΝ ΑΡΚΕΙ: ένα σχόλιο πείθει
// όποιον το διαβάσει. Αυτό εδώ κοκκινίζει.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'

const css = readFileSync('app/globals.css', 'utf8')
const page = readFileSync('app/page.tsx', 'utf8')
const fail = []

// ── 1. Ο κανόνας υπάρχει και δίνει και τα δύο μισά ────────────────────────
// Το `content-visibility` χωρίς `contain-intrinsic-size` δίνει ύψος μηδέν στις
// ενότητες εκτός κάδρου: η μπάρα κύλισης πηδά κάθε φορά που ζωγραφίζεται μία.
const rule = css.match(/\.lp-reveal\s*\{[^}]*\}/)
if (!rule) {
  fail.push('Ο κανόνας `.lp-reveal { … }` λείπει από το app/globals.css.')
} else {
  if (!/content-visibility:\s*auto/.test(rule[0])) fail.push('Ο κανόνας `.lp-reveal` δεν έχει `content-visibility: auto`.')
  if (!/contain-intrinsic-size:\s*auto\s+\d+px/.test(rule[0])) {
    fail.push('Ο κανόνας `.lp-reveal` δεν έχει `contain-intrinsic-size: auto <ύψος>px`. Χωρίς αυτό οι ενότητες εκτός κάδρου μετράνε μηδέν και η μπάρα κύλισης πηδά.')
  }
}

// ── 2. Το scrollytelling μένει ΕΞΩ από τον περιορισμό ─────────────────────
// Ταυτότητα της ενότητας είναι το `<ScrollStory`, όχι η σειρά της: όποιος
// μετακινήσει την ενότητα δεν ξεφεύγει από τον έλεγχο.
const at = page.indexOf('<ScrollStory')
if (at < 0) {
  fail.push('Δεν βρέθηκε `<ScrollStory` στο app/page.tsx — ο φύλακας δεν ξέρει πια τι φυλάει.')
} else {
  // Το ΑΝΟΙΓΜΑ της περικλείουσας ενότητας: το τελευταίο `<section` πριν από αυτήν.
  const open = page.lastIndexOf('<section', at)
  const tag = page.slice(open, page.indexOf('>', open) + 1)
  if (/lp-reveal/.test(tag)) {
    fail.push('Η ενότητα του `<ScrollStory>` πήρε την κλάση `lp-reveal`. Ο περιορισμός σε πρόγονο σπάει το `position: sticky` του πάνελ — το καρφίτσωμα χάνεται χωρίς κανένα ορατό σφάλμα.')
  }
}

if (fail.length) {
  console.error(`✗ ${fail.length} ${fail.length === 1 ? 'εύρημα' : 'ευρήματα'} στον περιορισμό της αρχικής:\n`)
  for (const f of fail) console.error(`   ${f}`)
  console.error('\n  Το «γιατί», με μετρήσεις: app/globals.css, πάνω από τον κανόνα `.lp-reveal`.')
  process.exit(1)
}
console.log('✓ ο περιορισμός της αρχικής στη θέση του — το scrollytelling μένει έξω από αυτόν')
