#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// Η ΟΔΟΣ ΤΟΥ ΙΔΙΟΚΤΗΤΗ ΔΕΝ ΓΡΑΦΕΤΑΙ ΠΟΥΘΕΝΑ, ΟΥΤΕ ΣΕ ΔΟΚΙΜΗ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΠΕΡΙΣΤΑΤΙΚΟ. Ο κανόνας του έργου λέει ότι κάθε παράδειγμα είναι προφανώς
// φανταστικό («Οδός Παραδείγματος 12, Αθήνα», ΤΚ 10000) και ότι η οδός όπου
// μένει ο ιδιοκτήτης του προϊόντος δεν γράφεται ΠΟΤΕ. Ο έλεγχος του Σεπτεμβρίου
// 2026 τη βρήκε σε ένα σημείο: ως διεύθυνση στο στιγμιότυπο δοκιμής των
// μηνυμάτων πελάτη (lib/clients/crmFeatures.test.ts), χωρίς κανένα assert πάνω
// της. Ο κανόνας ζούσε μόνο σε κείμενο οδηγιών, οπότε τον παρέκαμψε η πρώτη
// δοκιμή που χρειάστηκε μια «αληθοφανή» διεύθυνση.
//
// ΤΙ ΕΛΕΓΧΕΤΑΙ. ΚΑΘΕ αρχείο κειμένου του αποθετηρίου, δοκιμές και έγγραφα
// μαζί: ένα δημόσιο αποθετήριο ή ένα στιγμιότυπο οθόνης δεν ξεχωρίζει κώδικα
// από σχόλιο. Κάθε λέξη κανονικοποιείται (χωρίς τόνους, πεζά, «ς» ως «σ») και
// συγκρίνεται με τις απαγορευμένες μορφές, ελληνικές και λατινικές.
//
// ΓΙΑΤΙ ΑΠΟΤΥΠΩΜΑΤΑ ΚΑΙ ΟΧΙ Η ΛΕΞΗ. Ενας φύλακας που γράφει τη λέξη για να την
// απαγορεύσει είναι ο ίδιος η διαρροή: θα ήταν το ένα αρχείο του έργου όπου η
// διεύθυνση διαβάζεται αυτούσια. Εδώ ζουν μόνο τα SHA-256 των μορφών της.
// Για να προστεθεί μορφή: υπολόγισε το αποτύπωμα της κανονικοποιημένης λέξης
// με τη `norm` παρακάτω και πρόσθεσέ το στο σύνολο, χωρίς τη λέξη σε σχόλιο.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync, statSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { projectFiles } from './lib/git-files.mjs'

/** Αποτυπώματα των απαγορευμένων μορφών, μετά από `norm`. */
const FORBIDDEN = new Set([
  'c08c1f5b2048755def86d6d7e6746ea176e5cb01c4490cfaf6cec23ce26ebc54', // ελληνικά
  '2ac8d12e6bf55bbeeead6327400cbdbb29db787aba43e79168b2c2e7cb814889', // λατινικά, ΕΛΟΤ 743
  'e500111f2ac0be2763eabcee82b2ea04a1c4590433ad5c40decb6bb97629c5de', // λατινικά, φωνητικά
])
/** Ολες οι μορφές έχουν αυτό το μήκος: οι άλλες λέξεις δεν χρειάζεται να κατακερματιστούν. */
const LEN = 7

const norm = (w) => w.normalize('NFD').replace(/\p{M}/gu, '').toLowerCase().replace(/ς/g, 'σ')
const sha = (w) => createHash('sha256').update(w).digest('hex')

/** Δυαδικά αρχεία: δεν έχουν λέξεις να διαβαστούν. */
const BINARY = /\.(png|jpe?g|gif|webp|avif|ico|icns|pdf|woff2?|ttf|otf|eot|mp3|mp4|webm|mov|zip|gz|br|xlsx|docx|pptx|wasm|bin)$/i
const MAX_BYTES = 8 * 1024 * 1024

const files = projectFiles()
const hits = []
let scanned = 0
for (const file of files) {
  if (BINARY.test(file)) continue
  let size
  try { size = statSync(file).size } catch { continue }
  if (size > MAX_BYTES) continue
  scanned++
  const lines = readFileSync(file, 'utf8').split('\n')
  lines.forEach((line, i) => {
    for (const m of line.matchAll(/\p{L}+/gu)) {
      const w = norm(m[0])
      if (w.length === LEN && FORBIDDEN.has(sha(w))) hits.push(`${file}:${i + 1}`)
    }
  })
}

if (hits.length) {
  console.error(`\n✗ ${hits.length} εμφανίσεις της ιδιωτικής διεύθυνσης του ιδιοκτήτη:\n`)
  for (const h of hits.slice(0, 30)) console.error(`  ${h}`)
  if (hits.length > 30) console.error(`  … και ${hits.length - 30} ακόμη`)
  console.error(`
  ΤΙ ΝΑ ΚΑΝΕΙΣ: αντικατάστησε τη διεύθυνση με προφανώς φανταστική, π.χ.
  «Οδός Παραδείγματος 12, Αθήνα» και ΤΚ 10000. Ισχύει και για δοκιμές, σχόλια
  και έγγραφα. Αν είναι ήδη σε commit, πες το στον ιδιοκτήτη: το ιστορικό του
  git την κρατά.\n`)
  process.exit(1)
}
console.log(`✓ Καμία ιδιωτική διεύθυνση σε ${scanned} αρχεία κειμένου`)
