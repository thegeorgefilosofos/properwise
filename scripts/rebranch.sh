#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════
# ΞΑΝΑΣΤΗΝΕΙ ΤΟ ΚΛΑΔΙ ΕΡΓΑΣΙΑΣ ΠΑΝΩ ΣΤΟ ΤΡΕΧΟΝ main
# ─────────────────────────────────────────────────────────────────────────
# ΤΟ ΣΦΑΛΜΑ ΠΟΥ ΛΥΝΕΙ, ΚΑΙ ΕΓΙΝΕ ΔΥΟ ΦΟΡΕΣ ΜΕΣΑ ΣΤΗΝ ΙΔΙΑ ΜΕΡΑ. Τα PR αυτού του
# αποθετηρίου συγχωνεύονται με SQUASH: το main παίρνει ΕΝΑ νέο commit με το ίδιο
# περιεχόμενο, αλλά το κλαδί κρατά τα δικά του παλιά commits. Το επόμενο PR από
# το ίδιο κλαδί προσπαθεί λοιπόν να ξαναγράψει γραμμές που το main έχει ήδη·
# βγαίνει με σύγκρουση.
#
# ΚΑΙ ΕΔΩ ΕΙΝΑΙ ΤΟ ΜΕΡΟΣ ΠΟΥ ΔΕΝ ΦΑΙΝΕΤΑΙ: όταν ένα PR έχει σύγκρουση, το GitHub
# ΔΕΝ ΜΠΟΡΕΙ ΝΑ ΦΤΙΑΞΕΙ ΤΟ MERGE REF — και χωρίς αυτό δεν τρέχει ΚΑΝΕΝΑ workflow
# του συμβάντος `pull_request`. Δηλαδή το CI δεν βγαίνει κόκκινο· απλώς δεν
# υπάρχει. Ενας έλεγχος που λείπει μοιάζει με έλεγχο που αργεί· έτσι περιμένεις.
#
# ΓΙΑΤΙ ΟΧΙ `git rebase`. Το rebase προσπαθεί να ξαναπαίξει commits που το main
# έχει ήδη ως squash: κάθε ένα συγκρούεται με τον εαυτό του. Εδώ κρατάμε το
# ΑΠΟΤΕΛΕΣΜΑ και όχι τη διαδρομή — τη διαφορά περιεχομένου από το main — και τη
# βάζουμε καθαρά από πάνω του.
#
# ΔΕΝ ΚΑΝΕΙ ΤΙΠΟΤΑ ΣΤΑ ΤΥΦΛΑ. Αν η διαφορά ΔΕΝ εφαρμόζεται καθαρά πάνω στο νέο
# main, υπάρχει πραγματική σύγκρουση — κάποιος άλλος άλλαξε τα ίδια σημεία — και
# το σενάριο σταματά χωρίς να αγγίξει τίποτα. Αυτό θέλει άνθρωπο, όχι αυτοματισμό.
#
#   bash scripts/rebranch.sh
#
# Αφήνει τις αλλαγές ΣΤΑΔΙΑΣΜΕΝΕΣ και ΑΔΕΣΜΕΥΤΕΣ: το μήνυμα του commit το γράφει
# αυτός που ξέρει τι έκανε.
# ═══════════════════════════════════════════════════════════════════════════
set -euo pipefail

BASE="${1:-main}"
BRANCH="$(git rev-parse --abbrev-ref HEAD)"

if [ "$BRANCH" = "$BASE" ]; then
  echo "✗ Είσαι ΣΤΟ $BASE. Το σενάριο ξαναστήνει κλάδο εργασίας, όχι τη βάση."; exit 2
fi

if ! git diff --quiet || ! git diff --cached --quiet; then
  echo "✗ Υπάρχουν αδέσμευτες αλλαγές. Δέσμευσέ τες ή κράτα τες στην άκρη πρώτα:"
  git status --short; exit 2
fi

echo "→ φέρνω το $BASE"
git fetch origin "$BASE" --quiet

CHANGED="$(git diff --name-only "origin/$BASE" HEAD)"
if [ -z "$CHANGED" ]; then
  echo "✓ Το κλαδί δεν έχει καμία διαφορά περιεχομένου από το origin/$BASE."
  echo "  Ολη η δουλειά έχει ήδη συγχωνευθεί· το ξαναστήνω και τελειώνει εδώ."
  git checkout -B "$BRANCH" "origin/$BASE" --quiet
  exit 0
fi

echo "→ διαφορά περιεχομένου από το origin/$BASE:"
git diff --stat "origin/$BASE" HEAD | sed 's/^/   /'

PATCH="$(mktemp)"
trap 'rm -f "$PATCH"' EXIT
git diff --binary "origin/$BASE" HEAD > "$PATCH"

OLD="$(git rev-parse HEAD)"
git checkout -B "$BRANCH" "origin/$BASE" --quiet

if ! git apply --index "$PATCH"; then
  echo ""
  echo "✗ Η διαφορά ΔΕΝ εφαρμόζεται καθαρά πάνω στο νέο $BASE."
  echo "  Αυτό είναι πραγματική σύγκρουση: κάποιος άλλος άλλαξε τα ίδια σημεία."
  echo "  Το κλαδί γύρισε στο $OLD και δεν πειράχθηκε τίποτα."
  git checkout -B "$BRANCH" "$OLD" --quiet
  exit 1
fi

echo ""
echo "✓ Το κλαδί $BRANCH ξεκινά τώρα από το origin/$BASE, με τη δουλειά από πάνω."
echo "  Οι αλλαγές είναι σταδιασμένες. Γράψε το commit και σπρώξε με --force-with-lease."
