#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΚΑΝΕΝΑ EMAIL ΔΕΝ ΛΕΕΙ ΟΤΙ Η ΕΦΑΡΜΟΓΗ ΚΙΝΗΤΟΥ ΥΠΑΡΧΕΙ ΗΔΗ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΠΕΡΙΣΤΑΤΙΚΟ. Ο guard-native-app-claims φυλάει τις αποδιδόμενες σελίδες
// (app/**/*.tsx) — αλλά όχι τα emails. Ετσι το email κυκλοφορίας εφαρμογής στο
// emailCopy.ts έγραφε «Η εφαρμογή για κινητά είναι εδώ» και «Κατέβασε την
// εφαρμογή» (με κουμπί που, από πάνω, έδειχνε στο web dashboard), για προϊόν
// που ΔΕΝ έχει κυκλοφορήσει. Το ίδιο ψέμα, σε άλλη επιφάνεια, χωρίς φύλακα.
//
// ΤΙ ΕΛΕΓΧΕΤΑΙ, ΑΚΡΙΒΩΣ. Στα κοινά αρχεία email (supabase/functions/_shared),
// κάθε γραμμή κειμένου (όχι σχόλιο) που δηλώνει την εφαρμογή ως ΥΠΑΡΚΤΗ —
// «Κατέβασε την εφαρμογή», «η εφαρμογή … είναι εδώ», «πλέον στο κινητό σου»,
// ή ονομάζει «App Store»/«Google Play» — ΠΡΕΠΕΙ να κουβαλά και λέξη που τη
// δηλώνει μελλοντική (έρχεται, ετοιμάζουμε, όταν/θα κυκλοφορήσει, λίστα
// αναμονής, δεν έχει βγει). Αλλιώς λέει ότι υπάρχει — και δεν υπάρχει.
//
// ΓΙΑΤΙ ΜΟΝΟ ΤΟ _shared. Το launch-blast της ημέρας κυκλοφορίας ζει στη
// notify-mobile-launch και ΕΠΙΤΡΕΠΕΤΑΙ να λέει «μόλις κυκλοφόρησε»: στέλνεται
// μόνο όταν πράγματι βγει. Τα πρότυπα/κατάλογος (_shared) φεύγουν αυτόματα,
// σε κύκλο ζωής, σε οποιονδήποτε — εκεί το ψέμα κοστίζει.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync, readdirSync, statSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = 'supabase/functions/_shared'
const files = []
if (existsSync(ROOT)) {
  for (const e of readdirSync(ROOT)) {
    const full = join(ROOT, e)
    if (statSync(full).isFile() && e.endsWith('.ts')) files.push(full)
  }
}

// Ισχυρισμοί «η εφαρμογή υπάρχει τώρα». Στενοί, ώστε να μην πιάνουν αθώες
// φράσεις: το «η προσφορά είναι εδώ» δεν έχει «εφαρμογή» δίπλα· το «στο κινητό
// σου» χωρίς «πλέον» είναι μελλοντικό.
const CLAIM = /Κατέβασε την εφαρμογή|εφαρμογή[^\n]{0,40}είναι εδώ|πλέον στο κινητό σου|App Store|Google Play/
const GATE = /δεν έχει κυκλοφορήσει|όταν κυκλοφορήσει|θα κυκλοφορήσει|λίστα αναμονής|δεν υπάρχει|δεν έχει βγει|μόλις (βγει|κυκλοφορήσει)|Έρχεται|έρχεται|Ετοιμάζουμε|ετοιμάζουμε|ώσπου να κυκλοφορήσει/

const provlimata = []
for (const arxeio of files) {
  const lines = readFileSync(arxeio, 'utf8').split('\n')
  lines.forEach((line, i) => {
    if (/^\s*(\/\/|\*|\/\*)/.test(line)) return   // τα σχόλια εξηγούν, δεν στέλνουν email
    if (CLAIM.test(line) && !GATE.test(line)) {
      provlimata.push({ arxeio, grammi: i + 1, ti: line.trim().slice(0, 70) })
    }
  })
}

if (provlimata.length) {
  console.error(`\n✗ ${provlimata.length} κείμενα email δηλώνουν την εφαρμογή κινητού σαν να υπάρχει:\n`)
  for (const p of provlimata.slice(0, 30)) console.error(`  ${p.arxeio}:${p.grammi}  «${p.ti}»`)
  console.error(`\n  ΤΙ ΝΑ ΚΑΝΕΙΣ: γράψε την εφαρμογή σε μέλλοντα — «έρχεται», «ετοιμάζουμε»,`)
  console.error(`  «όταν κυκλοφορήσει», «λίστα αναμονής» — όπως η αρχική, ο βοηθός και το`)
  console.error(`  mobileLaunchEmail. Το launch-blast της κυκλοφορίας ανήκει στη`)
  console.error(`  notify-mobile-launch, όχι στον κατάλογο/πρότυπα.\n`)
  process.exit(1)
}
console.log(`✓ κανένα email δεν δηλώνει την εφαρμογή κινητού ως υπαρκτή (${files.length} αρχεία)`)
