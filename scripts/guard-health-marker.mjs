#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΤΑ ΔΥΟ ΣΗΜΑΔΙΑ ΤΟΥ ΕΛΕΓΧΟΥ ΥΓΕΙΑΣ ΔΕΝ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΞΕΚΟΛΛΗΣΟΥΝ
// ─────────────────────────────────────────────────────────────────────────
// Ο έλεγχος υγείας δεν εμπιστεύεται τον κωδικό απάντησης. Μια σελίδα μπορεί να
// γυρίσει 200 και να είναι σελίδα σφάλματος, ή 200 με άδειο σώμα από
// μισοτελειωμένο stream ή από σελίδα-φάντασμα του CDN. Γι' αυτό κοιτά ΠΕΡΙΕΧΟΜΕΝΟ:
//
//   ERROR_MARKER   αν το κείμενο της σελίδας σφάλματος βρεθεί μέσα σε 200,
//                  η απάντηση είναι αποτυχία μεταμφιεσμένη σε επιτυχία
//   ROUTES[].must  αν το αναμενόμενο κείμενο ΔΕΝ βρεθεί, η σελίδα είναι κενή
//
// ΤΟ ΣΦΑΛΜΑ ΠΟΥ ΦΥΛΑΕΙ, ΚΑΙ ΕΙΝΑΙ ΣΙΩΠΗΛΟ ΚΑΙ ΣΤΙΣ ΔΥΟ ΚΑΤΕΥΘΥΝΣΕΙΣ:
//
//   · Αλλάζει το κείμενο της σελίδας σφάλματος και ΟΧΙ το `ERROR_MARKER` →
//     ο έλεγχος δεν αναγνωρίζει πια τη σελίδα σφάλματος. Βλέπει 200, λέει «όλα
//     καλά» και η παραγωγή είναι σπασμένη. Καμία ειδοποίηση, ποτέ.
//   · Αλλάζει το `ERROR_MARKER` και ΟΧΙ η σελίδα → το ίδιο, αντίστροφα.
//   · Φεύγει το σήμα της μάρκας από τη δημόσια αρχική → ο έλεγχος κοκκινίζει
//     κάθε μέρα χωρίς λόγο και η ομάδα μαθαίνει να τον αγνοεί.
//
// ΤΟ ΣΧΟΛΙΟ ΤΟ ΥΠΟΣΧΟΤΑΝ ΗΔΗ, ΚΑΙ ΗΤΑΝ ΨΕΜΑ. Το ίδιο το probe.mjs γράφει «Ο
// guard-health-marker το επιβάλλει» — και ο φύλακας δεν υπήρχε. Μια υπόσχεση σε
// σχόλιο δεν είναι μηχανισμός· διαβάζεται όμως ως τέτοια από τον επόμενο, που
// τότε δεν κοιτά.
//
// ΤΙ ΜΠΟΡΕΙ ΚΑΙ ΤΙ ΔΕΝ ΜΠΟΡΕΙ ΝΑ ΑΠΟΔΕΙΞΕΙ ΑΥΤΟΣ Ο ΦΥΛΑΚΑΣ. Διαβάζει πηγαίο
// κώδικα, όχι αποδοθείσα σελίδα: επιβεβαιώνει ότι τα δύο σημάδια ΥΠΑΡΧΟΥΝ εκεί
// που πρέπει. Το ότι φτάνουν όντως στην απόδοση το κρίνει ο σαρωτής του CI και
// ο ίδιος ο έλεγχος υγείας στην παραγωγή. Ο φύλακας κλείνει τη ΜΙΑ τρύπα που
// κανείς άλλος δεν βλέπει: το ξεκόλλημα των δύο αρχείων.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync, existsSync } from 'node:fs'

const PROBE = 'supabase/functions/_shared/probe.mjs'
const SELIDA_SFALMATOS = 'app/error.tsx'

/** Οπου συντίθεται η δημόσια αρχική: κέλυφος, διάταξη, η ίδια η σελίδα. */
const DIMOSIO_KELYFOS = ['app/PublicChrome.tsx', 'app/layout.tsx', 'app/page.tsx']

const provlimata = []

if (!existsSync(PROBE)) {
  console.error(`\n✗ Δεν βρέθηκε το ${PROBE}. Αν ο ανιχνευτής μετακόμισε, μετακόμισε και αυτός ο φύλακας.\n`)
  process.exit(1)
}
const probe = readFileSync(PROBE, 'utf8')

// ── Το σημάδι της σελίδας σφάλματος ────────────────────────────────────────
// Διαβάζεται από το ΚΕΙΜΕΝΟ και όχι με εισαγωγή: ο φύλακας είναι .mjs και ο
// ανιχνευτής ζει σε φάκελο συναρτήσεων με δικό του χρόνο εκτέλεσης. Αν το
// σχήμα αλλάξει, ο φύλακας κοκκινίζει αντί να μείνει σιωπηλά τυφλός.
const mError = probe.match(/ERROR_MARKER\s*=\s*['"]([^'"]+)['"]/)
if (!mError) {
  provlimata.push(`${PROBE}: δεν διαβάστηκε το ERROR_MARKER. Αν άλλαξε το σχήμα, άλλαξε και ο φύλακας.`)
} else if (!existsSync(SELIDA_SFALMATOS)) {
  provlimata.push(`Δεν βρέθηκε το ${SELIDA_SFALMATOS}.`)
} else if (!readFileSync(SELIDA_SFALMATOS, 'utf8').includes(mError[1])) {
  provlimata.push(
    `Το «${mError[1]}» του ${PROBE} ΔΕΝ υπάρχει στο ${SELIDA_SFALMATOS}.\n`
    + `     Ο έλεγχος υγείας δεν θα αναγνωρίσει πια τη σελίδα σφάλματος: θα δει 200 και θα πει «υγιής».`,
  )
}

// ── Τα αναμενόμενα κείμενα των δημόσιων διαδρομών ──────────────────────────
const kelyfos = DIMOSIO_KELYFOS.filter(existsSync).map(f => readFileSync(f, 'utf8')).join('\n')
if (!kelyfos) {
  provlimata.push(`Καμία από τις διαδρομές του δημόσιου κελύφους δεν βρέθηκε: ${DIMOSIO_KELYFOS.join(', ')}`)
}

let vrethike = 0
for (const m of probe.matchAll(/\{\s*path:\s*['"]([^'"]+)['"]\s*,\s*must:\s*(?:['"]([^'"]+)['"]|null)\s*\}/g)) {
  const [, path, must] = m
  if (!must) continue
  vrethike++
  if (kelyfos.includes(must)) continue
  provlimata.push(
    `Το «${must}» που περιμένει ο ανιχνευτής στη διαδρομή «${path}» δεν υπάρχει σε κανένα από: ${DIMOSIO_KELYFOS.join(', ')}.\n`
    + `     Ο έλεγχος υγείας θα κοκκινίζει κάθε μέρα χωρίς λόγο, ώσπου να τον αγνοήσουν.`,
  )
}
if (!vrethike && !provlimata.length) {
  provlimata.push(`${PROBE}: δεν διαβάστηκε καμία διαδρομή με \`must\`. Αν το σχήμα άλλαξε, άλλαξε και ο φύλακας.`)
}

if (provlimata.length) {
  console.error(`\n✗ ${provlimata.length} σημάδια του ελέγχου υγείας ξεκόλλησαν:\n`)
  for (const p of provlimata) console.error(`  ${p}`)
  console.error(`
  ΤΑ ΔΥΟ ΑΡΧΕΙΑ ΑΛΛΑΖΟΥΝ ΜΑΖΙ. Το κείμενο της σελίδας σφάλματος και το σήμα της
  αρχικής ζουν σε δύο σημεία επίτηδες: το ένα το βλέπει ο χρήστης, το άλλο το
  διαβάζει ο ανιχνευτής από έξω. Οταν ξεκολλήσουν, ο έλεγχος δεν σπάει — γίνεται
  ΤΥΦΛΟΣ, που είναι χειρότερο: συνεχίζει να λέει «όλα καλά».
`)
  process.exit(1)
}

console.log(`✓ σελίδα σφάλματος και σήμα αρχικής συμφωνούν με τον ανιχνευτή (${vrethike} διαδρομή με αναμενόμενο κείμενο)`)
