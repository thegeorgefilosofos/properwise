// ═══════════════════════════════════════════════════════════════════════════
// Ο ΑΡΙΘΜΟΣ ΔΕΝ ΧΩΡΙΖΕΤΑΙ ΑΠΟ ΤΗ ΜΟΝΑΔΑ ΤΟΥ ΚΑΙ ΚΑΘΕ ΤΙΤΛΟΣ ΖΥΓΙΖΕΤΑΙ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΠΕΡΙΣΤΑΤΙΚΟ (29/10/2026). Ο ιδιοκτήτης: «η ζύγιση και η στοίχιση δεν
// είναι πλήρεις, σπάει λάθος». Η σάρωση ζύγισης (40 σκηνές του πάγκου και 31
// δημόσιες σελίδες, 11 πλάτη από 320 ώς 1.440, δύο θέματα) βρήκε δύο
// κατηγορίες που γίνονται μηχανικά:
//
//   1. ΑΡΙΘΜΟΣ ΚΑΙ ΜΟΝΑΔΑ ΣΕ ΔΥΟ ΓΡΑΜΜΕΣ. «…τις πρώτες 30» στο τέλος της
//      γραμμής και «ημέρες.» στην αρχή της επόμενης, στην κάρτα κάθε
//      υπολογιστή· «άνω των 80» / «τ.μ.» σε τέσσερις οδηγούς. Ο λόγος ήταν ένας:
//      517 σημεία σε 111 αρχεία έγραφαν αριθμό ή `{έκφραση}` και μονάδα με
//      ΑΠΛΟ κενό, που είναι επιτρεπτό σημείο αλλαγής γραμμής. Διορθώθηκαν όλα
//      με αδιάσπαστο (U+00A0). Ο φύλακας κρατά το μηδέν.
//
//   2. ΤΙΤΛΟΙ ΠΟΥ ΔΕΝ ΕΙΝΑΙ <h> ΜΕ ΜΙΑ ΛΕΞΗ ΜΟΝΗ ΣΤΗ ΔΕΥΤΕΡΗ ΓΡΑΜΜΗ. «Πρόσθεσε
//      ενοικιαστή και / ενοίκιο», «ΔΟΣΗ ΔΑΝΕΙΟΥ / / ΜΗΝΑ». Το `balance` ζούσε
//      μόνο στα <h1>–<h4>. Η ρίζα είναι δύο κανόνες με μηδενική εξειδίκευση στο
//      app/globals.css· αν σβηστούν, ξαναγυρίζουν σε όλες τις οθόνες μαζί και
//      κανένας άλλος έλεγχος δεν το βλέπει (το κείμενο είναι σωστό, σπάει μόνο
//      η εικόνα). Ο φύλακας απαιτεί να υπάρχουν.
//
// ΤΙ ΕΛΕΓΧΕΤΑΙ, ΑΚΡΙΒΩΣ.
//   · τα .tsx του app/** και του components/**, εκτός από δοκιμές και το
//     app/api/** (απαντήσεις JSON και email, όχι σελίδα)· οι γραμμές σχολίων
//     εξαιρούνται. ΟΧΙ τα σκέτα .ts: εκεί ζουν και τα κείμενα που πάνε στη Νόα
//     (prompt), στις εξαγωγές και στις δοκιμές, όπου το U+00A0 δεν βοηθά
//     καμία οθόνη και αλλάζει συγκρίσεις κειμένου. Ο,τι .ts γράφει μόνο για
//     σελίδα δένεται με το χέρι (app/landingContent.ts).
//     Απαγορεύεται: ψηφίο ή `}` (τέλος έκφρασης JSX ή `${…}`) + ΑΠΛΟ κενό +
//     μονάδα χρόνου, επιφάνειας, ενέργειας ή πλήθους (βλ. UNIT).
//   · app/globals.css: ο κανόνας `:where([class*="-title"], [class*="-label"] …)
//     { text-wrap-style: balance }` και ο `:where(p, li, dd, blockquote)…
//     { text-wrap-style: pretty }`. ΜΕ ΤΟ LONGHAND: το shorthand `text-wrap`
//     γράφει και `text-wrap-mode: wrap` και ακύρωνε το `nowrap` που
//     κληρονομούν τα ποσά των πινάκων («Αγορά 615,00€» σε τέσσερις σειρές).
//
// ΤΟ € ΔΕΝ ΕΙΝΑΙ ΕΔΩ: γράφεται κολλητά στο ποσό («1.234,56€», guard-euro-space)
// και ο αλγόριθμος αλλαγής γραμμής (UAX #14, LB25) δεν σπάει ποτέ ανάμεσα σε
// αριθμό και σύμβολο νομίσματος.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { projectFiles } from './lib/git-files.mjs'

const UNIT = '(?:ημέρες|ημέρα|ημερών|μέρες|μήνες|μήνα|μηνών|έτη|ετών|χρόνια|χρόνο|ώρες|εβδομάδες|εργάσιμες|δόσεις|δόση|τ\\.μ\\.|kWh|ακίνητα|ακίνητο|νύχτες|λεπτά)'
const RE = new RegExp(`(\\d|\\}) (?=${UNIT}(?!\\p{L}))`, 'gu')

const files = projectFiles("'app/**/*.tsx' 'components/**/*.tsx'")
  .filter(f => !/\.test\.tsx?$|testkit|^app\/api\//.test(f))

const provlimata = []
for (const f of files) {
  const lines = readFileSync(f, 'utf8').split('\n')
  lines.forEach((line, i) => {
    const t = line.trim()
    if (t.startsWith('//') || t.startsWith('*') || t.startsWith('/*')) return
    for (const m of line.matchAll(RE)) {
      provlimata.push({ arxeio: f, grammi: i + 1, ti: line.slice(Math.max(0, m.index - 25), m.index + 22).trim() })
    }
  })
}

const css = readFileSync('app/globals.css', 'utf8')
const kanones = [
  { re: /:where\(\[class\*="-title"\], \[class\*="-label"\][^{]*\)\s*\{\s*text-wrap-style:\s*balance;?\s*\}/, ti: 'ο κανόνας `:where([class*="-title"], [class*="-label"] …) { text-wrap-style: balance }`' },
  { re: /:where\(p, li, dd, blockquote\)[^{]*\{\s*text-wrap-style:\s*pretty;?\s*\}/, ti: 'ο κανόνας `:where(p, li, dd, blockquote)… { text-wrap-style: pretty }`' },
]
const leipoun = kanones.filter(k => !k.re.test(css))

if (provlimata.length || leipoun.length) {
  if (provlimata.length) {
    console.error(`\n✗ ${provlimata.length} αριθμοί χωρισμένοι από τη μονάδα τους με απλό κενό:\n`)
    for (const p of provlimata.slice(0, 30)) console.error(`  ${p.arxeio}:${p.grammi}  «${p.ti}»`)
    if (provlimata.length > 30) console.error(`  … και άλλα ${provlimata.length - 30}`)
    console.error(`\n  ΤΙ ΝΑ ΚΑΝΕΙΣ: γράψε αδιάσπαστο κενό (U+00A0) ανάμεσα στον αριθμό και τη μονάδα:`)
    console.error(`  «{n} ημέρες», «\${n} τ.μ.». Στο τερματικό φαίνεται ίδιο· ο περιηγητής δεν σπάει εκεί.\n`)
  }
  for (const k of leipoun) {
    console.error(`\n✗ Λείπει από το app/globals.css ${k.ti}.`)
    console.error(`  ΤΙ ΝΑ ΚΑΝΕΙΣ: ξαναβάλ' τον (βλ. «ΚΑΙ ΟΙ ΤΙΤΛΟΙ ΠΟΥ ΔΕΝ ΕΙΝΑΙ <h>» στο ίδιο αρχείο).\n`)
  }
  process.exit(1)
}
console.log(`✓ κανένας αριθμός χωρίς τη μονάδα του σε ${files.length} αρχεία · οι κανόνες ζύγισης τίτλων και παραγράφων στη θέση τους`)
