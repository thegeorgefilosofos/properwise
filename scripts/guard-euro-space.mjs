#!/usr/bin/env node
// ════════════════════════════════════════════════════════════════════════════
// ΤΟ ΕΥΡΩ ΓΡΑΦΕΤΑΙ ΚΟΛΛΗΤΑ ΣΤΟΝ ΑΡΙΘΜΟ: «1.234,56€»
// ────────────────────────────────────────────────────────────────────────
// ΑΥΤΟΣ Ο ΦΥΛΑΚΑΣ ΕΛΕΓΧΕ ΤΟ ΑΝΤΙΘΕΤΟ, ΚΑΙ Η ΑΛΛΑΓΗ ΗΤΑΝ ΑΠΟΦΑΣΗ ΤΟΥ ΕΡΓΟΥ.
// Γράφεται εδώ ώστε να μη διαβαστεί αύριο ως λάθος και «διορθωθεί» πίσω.
//
// Η ΠΡΟΗΓΟΥΜΕΝΗ ΘΕΣΗ, ΓΙΑ ΤΗΝ ΙΣΤΟΡΙΑ: η ελληνική και η γαλλική τυπογραφία
// βάζουν αδιάσπαστο κενό πριν το σύμβολο νομίσματος («1.234,50 ευρώ»)· ο
// φύλακας το επέβαλλε με U+00A0 ώστε το σύμβολο να μην πέφτει ποτέ μόνο του
// στην επόμενη γραμμή. Η απόφαση άλλαξε: το προϊόν γράφει «1.234,56€», παντού.
//
// ΤΟ ΝΟΗΜΑ ΤΟΥ ΦΥΛΑΚΑ ΔΕΝ ΑΛΛΑΞΕ, ΜΟΝΟ Η ΚΑΤΕΥΘΥΝΣΗ ΤΟΥ. Το πρόβλημα ήταν και
// παραμένει ΔΥΟ ΤΥΠΟΓΡΑΦΙΕΣ ΣΤΗΝ ΙΔΙΑ ΟΘΟΝΗ: ένα ποσό από τον μορφοποιητή
// δίπλα σε ένα γραμμένο με το χέρι, με άλλη απόσταση. Ο κανόνας είναι ένας,
// όποιος κι αν είναι — και επιβάλλεται και στα δύο.
//
// ΤΙ ΕΛΕΓΧΕΤΑΙ
//   · κανένα κενό —ούτε απλό ούτε αδιάσπαστο— ανάμεσα στο ψηφίο και στο σύμβολο
//   · κανένα ποσό σε πρόταση χωρίς μορφοποιητή: το «751» εκεί που όλη η
//     εφαρμογή γράφει «751,00» είναι ίδιο ποσό με δύο γραφές — η
//     υποδιαστολή δεν στοιχίζεται με τη διπλανή γραμμή
//
// Οι δοκιμές εξαιρούνται: εκεί το ποσό χωρίς μορφοποίηση μπορεί να είναι
// ΕΙΣΟΔΟΣ που ελέγχουμε ότι διαβάζεται σωστά.
// ════════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs';
import { projectFiles } from './lib/git-files.mjs'

const files = projectFiles("'app/**/*.ts' 'app/**/*.tsx' 'lib/**/*.ts' 'lib/**/*.tsx' 'components/**/*.ts' 'components/**/*.tsx'");

/**
 * ΚΕΝΟ ΠΡΙΝ ΤΟ ΣΥΜΒΟΛΟ — απλό ή αδιάσπαστο· απαγορεύονται και τα δύο.
 *
 * ΤΙ ΣΤΕΚΕΤΑΙ ΠΡΙΝ ΤΟ ΚΕΝΟ ΕΙΝΑΙ Ο,ΤΙ ΞΕΧΩΡΙΖΕΙ ΤΟ ΠΟΣΟ ΑΠΟ ΤΗΝ ΠΡΟΖΑ. Ενα
 * σκέτο «€» ως μονάδα σε επικεφαλίδα στήλης («Εκτίμηση €») ή σε πρόταση («σε €
 * ανά kWh») είναι σωστό και δεν αγγίζεται. Αυτό που δεν επιτρέπεται είναι το
 * κενό ανάμεσα σε ΠΟΣΟ και σύμβολο — κι εκεί το ποσό φτάνει με τρεις μορφές:
 *
 *     ψηφίο           «650 €»
 *     έκφραση         «${avg} €», «{avg} €» σε JSX
 *     μορφή αριθμού   '#,##0.00" €"' — το πρότυπο κελιού του Excel
 *
 * ΟΙ ΔΥΟ ΤΕΛΕΥΤΑΙΕΣ ΕΛΕΙΠΑΝ ΚΑΙ ΚΡΥΒΑΝ ΠΕΝΤΕ ΠΡΑΓΜΑΤΙΚΑ: τη μορφή «eur» και τη
 * «money()» του `sheetFormat.ts` (δηλαδή ΚΑΘΕ ποσό σε κάθε εξαγωγή προς
 * λογιστή), το αντίγραφό της στο `JournalExport.tsx` και έναν μέσο όρο στο
 * `BillsProviders.tsx` που γραφόταν ωμός ανάμεσα σε δύο μορφοποιημένα.
 */
const SPACED = /[\d}#][\u0020\u00A0]€/g;
/**
 * ΤΟ ΚΕΝΟ ΓΡΑΜΜΕΝΟ ΩΣ ΔΙΑΦΥΓΗ Η ΩΣ ΟΝΤΟΤΗΤΑ — ΚΑΙ ΧΩΡΙΣ ΨΗΦΙΟ ΜΠΡΟΣΤΑ.
 *
 * ΤΡΙΑ ΠΡΑΓΜΑΤΙΚΑ ΞΕΦΥΓΑΝ ΑΠΟ ΤΟΝ ΠΑΝΩ ΚΑΝΟΝΑ, γιατί ζητούσε ψηφίο ακριβώς
 * πριν το κενό:
 *
 *     ExpenseCompare.tsx   {pre}{int}<span>,{dec}</span>{'\\u00A0€'}
 *     ShowcasePanels.tsx   88,50&nbsp;€   ·   1.240,00&nbsp;€
 *
 * Στο πρώτο, το ψηφίο έμπαινε από διπλανή έκφραση JSX και πριν το κενό στεκόταν
 * αγκύλη· στα άλλα δύο το κενό ήταν οντότητα HTML. Και τα τρία ζωγράφιζαν στην
 * οθόνη ακριβώς αυτό που ο κανόνας απαγορεύει.
 *
 * ΓΙΑΤΙ ΔΕΝ ΘΕΛΕΙ ΨΗΦΙΟ ΜΠΡΟΣΤΑ. Το «\\u00A0» και το «&nbsp;» δεν γράφονται
 * ποτέ κατά λάθος και δεν έχουν άλλη χρήση δίπλα στο «€»: μπαίνουν επίτηδες,
 * για να κολλήσουν το σύμβολο σε ποσό. Οπότε η παρουσία τους ΕΙΝΑΙ η πρόθεση.
 */
const GLUE = /(?:\\u00[aA]0|\\x[aA]0|&nbsp;|&#160;|&#xa0;)€/g;
/**
 * ΠΟΣΟ ΠΟΥ ΜΠΑΙΝΕΙ ΣΕ ΠΡΟΤΑΣΗ ΧΩΡΙΣ ΝΑ ΠΕΡΑΣΕΙ ΑΠΟ ΜΟΡΦΟΠΟΙΗΤΗ.
 *
 * Το «${Math.round(prop.enfia)} €» γράφει «751 €» εκεί που όλη η εφαρμογή
 * γράφει «751,00 €»: ίδιο ποσό, δύο γραφές και η υποδιαστολή δεν στοιχίζεται
 * με τη διπλανή γραμμή. Βρέθηκαν έντεκα τέτοια, τα εφτά μέσα στους λόγους
 * απόρριψης του «Σπίτι μου ΙΙ» — δηλαδή στην οθόνη όπου ο χρήστης μαθαίνει
 * γιατί δεν δικαιούται δάνειο.
 */
const UNFORMATTED = /\$\{(?!\s*(?:fe|feAuto|feRate|feSigned|feCompact|pEur|fmtEur|eur|money)\s*\()[^}]*\}[\s\u00A0]*€/g;

/* ΤΟ «ΔΥΟ ΚΕΝΑ» ΚΑΙ ΤΟ «ΣΠΑΣΤΟ ΚΕΝΟ» ΕΦΥΓΑΝ ΩΣ ΞΕΧΩΡΙΣΤΟΙ ΚΑΝΟΝΕΣ. Ηταν δύο
   αποχρώσεις του ίδιου πράγματος —πόσο κενό μπαίνει πριν το σύμβολο— και τώρα
   η απάντηση είναι «κανένα», οπότε ένας κανόνας τα καλύπτει και τα δύο. */

/* ΤΑ ΣΧΟΛΙΑ ΣΑΡΩΝΟΝΤΑΙ ΚΙ ΑΥΤΑ, ΕΠΙΤΗΔΕΣ. Εδώ καθόταν μια `blankComments()`
   που έσβηνε τα σχόλια κρατώντας τις θέσεις — σαράντα γραμμές που ΚΑΝΕΝΑΣ δεν
   καλούσε: ο βρόχος πιο κάτω διαβάζει τον πηγαίο ως έχει. Ενα σχόλιο που
   εξηγεί υπολογισμό με τη λάθος γραφή τη διδάσκει στον επόμενο που θα
   αντιγράψει τη γραμμή, οπότε η σιωπηλή εξαίρεση δεν ήταν καν επιθυμητή. */

const spaced = [];
const unformatted = [];

// Ο ΜΟΡΦΟΠΟΙΗΤΗΣ ΔΕΝ ΕΛΕΓΧΕΙ ΤΟΝ ΕΑΥΤΟ ΤΟΥ. Το `lib/core/format.ts` ΕΙΝΑΙ η
// γραμμή που παράγει το ποσό· ζητώντας του να περάσει από μορφοποιητή, θα
// ζητούσαμε να καλέσει τον εαυτό του. Ιδια εξαίρεση με τον φύλακα ποσοστών.
const SELF = ['lib/core/format.ts', 'components/tokens.ts', 'supabase/functions/_shared/format.ts'];

// ΤΑ ΔΥΟ ΑΡΧΕΙΑ ΠΟΥ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΓΡΑΨΟΥΝ ΤΗΝ ΑΠΑΓΟΡΕΥΜΕΝΗ ΜΟΡΦΗ είναι οι
// έλεγχοι των ίδιων των μορφοποιητών: εκεί η παλιά γραφή γράφεται για να
// δηλωθεί ρητά ότι ΔΕΝ βγαίνει πια.
const DOC = ['lib/core/format.test.ts', 'lib/print/format.test.ts'];

for (const file of files) {
  if (DOC.some(x => file.endsWith(x))) continue;
  const isTest = /\.test\.tsx?$/.test(file);
  if (SELF.some(x => file.endsWith(x))) continue;
  const src = readFileSync(file, 'utf8');
  src.split('\n').forEach((line, i) => {
    // ΚΑΙ ΣΤΑ ΣΧΟΛΙΑ: ένα σχόλιο που εξηγεί υπολογισμό με τη λάθος γραφή τη
    // διδάσκει στον επόμενο που θα αντιγράψει τη γραμμή.
    // Ο ΚΑΝΟΝΑΣ ΤΗΣ ΔΙΑΦΥΓΗΣ ΙΣΧΥΕΙ ΚΑΙ ΣΤΙΣ ΔΟΚΙΜΕΣ, Ο ΚΑΝΟΝΑΣ ΤΟΥ ΚΕΝΟΥ ΟΧΙ.
    // Το τέταρτο ξέφυγε ακριβώς εκεί: ο `assistantPersona.test.ts` περίμενε
    // «\u00A0€/μήνα» και θα κρατούσε την παλιά γραφή ζωντανή. Ενα ΩΜΟ κενό
    // όμως, σε δοκιμή, μπορεί κάλλιστα να είναι ΕΙΣΟΔΟΣ: το
    // `lib/localPrivacy.test.ts` κρατά ιστορικό συνομιλίας όπου ο ΧΡΗΣΤΗΣ
    // πληκτρολόγησε «χρωστάει 650 €». Δεν το γράφει το προϊόν και δεν
    // ξαναγράφεται.
    for (const m of line.matchAll(GLUE)) spaced.push(`${file}:${i + 1}  «${m[0]}»`);
    if (isTest) return;
    for (const m of line.matchAll(SPACED)) spaced.push(`${file}:${i + 1}  «${m[0]}»`);
    for (const m of line.matchAll(UNFORMATTED)) unformatted.push(`${file}:${i + 1}  «${m[0].slice(0, 46)}»`);
  });
}

const red = (s) => `\x1b[31m${s}\x1b[0m`;
let bad = false;

if (spaced.length) {
  bad = true;
  console.log(red(`\n✗ ${spaced.length} ποσά με κενό πριν το σύμβολο του ευρώ:\n`));
  for (const g of spaced.slice(0, 30)) console.log('  ' + g);
  if (spaced.length > 30) console.log(`  … και άλλα ${spaced.length - 30}`);
  console.log('\n  Το προϊόν γράφει το σύμβολο ΚΟΛΛΗΤΑ στον αριθμό: «1.234,56» και αμέσως');
  console.log('  μετά το σύμβολο, χωρίς κενό. Για υπολογισμένο ποσό χρησιμοποίησε το');
  console.log('  fe() (lib/core/format.ts), που το κάνει ήδη.');
}

if (unformatted.length) {
  bad = true;
  console.log(red(`\n✗ ${unformatted.length} ποσά που δεν πέρασαν από μορφοποιητή:\n`));
  for (const u of unformatted.slice(0, 25)) console.log('  ' + u);
  if (unformatted.length > 25) console.log(`  … και άλλα ${unformatted.length - 25}`);
  console.log('\n  Τα ποσά γράφονται πάντα με δύο δεκαδικά, ώστε οι υποδιαστολές να');
  console.log('  στοιχίζονται κάθετα. Πέρνα την τιμή από fe(), ή feRate() για μοναδιαία τιμή.');
}

if (bad) process.exit(1);
console.log(`✓ κάθε ποσό γράφει το σύμβολο κολλητά, σε ${files.length} αρχεία`);
