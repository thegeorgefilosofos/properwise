// φτιάχνεται λάμψη: `inset: -14% -18% auto` μέσα σε κουτί με `overflow: hidden`.
//
// ΔΥΟ ΣΑΡΩΤΕΣ ΤΙΣ ΚΑΤΗΓΓΕΙΛΑΝ, ΜΕ ΔΥΟ ΔΙΑΦΟΡΕΤΙΚΕΣ ΛΕΞΕΙΣ:
//
//     e2e-rendered   «ξεφεύγει» και «κόβεται», 16 φορές σε οκτώ πλάτη
//     e2e-mobile     «οριζόντια υπερχείλιση — lp-aurora +148px», 4 φορές
//
// Και οι δύο έχουν δίκιο στη μέτρηση και άδικο στο συμπέρασμα: η οριζόντια
// κύλιση της σελίδας μετρήθηκε ΜΗΔΕΝ σε κάθε πλάτος, γιατί το `.lp-root` έχει
// `overflow-x: clip` και το `.lp-hero` `overflow: hidden`.
//
// ΚΑΙ ΦΑΝΗΚΕ ΜΟΝΟ ΤΩΡΑ. Δεκαέξι μέρες ο κανόνας `.lp-aurora` ήταν νεκρός: τον
// έτρωγε ένα ορφανό `}`. Χωρίς `position: absolute` και χωρίς `inset`, τίποτα
// δεν ξέφευγε. Η επαναφορά του ξύπνησε είκοσι ευρήματα σε δύο σαρωτές.
//
// ΓΙΑΤΙ ΕΔΩ ΚΑΙ ΟΧΙ ΔΥΟ ΦΟΡΕΣ. Γραμμένο σε κάθε σαρωτή χωριστά, θα απέκλινε
// στην πρώτη αλλαγή και ο ένας θα άρχιζε να κατηγορεί ό,τι ο άλλος συγχωρεί.
// Ενα αρχείο, δύο σαρωτές, μία απόφαση.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Τρέχει ΜΕΣΑ στη σελίδα, πριν από κάθε script της, μέσω `addInitScript`.
 * Γράφει το `window.__mpogia`, που το διαβάζουν οι σαρωτές.
 *
 * ΤΡΕΙΣ ΣΥΝΘΗΚΕΣ ΜΑΖΙ, ΠΟΤΕ ΔΥΟ:
 *
 *     χωρίς δικό του κείμενο      → δεν έχει τι να χάσει
 *     aria-hidden                 → δεν το ανακοινώνει κανείς
 *     pointer-events: none        → δεν πατιέται
 *
 * Κείμενο που κόβεται έχει κείμενο. Κουμπί που ξεφεύγει πιάνει δείκτη.
 * Εικονίδιο με νόημα δεν είναι `aria-hidden`. Ο,τι περνά και τα τρία είναι
 * στρώμα χρώματος — και για το χρώμα το «κόβεται» είναι ο σκοπός του.
 */
export function installPaint() {
  window.__mpogia = (el, cs) => (cs || getComputedStyle(el)).pointerEvents === 'none'
    && (el.getAttribute('aria-hidden') === 'true' || !!el.closest('[aria-hidden="true"]'))
    && !(el.textContent || '').trim()
}
