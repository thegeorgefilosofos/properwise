// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ ΜΑΛΑΚΟ ΕΝΩΤΙΚΟ ΕΙΝΑΙ ΑΟΡΑΤΟ ΣΤΟΝ ΑΝΘΡΩΠΟ ΚΑΙ ΟΡΑΤΟ ΣΤΟΝ ΕΛΕΓΧΟ
// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΕΣΠΑΣΕ, ΜΕ ΤΟ ΟΝΟΜΑ ΤΟΥ. Ο σαρωτής χρημάτων ρωτούσε αν η οθόνη
// προειδοποιεί για την τεκμαρτή έκπτωση:
//
//     body.includes('τεκμαρτή έκπτωση 5%')
//
// Μόλις η ίδια πρόταση απέκτησε πλήρη στοίχιση, ο συλλαβιστής εμφύτευσε U+00AD
// στα σημεία τομής: «τεκ·μαρ·τή έκ·πτω·ση». Στην οθόνη τίποτα δεν άλλαξε — ο
// χαρακτήρας δεν ζωγραφίζεται παρά μόνο αν σπάσει εκεί η γραμμή. Στο
// `innerText` όμως υπάρχει, οπότε η υποσυμβολοσειρά δεν ταιριάζει πια κι ο
// έλεγχος κοκκίνισε λέγοντας ότι λείπει μια προειδοποίηση που ΕΙΝΑΙ εκεί.
//
// ΓΙΑΤΙ ΚΟΙΝΟΣ ΒΟΗΘΟΣ ΚΑΙ ΟΧΙ ΜΠΑΛΩΜΑ ΣΤΗ ΜΙΑ ΓΡΑΜΜΗ. Η στοίχιση μπήκε σε
// τριάντα σημεία του προϊόντος κι θα μπει κι σε άλλα. Καθένα από αυτά είναι
// μελλοντικός έλεγχος που θα κοκκινίσει για λάθος λόγο, σε άσχετη υποβολή,
// ώρες αφότου γράφτηκε η αιτία. Ο κανόνας λέγεται μία φορά: ΚΑΝΕΝΑΣ έλεγχος
// δεν βλέπει ποτέ μαλακό ενωτικό.
//
// ΤΟ ΑΝΤΙΘΕΤΟ ΘΑ ΗΤΑΝ ΝΑ ΓΡΑΦΤΕΙ Ο ΣΥΛΛΑΒΙΣΜΟΣ ΜΕΣΑ ΣΤΟΝ ΕΛΕΓΧΟ — δηλαδή ο
// έλεγχος να περιμένει «τεκ·μαρ·τή». Απορρίφθηκε: θα κλείδωνε τον έλεγχο πάνω
// στους κανόνες του συλλαβιστή, οπότε κάθε βελτίωση της ελληνικής γραμματικής
// θα έσπαγε δεκάδες ελέγχους που δεν έχουν καμία σχέση με αυτήν.
// ═══════════════════════════════════════════════════════════════════════════

/** U+00AD — μπαίνει από το lib/core/hyphenate.ts, δεν το γράφει άνθρωπος. */
const SHY = /­/g;

/**
 * Το κείμενο όπως το ΔΙΑΒΑΖΕΙ ο άνθρωπος: χωρίς τους αόρατους χαρακτήρες που
 * βάζει η τυπογραφία. Χρησιμοποίησέ το σε ΚΑΘΕ σύγκριση κειμένου οθόνης.
 */
export const plain = (s) => (s || '').replace(SHY, '');

/**
 * Το ίδιο, μέσα στον περιηγητή: γυρίζει το `innerText` του σώματος καθαρό.
 * Ο,τι μπαίνει σε `page.evaluate` τρέχει σε ΑΛΛΟ πλαίσιο κι δεν βλέπει τα
 * imports του Node, γι' αυτό ο χαρακτήρας γράφεται εδώ ρητά.
 */
export const bodyText = (page) =>
  page.evaluate(() => document.body.innerText.replace(/­/g, ''));
