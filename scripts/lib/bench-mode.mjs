// ΤΟ BENCH_MODE ΕΦΤΑΝΕ ΩΣ ΤΟΝ ΠΑΓΚΟ ΚΑΙ ΣΤΑΜΑΤΟΥΣΕ ΕΚΕΙ
// ─────────────────────────────────────────────────────────────────────────
// Ο πάγκος κινητού γράφει `data-mode` στο HTML του, οπότε το `BENCH_MODE=light`
// άλλαζε ΟΛΕΣ τις σκηνές του ταμπλό. Οι δημόσιες σελίδες όμως δεν βγαίνουν από
// τον πάγκο: τις σερβίρει ο ίδιος ο διακομιστής και το θέμα τους το διαβάζει το
// script πριν το πρώτο paint από το `localStorage.pos_mode` (app/layout.tsx).
// Χωρίς αυτό εδώ, το `npm run e2e:light` σάρωνε τον πίνακα ελέγχου στο φωτεινό
// και την αρχική, τη σύνδεση και τα εργαλεία στο ΣΚΟΥΡΟ — δηλαδή έλεγε «φωτεινό»
// για μια σάρωση που ήταν μισή σκούρα.
//
// ΤΟ ΚΛΕΙΔΙ ΓΡΑΦΕΤΑΙ ΜΙΑ ΦΟΡΑ, ΕΔΩ. Το ίδιο όνομα το ξέρουν το script πριν το
// paint, ο ThemeProvider και ο φύλακας scripts/guard-tokens.mjs· αν διαφωνήσουν,
// η σελίδα αναβοσβήνει με λάθος θέμα. Ενας ορισμός, τρεις αναγνώστες.
export const MODE = process.env.BENCH_MODE === 'light' ? 'light' : 'dark';

// Μπαίνει σε context ή σε page — και τα δύο έχουν `addInitScript`. Πρέπει να
// τρέξει ΠΡΙΝ φορτώσει η σελίδα: μετά το πρώτο paint η αλλαγή θέματος είναι
// ορατή ως αναβόσβημα και μετράει άλλα χρώματα από αυτά που είδε ο μετρητής.
export const applyMode = (target) =>
  target.addInitScript((m) => {
    try { localStorage.setItem('pos_mode', m); } catch { /* κλειστή αποθήκη */ }
  }, MODE);
