// ΤΟ ΣΦΑΛΜΑ, ΜΕ ΗΜΕΡΟΜΗΝΙΕΣ ΓΡΑΜΜΕΝΕΣ ΑΠΟ ΤΟΝ ΙΔΙΟ ΤΟΝ ΚΩΔΙΚΑ. Το
// scripts/percent-baseline.json καταγράφει ΔΥΟ φορές το ίδιο συμβάν:
//
//   23/08/2026  «η καστάνια είχε μείνει έναν πάνω από τη μέτρηση, δηλαδή ένα
//                νέο ποσοστό χωρίς μορφοποιητή θα περνούσε αθόρυβα»
//   27/08/2026  «ΓΙΑ ΤΟΝ ΙΔΙΟ ΛΟΓΟ ΜΕ ΤΗΝ 23/08: η μέτρηση είχε πέσει, το όριο
//                έμεινε — και η καστάνια ξαναέγινε τζόγος»
//
// Και το ίδιο αρχείο γράφει τον κανόνα: «Οποτε πέφτει η μέτρηση, πέφτει και το
// όριο· αλλιώς η καστάνια φυλάει μια θέση για την επόμενη οπισθοδρόμηση.»
//
// ΤΡΙΤΗ ΦΟΡΑ, ΜΕΤΡΗΜΕΝΗ ΣΗΜΕΡΑ: τα ποσοστά ήταν 74 με όριο 78, οι επιφάνειες
// 97 με όριο 101. Οκτώ θέσεις κρατημένες για οπισθοδρομήσεις που δεν θα τις
// έβλεπε κανείς. Ο κανόνας ήταν γραμμένος σε ΕΝΝΕΑ φύλακες ως ευγενική
// παράκληση («Κατέβασε το όριο») και τηρήθηκε καμία φορά.
//
// ΜΙΑ ΠΑΡΑΚΛΗΣΗ ΠΟΥ ΑΓΝΟΕΙΤΑΙ ΕΙΝΑΙ ΧΕΙΡΟΤΕΡΗ ΑΠΟ ΑΝΥΠΑΡΚΤΗ: το πράσινο
// διαβάζεται ως «εντάξει» ενώ ο φύλακας μόλις παραιτήθηκε από μέρος της
// δουλειάς του. Εδώ ο κανόνας γίνεται εκτελεστός, μία φορά για όλους.
//
// ΤΙ ΔΕΝ ΠΕΡΝΑΕΙ ΑΠΟ ΕΔΩ, ΚΑΙ ΕΙΝΑΙ ΣΚΟΠΙΜΟ. Οι καστάνιες που μετρώνται σε
// ΠΕΡΙΗΓΗΤΗ (ύψη σελίδας, πλήθος ορατών χειριστηρίων) κουνιούνται κατά ένα
// εικονοστοιχείο ανάμεσα σε μηχανές. Εκεί το «κάτω από το όριο» είναι θόρυβος
// και όχι βελτίωση· ένας φύλακας που κοκκινίζει από θόρυβο παρακάμπτεται.
// Εδώ περνούν μόνο ΣΤΑΤΙΚΕΣ σαρώσεις κώδικα, που δίνουν τον ίδιο αριθμό πάντα.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Η ΕΤΥΜΗΓΟΡΙΑ ΟΤΑΝ Η ΜΕΤΡΗΣΗ ΔΕΝ ΞΕΠΕΡΑΣΕ ΤΟ ΟΡΙΟ — ΚΑΙ ΜΟΝΟ ΤΟΤΕ.
 *
 * Το «πάνω από το όριο» το κρίνει ΚΑΘΕ φύλακας μόνος του: εκεί ζει η δική του
 * καθοδήγηση, που ξέρει τι είναι ακτίνα, τι σιωπηλή ανάγνωση και τι κουμπί
 * ζωγραφισμένο στο χέρι. Εδώ ενοποιείται μόνο το κομμάτι που ήταν λάθος και
 * στους εννέα: τι γίνεται όταν η μέτρηση ΕΠΕΣΕ.
 *
 * @returns `true` όταν η καστάνια είναι σφιχτή· `false` όταν έχει τζόγο
 */
export function tightened({ total, max, what, file, key }) {
  if (total === max) {
    console.log(`✓ ${total} ${what}, όσα και το όριο`)
    return true
  }
  console.error(`✗ ${what}: η μέτρηση έπεσε σε ${total}, το όριο έμεινε ${max}.\n`)
  console.error('  ΤΖΟΓΟΣ ΣΕ ΚΑΣΤΑΝΙΑ ΕΙΝΑΙ ΚΑΣΤΑΝΙΑ ΠΟΥ ΔΕΝ ΠΙΑΝΕΙ ΤΗΝ ΕΠΟΜΕΝΗ')
  const slack = max - total
  console.error(slack === 1
    ? '  ΟΠΙΣΘΟΔΡΟΜΗΣΗ: η μία θέση που περισσεύει είναι θέση κρατημένη για'
    : `  ΟΠΙΣΘΟΔΡΟΜΗΣΗ: οι ${slack} θέσεις που περισσεύουν είναι θέσεις κρατημένες για`)
  console.error('  σφάλμα που θα περάσει πράσινο.\n')
  console.error(`  ΔΙΟΡΘΩΣΗ: «${key}»: ${total} στο ${file}. Η βελτίωση κλειδώνει.`)
  return false
}
