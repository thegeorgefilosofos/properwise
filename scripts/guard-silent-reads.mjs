#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// Η ΑΝΑΓΝΩΣΗ ΠΟΥ ΑΠΕΤΥΧΕ ΔΕΝ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΜΟΙΑΖΕΙ ΜΕ «ΔΕΝ ΥΠΑΡΧΕΙ ΤΙΠΟΤΑ»
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΧΗΜΑ ΤΟΥ ΣΦΑΛΜΑΤΟΣ. Το PostgREST απαντά πάντα `{ data, error }`. Οταν το
// ερώτημα αποτύχει —δίκτυο, δικαίωμα, ορθογραφικό σε όνομα στήλης— το `data`
// είναι `null`. Ο κώδικας που γράφει
//
//     const { data } = await db.from('expenses').select(...)
//     return (data || []) as T[]
//
// μετατρέπει την αποτυχία σε άδεια λίστα, δηλαδή στην ΙΔΙΑ απάντηση με το «δεν
// έχεις καταχωρήσει τίποτα». Καμία εξαίρεση, κανένα μήνυμα, καμία ένδειξη.
//
// ΠΟΥ ΚΟΣΤΙΖΕΙ ΠΡΑΓΜΑΤΙΚΑ. Οπου η άδεια λίστα γίνεται ΠΟΣΟ: στη Λογιστική μια
// αποτυχημένη ανάγνωση δαπανών δίνει «μηδέν δαπάνες», δηλαδή μεγαλύτερο
// φορολογητέο εισόδημα και μεγαλύτερο φόρο, σε οθόνη που παράγει Ε2, βεβαίωση
// ενοικίου και φάκελο λογιστή. Γι' αυτό οι τρεις αναγνώσεις εκείνης της οθόνης
// έχουν εκδοχή `…WithError` και η οθόνη αρνείται να δείξει εικόνα που δεν
// διάβασε.
//
// ΓΙΑΤΙ ΚΑΣΤΑΝΙΑ ΚΑΙ ΟΧΙ ΑΠΑΓΟΡΕΥΣΗ. Τα υπόλοιπα σημεία δεν είναι όλα σφάλμα:
// σε πολλά η άδεια λίστα ΕΙΝΑΙ η σωστή απάντηση και το σφάλμα δεν αλλάζει τι
// βλέπει ο χρήστης. Μια ολική απαγόρευση θα ζητούσε ξαναγράψιμο σαράντα
// συναρτήσεων σε μια κίνηση, δηλαδή ακριβώς τη βιασύνη που παράγει σφάλματα.
// Ο κανόνας είναι «ούτε μία παραπάνω»: κάθε νέα σιωπηλή ανάγνωση κοκκινίζει,
// και το όριο κατεβαίνει όποτε μια παλιά μετατρέπεται.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { projectFiles } from './lib/git-files.mjs'
import { tightened } from './lib/ratchet.mjs'

const BASELINE = JSON.parse(readFileSync('scripts/silent-reads-baseline.json', 'utf8'))

// ── ΤΟ ΠΕΔΙΟ ΗΤΑΝ app/ ΚΑΙ lib/, ΚΑΙ ΕΛΕΙΠΕ ΕΚΕΙ ΠΟΥ ΠΟΝΑΕΙ ΠΕΡΙΣΣΟΤΕΡΟ ─────
// Οι προγραμματισμένες εργασίες (supabase/functions) είχαν 48 σιωπηλές
// αναγνώσεις που δεν τις μετρούσε ΚΑΜΙΑ καστάνια. Και εκεί η σιωπή κοστίζει
// περισσότερο από ό,τι σε οθόνη: μια οθόνη που δείχνει κενό την κοιτά άνθρωπος
// και απορεί, μια εργασία που δεν βρήκε τίποτα απαντά «success» και κανείς δεν
// τη ρωτά ξανά. Η μία από αυτές έσβηνε ΟΛΟΚΛΗΡΗ την αποστολή υπενθυμίσεων με
// πράσινο: αποτυχία ανάγνωσης → κενός πίνακας → 200 «No users».
//
// Το components/ έλειπε για τον ίδιο λόγο που έλειπε από δέκα άλλους φύλακες:
// κανείς δεν το πρόσθεσε ποτέ.
const files = projectFiles("'app/**/*.ts' 'app/**/*.tsx' 'lib/**/*.ts' 'lib/**/*.tsx' 'components/**/*.ts' 'components/**/*.tsx' 'supabase/functions/**/*.ts'").filter(f => !f.includes('.test.'))

/** `const { data } = await …` — η απάντηση διαβάζεται χωρίς το σφάλμα της. */
const SILENT = /const\s*\{\s*data(?:\s*:\s*\w+)?\s*\}\s*=\s*await\b/

const hits = []
for (const file of files) {
  const src = readFileSync(file, 'utf8')
  src.split('\n').forEach((line, i) => {
    const t = line.trim()
    if (t.startsWith('//') || t.startsWith('*')) return
    if (SILENT.test(line)) hits.push({ file, line: i + 1, code: t.slice(0, 90) })
  })
}

// ═══ Ο ΑΡΙΘΜΟΣ ΔΕΝ ΕΦΤΑΝΕ: ΕΞΙ ΟΠΟΙΕΣΔΗΠΟΤΕ ΠΕΡΝΟΥΣΑΝ ═══════════════════════
// Ο φύλακας έκρινε μόνο `hits.length > max`. Δηλαδή μια ΝΕΑ σιωπηλή ανάγνωση
// μπορούσε να πάρει τη θέση μιας κριμένης — διορθώνεις το δώρο σύστασης,
// προσθέτεις σιωπή στα ενοίκια, το άθροισμα μένει έξι, το CI πράσινο. Οι έξι
// δικαιολογίες ήταν γραμμένες στο baseline και ΚΑΝΕΝΑΣ κώδικας δεν τις
// διάβαζε: κείμενο δίπλα σε αριθμό, όχι κανόνας.
//
// ΤΑΥΤΟΤΗΤΑ ΕΙΝΑΙ ΑΡΧΕΙΟ + ΓΡΑΜΜΗ ΚΩΔΙΚΑ, ΟΧΙ ΑΡΙΘΜΟΣ ΓΡΑΜΜΗΣ. Ο αριθμός
// κουνιέται με κάθε προσθήκη από πάνω και θα έκανε τον φύλακα θορυβώδη χωρίς
// λόγο. Ο κώδικας αλλάζει μόνο όταν αλλάξει η ίδια η ανάγνωση — και τότε
// ΠΡΕΠΕΙ να ξανακριθεί, γιατί η δικαιολογία γράφτηκε για την παλιά μορφή.
const fp = h => `${h.file}\u0000${h.code}`
const allowed = new Map((BASELINE.allowed || []).map(a => [`${a.file}\u0000${a.code}`, a]))

if (allowed.size !== BASELINE.max) {
  console.error(`✗ Το baseline λέει max ${BASELINE.max} αλλά ονομάζει ${allowed.size}.`)
  console.error('  Τα δύο πρέπει να συμφωνούν: ο αριθμός είναι το μήκος του καταλόγου.')
  process.exit(1)
}

const unlisted = hits.filter(h => !allowed.has(fp(h)))
if (unlisted.length) {
  console.error(`✗ ${unlisted.length} σιωπηλές αναγνώσεις που ΔΕΝ είναι στον κατάλογο:\n`)
  for (const h of unlisted) console.error(`   ${h.file}:${h.line}  ${h.code}`)
  console.error(`
  Μια ανάγνωση που αγνοεί το \`error\` γυρίζει άδειο και όταν αποτύχει.
  Οπου το άδειο γίνεται ΠΟΣΟ, γράψε εκδοχή που επιστρέφει το σφάλμα
  (δες \`ledgerWithError\`, \`ofPropertyWithError\`) και δείξ' το στην οθόνη.
  Σε προγραμματισμένη εργασία δεν υπάρχει οθόνη: εκεί η αποτυχία απαντά 500 ή,
  αν αφορά έναν παραλήπτη, τον πηδά ΚΑΙ μπαίνει σε μετρητή που ταξιδεύει στην
  απάντηση — «success» με σιωπηλές παραλείψεις είναι το ίδιο ψέμα.

  ΑΝ ΕΙΝΑΙ ΟΝΤΩΣ ΑΒΛΑΒΗΣ: γράψε την στο \`allowed\` του
  scripts/silent-reads-baseline.json με το «γιατί» της. Οχι «δεν πειράζει» —
  τι ΑΚΡΙΒΩΣ βλέπει ο χρήστης όταν αυτή η ανάγνωση αποτύχει — και γιατί αυτό
  δεν είναι ψέμα. Ο κατάλογος μόνο μικραίνει.`)
  process.exit(1)
}

// Η άλλη κατεύθυνση: δικαιολογία που περισσεύει είναι θέση κρατημένη για
// σφάλμα. Αν μια ανάγνωση διορθώθηκε, φεύγει και από τον κατάλογο.
const stale = [...allowed.values()].filter(a => !hits.some(h => fp(h) === `${a.file}\u0000${a.code}`))
if (stale.length) {
  console.error(`✗ ${stale.length} ${stale.length === 1 ? 'εγγραφή του καταλόγου δεν αντιστοιχεί' : 'εγγραφές του καταλόγου δεν αντιστοιχούν'} σε καμία ανάγνωση:\n`)
  for (const a of stale) console.error(`   ${a.file}  ${a.code}`)
  console.error(`
  Η ανάγνωση διορθώθηκε ή άλλαξε μορφή. Βγάλ' την από το \`allowed\` και
  κατέβασε το \`max\` — ή, αν άλλαξε μορφή, ξαναγράψε τη γραμμή ΚΑΙ ξανάκρινε
  τη δικαιολογία: γράφτηκε για τον παλιό κώδικα.`)
  process.exit(1)
}

if (!tightened({ total: hits.length, max: BASELINE.max, what: 'σιωπηλές αναγνώσεις', file: 'scripts/silent-reads-baseline.json', key: 'max' })) process.exit(1)
console.log(`   και οι ${hits.length} ονομασμένες, με γραμμένο «γιατί»`)
