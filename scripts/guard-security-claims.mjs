#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΚΑΜΙΑ ΔΗΜΟΣΙΑ ΥΠΟΣΧΕΣΗ ΑΣΦΑΛΕΙΑΣ ΧΩΡΙΣ ΓΡΑΜΜΗ ΚΩΔΙΚΑ ΑΠΟ ΚΑΤΩ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ, ΟΠΩΣ ΜΕΤΡΗΘΗΚΕ. Η σελίδα /trust έγραφε δημόσια «Μπορείς να
// ενεργοποιήσεις σύνδεση δύο βημάτων (TOTP)» και το μητρώο
// docs/security-known-accepted.md §4 βεβαίωνε γραπτώς «TOTP | Enabled |
// ΕΦΑΡΜΟΣΜΕΝΟ (επιβεβαιώθηκε 27/07/2026)». Ταυτόχρονα:
//
//     grep -rn "aal2|assurance|getAuthenticatorAssuranceLevel" app lib supabase
//     έξοδος 1, μηδέν γραμμές
//
// Η εγγραφή συσκευής υπήρχε· η ΠΡΟΚΛΗΣΗ στη σύνδεση δεν υπήρχε πουθενά. Ο
// χρήστης σάρωνε τον κωδικό QR, διάβαζε «Ενεργή» και ο κλεμμένος κωδικός
// συνέχιζε να ανοίγει ολόκληρο τον λογαριασμό.
//
// ΓΙΑΤΙ ΕΙΝΑΙ ΧΕΙΡΟΤΕΡΟ ΑΠΟ ΤΗΝ ΑΠΟΥΣΙΑ. Μητρώο ασφαλείας που πιστοποιεί
// ανύπαρκτο έλεγχο δεν είναι κενό: είναι λάθος πληροφορία πάνω στην οποία
// παίρνονται αποφάσεις — από τον χρήστη που χαλαρώνει με τον κωδικό του, από
// τον επόμενο ελεγκτή που δεν ξανακοιτά το σημείο, από τον αγοραστή σε έλεγχο
// εξαγοράς. Και η δημόσια δήλωση στο /trust δεσμεύει.
//
// ── Ο ΜΗΧΑΝΙΣΜΟΣ: ΖΕΥΓΗ «ΥΠΟΣΧΕΣΗ» ΠΡΟΣ «ΑΠΟΔΕΙΞΗ» ─────────────────────
// Καθε ζεύγος έχει δύο πλευρές και έναν γραμμένο λόγο:
//
//   ΥΠΟΣΧΕΣΗ  φράση σε κείμενο που διαβάζει άνθρωπος (η δημόσια σελίδα, ή το
//             μητρώο ευρημάτων). Αρκεί ΜΙΑ να υπάρχει για να ενεργοποιηθεί
//             το ζεύγος: η υπόσχεση δόθηκε, δεν έχει σημασία σε ποια από τις
//             δύο επιφάνειες.
//   ΑΠΟΔΕΙΞΗ  συγκεκριμένη γραμμή σε συγκεκριμένο αρχείο. Πρέπει να υπάρχουν
//             ΟΛΕΣ. Μία απόδειξη που λείπει σημαίνει αλυσίδα σπασμένη.
//
// Ο κανόνας ΔΕΝ είναι «γράψε τον έλεγχο». Είναι «μη λες ότι τον έχεις όσο δεν
// τον έχεις». Η δεύτερη νόμιμη διόρθωση, όποτε ο έλεγχος όντως δεν υπάρχει,
// είναι να ΦΥΓΕΙ Η ΦΡΑΣΗ. Ο φύλακας δέχεται και τις δύο κινήσεις· δεν δέχεται
// να μείνει η φράση χωρίς τον έλεγχο.
//
// ── ΓΙΑΤΙ ΟΧΙ «ΕΛΕΓΞΕ ΑΝ Η ΣΕΛΙΔΑ ΛΕΕΙ ΤΗΝ ΑΛΗΘΕΙΑ» ────────────────────
// Δεν είναι μετρήσιμο από στατικό έλεγχο. Ο,τι είναι μετρήσιμο είναι η ΔΟΜΗ:
// υπάρχει ή δεν υπάρχει η γραμμή που κάνει τη δουλειά. Ιδια λογική με τον
// guard-billing-claims, που δένει τα νομικά κείμενα με τη συνθήκη του ταμείου.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync, existsSync } from 'node:fs';

const GUARD = 'scripts/guard-security-claims.mjs';
const TRUST = 'app/trust/page.tsx';
const REGISTRY = 'docs/security-known-accepted.md';

/** Το περιεχόμενο ενός αρχείου, ή κενό όταν δεν υπάρχει. */
const read = (f) => (existsSync(f) ? readFileSync(f, 'utf8') : '');

/**
 * Τα ζεύγη. Καθε απόδειξη κουβαλά ΤΟΝ ΛΟΓΟ ΤΗΣ: χωρίς αυτόν, ο επόμενος που
 * θα τη δει κόκκινη δεν ξέρει αν διορθώνει ασφάλεια ή γραφειοκρατία.
 */
const PAIRS = [
  {
    control: 'δεύτερο βήμα στη σύνδεση (TOTP)',
    promises: [
      { file: TRUST, text: 'σύνδεση δύο βημάτων' },
      { file: REGISTRY, text: 'ροή MFA' },
    ],
    proofs: [
      {
        file: 'app/dashboard/components/SecuritySettings.tsx',
        needle: 'mfa.enroll(',
        why: 'χωρίς εγγραφή συσκευής, κανένας χρήστης δεν μπορεί καν να ενεργοποιήσει τα δύο βήματα',
      },
      {
        file: 'lib/auth/mfa.ts',
        needle: 'sessionNeedsSecondStep',
        why: 'εδώ κρίνεται αν μια συνεδρία χρωστά το δεύτερο βήμα. Χωρίς αυτό δεν υπάρχει κανόνας, μόνο οθόνες',
      },
      {
        file: 'app/login/page.tsx',
        needle: 'getAuthenticatorAssuranceLevel',
        why: 'η σύνδεση έκανε signInWithPassword και αμέσως router.push. Χωρίς αυτή την ερώτηση, η συσκευή δεν ζητιέται ΠΟΤΕ',
      },
      {
        file: 'proxy.ts',
        needle: 'sessionNeedsSecondStep',
        why: 'έλεγχος μόνο στην οθόνη σύνδεσης παρακάμπτεται με σύνδεση εκτός περιηγητή. Ο διαμεσολαβητής είναι η πόρτα που δεν προσπερνιέται',
      },
    ],
  },
  {
    control: 'καθημερινό κρυπτογραφημένο αντίγραφο ασφαλείας',
    promises: [
      { file: TRUST, text: 'AES-256' },
    ],
    proofs: [
      {
        file: '.github/workflows/db-backup.yml',
        needle: '--cipher-algo AES256',
        why: 'η σελίδα ονομάζει τον αλγόριθμο. Χωρίς αυτή τη σημαία το αντίγραφο ανεβαίνει με ό,τι προεπιλογή βρει το gpg',
      },
      {
        file: '.github/workflows/db-backup.yml',
        needle: 'BACKUP_PASSPHRASE',
        why: 'η σελίδα υπόσχεται «κρυπτογραφημένο αντίγραφο ή κανένα». Χωρίς το μυστικό, δεν υπάρχει κλειδί και η υπόσχεση καταρρέει σιωπηλά',
      },
    ],
  },
  {
    control: 'ιστορικό ενεργειών ασφαλείας',
    promises: [
      { file: TRUST, text: 'Ιστορικό ενεργειών ασφαλείας' },
    ],
    proofs: [
      {
        file: 'app/dashboard/components/SecuritySettings.tsx',
        needle: "'mfa_enabled', 'security'",
        why: 'η σελίδα απαριθμεί ονομαστικά την ενεργοποίηση δύο βημάτων ως καταγεγραμμένη ενέργεια',
      },
      {
        file: 'app/dashboard/components/SecuritySettings.tsx',
        needle: "'signed_out_all', 'security'",
        why: 'η σελίδα απαριθμεί ονομαστικά την αποσύνδεση από όλες τις συσκευές',
      },
      {
        file: 'lib/activity.ts',
        needle: 'mfa_enabled',
        why: 'μια καταγραφή χωρίς ελληνική περιγραφή είναι κωδικός σε πίνακα, όχι ιστορικό που «μπορείς να δεις ο ίδιος»',
      },
    ],
  },
];

const problems = [];

for (const pair of PAIRS) {
  const given = pair.promises.filter(p => read(p.file).includes(p.text));
  if (!given.length) continue;

  for (const proof of pair.proofs) {
    const src = read(proof.file);
    if (src.includes(proof.needle)) continue;
    const missing = src ? `δεν περιέχει «${proof.needle}»` : 'λείπει ολόκληρο';
    problems.push([
      `«${pair.control}»: το ${proof.file} ${missing}.`,
      `      το υπόσχεται: ${given.map(g => `${g.file} («${g.text}»)`).join(' · ')}`,
      `      γιατί μετράει: ${proof.why}`,
    ].join('\n'));
  }
}

// ── ΚΑΙ Ο ΚΑΤΑΛΟΓΟΣ ΔΕΝ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΑΔΕΙΑΣΕΙ ──────────────────────────
// Ενας φύλακας που δεν κοιτά τίποτα τυπώνει το ίδιο πράσινο με έναν που τα
// κοίταξε όλα. Το πλήθος γράφεται στην έξοδο για τον ίδιο λόγο.
if (!PAIRS.length) {
  console.error(`✗ ${GUARD}: κανένα ζεύγος υπόσχεσης προς απόδειξη. Ο έλεγχος δεν κοιτά τίποτα.`);
  process.exit(1);
}

if (problems.length) {
  console.error(`\n✗ ${problems.length} υποσχέσεις ασφαλείας χωρίς απόδειξη στον κώδικα:\n`);
  problems.forEach(p => console.error('  · ' + p));
  console.error(`
  ΔΥΟ ΝΟΜΙΜΕΣ ΚΙΝΗΣΕΙΣ, ΚΑΜΙΑ ΤΡΙΤΗ:
    1. γράψε τον έλεγχο που λείπει, ή
    2. σβήσε τη φράση από τη δημόσια σελίδα και από το μητρώο.

  Μητρώο ασφαλείας που πιστοποιεί ανύπαρκτο έλεγχο είναι χειρότερο από την
  απουσία του: πάνω του παίρνονται αποφάσεις.
  (Ο ίδιος ο φύλακας: ${GUARD})`);
  process.exit(1);
}

const proofs = PAIRS.reduce((n, p) => n + p.proofs.length, 0);
console.log(`✓ ασφάλεια: ${PAIRS.length} υποσχέσεις, ${proofs} αποδείξεις στον κώδικα και υπάρχουν όλες`);
