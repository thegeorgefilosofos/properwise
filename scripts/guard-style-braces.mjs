#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΕΝΑ ΠΕΡΙΣΣΕΥΟΥΜΕΝΟ } ΔΕΝ ΣΠΑΕΙ ΤΗ ΣΕΛΙΔΑ. ΤΡΩΕΙ ΤΟΝ ΕΠΟΜΕΝΟ ΚΑΝΟΝΑ.
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ, ΟΠΩΣ ΕΖΗΣΕ ΔΕΚΑΕΞΙ ΜΕΡΕΣ ΣΤΗΝ ΠΑΡΑΓΩΓΗ. Μια αλλαγή αφαίρεσε την
// κίνηση του κόκκου από την αρχική και άφησε πίσω της το σχόλιο και το
// κλείσιμο του κανόνα:
//
//     .lp-atmos::after { … }
//     /* Ο κόκκος «ζει»: μετατοπίζεται σε οκτώ θέσεις. … */
//             }                            ← ορφανό
//     .lp-aurora { position: absolute; inset: -14% -18% auto; … }
//
// Η ΜΕΤΑΓΛΩΤΤΙΣΗ ΔΕΝ ΕΙΧΕ ΛΟΓΟ ΝΑ ΜΙΛΗΣΕΙ: το CSS ζει μέσα σε template
// literal του JSX, δηλαδή για τον TypeScript είναι συμβολοσειρά. Δεν μιλά
// ούτε ο περιηγητής: ο επεξεργαστής CSS ΔΕΝ σταματά σε ορφανό `}` — μαζεύει
// κανόνα μέχρι το πρώτο μπλοκ και πετά ΟΛΟΚΛΗΡΟ ό,τι μάζεψε. Εδώ ο κανόνας
// που πετάχτηκε ήταν ο ΕΠΟΜΕΝΟΣ, ο `.lp-aurora`.
//
// ΤΙ ΕΙΔΕ Ο ΧΡΗΣΤΗΣ. Το `.lp-aurora` κρατούσε τέσσερα πράγματα μαζί:
// `position: absolute` (οι δύο αύρες τοποθετούνται μέσα στο hero),
// `inset`/`height` (πόσο πιάνουν), `z-index: 0` (μένουν πίσω) και
// `pointer-events: none` (ΔΕΝ πιάνουν κλικ). Χωρίς αυτόν, τα δύο ψευδοστοιχεία
// βρήκαν για γονέα τη ρίζα της σελίδας: δύο θολές κηλίδες εκατοντάδων
// εικονοστοιχείων, καρφωμένες σε λάθος σημείο, σε άγνωστη σειρά στοίβαξης, να
// πιάνουν τον δείκτη πάνω από τα κουμπιά του hero.
//
// ΓΙΑΤΙ ΔΕΝ ΤΟ ΕΠΙΑΣΕ ΚΑΝΕΙΣ ΑΠΟ ΤΟΥΣ 128. Είναι το είδος σφάλματος που δεν
// αφήνει ίχνος σε κανένα από τα εργαλεία που υπάρχουν: δεν είναι λάθος τύπου,
// δεν είναι αποτυχία δοκιμής, δεν είναι λάθος χρώμα, δεν είναι λάθος κείμενο.
// Είναι ΣΙΩΠΗΛΗ ΑΠΩΛΕΙΑ ΕΝΟΣ ΚΑΝΟΝΑ — και όποιος κοιτάξει το αρχείο βλέπει
// τον κανόνα γραμμένο, μαύρο πάνω σε άσπρο, τρεις γραμμές πιο κάτω.
//
// ΤΙ ΕΛΕΓΧΕΤΑΙ. Κάθε `<style>{`…`}</style>` των δημόσιων και εσωτερικών
// οθονών: τα άγκιστρα ζυγίζουν και κανένα `}` δεν εμφανίζεται σε βάθος
// μηδέν. Οχι ύφος, ούτε ονόματα κλάσεων: ΜΟΝΟ η δομή, που είναι και το μόνο
// πράγμα εδώ που μπορεί να χαθεί χωρίς να ουρλιάξει τίποτα.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { projectFiles } from './lib/git-files.mjs'

const files = projectFiles("'app/**/*.tsx' 'components/**/*.tsx'")

const ANOIGMA = /<style[^>]*>\{`/g
const KLEISIMO = '`}</style>'

/**
 * Σχόλια έξω, ΜΕ ΤΙΣ ΓΡΑΜΜΕΣ ΤΟΥΣ ΜΕΣΑ.
 *
 * Αν το σχόλιο απλώς σβηνόταν, θα έφευγαν και οι αλλαγές γραμμής του και ο
 * φύλακας θα κατήγγειλλε λάθος γραμμή — δηλαδή θα έστελνε τον επόμενο να
 * ψάξει σε σημείο όπου δεν υπάρχει τίποτα. Τα `url(...)` ουδετεροποιούνται
 * γιατί ένα data URI μπορεί να κουβαλά άγκιστρα μέσα σε κωδικοποίηση.
 */
const kathara = (css) => css
  .replace(/\/\*[\s\S]*?\*\//g, m => m.replace(/[^\n]/g, ' '))
  .replace(/url\((["']?)[\s\S]*?\1\)/g, m => m.replace(/[^\n]/g, ' '))

const provlimata = []

for (const file of files) {
  const src = readFileSync(file, 'utf8')
  ANOIGMA.lastIndex = 0
  let m
  while ((m = ANOIGMA.exec(src))) {
    const arxi = m.index + m[0].length
    const mikos = src.slice(arxi).indexOf(KLEISIMO)
    if (mikos < 0) {
      provlimata.push({ file, gr: src.slice(0, arxi).split('\n').length, ti: 'το <style> δεν κλείνει ποτέ' })
      break
    }
    const css = kathara(src.slice(arxi, arxi + mikos))
    let vathos = 0
    let gr = src.slice(0, arxi).split('\n').length
    for (const ch of css) {
      if (ch === '\n') gr++
      else if (ch === '{') vathos++
      else if (ch === '}') {
        if (vathos === 0) {
          provlimata.push({ file, gr, ti: 'ορφανό } σε βάθος μηδέν — ο ΕΠΟΜΕΝΟΣ κανόνας πετιέται ολόκληρος' })
        } else vathos--
      }
    }
    if (vathos > 0) {
      provlimata.push({ file, gr, ti: `${vathos} κανόνας δεν κλείνει ώς το τέλος του <style>` })
    }
    ANOIGMA.lastIndex = arxi + mikos
  }
}

if (provlimata.length) {
  console.error(`\n✗ ${provlimata.length} σημεία όπου τα άγκιστρα του CSS δεν ζυγίζουν:\n`)
  for (const p of provlimata) console.error(`  ${p.file}:${p.gr}  ${p.ti}`)
  console.error(`
  ΔΕΝ ΘΑ ΔΕΙΣ ΣΦΑΛΜΑ ΠΟΥΘΕΝΑ. Ο TypeScript βλέπει συμβολοσειρά και ο περιηγητής
  κάνει ανάκαμψη σιωπηλά: μαζεύει κανόνα ώς το πρώτο μπλοκ και τον πετά ΟΛΟ.
  Χάνεται ο ΕΠΟΜΕΝΟΣ κανόνας, όχι αυτός που έχει το λάθος — γι' αυτό και ψάχνεις
  πάντα σε λάθος σημείο.

  Βρες το ορφανό } στη γραμμή που αναφέρεται και σβήσ' το. Αν έμεινε από κανόνα
  ή @keyframes που αφαιρέθηκε, σβήσε και το σχόλιο που το συνόδευε: περιγράφει
  συμπεριφορά που δεν υπάρχει πια.
`)
  process.exit(1)
}

console.log(`✓ τα άγκιστρα του CSS ζυγίζουν σε ${files.length} οθόνες`)
