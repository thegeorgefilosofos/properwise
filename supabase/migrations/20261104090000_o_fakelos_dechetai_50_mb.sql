-- Ο ΦΑΚΕΛΟΣ ΤΟΥ ΑΚΙΝΗΤΟΥ ΔΕΧΕΤΑΙ ΑΡΧΕΙΑ ΕΩΣ 50 MB
-- ─────────────────────────────────────────────────────────────────────────
-- Ο ιδιοκτήτης ζήτησε (04/11/2026) η σάρωση και το ανέβασμα να δέχονται κάθε
-- PDF, PNG ή JPG έως 50 MB: σκαναρισμένα Ε1/Ε9, συμβόλαια, ετήσιες καταστάσεις
-- πλατφορμών. Ως τώρα ο κάδος `property-files` κρατούσε 20 MB
-- (20260724091000_storage_upload_limits.sql) και η εφαρμογή έγραφε τρία
-- διαφορετικά όρια σε διαφορετικές οθόνες (8, 10 και 20 MB).
--
-- Το ίδιο όριο ισχύει σε τρία σημεία, που πρέπει να μείνουν ίσα:
--   · εδώ, στον κάδο (το επιβάλλει το Storage στον διακομιστή),
--   · SCAN_FILE_MAX_MB / MAX_SCAN_MB στο app/dashboard/components/scanDoc.ts,
--   · STAGE_MAX_BYTES στο lib/assistant/stagedFile.ts.
-- Οι τύποι αρχείων δεν αλλάζουν. Οι άλλοι κάδοι δεν αλλάζουν.
-- ═══════════════════════════════════════════════════════════════════════════

update storage.buckets
   set file_size_limit = 52428800  -- 50 MB
 where id = 'property-files';
