-- Το αυτόματο πέρασμα διάβασε τη σελίδα «Συχνές ερωτήσεις» του eurobank.gr
-- και έγραψε:
--     fixed_3yr   '2.50-2.90' → '2.90'
--     fixed_5yr   '3.40-3.50' → '3.50'
--     fixed_10yr  '3.80-3.90' → '3.90'
--     fixed_15yr  '4.10-4.20' → '4.20'
--     fixed_20yr  '4.10-4.20' → '4.20'
--     variable_spread_min  0.80 → 1.45
-- Τα σταθερά ήταν το πάνω άκρο του εύρους που ήδη υπήρχε (βασικό επιτόκιο),
-- όχι αλλαγή· το εύρος χάθηκε και μαζί του το «από 2,50%» της πρώτης
-- κατοικίας. Το 1,45% είναι ο αριθμός που το 20260928150000 είχε ήδη βγάλει
-- από τα χαρακτηριστικά ως ασύμφωνο με το δελτίο.
--
-- ΠΗΓΗ ΤΗΣ ΕΠΑΝΑΦΟΡΑΣ: το δελτίο της τράπεζας, όπως το κατέγραψε το
-- 20260928150000 (https://www.eurobank.gr/-/media/eurobank/rates/epitokia-daneiakon-proionton.pdf,
-- έγγραφο 27/07/2026): κυμαινόμενο Euribor 3M + 0,80% έως 2,70%· σταθερό
-- 3ε 2,90 · 5ε 3,50 · 10ε 3,90 · 15ε 4,20 · 20ε 4,20, πρώτη κατοικία −0,40
-- στο 3ετές και −0,10 στα υπόλοιπα.
--
-- ΕΝΤΟΛΗ ΙΔΙΟΚΤΗΤΗ (29/09/2026): «ισχύει το επίσημο PDF».
--
-- ΓΙΑΤΙ ΔΕΝ ΘΑ ΞΑΝΑΓΙΝΕΙ: στο ίδιο PR, τιμή ίση με άκρο δημοσιευμένου εύρους
-- δεν είναι αλλαγή (lib/loans/rateFeed.ts, diffBank), σελίδα συχνών ερωτήσεων
-- δεν είναι επίσημη πηγή (isOfficialSource) και από μη επίσημη πηγή δεν
-- γράφεται καμία τιμή (bank-rates-updater).
-- ═══════════════════════════════════════════════════════════════════════════

update public.bank_rates set
  fixed_3yr = '2.50-2.90',
  fixed_5yr = '3.40-3.50',
  fixed_10yr = '3.80-3.90',
  fixed_15yr = '4.10-4.20',
  fixed_20yr = '4.10-4.20',
  fixed_min = 2.50,
  variable_spread_min = 0.80,
  variable_spread_max = 2.70,
  source_url = 'https://www.eurobank.gr/-/media/eurobank/rates/epitokia-daneiakon-proionton.pdf',
  source_doc_date = date '2026-07-27',
  verified_at = date '2026-09-28'
where bank_id = 'eurobank';
