-- ═══════════════════════════════════════════════════════════════════════════
-- ΕΠΑΓΓΕΛΜΑΤΙΑΣ: 29,90 € ΤΟΝ ΜΗΝΑ, 299,00 € ΤΟΝ ΧΡΟΝΟ
-- ─────────────────────────────────────────────────────────────────────────
-- ΠΗΓΗ ΤΗΣ ΑΛΛΑΓΗΣ. Απόφαση ιδιοκτήτη (25.09.2026), μετά από ανάλυση κόστους:
-- στα 24,90 € ο διαχειριστής 15 ακινήτων πλήρωνε 1,66 € ανά ακίνητο, το
-- φθηνότερο ανά ακίνητο σκαλί του τιμοκαταλόγου, για δαπάνη που εκπίπτει. Τα
-- άλλα τρία πακέτα μένουν ως έχουν. Το ετήσιο κρατά τον κανόνα των δύο μηνών
-- δώρο (10 × 29,90).
--
-- ΚΑΝΕΝΑΣ ΣΥΝΔΡΟΜΗΤΗΣ ΔΕΝ ΜΕΝΕΙ ΣΤΗΝ ΠΑΛΙΑ ΤΙΜΗ, ΓΙΑΤΙ ΔΕΝ ΥΠΑΡΧΕΙ ΚΑΝΕΝΑΣ.
-- Την ημέρα της αλλαγής καμία γραμμή του `billing_profiles` δεν έχει
-- `mor_subscription_id`: η χρέωση δεν έχει ανοίξει. Αν υπήρχε, η
-- `plan_price` θα έλεγε στην προαναγγελία χρέωσης ποσό διαφορετικό από αυτό
-- που χρεώνει ο έμπορος· τότε το ποσό θα έπρεπε να διαβάζεται από τη συνδρομή.
--
-- Η ΣΥΝΑΡΤΗΣΗ ΞΑΝΑΓΡΑΦΕΤΑΙ ΟΛΟΚΛΗΡΗ. Αλλάζουν μόνο οι δύο γραμμές του
-- `agency`· το db-replay την αντιπαραβάλλει με το PLANS του
-- lib/billing/plans.ts, όπως και στη μετάβαση 20260820240000.
-- ═══════════════════════════════════════════════════════════════════════════

create or replace function public.plan_price(p_plan text, p_cycle text)
returns numeric language sql immutable
set search_path = public
as $$
  select case
    when p_cycle = 'annual' then
      case p_plan
        when 'solo'   then 42.90
        when 'owner'  then 99.00
        when 'agency' then 299.00
        when 'office' then 799.00
        else 0
      end
    else
      case p_plan
        when 'solo'   then 3.90
        when 'owner'  then 9.90
        when 'agency' then 29.90
        when 'office' then 79.90
        else 0
      end
  end
$$;

comment on function public.plan_price(text, text) is
  'Η τιμή ενός πακέτου ανά κύκλο, σε ευρώ. Ταυτόσημη με το PLANS του lib/billing/plans.ts· το db-replay τις αντιπαραβάλλει και οι δύο πλευρές.';
