-- Η ΛΗΞΗ ΤΟΥ ΠΕΑ ΠΟΥ ΗΞΕΡΕ ΗΔΗ ΤΟ ΗΜΕΡΟΛΟΓΙΟ ΠΕΡΝΑ ΣΤΟ ΑΚΙΝΗΤΟ
-- ─────────────────────────────────────────────────────────────────────────
-- ΓΙΑΤΙ ΑΓΓΙΖΕΤΑΙ ΤΟ supabase/migrations. Συνέχεια του 20261112094100, με την
-- ίδια πηγή: ν. 4122/2013, άρθρο 12 παρ. 1 περ. δ΄ (όπως αντικαταστάθηκε με το
-- άρθρο 65 του ν. 4685/2020), «Η έκδοση ΠΕΑ είναι υποχρεωτική: ... δ) κατά τη
-- μίσθωση (μακροχρόνια, βραχυχρόνια, υπεκμίσθωση) σε νέο ενοικιαστή κτιρίου ή
-- κτιριακής μονάδας». Η ειδοποίηση «Χρειάζεται ΠΕΑ σε ισχύ» της μίσθωσης κρίνει
-- από τη στήλη `pea_expiry`.
--
-- ΤΟ ΚΕΝΟ. Πριν από τη στήλη, η σάρωση ΠΕΑ έγραφε τη λήξη ΜΟΝΟ ως γεγονός
-- ημερολογίου «Λήξη ΠΕΑ». Για όσα ακίνητα σαρώθηκαν τότε, η στήλη είναι κενή
-- και η ειδοποίηση θα έλεγε «Δεν έχουμε καταχωρημένη λήξη ΠΕΑ» για ΠΕΑ που η
-- εφαρμογή ήδη ξέρει.
--
-- ΤΙ ΚΑΝΕΙ. Μία φορά και μόνο όπου η στήλη είναι κενή: παίρνει την ΠΙΟ
-- ΠΡΟΣΦΑΤΗ ημερομηνία γεγονότος με ακριβώς αυτόν τον τίτλο, του ίδιου
-- ακινήτου και του ίδιου χρήστη. Η πιο πρόσφατη, γιατί η σάρωση δεν έγραφε
-- ποτέ λήξη παλαιότερη από όση ήξερε (φρουρός «Λήξη ΠΕΑ», PR #402) και το
-- νεότερο ΠΕΑ αντικαθιστά το παλιό (άρθρο 11 παρ. 6 περ. γ΄). Δεν αγγίζει
-- κατηγορία, αριθμό ή έκδοση και δεν γράφει υπενθυμίσεις: το παλιό γεγονός
-- μένει όπως ήταν, με τις υπενθυμίσεις που είχε.
--
-- ΞΑΝΑΤΡΕΧΕΙ ΧΩΡΙΣ ΖΗΜΙΑ: μετά την πρώτη φορά η στήλη δεν είναι πια κενή.
-- Ο έλεγχος της έκδοσης κρατά τον περιορισμό user_properties_pea_dates_chk.
-- ═══════════════════════════════════════════════════════════════════════════

update public.user_properties p
   set pea_expiry = e.last_expiry
  from (
    select property_id, user_id, max(event_date) as last_expiry
      from public.calendar_events
     where title = 'Λήξη ΠΕΑ'
     group by property_id, user_id
  ) e
 where p.pea_expiry is null
   and e.property_id = p.id
   and e.user_id = p.user_id
   and (p.pea_issued is null or p.pea_issued <= e.last_expiry);
