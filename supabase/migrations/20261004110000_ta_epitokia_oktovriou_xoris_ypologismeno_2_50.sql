-- ΤΙ ΗΤΑΝ ΛΑΘΟΣ. Η 20260928150000 έγραψε για την Eurobank σταθερό 2,50% ως
-- «2,90 μείον την έκπτωση πρώτης κατοικίας 0,40». Το δελτίο δεν τυπώνει 2,50
-- πουθενά ως τέτοιο επιτόκιο (το 2,50 που υπάρχει είναι επιτόκιο
-- υπερημερίας). Στην Alpha το 2,50 ανήκει σε άλλα προϊόντα (Alpha Ανακαίνιση
-- Κατοικίας με εξασφάλιση (κυμαινόμενο) και Alpha Μέτρον Άριστον) και όχι στο
-- σταθερό της Alpha Κατοικία. Στην Credia η οθόνη έγραφε σταθερό 3,00% χωρίς
-- δείκτη, ενώ η σελίδα της τράπεζας γράφει «από 2,15%».
--
-- ΠΟΙΟΣ ΕΛΕΓΞΕ. Η ομάδα Grok διάβασε τα έγγραφα στις 04/10/2026 και ο
-- ιδιοκτήτης έδωσε εντολή να μπουν την ίδια μέρα. Ο διαμεσολαβητής δικτύου
-- εδώ μπλοκάρει τους ιστότοπους των τραπεζών, οπότε οι αριθμοί δεν
-- ξαναδιαβάστηκαν από αυτό το περιβάλλον. Κάθε αλλαγή γράφεται με την πηγή
-- της και την παλιά τιμή. Μόνο update, καμία διαγραφή γραμμής.
--
-- ΤΟ ΙΔΙΟ ΣΤΟ app/dashboard/components/TabLoanData.tsx (BANKS), την εφεδρική
-- εκδοχή του ίδιου πίνακα.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── Eurobank ─────────────────────────────────────────────────────────────
-- ΠΗΓΗ: https://www.eurobank.gr/-/media/eurobank/rates/epitokia-daneiakon-proionton.pdf
-- Ισχύς 27/07/2026. Αγορά ή ανέγερση: Euribor 3M + 0,80% έως 2,70% (ίδιο).
-- Σταθερό 3 ετών 2,90%. Επιπλέον έκπτωση 0,40% για 3 έτη σε δικαιούχους
-- πρώτης κατοικίας: γράφεται ως κείμενο, ΔΕΝ αφαιρείται.
--     fixed_3yr   '2.50-2.90'  → '2.90'
--     fixed_min   2.50         → 2.90
update public.bank_rates set
  fixed_3yr  = '2.90',
  fixed_min  = 2.90,
  features   = array_append(array_remove(features, 'Δικαιούχοι πρώτης κατοικίας: επιπλέον έκπτωση 0,40% για 3 έτη'),
                            'Δικαιούχοι πρώτης κατοικίας: επιπλέον έκπτωση 0,40% για 3 έτη'),
  verified_at = date '2026-10-04'
where bank_id = 'eurobank';

-- ── Alpha Bank ───────────────────────────────────────────────────────────
-- ΠΗΓΗ: https://www.alpha.gr/-/media/AlphaGr/pdf-files/diafora-sunodeutika-pdf/xrisima-eggrafa/oroi-sunallagon-epitokia-katatheseon-xorigiseon.pdf
-- Ενημέρωση 21/09/2026. Alpha Κατοικία: Euribor 3M + 1,80% (ίδιο), σταθερό
-- 1 έτους 2,70%, 3 ετών 2,90%. Το 2,50% δεν είναι σταθερό της Alpha Κατοικία.
--     fixed_3yr   '2.50-2.90'  → '2.90'
--     fixed_min   2.50         → 2.70 (το σταθερό 1 έτους)
--     feature «2,50% για νέους (3ετία)» φεύγει· note «Ειδικό πρόγραμμα για νέους» αλλάζει
update public.bank_rates set
  fixed_3yr  = '2.90',
  fixed_min  = 2.70,
  -- Η βάση το γράφει με κόμμα, η εφεδρική λίστα με τελεία: φεύγουν και τα δύο.
  features   = array_remove(array_remove(features, '2,50% για νέους (3ετία)'), '2.50% για νέους (3ετία)'),
  note       = 'Alpha Κατοικία: σταθερό 1 έτους 2,70% και 3 ετών 2,90%',
  verified_at = date '2026-10-04'
where bank_id = 'alpha';

-- ── CrediaBank ───────────────────────────────────────────────────────────
-- ΠΗΓΗ: https://www.crediabank.com/idiotes/daneia/stegastika/stegastiko-daneio-crediabank-first-home/
-- Χωρίς ημερομηνία δελτίου. First Home: σταθερό από 2,15%, περιθώριο από
-- 1,60%, Euribor 3M, εισφορά ν.128/75 0,12%. Το Euribor 2,293% του
-- παραδείγματος (29/06/2026) ΔΕΝ αποθηκεύεται. Τα ανά διάρκεια εύρη δεν τα
-- γράφει η σελίδα: γίνονται null, όπως το 3ετές της Optima στη 20260928150000.
-- Αν έμεναν, η οθόνη θα έδειχνε «από 2,15%» δίπλα σε «3.00-3.30» του
-- συγκριτικού ιστότοπου, με την ίδια ημερομηνία επιβεβαίωσης.
--     fixed_min   3.00   → 2.15
--     fixed_3yr…fixed_20yr, variable_spread_max → null (δεν δημοσιεύονται)
--     rate_index  null   → '3M'
update public.bank_rates set
  fixed_3yr  = null,
  fixed_5yr  = null,
  fixed_10yr = null,
  fixed_15yr = null,
  fixed_20yr = null,
  variable_spread_max = null,
  fixed_min  = 2.15,
  variable_spread_min = 1.60,
  rate_index = '3M',
  features   = array_append(array_remove(features, 'Εισφορά ν.128/75: 0,12%'), 'Εισφορά ν.128/75: 0,12%'),
  note       = 'First Home: σταθερό από 2,15%. Τα εύρη ανά διάρκεια δεν δημοσιεύονται στη σελίδα της τράπεζας',
  source_url = 'https://www.crediabank.com/idiotes/daneia/stegastika/stegastiko-daneio-crediabank-first-home/',
  source_doc_date = null,
  verified_at = date '2026-10-04'
where bank_id = 'credia';

-- ── Εθνική Τράπεζα ───────────────────────────────────────────────────────
-- ΠΗΓΗ: https://www.nbg.gr/el/idiwtes/daneia/stegastika-daneia (χωρίς
-- ημερομηνία τιμολογίου) και το τιμολόγιο με «Ενημέρωση: 01/10/2026»
-- https://www.nbg.gr/-/jssmedia/Files/Timologio/web_portal_elliniko_epitokia-timologio_daneiwn.pdf
-- ΕΣΤΙΑ σταθερό από 2,90% (ίδιο). Η σελίδα έχει χωριστή γραμμή «σταθερό από
-- 2,5%», αλλά η ανάγνωση δεν τη δένει καθαρά με το «ΤΟ ΠΡΩΤΟ ΜΟΥ ΣΠΙΤΙ»: το
-- fixed_min 2,50 μένει (τυπώνεται), η ονομασία του προϊόντος φεύγει. Η
-- 30/06/2026 είναι προθεσμία απαλλαγής εξόδων, όχι ημερομηνία τιμής.
update public.bank_rates set
  features   = array_append(
                 array_remove(features, '«το Πρώτο μου Σπίτι»: σταθερό από 2,50%, αιτήσεις έως 31/12/2026'),
                 'Χωριστή γραμμή στη σελίδα της τράπεζας: σταθερό από 2,50%'),
  verified_at = date '2026-10-04'
where bank_id = 'ethniki'
  and not ('Χωριστή γραμμή στη σελίδα της τράπεζας: σταθερό από 2,50%' = any(features));
