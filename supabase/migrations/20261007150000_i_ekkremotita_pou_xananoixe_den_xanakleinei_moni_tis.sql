-- Η ΕΚΚΡΕΜΟΤΗΤΑ ΠΟΥ ΞΑΝΑΝΟΙΞΕΣ ΔΕΝ ΞΑΝΑΚΛΕΙΝΕΙ ΜΟΝΗ ΤΗΣ
-- ─────────────────────────────────────────────────────────────────────────
-- ΓΙΑΤΙ ΑΓΓΙΖΕΤΑΙ ΠΡΟΣΤΑΤΕΥΜΕΝΗ ΔΙΑΔΡΟΜΗ. Πηγή του ευρήματος: ανάγνωση του
-- κώδικα και αναπαραγωγή σε τεστ (07/10/2026), όχι νόμος, ΦΕΚ ή απόφαση ΑΑΔΕ,
-- γιατί το εύρημα είναι ακεραιότητας δεδομένων: μια ενέργεια του χρήστη
-- ακυρωνόταν σιωπηλά. Προστίθεται μία στήλη με NULL· καμία υπάρχουσα γραμμή
-- δεν αλλάζει, καμία πολιτική δεν αλλάζει.
--
-- ΤΟ ΣΦΑΛΜΑ. Η καρτέλα «Εκκρεμότητες» (TabChecklist.tsx) κλείνει σε κάθε
-- φόρτωση τη δόση ΕΝΦΙΑ που έχει προθεσμία στον ίδιο μήνα με πληρωμένο
-- λογαριασμό ΕΝΦΙΑ (lib/checklist/obligationTasks.ts, `enfiaTasksPaidByBills`).
-- Ο χρήστης που ξε-τσεκάρει τη δόση, γιατί ο λογιστής του είπε ότι η πληρωμή
-- δεν πέρασε ή γιατί ο λογαριασμός ήταν άλλης δόσης, τη βλέπει ανοιχτή ως την
-- επόμενη φόρτωση και μετά ξανά κλειστή. Τίποτα στη γραμμή δεν θυμάται ότι
-- την άνοιξε ο ίδιος: το ξανα-άνοιγμα γράφει `status = 'pending'`,
-- `completed = false`, `completed_at = null`, δηλαδή ακριβώς ό,τι είχε μια δόση
-- που δεν έκλεισε ποτέ.
--
-- ΓΙΑΤΙ ΣΤΗΛΗ ΚΑΙ ΟΧΙ ΚΑΤΙ ΠΟΥ ΥΠΑΡΧΕΙ ΗΔΗ. Ο πίνακας δεν έχει `updated_at`
-- ούτε ιστορικό κατάστασης. Το `completed_at` σβήνει στο ξανα-άνοιγμα, για να
-- συμφωνούν οι τρεις στήλες της κατάστασης (lib/data/checklist.ts). Το JSON του
-- `note` κρατά μεταδεδομένα, αλλά το γράφει μόνο όποιος έχει φορτώσει τη γραμμή,
-- οπότε κάθε διαδρομή που αλλάζει κατάσταση θα έπρεπε να το θυμάται χωριστά.
-- Η στήλη γράφεται από ΕΝΑ σημείο (`reopenFields` / `statusFields` του
-- lib/data/checklist.ts), όποια οθόνη κι αν ξανανοίγει την εργασία.
--
-- Ο ΚΑΝΟΝΑΣ ΠΟΥ ΤΗΝ ΔΙΑΒΑΖΕΙ. Το αυτόματο κλείσιμο παραλείπει εργασία που
-- ξανανοίχτηκε ΜΕΤΑ την πληρωμή του λογαριασμού που την κλείνει
-- (`bills.paid_at`). Αν ο λογαριασμός σημειωθεί πληρωμένος ξανά αργότερα, νέα
-- πληρωμή, η εργασία κλείνει κανονικά.
--
-- RLS. Ο πίνακας έχει ήδη `own_checklist_items` και την περιοριστική
-- `mfa_checklist_items`· η νέα στήλη καλύπτεται από αυτές όπως κάθε άλλη.
--
-- ΙΔΙΟΔΥΝΑΜΗ. `add column if not exists` και `comment on`: ξανατρέχει χωρίς
-- σφάλμα και χωρίς αλλαγή.
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.checklist_items
  add column if not exists reopened_at timestamptz;

comment on column public.checklist_items.reopened_at is
  'Πότε ο χρήστης ξανάνοιξε την εργασία (από done ή skipped σε ανοιχτή). Το αυτόματο κλείσιμο από πληρωμένο λογαριασμό δεν την ξανακλείνει αν ο λογαριασμός πληρώθηκε πριν από αυτή τη στιγμή.';
