-- ═══════════════════════════════════════════════════════════════════════════
-- Η ΕΡΩΤΗΣΗ ΠΟΥ ΔΕΝ ΑΠΑΝΤΗΘΗΚΕ ΓΥΡΙΖΕΙ ΣΤΟ ΠΑΚΕΤΟ
-- ─────────────────────────────────────────────────────────────────────────
-- ΤΟ ΣΦΑΛΜΑ, ΜΕΤΡΗΜΕΝΟ. Οι αριθμοί γραμμών είναι του app/api/anthropic/route.tsx
-- ΠΡΙΝ τη διόρθωση. Η `bump_ai_usage` χρεώνει στη γραμμή 108. Ο πάροχος
-- καλείται στη γραμμή 257. Ανάμεσά τους υπάρχουν έξι έξοδοι που ΔΕΝ φέρνουν
-- απάντηση:
--
--   γρ. 173  λείπει το ANTHROPIC_API_KEY
--   γρ. 184  σώμα πάνω από 12 MB
--   γρ. 190  χαλασμένο JSON στο αίτημα (πέφτει στο catch της γρ. 278)
--   γρ. 198  κανένα μήνυμα
--   γρ. 257  αποτυχία δικτύου προς τον πάροχο
--   γρ. 269  σφάλμα του παρόχου (401, 429, 5xx)
--
-- Καμία από τις έξι δεν ξαναδίνει τη μονάδα. Ο συνδρομητής χάνει ερώτηση από
-- το πακέτο του για κάθε αποτυχία, ενώ η οθόνη του γράφει «Δεν μπόρεσα να
-- απαντήσω τώρα, δοκίμασε ξανά σε λίγο» (PropertyAssistant.tsx:1710) — δηλαδή
-- τον καλεί να χάσει άλλη μία. Στο δοκιμαστικό πακέτο των επτά ερωτήσεων την
-- ημέρα, μια κακή στιγμή του παρόχου αδειάζει τη μέρα του χωρίς μία απάντηση.
--
-- ── ΓΙΑΤΙ ΔΕΝ ΤΗ ΔΙΝΟΥΜΕ ΣΤΟΝ `authenticated` ─────────────────────────────
-- Η `bump_ai_usage` μόνο ΑΥΞΑΝΕΙ: ακίνδυνο να την καλεί ο ίδιος ο χρήστης.
-- Αυτή εδώ ΜΕΙΩΝΕΙ. Με δικαίωμα στον `authenticated`, ο καθένας θα ζητούσε
-- απάντηση από τη διαδρομή και αμέσως μετά θα καλούσε το RPC για να μηδενίσει
-- τη χρέωση: απεριόριστος βοηθός, δωρεάν, για όλους. Την εκτελεί ΜΟΝΟ ο
-- `service_role`, από τον διακομιστή, γι' αυτό δέχεται ρητό `p_uid` αντί να
-- διαβάζει `auth.uid()` (που με service_role είναι null ούτως ή άλλως).
--
-- ── ΤΙ ΔΕΝ ΕΠΙΣΤΡΕΦΕΤΑΙ, ΚΑΙ ΓΙΑΤΙ ΕΙΝΑΙ ΣΚΟΠΙΜΟ ──────────────────────────
--
--   ΤΟ ΛΕΠΤΟ (`minute_count`). Δεν είναι πακέτο, είναι φράγμα ρυθμού: υπάρχει
--   για να μη γίνουν είκοσι αιτήματα σε εξήντα δευτερόλεπτα. Η αποτυχία είναι
--   ακριβώς η στιγμή που ένας πελάτης ξαναδοκιμάζει σε βρόχο. Αν το
--   επιστρέφαμε, το φράγμα θα άνοιγε μόνο του στη στιγμή που το χρειάζεται
--   περισσότερο. Ο χρήστης δεν το αντιλαμβάνεται ως πακέτο ούτως ή άλλως:
--   ανανεώνεται μόνο του στο επόμενο λεπτό.
--
--   Η ΔΕΞΑΜΕΝΗ, ΟΤΑΝ ΤΟ ΖΗΤΗΣΕΙ Ο ΚΑΛΩΝ (`p_pool = false`). Το πακέτο του
--   χρήστη μετράει ΑΠΑΝΤΗΣΕΙΣ. Η κοινή δεξαμενή μετράει ΧΡΗΜΑ. Οταν το αίτημα
--   κόπηκε στο χρονικό όριο, ο πάροχος δούλευε σαράντα πέντε δευτερόλεπτα και
--   πιθανότατα παρήγαγε tokens που θα χρεωθούν: το πακέτο πρέπει να γυρίσει
--   (ο χρήστης δεν πήρε τίποτα), η δεξαμενή όχι (τα λεφτά φύγανε). Σε σφάλμα
--   4xx ή 5xx του παρόχου δεν παρήχθη τίποτα, οπότε γυρίζουν και τα δύο.
--
-- ── ΓΙΑΤΙ `greatest(… - 1, 0)` ────────────────────────────────────────────
-- Οι μετρητές μηδενίζονται μόνοι τους σε κάθε νέα ημέρα ή μήνα (ώρα Αθήνας).
-- Αν η αποτυχία συμβεί πάνω στην αλλαγή, η επιστροφή μπορεί να βρει φρέσκο
-- μετρητή στο μηδέν: το πάτωμα τον κρατά εκεί αντί να τον πάει στο μείον ένα,
-- που θα χάριζε ερώτηση στην επόμενη περίοδο. Το ίδιο ισχύει για τη δεξαμενή.
--
-- ── ΔΕΝ ΕΙΝΑΙ IDEMPOTENT ΚΑΙ ΔΕΝ ΤΟ ΠΡΟΣΠΟΙΕΙΤΑΙ ──────────────────────────
-- Δύο κλήσεις για την ίδια αποτυχία αφαιρούν δύο μονάδες. Η εγγύηση «μία
-- φορά» ζει στον καλούντα: το route.tsx κρατά μία σημαία ανά αίτημα και
-- υπάρχει ΕΝΑ σημείο κλήσης. Πίνακας αιτημάτων με κλειδί ιδεατότητας θα ήταν
-- τρίτη εγγραφή στη βάση για να φυλάξει μία αφαίρεση — περισσότερος κίνδυνος
-- από όσο αποτρέπει.
--
-- ΕΛΕΓΧΘΗΚΕ ΣΕ PostgreSQL 16, με το σχήμα του baseline: τρεις χρεώσεις έδωσαν
-- λεπτό/ημέρα/μήνα 3 και δεξαμενή 3· μία επιστροφή έδωσε λεπτό 3 (άθικτο),
-- ημέρα 2, μήνα 2, δεξαμενή 2· τέσσερις συνεχόμενες επιστροφές σταμάτησαν στο
-- μηδέν· άγνωστος χρήστης έδωσε `no_row` χωρίς εξαίρεση· `p_uid = null` έδωσε
-- `uid` χωρίς εξαίρεση· σε συνδρομητή που πληρώνει η δεξαμενή έμεινε άθικτη.
-- ═══════════════════════════════════════════════════════════════════════════

create or replace function public.refund_ai_usage(
  p_uid  uuid,
  p_pool boolean default true
) returns json language plpgsql security definer set search_path to 'public' as $$
declare
  v_now  timestamptz := now();
  v_mon  date        := date_trunc('month', (v_now at time zone 'Europe/Athens'))::date;
  v_pay  boolean;
  v_dayc integer;
  v_monc integer;
begin
  if p_uid is null then
    return json_build_object('refunded', false, 'reason', 'uid');
  end if;

  -- Ο ΜΕΤΡΗΤΗΣ ΤΟΥ ΛΕΠΤΟΥ ΔΕΝ ΑΓΓΙΖΕΤΑΙ. Δες την επικεφαλίδα: είναι φράγμα
  -- ρυθμού, όχι πακέτο.
  update public.ai_usage set
    day_count   = greatest(public.ai_usage.day_count   - 1, 0),
    month_count = greatest(public.ai_usage.month_count - 1, 0),
    updated_at  = v_now
  where user_id = p_uid
  returning public.ai_usage.day_count, public.ai_usage.month_count into v_dayc, v_monc;

  -- Καμία γραμμή σημαίνει ότι δεν χρεώθηκε ποτέ τίποτα. Δεν είναι σφάλμα.
  if not found then
    return json_build_object('refunded', false, 'reason', 'no_row');
  end if;

  if p_pool then
    -- Ο ΙΔΙΟΣ ΟΡΙΣΜΟΣ ΤΟΥ «ΠΛΗΡΩΝΕΙ» ΜΕ ΤΗ bump_ai_usage. Γραμμένος δεύτερη
    -- φορά εδώ επίτηδες: αν αύριο προστεθεί πακέτο που χρεώνεται, πρέπει να
    -- μπει και στα δύο σημεία, αλλιώς η δεξαμενή θα χρεώνεται χωρίς να
    -- πιστώνεται ποτέ.
    select coalesce(plan, 'free') in ('solo', 'owner', 'agency', 'office')
      into v_pay from public.billing_profiles where user_id = p_uid;

    if not coalesce(v_pay, false) then
      update public.ai_budget
         set free_count = greatest(public.ai_budget.free_count - 1, 0),
             updated_at = v_now
       where month = v_mon;
    end if;
  end if;

  return json_build_object('refunded', true, 'day', v_dayc, 'month', v_monc);
end; $$;

-- ΤΟ ΔΙΚΑΙΩΜΑ ΕΙΝΑΙ ΟΛΗ Η ΑΣΦΑΛΕΙΑ ΑΥΤΗΣ ΤΗΣ ΣΥΝΑΡΤΗΣΗΣ. Το `public` στην
-- Postgres περιλαμβάνει κάθε ρόλο: χωρίς την ανάκληση, το EXECUTE θα το είχαν
-- και ο `anon` και ο `authenticated` από την προεπιλογή.
revoke all on function public.refund_ai_usage(uuid, boolean) from public, anon, authenticated;
grant execute on function public.refund_ai_usage(uuid, boolean) to service_role;

comment on function public.refund_ai_usage(uuid, boolean) is
  'Επιστρέφει μία μονάδα AI στο ημερήσιο και στο μηνιαίο πακέτο του χρήστη όταν η κλήση στον πάροχο δεν έδωσε απάντηση. Το λεπτό δεν επιστρέφεται (φράγμα ρυθμού). Η κοινή δεξαμενή επιστρέφεται μόνο με p_pool = true. Εκτελείται μόνο από service_role.';
