-- ΓΙΑΤΙ ΑΓΓΙΖΕΤΑΙ ΠΡΟΣΤΑΤΕΥΜΕΝΗ ΔΙΑΔΡΟΜΗ. Πηγή: ΚΥΑ 86272/ΕΞ2026 (ΦΕΚ Β΄
-- 3058/02.06.2026), όπως τροποποιήθηκε με τις ΚΥΑ 116171/ΕΞ2026 (ΦΕΚ Β΄
-- 4372/16.07.2026) και 137219/ΕΞ2026 (ΦΕΚ Β΄ 5347/31.08.2026). Ο κύκλος του
-- 2026 είναι η δράση «Ανακαίνιση Κατοικίας», με επιχορήγηση 80% ή 70% ανά
-- εισοδηματική κατηγορία και βεβαιώσεις επιλεξιμότητας που έκλεισαν 31/07 και
-- 30/09/2026. Τα στοιχεία ζουν στο lib/accounting/anakainisi2026.ts. Αλλάζει
-- ΜΙΑ γραμμή δεδομένων αναφοράς· κανένα δεδομένο χρήστη, καμία στήλη, καμία
-- πολιτική.
--
-- ΤΟ ΣΦΑΛΜΑ. Μετρημένο στις 08/10/2026 με SELECT στην παραγωγή: η όψη
-- `active_loan_programs` γύριζε ΜΙΑ γραμμή, την `anakainizo_noikazo` με
-- «40% επιδότηση ανακαίνισης συν εγγυημένο ενοίκιο για 5 έτη μέσω ΟΠΕΚΑ»,
-- `max_amount` 15000, «Τρέχον, έλεγξε στον φορέα», ενεργή από τις 08/07/2026.
-- Η καρτέλα «Δάνεια» έδειχνε μόνο αυτή, γιατί η λίστα ήταν «βάση ή κατάλογος»
-- (app/dashboard/components/loan/useLoan.ts). Τα άλλα τρία προγράμματα του
-- πίνακα είναι ήδη `ended`.
--
-- Η ΔΙΟΡΘΩΣΗ. Η γραμμή κλείνει (`status = 'ended'`), οπότε η όψη την αφήνει
-- έξω και η κάρτα του προγράμματος έρχεται από τον κατάλογο του κώδικα
-- (STATE_PROGRAMS στο TabLoanData.tsx), που διαβάζει τις σταθερές με ΦΕΚ και
-- κρίνει την κατάσταση από τις ημερομηνίες. Μαζί αλλάζει και ο κώδικας: η
-- λίστα γίνεται ένωση (`programsWithLive`), ώστε καμία γραμμή βάσης να μη
-- σβήνει ξανά τον κατάλογο.
--
-- ΙΔΙΟΔΥΝΑΜΗ. Ξανατρέχει χωρίς αλλαγή· σε βάση χωρίς τη γραμμή (staging,
-- αναπαραγωγή) δεν αγγίζει τίποτα.
-- ═══════════════════════════════════════════════════════════════════════════

update public.loan_programs
   set status = 'ended',
       verified_at = date '2026-10-08'
 where program_id = 'anakainizo_noikazo'
   and status is distinct from 'ended';
