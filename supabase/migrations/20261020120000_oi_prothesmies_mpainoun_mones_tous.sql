-- ΤΟ ΚΕΝΟ (αξιολόγηση χρήστη 20.10.2026). Οι δόσεις ΕΝΦΙΑ, το Ε1/Ε2, το Ε9 και
-- οι μηνιαίες δηλώσεις της βραχυχρόνιας φαίνονταν στην Επισκόπηση, αλλά στο
-- `calendar_events` γράφονταν ΜΟΝΟ όταν ο χρήστης πατούσε «⋯ → Συγχρονισμός
-- δεδομένων → Φορολογικά». Και από το `calendar_events` διαβάζουν και οι τρεις
-- δρόμοι που φτάνουν στο κινητό: οι υπενθυμίσεις email (send-reminders), οι
-- ειδοποιήσεις push (/api/push) και η συνδρομή ημερολογίου (/imerologio).
-- Οποιος δεν πατούσε το κουμπί, δεν έπαιρνε καμία υπενθύμιση φόρου.
--
-- Η ΜΙΑ ΠΗΓΗ ΜΕΝΕΙ ΜΙΑ. Δεν γράφεται δεύτερο αντίγραφο των προθεσμιών για τις
-- ειδοποιήσεις: ο ίδιος συγχρονισμός (lib/calendar/taxSync.ts, πάνω στο
-- lib/tax/greekTaxCalendar.ts) τρέχει πλέον μόνος του, όταν γράφεται ή αλλάζει
-- κατάσταση ένα ακίνητο και κάθε πρωί πριν από τις ειδοποιήσεις (ενότητα 4). Το
-- κουμπί μένει ως «Ανανέωση τώρα».
--
-- ΤΙ ΑΛΛΑΖΕΙ ΣΤΟ ΣΧΗΜΑ. Καμία νέα γραμμή πίνακα, άρα καμία νέα πολιτική: το
-- `calendar_events` έχει ήδη RLS (own_calendar_events, scope_property_*,
-- mfa_calendar_events) και το `calendar_feed_tokens` επίσης (own feed token *).
-- Οι δύο νέες στήλες ζουν κάτω από τις ίδιες πολιτικές.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── 1. ΤΙ ΕΓΡΑΨΕ Η ΜΗΧΑΝΗ, ΓΙΑ ΝΑ ΞΕΧΩΡΙΖΕΙ ΤΙ ΑΛΛΑΞΕ Ο ΧΡΗΣΤΗΣ ─────────────
-- Ο παλιός συγχρονισμός έσβηνε και ξανάγραφε όλα τα `tax:*` του ακινήτου: όποιος
-- είχε μετακινήσει μια προθεσμία ή είχε γράψει σημείωση την έχανε στο επόμενο
-- πάτημα. Ενας αυτόματος συγχρονισμός που τρέχει κάθε πρωί θα την έχανε κάθε
-- πρωί. Το `auto_hash` κρατά το αποτύπωμα του περιεχομένου που έγραψε η
-- μηχανή· αν η γραμμή δεν ταιριάζει πια με αυτό, την άλλαξε ο χρήστης και ο
-- συγχρονισμός δεν την αγγίζει. Κενό σημαίνει γραμμή του παλιού συγχρονισμού,
-- που η μηχανή υιοθετεί: εκείνος την ξανάγραφε ούτως ή άλλως σε κάθε πάτημα.
alter table public.calendar_events add column if not exists auto_hash text;

comment on column public.calendar_events.auto_hash is
  'Αποτύπωμα του περιεχομένου που έγραψε ο αυτόματος συγχρονισμός προθεσμιών (lib/calendar/taxSync.ts). Διαφορετικό από το τωρινό = το άλλαξε ο χρήστης και ο συγχρονισμός δεν το αγγίζει. Κενό σε γραμμές που δεν έγραψε η μηχανή.';

-- ── 2. ΜΙΑ ΘΕΣΜΙΚΗ ΠΡΟΘΕΣΜΙΑ ΑΝΑ ΑΚΙΝΗΤΟ, ΠΟΤΕ ΔΥΟ ──────────────────────────
-- Με δύο γραφείς (το πρόγραμμα του πρωινού και η καρτέλα που μόλις αποθήκευσε
-- ακίνητο) ο έλεγχος «υπάρχει ήδη;» στον κώδικα δεν αρκεί: δύο γραφές την ίδια
-- στιγμή βλέπουν και οι δύο «όχι». Το κλειδί το κρατά η βάση.
--
-- Πριν από το κλειδί φεύγουν τα διπλά που ίσως άφησε ο παλιός συγχρονισμός
-- (έγραφε πρώτα και έσβηνε μετά, οπότε μια διακοπή στη μέση άφηνε δύο). Μένει
-- η γραμμή που έκλεισε ο χρήστης (πληρωμένη ή ακυρωμένη) και μετά η παλαιότερη.
with ranked as (
  select id,
         row_number() over (
           partition by property_id, source
           order by (lower(coalesce(status, '')) in ('paid', 'cancelled', 'canceled', 'done', 'completed', 'skipped')) desc,
                    created_at asc nulls last, id asc
         ) as n
    from public.calendar_events
   where source like 'tax:%'
)
delete from public.calendar_events e
 using ranked r
 where e.id = r.id and r.n > 1;

create unique index if not exists calendar_events_tax_once
  on public.calendar_events (property_id, source)
  where source like 'tax:%';

comment on index public.calendar_events_tax_once is
  'Μία θεσμική προθεσμία (tax:<id>) ανά ακίνητο. Ο αυτόματος συγχρονισμός είναι αδύναμος να διπλογράψει, όσοι γραφείς κι αν τρέξουν μαζί.';

-- ── 3. ΣΥΝΔΕΘΗΚΕ ΠΟΤΕ ΤΟ ΗΜΕΡΟΛΟΓΙΟ ΤΟΥ ΚΙΝΗΤΟΥ; ────────────────────────────
-- Η πρόταση «Βάλε τις προθεσμίες στο ημερολόγιο του κινητού» μπαίνει πλέον εκεί
-- όπου φαίνονται οι προθεσμίες (Επισκόπηση, Ημερολόγιο, πίνακας υποδοχής), όχι
-- μόνο στον Λογαριασμό. Για να φύγει όταν έγινε, χρειάζεται ένα γεγονός και όχι
-- ένα «το είδα»: ότι κάποιο ημερολόγιο ζήτησε πράγματι τη διεύθυνση. Τη στήλη
-- τη γράφει ΜΟΝΟ ο διακομιστής (app/imerologio/[token]/route.ts, με τον πελάτη
-- υπηρεσίας)· ο χρήστης δεν έχει πολιτική ενημέρωσης σε αυτόν τον πίνακα.
alter table public.calendar_feed_tokens add column if not exists last_fetched_at timestamptz;

comment on column public.calendar_feed_tokens.last_fetched_at is
  'Η τελευταία φορά που ένα εξωτερικό ημερολόγιο διάβασε τη συνδρομή. Το γράφει μόνο η διαδρομή /imerologio. Κενό = δεν συνδέθηκε ακόμη.';

