-- ── Alpha Bank ───────────────────────────────────────────────────────────
-- ΠΗΓΗ: https://www.alpha.gr/-/media/AlphaGr/pdf-files/diafora-sunodeutika-pdf/xrisima-eggrafa/oroi-sunallagon-epitokia-katatheseon-xorigiseon.pdf
-- Ενημέρωση 21/09/2026, σημείωση 4: νέες αιτήσεις από 01/06/2026.
-- Alpha Κατοικία, άνω των 300.000€ και έως 60% της αξίας: Euribor 3M + 1,80%,
-- σταθερό 1 έτους 2,70%, 3 ετών 2,90%. Alpha Δέσμευση, χωριστή γραμμή:
-- Euribor 3M + 1,00%, σταθερό 5 ετών 2,90%. Εισφορά ν.128/75 0,12% (0,60% για
-- μη οικιστικά). Το 2,50% ανήκει σε άλλα προϊόντα (Ανακαίνιση, Μέτρον Άριστον)
-- και το +2,5 μονάδες είναι τόκος υπερημερίας: κανένα δεν γράφεται.
--     fixed_min   2.90 (της ενημέρωσης 05/10)  → 2.70
--     note        'Alpha Κατοικία: σταθερό 1 έτους 2,70% και 3 ετών 2,90%' → παρακάτω
update public.bank_rates set
  fixed_min = 2.70,
  note      = 'Alpha Κατοικία: Euribor 3M + 1,80% για δάνεια άνω των 300.000€ έως 60% της αξίας, σταθερό 1 έτους 2,70% και 3 ετών 2,90%. Alpha Δέσμευση, χωριστό προϊόν: Euribor 3M + 1,00% ή σταθερό 5 ετών 2,90%. Για νέες αιτήσεις από 1.6.2026',
  features  = array_append(array_remove(features, 'Εισφορά ν.128/75: 0,12% (0,60% για μη οικιστικά)'),
                           'Εισφορά ν.128/75: 0,12% (0,60% για μη οικιστικά)'),
  verified_at = date '2026-10-05'
where bank_id = 'alpha';

-- ── Eurobank ─────────────────────────────────────────────────────────────
-- ΠΗΓΗ: https://www.eurobank.gr/-/media/eurobank/rates/epitokia-daneiakon-proionton.pdf
-- Ισχύς 27/07/2026. Euribor 3M + 0,80% έως 2,70%, σταθερό 3 ετών 2,90%
-- (ίδια). Η έκπτωση 0,40% για 3 έτη σε δικαιούχους πρώτης κατοικίας ΔΕΝ
-- αφαιρείται από το 2,90. Το 2,50% του δελτίου είναι τόκος υπερημερίας.
--     note  'Ανταγωνιστικοί όροι' → παρακάτω
update public.bank_rates set
  note = 'Δικαιούχοι πρώτης κατοικίας: επιπλέον έκπτωση 0,40% για 3 έτη, χωριστά από το σταθερό 3 ετών 2,90%'
where bank_id = 'eurobank';

