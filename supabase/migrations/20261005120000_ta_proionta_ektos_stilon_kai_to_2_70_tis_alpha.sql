update public.bank_rates set
  note = 'Σταθερό 3 έως 30 ετών σε ενιαίο εύρος 2,40% έως 4,70%, όπως το δημοσιεύει η τράπεζα. Σπίτι 25: 2,20% έως 2,75% τα 4 πρώτα έτη, 2,90% έως 3,70% το 5ο. Με εξασφάλιση καταθέσεων (cash collateral): Euribor 1M + 1,00% για αιτήσεις έως 31/12/2026, με ενέχυρο μετρητών 105%',
  verified_at = date '2026-10-05'
where bank_id = 'piraeus';

