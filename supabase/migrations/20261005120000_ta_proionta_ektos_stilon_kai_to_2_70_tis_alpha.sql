--      κανόνας θα έσβηνε το 2,50 της Εθνικής. Η διόρθωση του κανόνα είναι στο
--      supabase/functions/bank-rates-updater/index.ts, στην ίδια αλλαγή.
--   2. Η κάρτα της τράπεζας δείχνει το `note`, όχι τα `features`. Η Alpha
--      Δέσμευση, το Σπίτι 25 και το cash collateral της Πειραιώς και το ΕΣΤΙΑ
--      της Εθνικής δεν φαίνονταν πουθενά· στη θέση τους υπήρχαν φράσεις χωρίς
--      πηγή («Ανταγωνιστικοί όροι», «Premium εξυπηρέτηση»).
--
-- ΠΟΙΟΣ ΕΛΕΓΞΕ. Οι τιμές και οι πηγές είναι από την οδηγία του ιδιοκτήτη της
-- 05/10/2026, από την ανάγνωση της ομάδας Grok. Ο διαμεσολαβητής δικτύου εδώ
-- μπλοκάρει τους ιστότοπους των τραπεζών, οπότε τα έγγραφα δεν ξαναδιαβάστηκαν
-- από αυτό το περιβάλλον. Μόνο update, καμία διαγραφή, καμία αλλαγή στις στήλες
-- επιτοκίων εκτός από το fixed_min της Alpha. Ξανατρέχει χωρίς παρενέργεια.
