-- ΠΗΓΗ: https://www.piraeusbank.gr/el/support/epitokia-deltia-timwn/ (20/02/2026):
-- Euribor 1M + 1,40% έως 2,45%, σταθερό 2,40% έως 4,70% (ίδια). «Σπίτι 25»:
-- 2,20% έως 2,75% τα 4 πρώτα έτη, 2,90% έως 3,70% το 5ο.
-- ΠΗΓΗ: https://www.piraeusbank.gr/el/idiwtes/proionta-upiresies/stegastika-daneia/stegastiko-daneio-me-eksasfalisi-katatheseon-cash-collateral
-- Euribor 1M + 1,00% για αιτήσεις έως 31/12/2026, με ενέχυρο μετρητών 105%.
