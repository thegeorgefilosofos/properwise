// ΤΟ `property` ΤΑΞΙΔΕΥΕΙ (έλεγχος 21/10/2026, εύρημα D). Η παλιά διεύθυνση
// `?token=…&property=X` έδειχνε ΕΝΑ ακίνητο. Η ανακατεύθυνση το πετούσε και ο
// συνδρομητής έβλεπε ξαφνικά όλα τα ακίνητα, τους λογαριασμούς και τα ενοίκια
// του λογαριασμού στο ημερολόγιο όπου είχε βάλει ένα. Οποιος έδωσε τη
// διεύθυνση ενός ακινήτου σε συνεργάτη, του έδωσε χωρίς να το ξέρει όλα τα
// υπόλοιπα. Τώρα το `property` περνά όταν είναι uuid και η διαδρομή
// (app/imerologio/[token]/route.ts) δείχνει μόνο εκείνο, μόνο αν ανήκει στον
// κάτοχο του κουπονιού. Οτι δεν είναι uuid δεν φτάνει πουθενά: η διεύθυνση
// δεν ανοίγει, αντί να ανοίξει πλατύτερα απ' ό,τι ζητήθηκε.
//
// ΦΙΛΤΡΟ ΕΜΦΑΝΙΣΗΣ, ΟΧΙ ΟΡΙΟ ΠΡΟΣΒΑΣΗΣ. Το κουπόνι είναι του ΛΟΓΑΡΙΑΣΜΟΥ, όχι
// του ακινήτου: όποιος έχει τη διεύθυνση και σβήσει το `?property=` παίρνει
// όλο τον λογαριασμό, όπως και πριν από την ανακατεύθυνση με την παλιά
// διεύθυνση χωρίς `property`. Το `property` κρατά ό,τι έβλεπε ο συνδρομητής·
// δεν προστατεύει τίποτα από όποιον κρατά το κουπόνι. Αληθινή κοινοποίηση ενός
// ακινήτου θέλει κουπόνι ανά ακίνητο (πρόταση, όχι μέρος αυτής της αλλαγής).
// ═══════════════════════════════════════════════════════════════════════════

/** Ο ίδιος κανόνας μορφής με τη νέα διαδρομή. */
export const TOKEN_SHAPE = /^[0-9a-f]{16,64}$/;

/** Μορφή uuid (οποιασδήποτε έκδοσης), πεζά ή κεφαλαία. */
export const UUID_SHAPE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Η διαδρομή της νέας συνδρομής για τα ερωτήματα της παλιάς, ή `null` όταν η
 * παλιά διεύθυνση δεν είναι έγκυρη (κουπόνι ή ακίνητο σε λάθος μορφή).
 */
export function legacyFeedPath(search: URLSearchParams): string | null {
  const token = (search.get('token') || '').toLowerCase();
  if (!TOKEN_SHAPE.test(token)) return null;
  const raw = search.get('property');
  if (raw === null || raw.trim() === '') return `/imerologio/${token}.ics`;
  const property = raw.trim().toLowerCase();
  if (!UUID_SHAPE.test(property)) return null;
  return `/imerologio/${token}.ics?property=${property}`;
}
