import { p, PACKAGE_NAME, type PackageId, type Personal } from '../emailTemplates.ts'
import { APP_URL } from '../site.ts'

export const app = (c: Personal) => c.appUrl || APP_URL
export const dash = (c: Personal) => `${app(c)}/dashboard`
export const esc = (v: unknown) => String(v ?? '').replace(/[&<>]/g, ch => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' }[ch] || ch))
export const has = (n: unknown): n is number => typeof n === 'number' && isFinite(n) && n > 0
export const plural = (n: number, one: string, many: string) => `${n.toLocaleString('el-GR')} ${n === 1 ? one : many}`

// Τυποποιημένες, ομοιογενείς ρήτρες κλεισίματος (μία φωνή σε όλο το catalog).
/** Το όνομα του πακέτου αν το πεδίο κρατά ΠΑΚΕΤΟ· τύπος προφίλ δεν αρκεί. */
export const packageName = (v: unknown): string => {
  const k = String(v ?? '');
  return k in PACKAGE_NAME ? PACKAGE_NAME[k as PackageId] : '';
};

