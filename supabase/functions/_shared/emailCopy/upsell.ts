import {
  emailShell, eyebrow, h, p, bullets, button, greeting, note, heroStat, PACKAGE_NAME,
  PACKAGE_MAX_PROPERTIES,
} from '../emailTemplates.ts'
import { eur } from '../format.ts'
import { dash, has, plural, NOTE, type CopyFn, offer, codeLine } from './kit.ts'

// ── Φάση 3: Upsell & Conversion ──────────────────────────────────────────────
export const UPSELL: Record<string, CopyFn> = {

  // 24β. Μηνιαία παρότρυνση αναβάθμισης (χρήστες χωρίς συνδρομή)
  free_month_upgrade: (c) => ({
    subject: 'Άλλος ένας μήνας. Μήπως ήρθε η ώρα;',
    html: emailShell({
      preheader: 'Περισσότερα δεδομένα, σωστότερες αποφάσεις.',
      unsubUrl: c.unsubUrl,
      bodyHtml: eyebrow('Αναβάθμιση') + h('Δώσε στο ακίνητό σου περισσότερα') + greeting(c.name)
        + p('Άλλος ένας μήνας στο δωρεάν πακέτο. Μήπως ήρθε η ώρα για τη Νόα, τον ψηφιακό βοηθό, ή για περισσότερα ακίνητα, ώστε να παίρνεις σωστότερες αποφάσεις με λιγότερο κόπο;')
        + p(`Με ένα πακέτο συνδρομής, από το «${PACKAGE_NAME.solo}» ως το «${PACKAGE_NAME.office}», κερδίζεις χρόνο στη διαχείριση, με λίγα μόλις κλικ από το κινητό σου.`)
        + button('Δες τα πακέτα', dash(c))
        + note(NOTE.cancel),
    }),
  }),

  // 25. Αναβάθμιση ιδιώτη χωρίς συνδρομή. Η SQL το στέλνει σε όποιον έχει 2+
  // ακίνητα, οπότε το πακέτο που του ταιριάζει είναι το «Ιδιοκτήτης+»: το
  // «Ιδιώτης» είναι τρόπος χρήσης και δεν αγοράζεται.
  upsell_to_individual: (c) => {
    const pack = `«${PACKAGE_NAME.owner}»`;
    const proof = has(c.properties)
      ? p(`Έχεις ήδη <b>${plural(c.properties, 'ακίνητο', 'ακίνητα')}</b> στο PROPERWISE. Με το ${pack}, το καθένα δουλεύει στο έπακρο για σένα.`)
      : p(`Χρησιμοποιείς ήδη τα βασικά. Με το ${pack} έχεις όσα κάνουν τη διαχείριση πραγματικά αβίαστη.`);
    return { subject: 'Δώσε στα ακίνητά σου το πλήρες PROPERWISE', html: emailShell({
      preheader: 'Απεριόριστες καταστάσεις, αυτόματες υπενθυμίσεις, επίσημες αναφορές.',
      unsubUrl: c.unsubUrl,
      bodyHtml: eyebrow(`Πακέτο ${PACKAGE_NAME.owner}`) + h('Ώρα για το επόμενο βήμα') + greeting(c.name)
        + proof
        + p('Τι προσθέτει στη ρουτίνα σου:')
        + bullets([
            'Απεριόριστες καταστάσεις και βεβαιώσεις ενοικίου.',
            'Αυτόματες υπενθυμίσεις για εισπράξεις και προθεσμίες.',
            'Επίσημες αναφορές PDF με αριθμό και κωδικό επαλήθευσης.',
          ])
        + button(`Δες το ${pack}`, dash(c))
        + note(NOTE.cancel),
    }) };
  },

  // 26. Αναβάθμιση προς το πακέτο «Επαγγελματίας»
  upsell_to_professional: (c) => {
    const proof = (has(c.properties) && c.properties >= 2)
      ? p(`Διαχειρίζεσαι <b>${plural(c.properties, 'ακίνητο', 'ακίνητα')}</b>. Όσο μεγαλώνει το χαρτοφυλάκιό σου, τόσο περισσότερο κερδίζεις από το πακέτο Επαγγελματία.`)
      : p('Καθώς το χαρτοφυλάκιό σου μεγαλώνει, το πακέτο Επαγγελματία σε κρατά μπροστά χωρίς επιπλέον κόπο.');
    return { subject: 'Το χαρτοφυλάκιό σου μεγαλώνει', html: emailShell({
      preheader: 'Πολλά ακίνητα, επώνυμες αναφορές, μαζική επικοινωνία.',
      unsubUrl: c.unsubUrl,
      bodyHtml: eyebrow('Πακέτο Επαγγελματία') + h('Φτιαγμένο για χαρτοφυλάκιο') + greeting(c.name)
        + proof
        + p('Τι προσθέτει:')
        + bullets([
            `Έως ${PACKAGE_MAX_PROPERTIES.agency} ακίνητα, με συνολική εικόνα και ανάλυση ανά ακίνητο.`,
            'Επώνυμες αναφορές και μαζική επικοινωνία με τους πελάτες σου.',
            'Λογιστικό ημερολόγιο και κατανομή σε συνιδιοκτήτες, έτοιμα για τον λογιστή.',
          ])
        + button('Αναβάθμισε σε Επαγγελματία', dash(c))
        + note(NOTE.cancel),
    }) };
  },

  // 27. Έφτασε το όριο ακινήτων του δωρεάν πακέτου
  limit_reached: (c) => ({
    subject: 'Έφτασες στο όριο των ακινήτων σου',
    html: emailShell({
      preheader: 'Ένα βήμα για να συνεχίσεις χωρίς φραγμό.',
      unsubUrl: c.unsubUrl,
      bodyHtml: eyebrow('Χώρος για ανάπτυξη') + h('Χρειάζεσαι λίγο περισσότερο χώρο') + greeting(c.name)
        // Το δωρεάν πακέτο και το «Ιδιοκτήτης με Νόα» κρατούν από ένα ακίνητο:
        // το επόμενο σκαλί που δίνει χώρο είναι το «Ιδιοκτήτης+», όχι το φθηνότερο.
        + p(`Το δωρεάν πακέτο «Ιδιοκτήτης» κρατά ένα ακίνητο. Για δεύτερο και τρίτο υπάρχει το «${PACKAGE_NAME.owner}», με έως ${PACKAGE_MAX_PROPERTIES.owner} ακίνητα και τη Νόα μέσα.`)
        + p('Κρατάς ό,τι έχεις καταχωρήσει. Φεύγει μόνο το όριο.')
        + button('Δες τα πακέτα', dash(c))
        + note(NOTE.cancel),
    }),
  }),

  // 28. Αξία που μένει αναξιοποίητη
  value_left: (c) => {
    const proof = has(c.collected)
      ? p(`Μέσα από το PROPERWISE έχεις ήδη οργανώσει <b>${eur(c.collected)}</b> σε εισπράξεις. Φαντάσου την ίδια καθαρή εικόνα και στη λογιστική, στους φόρους και στις αναφορές σου.`)
      : p('Χρησιμοποιείς ένα μέρος από όσα προσφέρει το PROPERWISE. Το υπόλοιπο σε περιμένει, έτοιμο να σου γλιτώσει χρόνο.');
    return { subject: 'Αφήνεις αξία αναξιοποίητη', html: emailShell({
      preheader: 'Δες τι μένει ανεκμετάλλευτο στο πακέτο σου.',
      unsubUrl: c.unsubUrl,
      bodyHtml: eyebrow('Αξία που περιμένει') + h('Υπάρχει κι άλλο, έτοιμο για σένα') + greeting(c.name)
        + proof
        + p('Με την αναβάθμιση έρχονται αυτόματες υπενθυμίσεις και αναλυτικότερες αναφορές, χωρίς να αλλάξεις τίποτα στη ρουτίνα σου.')
        + button('Δες τι κερδίζεις', dash(c))
        + note(NOTE.cancel),
    }) };
  },

  // 29. Έκπτωση ετήσιας χρέωσης
  // Χωρίς προσφορά, η αλήθεια της ετήσιας είναι «έως δύο μήνες δωρεάν»: η ετήσια
  // τιμή ισούται με ~10 μηνιαίες στα πληρωμένα πακέτα (≈16,7%), μία λιγότερη στο
  // solo. Δεν δηλώνεται σταθερό ποσοστό (π.χ. 20%) που θα υπερέβαλλε· μόνο όταν
  // δοθεί ρητή έκπτωση προσφοράς (discountPct) γράφεται το ποσοστό.
  annual_discount: (c) => {
    const o = offer(c);
    const promo = !!o;
    const lead = o
      ? `Αν το PROPERWISE έγινε μέρος της καθημερινότητάς σου, η ετήσια χρέωση σου χαρίζει <b>${o.pct}%</b> έκπτωση σε σχέση με τη μηνιαία, με τον κωδικό <b>${o.code}</b> στο ταμείο. Ίδιες δυνατότητες, μικρότερο κόστος.`
      : 'Αν το PROPERWISE έγινε μέρος της καθημερινότητάς σου, η ετήσια χρέωση κοστίζει λιγότερο από δώδεκα μηνιαίες: έως δύο μήνες δωρεάν τον χρόνο. Ίδιες δυνατότητες, μικρότερο κόστος.';
    return { subject: promo ? `Πλήρωσε ετησίως και εξοικονόμησε ${c.discountPct}%` : 'Πλήρωσε ετησίως και κέρδισε έως δύο μήνες', html: emailShell({
      preheader: 'Ίδιο πακέτο, μικρότερο κόστος.',
      unsubUrl: c.unsubUrl,
      hero: heroStat(promo ? `${c.discountPct}%` : 'έως 2 μήνες', promo ? 'εξοικονόμηση' : 'δωρεάν'),
      bodyHtml: eyebrow('Ετήσια χρέωση') + h('Λιγότερο κόστος με την ετήσια συνδρομή') + greeting(c.name)
        + p(lead)
        + p('Η αλλαγή γίνεται στον Λογαριασμό, ενότητα Συνδρομή.')
        + button('Πέρνα σε ετήσια χρέωση', dash(c))
        + note(NOTE.cancel),
    }) };
  },

  // 30. Λήγει η δοκιμαστική περίοδος
  trial_ending: (c) => {
    const left = has(c.trialDaysLeft)
      ? (c.trialDaysLeft === 1 ? 'Αύριο' : `Σε ${plural(c.trialDaysLeft, 'μέρα', 'μέρες')}`)
      : 'Σε λίγες μέρες';
    return { subject: 'Η δοκιμή σου τελειώνει σύντομα', html: emailShell({
      preheader: 'Κράτησε ό,τι έστησες, χωρίς διακοπή.',
      unsubUrl: c.unsubUrl,
      bodyHtml: eyebrow('Δοκιμή') + h('Ας μη σταματήσει η ροή σου') + greeting(c.name)
        + p(`${left} ολοκληρώνεται η δοκιμαστική σου περίοδος. Μετά συνεχίζεις δωρεάν στο πακέτο «Ιδιοκτήτης», με ένα ακίνητο και τα φορολογικά. Για τη Νόα, περισσότερα ακίνητα ή τα εργαλεία των μεγαλύτερων πακέτων, διάλεξε πακέτο όποτε σε βολεύει.`)
        + p('Ό,τι έχεις καταχωρήσει μένει ακριβώς εκεί που το άφησες.')
        + button('Διάλεξε πακέτο', dash(c))
        + note(NOTE.cancel),
    }) };
  },

  // 31. Μετά την υποβάθμιση, ευγενική πόρτα επιστροφής
  winback_downgrade: (c) => ({
    subject: 'Είμαστε εδώ, όποτε θες',
    html: emailShell({
      preheader: 'Τα δεδομένα σου σε περιμένουν, ακέραια.',
      unsubUrl: c.unsubUrl,
      bodyHtml: eyebrow('Καλωσόρισες πίσω') + h('Η πόρτα μένει ανοιχτή') + greeting(c.name)
        + p('Πέρασες σε πιο βασικό πακέτο και το σεβόμαστε απόλυτα. Τα ακίνητα, οι εισπράξεις και το ιστορικό σου παραμένουν ακέραια και δικά σου.')
        + p('Αν κάποια στιγμή θελήσεις ξανά τις αυτόματες υπενθυμίσεις και τις επίσημες αναφορές, θα τα βρεις όλα εκεί που τα άφησες.')
        + button('Δες τα πακέτα', dash(c))
        + note(NOTE.dataOwn),
    }),
  }),

  // 32. Προσφορά επανενεργοποίησης
  reactivation_offer: (c) => {
    const o = offer(c)
    if (!o) return null
    return { subject: `Γύρνα με ${o.pct}% έκπτωση`, html: emailShell({
      preheader: 'Μια αφορμή για να ξαναρχίσεις.',
      unsubUrl: c.unsubUrl,
      hero: heroStat(`${o.pct}%`, 'έκπτωση'),
      bodyHtml: eyebrow('Πρόσκληση επιστροφής') + h('Μια έκπτωση για την επιστροφή σου') + greeting(c.name)
        + p(`Μας έλειψες. Αν θέλεις να ξαναδώσεις στο PROPERWISE μια θέση στη ρουτίνα σου, κρατάμε για σένα <b>${o.pct}%</b> έκπτωση στην αναβάθμιση.`)
        + codeLine(o)
        + p('Ο λογαριασμός σου είναι ακριβώς όπως τον άφησες, έτοιμος να συνεχίσεις.')
        + button(`Κλείσε το ${o.pct}%`, dash(c))
        + note(NOTE.cancel),
    }) };
  },

  // 83. Έναρξη δοκιμαστικής περιόδου (ημέρα 0)
  trial_started: (c) => {
    const days = has(c.trialDaysLeft) ? plural(c.trialDaysLeft, 'μέρα', 'μέρες') : 'λίγες μέρες';
    // Η δοκιμή τρέχει ΠΑΝΤΑ στο TRIAL_PLAN (lib/billing/entitlements.ts), όποιο
    // κι αν είναι το προφίλ· το `c.plan` εδώ είναι τύπος προφίλ, όχι πακέτο.
    const planLine = ` στο <b>«${PACKAGE_NAME.owner}»</b>`;
    return { subject: 'Η δοκιμή σου ξεκίνησε. Ας την αξιοποιήσουμε', html: emailShell({
      preheader: 'Τι περιλαμβάνει η δοκιμή σου.', unsubUrl: c.unsubUrl,
      bodyHtml: eyebrow('Δοκιμή') + h('Καλή αρχή. Πάμε να δεις την αξία') + greeting(c.name)
        + p(`Ξεκίνησες τη δοκιμή${planLine} και έχεις πλήρη πρόσβαση για ${days}. Δοκίμασέ το με τα δικά σου στοιχεία.`)
        + bullets([
            'Άφησε τις αυτόματες υπενθυμίσεις να δουλέψουν για σένα.',
            'Βγάλε μια επίσημη αναφορά ή κατάσταση.',
            'Ρώτα τη Νόα κάτι για τα ακίνητά σου.',
          ])
        + button('Ξεκίνα από εδώ', dash(c))
        + note('Χωρίς δέσμευση. Στο τέλος της δοκιμής, αποφασίζεις εσύ.'),
    }) };
  },
}
