import { emailShell, eyebrow, h, p, button, greeting, note } from '../emailTemplates.ts'
import { eur } from '../format.ts'
import { dash, esc, has, NOTE, type CopyFn } from './kit.ts'

// ── Φάση 13: Συνδρομή & Χρέωση (Billing) ──────────────────────────────────────
// Συναλλακτικά, χωρίς απεγγραφή. Προλαμβάνουν την ακούσια απώλεια συνδρομητή.
export const BILLING: Record<string, CopyFn> = {

  // 89. Λήξη κάρτας πληρωμής (προληπτικά)
  card_expiring: (c) => {
    const tail = c.cardLast4 ? `με τα τελευταία ψηφία <b>${esc(c.cardLast4)}</b>` : 'πληρωμής σου';
    const when = c.deadlineDate ? ` πριν την ανανέωση στις <b>${esc(c.deadlineDate)}</b>` : '';
    return { subject: 'Η κάρτα πληρωμής σου λήγει σύντομα', html: emailShell({
      preheader: 'Μια γρήγορη ενημέρωση αποτρέπει τη διακοπή.',
      bodyHtml: eyebrow('Συνδρομή') + h('Ενημέρωσε την κάρτα σου') + greeting(c.name)
        + p(`Η κάρτα ${tail} λήγει σύντομα. Ενημέρωσέ την${when}, ώστε η συνδρομή σου να συνεχίσει χωρίς διακοπή.`)
        + button('Ενημέρωσε την κάρτα', dash(c))
        + note('Χρειάζεται λιγότερο από ένα λεπτό και σε γλιτώνει από ακούσια διακοπή.'),
    }) };
  },

  // ── 90. ΠΡΙΝ ΦΥΓΕΙ ΤΟ ΠΟΣΟ ΑΠΟ ΤΗΝ ΚΑΡΤΑ ──────────────────────────────
  // ΤΟ ΥΠΟΣΧΟΝΤΑΙ ΟΙ ΟΡΟΙ ΚΑΙ ΔΕΝ ΥΠΗΡΧΕ: «λαμβάνεις ειδοποίηση πριν από
  // κάθε ανανέωση», «στην ετήσια τουλάχιστον τριάντα ημέρες πριν, στη μηνιαία
  // τουλάχιστον τρεις». Το μόνο μήνυμα που έφευγε γύρω από τη δοκιμή πήγαινε
  // σε όσους ΔΕΝ επρόκειτο να χρεωθούν· εκείνοι που θα χρεώνονταν την 31η
  // ημέρα δεν άκουγαν τίποτα και το μάθαιναν από την κίνηση της κάρτας.
  //
  // ΕΝΑ ΠΡΟΤΥΠΟ ΚΑΙ ΓΙΑ ΤΙΣ ΔΥΟ ΠΕΡΙΠΤΩΣΕΙΣ, γιατί η ουσία είναι η ίδια:
  // πόσο, πότε και πώς σταματά. Η πρώτη χρέωση μετά τη δοκιμή αλλάζει μόνο
  // την ταμπέλα και τον τίτλο — και τα αλλάζει από ΔΕΔΟΜΕΝΟ, όχι από δεύτερο
  // πρότυπο που θα ξεχνούσε τη μισή αλήθεια.
  charge_upcoming: (c) => {
    const first = has(c.trialDaysLeft);
    const when = c.deadlineDate ? `στις <b>${esc(c.deadlineDate)}</b>` : 'στην επόμενη ανανέωση';
    const sum = has(c.amount) ? `<b>${eur(c.amount)}</b>` : 'το ποσό της συνδρομής σου';
    return {
      subject: first ? 'Η δοκιμή σου τελειώνει και ξεκινά η συνδρομή' : 'Η συνδρομή σου ανανεώνεται σύντομα',
      html: emailShell({
        preheader: 'Πόσο, πότε και πώς σταματά αν δεν το θέλεις.',
        bodyHtml: eyebrow('Συνδρομή')
          + h(first ? 'Ξεκινά η συνδρομή σου' : 'Έρχεται η ανανέωση')
          + greeting(c.name)
          + p(first
            ? `Η δοκιμαστική σου περίοδος ολοκληρώνεται και η πρώτη χρέωση γίνεται ${when}: ${sum}.`
            : `Η συνδρομή σου ανανεώνεται ${when} και θα χρεωθεί ${sum}.`)
          // ΤΟ «ΔΕΝ ΘΑ ΧΡΕΩΘΕΙΣ» ΕΦΥΓΕ ΚΑΙ ΟΧΙ ΓΙΑ ΝΑ ΠΕΡΑΣΕΙ Ο ΦΥΛΑΚΑΣ. Η
          // φράση είναι απόλυτη δήλωση για το μοντέλο χρέωσης και τέτοιες
          // ζουν σε ΕΝΑ σημείο (lib/legal/billingWords.ts) που η συνάρτηση
          // άκρης δεν μπορεί να διαβάσει. Χωρίς αυτήν το μήνυμα δεν χάνει
          // τίποτα: η ημερομηνία και το ποσό είναι ήδη γραμμένα από πάνω και
          // «ακύρωσε πριν από αυτήν» λέει το ίδιο πράγμα χωρίς υπόσχεση που θα
          // μπορούσε κάποτε να πάψει να ισχύει.
          + p('Δεν χρειάζεται να κάνεις τίποτα για να συνεχίσεις. Αν δεν θέλεις την ανανέωση, ακύρωσε ή άλλαξε πακέτο πριν από αυτή την ημερομηνία.')
          + button('Δες τη συνδρομή σου', dash(c))
          + note(NOTE.cancel),
      }),
    };
  },

  // ── 91. ΠΡΙΝ ΣΒΗΣΤΕΙ Ο ΛΟΓΑΡΙΑΣΜΟΣ ΧΩΡΙΣ ΣΥΝΔΡΟΜΗ ────────────────────
  // ΤΟ ΠΙΟ ΣΟΒΑΡΟ ΜΗΝΥΜΑ ΠΟΥ ΣΤΕΛΝΟΥΜΕ. Ανακοινώνει ότι σε τόσες ημέρες
  // παύουν να υπάρχουν τα δεδομένα κάποιου. Γράφεται ανάλογα:
  //
  //   · Η ΗΜΕΡΟΜΗΝΙΑ ΠΡΩΤΗ, όχι θαμμένη σε παράγραφο. Είναι η μόνη
  //     πληροφορία που πρέπει να περάσει ακόμη κι αν διαβαστεί στα γρήγορα.
  //   · ΔΥΟ ΕΞΟΔΟΙ ΚΑΙ ΟΙ ΔΥΟ ΙΣΟΤΙΜΕΣ. Συνδρομή για όποιον μένει, εξαγωγή
  //     για όποιον φεύγει. Ενα μήνυμα που προσφέρει μόνο τη συνδρομή είναι
  //     εκβιασμός με τα δεδομένα του άλλου.
  //   · ΚΑΜΙΑ ΥΠΟΣΧΕΣΗ ΓΙΑ ΤΟ ΜΟΝΤΕΛΟ ΧΡΕΩΣΗΣ. Οι απόλυτες δηλώσεις για το
  //     τι χρεώνεται και πότε ζουν στο lib/legal/billingWords.ts, που η
  //     συνάρτηση άκρης δεν το βλέπει· εδώ λέγεται μόνο το γεγονός.
  //   · ΣΥΝΑΛΛΑΚΤΙΚΟ. Κανένας σύνδεσμος απεγγραφής: δεν πουλάει τίποτα και
  //     δεν επιτρέπεται να απεγγραφεί κανείς από την ειδοποίηση της
  //     διαγραφής του.
  account_lapse_warning: (c) => {
    const left = has(c.daysLeft) ? Number(c.daysLeft) : 0;
    const last = left <= 2;
    const when = c.deadlineDate ? `στις <b>${esc(c.deadlineDate)}</b>` : 'σύντομα';
    const count = left === 1 ? 'σε μία ημέρα' : `σε ${left} ημέρες`;
    return {
      subject: last ? 'Αύριο διαγράφεται ο λογαριασμός σου' : 'Ο λογαριασμός σου διαγράφεται σε μία εβδομάδα',
      html: emailShell({
        preheader: `Ο λογαριασμός σου και τα δεδομένα του διαγράφονται ${count}.`,
        bodyHtml: eyebrow('Λογαριασμός')
          + h(last ? 'Τελευταία υπενθύμιση' : 'Ο λογαριασμός σου λήγει')
          + greeting(c.name)
          + p(`Ο λογαριασμός σου δεν έχει ενεργή συνδρομή. Ο λογαριασμός και όλα τα δεδομένα του, ακίνητα, έγγραφα, δαπάνες και επαφές, διαγράφονται οριστικά ${when}, δηλαδή ${count}.`)
          + p('Δύο πράγματα μπορείς να κάνεις και τα δύο μέσα από την εφαρμογή: να ενεργοποιήσεις συνδρομή, οπότε ο λογαριασμός συνεχίζει όπως ήταν, ή να κατεβάσεις τα δεδομένα σου και να φύγεις με αυτά στα χέρια σου.')
          + button('Άνοιξε τον λογαριασμό σου', dash(c))
          + note('Η διαγραφή είναι οριστική: μετά την ημερομηνία δεν υπάρχει τρόπος να επανέλθουν τα δεδομένα.'),
      }),
    };
  },
}
