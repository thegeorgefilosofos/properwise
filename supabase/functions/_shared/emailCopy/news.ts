import { emailShell, eyebrow, h, p, bullets, button, greeting, note } from '../emailTemplates.ts'
import { dash, esc, NOTE, type CopyFn } from './kit.ts'

// ── Πρόγραμμα «Επικαιρότητα» (topical, editorial) ────────────────────────────
// Καμπάνιες που στέλνονται ΜΕ ΑΦΟΡΜΗ ένα πραγματικό γεγονός (νέος νόμος, κίνηση
// επιτοκίων, φυσικό συμβάν) — όχι αυτόματες ειδοποιήσεις ανά χρήστη. Η ομάδα
// δίνει επιμελημένα το headline και το summaryText· εδώ μπαίνει το πλαίσιο και το
// χρήσιμο επόμενο βήμα. Τόνος με σεβασμό, χωρίς εκμετάλλευση, με disclaimers.
export const NEWS: Record<string, CopyFn> = {

  // 103. Κίνηση επιτοκίων (με αφορμή μεταβολή στην αγορά)
  news_rate_move: (c) => {
    const ctx = c.summaryText ? p(esc(c.summaryText)) : p('Τα επιτόκια στην αγορά κινήθηκαν. Αν έχεις δάνειο με κυμαινόμενο επιτόκιο ή σκέφτεσαι να δανειστείς, αυτή η μεταβολή αφορά τη δόση σου.')
    return { subject: c.headline ? esc(c.headline) : 'Τα επιτόκια κινήθηκαν. Δες τι σημαίνει για σένα', html: emailShell({
      preheader: 'Μια κίνηση της αγοράς που αγγίζει τη δόση σου.', unsubUrl: c.unsubUrl,
      bodyHtml: eyebrow('Επικαιρότητα') + h('Τα επιτόκια κινήθηκαν') + greeting(c.name)
        + ctx
        + p('Στο PROPERWISE συγκρίνεις <b>τραπεζικές τιμές</b>, υπολογίζεις τη νέα δόση με τα δικά σου δεδομένα και βλέπεις αν συμφέρει μια <b>αναχρηματοδότηση</b>.')
        + button('Δες την επίδραση στη δόση σου', dash(c))
        + note('Ενδεικτικά, με βάση δημόσια στοιχεία της αγοράς. Δεν αποτελεί δεσμευτική προσφορά τράπεζας.'),
    }) }
  },

  // 104. Ασφάλεια κατοικίας (με αφορμή αυξημένο κίνδυνο/συμβάν) — με σεβασμό
  news_insurance_risk: (c) => {
    const ctx = c.summaryText ? p(esc(c.summaryText)) : p('Με αφορμή τα πρόσφατα γεγονότα, είναι μια καλή στιγμή να βεβαιωθείς ότι το ακίνητό σου είναι προστατευμένο.')
    return { subject: c.headline ? esc(c.headline) : 'Προστάτεψε το ακίνητό σου, με το σωστό ασφαλιστήριο', html: emailShell({
      preheader: 'Προστασία σήμερα, πιθανό όφελος και στον ΕΝΦΙΑ.', unsubUrl: c.unsubUrl,
      bodyHtml: eyebrow('Επικαιρότητα') + h('Η σιγουριά ξεκινά από την προστασία') + greeting(c.name)
        + ctx
        + p('Κράτα στοιχεία και λήξη του ασφαλιστηρίου στο ακίνητο, για να μη σου ξεφύγει η ανανέωση.')
        + bullets([
            'Προστασία από σεισμό, φωτιά και πλημμύρα, ανάλογα με το πρόγραμμα.',
            'Για ασφαλισμένα ακίνητα ενδέχεται, υπό προϋποθέσεις, να προβλέπεται και μείωση στον ΕΝΦΙΑ.',
          ])
        + button('Άνοιξε το ακίνητο', dash(c))
        + note(NOTE.aade),
    }) }
  },

  // 105. Νέα φορολογική/θεσμική ρύθμιση (με αφορμή αλλαγή νομοθεσίας)
  news_tax_change: (c) => {
    const ctx = c.summaryText ? p(esc(c.summaryText)) : p('Άλλαξε κάτι στο πλαίσιο για τα ακίνητα. Δες τι σημαίνει πρακτικά για σένα και τι χρειάζεται να προσέξεις.')
    return { subject: c.headline ? esc(c.headline) : 'Νέα ρύθμιση για τα ακίνητα. Τι αλλάζει για σένα', html: emailShell({
      preheader: 'Τι αλλάζει και τι χρειάζεται να κάνεις.', unsubUrl: c.unsubUrl,
      bodyHtml: eyebrow('Επικαιρότητα') + h('Κάτι άλλαξε. Ας το δούμε καθαρά') + greeting(c.name)
        + ctx
        + p('Το PROPERWISE κρατά τα δεδομένα σου ενημερωμένα και έτοιμα, ώστε η όποια αλλαγή να σε βρίσκει σε τάξη, όχι στην τελευταία στιγμή.')
        + button('Βάλε το ακίνητό σου σε τάξη', dash(c))
        + note(NOTE.legal),
    }) }
  },

  // 106. Γενική επικαιρότητα αγοράς (ευέλικτο πλαίσιο)
  news_market: (c) => {
    const ctx = c.summaryText ? p(esc(c.summaryText)) : p('Η αγορά ακινήτων κινείται. Μια ματιά στα δικά σου δεδομένα σε κρατά ένα βήμα μπροστά.')
    return { subject: c.headline ? esc(c.headline) : 'Η αγορά κινείται. Εσύ πού βρίσκεσαι;', html: emailShell({
      preheader: 'Τα δικά σου δεδομένα, μέσα στο σήμερα.', unsubUrl: c.unsubUrl,
      bodyHtml: eyebrow('Επικαιρότητα') + h('Δες πού βρίσκεσαι, σήμερα') + greeting(c.name)
        + ctx
        + p('Απόδοση, αξία χαρτοφυλακίου και ευκαιρίες, με τα δικά σου στοιχεία.')
        + button('Άνοιξε τον πίνακά σου', dash(c))
        + note('Ενημερωτικά, με βάση δημόσια στοιχεία και τα δικά σου δεδομένα.'),
    }) }
  },

  // 107. Κίνηση τιμών σε ρεύμα/αέριο/internet (με αφορμή μεταβολή τιμολογίων)
  news_utility_prices: (c) => {
    const ctx = c.summaryText ? p(esc(c.summaryText)) : p('Οι τιμές σε ρεύμα, φυσικό αέριο και internet κινήθηκαν ξανά. Όταν αλλάζουν τα τιμολόγια, αλλάζει μαζί τους και το πάγιο κόστος του ακινήτου σου, συχνά χωρίς να το προσέξεις.')
    return { subject: c.headline ? esc(c.headline) : 'Άλλαξαν οι τιμές σε ρεύμα και internet. Μήπως αξίζει καλύτερο πρόγραμμα;', html: emailShell({
      preheader: 'Μια σύγκριση σήμερα μπορεί να ρίξει το πάγιο κόστος του ακινήτου σου.', unsubUrl: c.unsubUrl,
      bodyHtml: eyebrow('Επικαιρότητα') + h('Οι τιμές κινήθηκαν. Δες αν πληρώνεις παραπάνω') + greeting(c.name)
        + ctx
        + p('Στο PROPERWISE συγκρίνεις προγράμματα <b>ρεύματος</b>, <b>φυσικού αερίου</b> και <b>internet</b> για το ακίνητό σου και βλέπεις ποιο συμφέρει για τη δική σου κατανάλωση, χωρίς τηλεφωνήματα και χωρίς ψιλά γράμματα.')
        + button('Σύγκρινε προγράμματα', dash(c))
        + note('Ενδεικτικά, με βάση τα δικά σου δεδομένα κατανάλωσης.'),
    }) }
  },
}
