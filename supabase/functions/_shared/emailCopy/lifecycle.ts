import { emailShell, eyebrow, h, p, bullets, button, greeting, note } from '../emailTemplates.ts'
import { eur } from '../format.ts'
import { app, dash, esc, has, packageName, NOTE, type CopyFn } from './kit.ts'

// ── Φάση 6: Lifecycle, Νομικά & Συναλλαγές ───────────────────────────────────
export const LIFECYCLE: Record<string, CopyFn> = {

  // 43. Απόδειξη συνδρομής (συναλλακτικό, χωρίς απεγγραφή)
  subscription_receipt: (c) => {
    const amt = has(c.invoiceAmount) ? eur(c.invoiceAmount) : '';
    const num = c.invoiceNumber ? esc(c.invoiceNumber) : '';
    // ΤΟ ΠΑΚΕΤΟ, ΟΧΙ Ο ΤΥΠΟΣ ΠΡΟΦΙΛ. Το PLAN_LABEL τύπωνε «πακέτο Ιδιώτης»,
    // που δεν αγοράζεται. Χωρίς αναγνωρίσιμο πακέτο, η γενική διατύπωση.
    const pkg = packageName(c.plan);
    const planLine = pkg ? `πακέτο <b>${pkg}</b>` : 'τη συνδρομή σου';
    const detail = (amt || num)
      ? p(`${num ? `Παραστατικό <b>${num}</b>. ` : ''}${amt ? `Ποσό <b>${amt}</b>. ` : ''}Αφορά ${planLine}.`)
      : p(`Η πληρωμή για ${planLine} καταχωρήθηκε κανονικά.`);
    return { subject: c.invoiceNumber ? `Απόδειξη συνδρομής ${esc(c.invoiceNumber)}` : 'Η απόδειξη της συνδρομής σου', html: emailShell({
      preheader: 'Η πληρωμή σου ολοκληρώθηκε.',
      bodyHtml: eyebrow('Παραστατικό') + h('Ευχαριστούμε για τη συνδρομή σου') + greeting(c.name)
        + p('Λάβαμε την πληρωμή σου και όλα είναι εντάξει. Να τα στοιχεία για το αρχείο σου:')
        + detail
        + p('Το πλήρες παραστατικό είναι διαθέσιμο στον Λογαριασμό, στην ενότητα Συνδρομή.')
        + button('Δες τη συνδρομή σου', dash(c))
        + note('Κράτησε αυτό το μήνυμα για τα αρχεία σου.'),
    }) };
  },

  // 44. Επιβεβαίωση αλλαγής πακέτου
  plan_changed: (c) => {
    const pkg = packageName(c.plan);
    const planSentence = pkg ? `Το πακέτο σου είναι πλέον <b>${pkg}</b>.` : 'Το πακέτο σου μόλις ενημερώθηκε.';
    return { subject: 'Το πακέτο σου ενημερώθηκε', html: emailShell({
      preheader: 'Η αλλαγή καταχωρήθηκε.',
      bodyHtml: eyebrow('Αλλαγή πακέτου') + h('Η αλλαγή ολοκληρώθηκε') + greeting(c.name)
        + p(`${planSentence} Η αλλαγή ισχύει άμεσα και τα δεδομένα σου παραμένουν ακέραια.`)
        + p('Αν η αλλαγή δεν έγινε από εσένα, απάντησε σε αυτό το μήνυμα και θα το δούμε αμέσως.')
        + button('Δες τον λογαριασμό σου', dash(c))
        + note(NOTE.dataOwn),
    }) };
  },

  // 45. Αποτυχία πληρωμής
  payment_failed: (c) => ({
    subject: 'Η πληρωμή της συνδρομής δεν ολοκληρώθηκε',
    html: emailShell({
      preheader: 'Μια γρήγορη ενημέρωση της κάρτας το λύνει.',
      bodyHtml: eyebrow('Πληρωμή') + h('Κάτι δεν πήγε καλά με την πληρωμή') + greeting(c.name)
        + p('Προσπαθήσαμε να ανανεώσουμε τη συνδρομή σου, αλλά η πληρωμή δεν ολοκληρώθηκε. Συνήθως φταίει μια κάρτα που έληξε ή ένα προσωρινό όριο.')
        + p('Ενημέρωσε τα στοιχεία πληρωμής και όλα συνεχίζουν κανονικά, χωρίς καμία διακοπή.')
        + button('Ενημέρωσε την πληρωμή', dash(c))
        + note('Θα ξαναπροσπαθήσουμε αυτόματα τις επόμενες μέρες.'),
    }),
  }),

  // 46. Ειδοποίηση ασφαλείας για νέα σύνδεση
  security_login: (c) => {
    const dv = c.device ? esc(c.device) : '';
    const loc = c.location ? esc(c.location) : '';
    const detail = (dv || loc)
      ? p(`Σύνδεση${dv ? ` από <b>${dv}</b>` : ''}${loc ? `${dv ? ', ' : ' από '}${loc}` : ''}.`)
      : p('Καταγράψαμε μια νέα σύνδεση στον λογαριασμό σου.');
    return { subject: 'Νέα σύνδεση στον λογαριασμό σου', html: emailShell({
      preheader: 'Αν ήσουν εσύ, δεν χρειάζεται καμία ενέργεια.',
      bodyHtml: eyebrow('Ασφάλεια') + h('Μια νέα σύνδεση') + greeting(c.name)
        + detail
        + p('Αν ήσουν εσύ, όλα είναι εντάξει. Αν όχι, άλλαξε αμέσως τον κωδικό σου και ειδοποίησέ μας.')
        + button('Έλεγξε την ασφάλεια', dash(c))
        + note('Δεν ζητάμε ποτέ τον κωδικό σου μέσω email.'),
    }) };
  },

  // 46α. ΕΠΑΝΑΦΟΡΑ ΚΩΔΙΚΟΥ — ΤΟ ΧΕΙΡΟΤΕΡΟ ΨΕΜΑ ΠΟΥ ΕΙΧΕ Ο ΚΑΤΑΛΟΓΟΣ.
  //
  // Το πρότυπο `password_reset` έγραφε «Ο σύνδεσμος λήγει σε 30 λεπτά και
  // χρησιμοποιείται μία φορά» κάτω από ένα κουμπί που πήγαινε στο
  // `/dashboard`. Κανένα token, καμία λήξη, καμία μοναδική χρήση: τρεις
  // ισχυρισμοί ασφαλείας και οι τρεις αναληθείς. Δεν στάλθηκε ποτέ, γιατί
  // κανείς δεν έβαζε αυτό το είδος στην ουρά — αλλά ήταν ένα «Αποστολή»
  // μακριά από το να σταλεί.
  //
  // Η επαναφορά γίνεται με `supabase.auth.resetPasswordForEmail`
  // (app/reset-password/page.tsx) και το μήνυμα με το πραγματικό token το
  // στέλνει το Supabase Auth. Ένα ΔΕΥΤΕΡΟ μήνυμα από εμάς δεν θα μπορούσε ποτέ
  // να έχει έγκυρο σύνδεσμο — το token δεν φτάνει ποτέ σε αυτόν τον κώδικα.

  // 46β. Αυτόματη επιβεβαίωση απάντησης (auto-responder)
  // 45β. Ο ΠΕΛΑΤΗΣ ΑΠΑΝΤΗΣΕ ΣΤΟΝ ΛΟΓΙΣΤΗ ΤΟΥ.
  //
  // Ο λογιστής ζητά κάτι από την πύλη του, ο ιδιοκτήτης πατά «το έστειλα» στον
  // πίνακά του και ο κύκλος έκλεινε ΣΙΩΠΗΛΑ: ο λογιστής ξαναέμπαινε στην πύλη
  // για να δει αν ήρθε. Το μήνυμα είναι ο λόγος να ξαναμπεί, τη σωστή στιγμή.
  //
  // ΣΥΝΑΛΛΑΚΤΙΚΟ, ΓΙΑΤΙ ΑΠΑΝΤΑ ΣΕ ΔΙΚΟ ΤΟΥ ΑΙΤΗΜΑ. Δεν πουλά τίποτα και δεν
  // ενημερώνει για τίποτα: λέει ότι ήρθε αυτό που ο ίδιος ζήτησε, ώρες πριν.
  accountant_request_answered: (c) => ({
    subject: `${esc(c.clientName || 'Ο πελάτης σου')}: ήρθε αυτό που ζήτησες`,
    html: emailShell({
      preheader: 'Το αίτημά σου απαντήθηκε.',
      bodyHtml: eyebrow('Πύλη λογιστή') + h('Ο πελάτης σου απάντησε') + greeting(c.name)
        + p(`Ο <b>${esc(c.clientName || 'πελάτης σου')}</b> σημείωσε ως απαντημένο το αίτημα:`)
        + p(`<b>${esc(c.requestItem || 'Αίτημα')}</b>`)
        + p('Η κατάστασή του είναι ενημερωμένη στην πύλη, με τα ποσά της χρήσης και ό,τι ακόμη λείπει.')
        + button('Δες τους πελάτες σου', `${app(c)}/accountant/workspace`)
        + note('Το ότι το σημείωσε ο ιδιοκτήτης δεν σημαίνει ότι το ελέγξαμε εμείς.'),
    }),
  }),

  reply_ack: (c) => ({
    subject: 'Λάβαμε το μήνυμά σου',
    html: emailShell({
      preheader: 'Σε ευχαριστούμε. Θα σου απαντήσουμε σύντομα.',
      bodyHtml: eyebrow('Επικοινωνία') + h('Το μήνυμά σου έφτασε') + greeting(c.name)
        + p('Σε ευχαριστούμε που μας έγραψες. Το μήνυμά σου καταχωρήθηκε και ένα μέλος της ομάδας μας θα το δει και θα σου απαντήσει το συντομότερο, συνήθως εντός μίας εργάσιμης ημέρας.')
        + p('Αν είναι κάτι επείγον για κάποιο ακίνητό σου, μπορείς εν τω μεταξύ να ρωτήσεις τη Νόα μέσα στην εφαρμογή. Ξέρει τα δεδομένα σου και απαντά αμέσως.')
        + button('Ρώτα τη Νόα', dash(c))
        + note('Αυτή είναι μια αυτόματη επιβεβαίωση. Η προσωπική απάντηση έρχεται από άνθρωπο.'),
    }),
  }),

  // 47. Εφαρμογή για κινητά — έρχεται (λίστα αναμονής). Η εφαρμογή ΔΕΝ έχει
  // κυκλοφορήσει· το κείμενο μιλά σε μέλλοντα χρόνο, όπως η αρχική και Νόα.
  // Την ημέρα που βγει, το launch-blast το στέλνει η notify-mobile-launch.
  mobile_launch: (c) => ({
    subject: 'Έρχεται το PROPERWISE στο κινητό σου',
    html: emailShell({
      preheader: 'Μπες νωρίς στη λίστα αναμονής.',
      unsubUrl: c.unsubUrl,
      bodyHtml: eyebrow('Έρχεται') + h('Τα ακίνητά σου, παντού μαζί σου') + greeting(c.name)
        + p('Ετοιμάζουμε την εφαρμογή για κινητά. Οι εισπράξεις, οι ειδοποιήσεις και τα ακίνητά σου, στην τσέπη σου, όπου κι αν βρίσκεσαι.')
        + bullets([
            'Ειδοποιήσεις σε πραγματικό χρόνο για εισπράξεις και προθεσμίες.',
            'Γρήγορη καταχώρηση εσόδων και εξόδων με λίγα αγγίγματα.',
            'Ρώτα τη Νόα για τα ακίνητά σου, από όπου κι αν είσαι.',
          ])
        + p('Ώσπου να κυκλοφορήσει, ανοίγεις το PROPERWISE από τον browser του κινητού και το προσθέτεις στην αρχική οθόνη, σαν εφαρμογή.')
        + button('Μπες στη λίστα αναμονής', dash(c))
        + note('Θα είσαι από τους πρώτους που θα ειδοποιήσουμε μόλις είναι έτοιμη.'),
    }),
  }),

  // 48. Ενημέρωση νομοθεσίας ακινήτων
  legislation_update: (c) => {
    const head = c.headline ? esc(c.headline) : 'Μια αλλαγή που σε αφορά';
    const summary = c.summaryText
      ? p(esc(c.summaryText))
      : p('Μια πρόσφατη αλλαγή στη νομοθεσία των ακινήτων ίσως επηρεάζει τις υποχρεώσεις σου. Δες τι σημαίνει για τα δικά σου ακίνητα.');
    return { subject: `Νομοθεσία ακινήτων: ${head}`, html: emailShell({
      preheader: 'Τι αλλάζει και τι χρειάζεται να προσέξεις.',
      unsubUrl: c.unsubUrl,
      bodyHtml: eyebrow('Νομοθεσία ακινήτων') + h(head) + greeting(c.name)
        + summary
        + p('Το PROPERWISE ενημερώνεται συνεχώς, ώστε τα ακίνητά σου να μένουν σε τάξη, εύκολα και σωστά. Είναι καλή στιγμή να ρίξεις μια ματιά.')
        + button('Έλεγξε τα ακίνητά σου', dash(c))
        + note(NOTE.aade),
    }) };
  },
}
