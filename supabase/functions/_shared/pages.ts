// ΟΛΕΣ ΟΙ ΓΡΑΜΜΕΣ, ΣΕ ΣΕΛΙΔΕΣ: ΚΑΜΙΑ ΕΡΓΑΣΙΑ ΔΕΝ ΚΟΒΕΤΑΙ ΣΤΙΣ 1.000
// ─────────────────────────────────────────────────────────────────────────
// Το PostgREST επιστρέφει το πολύ `max_rows` γραμμές ανά αίτημα (1.000 στο
// Supabase) και ΔΕΝ λέει ότι έκοψε. Μια ανάγνωση «όλων των χρηστών» χωρίς
// σελίδες έφερνε τους πρώτους 1.000 και οι υπόλοιποι έμεναν εκτός σιωπηλά:
// χωρίς υπενθύμιση, χωρίς μηνιαία κατάσταση και, στο newsletter, με κενό
// χάρτη προτιμήσεων, δηλαδή αποστολή και σε όσους είχαν κάνει απεγγραφή
// (έλεγχος κλίμακας 10/11/2026).
//
// Η σελίδα είναι ΜΙΚΡΟΤΕΡΗ από το όριο του διακομιστή, ώστε μια σελίδα που
// γύρισε γεμάτη να σημαίνει πάντα «υπάρχει κι άλλη». Το ερώτημα χρειάζεται
// σταθερή ταξινόμηση με μοναδικό κλειδί στο τέλος, αλλιώς οι σελίδες
// επικαλύπτονται ή αφήνουν κενά.
// ═══════════════════════════════════════════════════════════════════════════

export const PAGE_SIZE = 500

type PageResult<T> = PromiseLike<{ data: T[] | null; error: { message: string } | null }>

/**
 * Διαβάζει όλες τις σελίδες. Το `page(from, to)` χτίζει ΚΑΘΕ φορά νέο ερώτημα
 * με `.order(...).range(from, to)`. Στο πρώτο σφάλμα σταματά και το επιστρέφει,
 * μαζί με όσα διαβάστηκαν: ο καλών αποφασίζει αν μια μισή λίστα αρκεί.
 */
export async function allPages<T>(
  page: (from: number, to: number) => PageResult<T>,
  size = PAGE_SIZE,
  maxPages = 10_000,
): Promise<{ rows: T[]; error: { message: string } | null }> {
  const rows: T[] = []
  for (let i = 0; i < maxPages; i++) {
    const from = i * size
    const { data, error } = await page(from, from + size - 1)
    if (error) return { rows, error }
    const got = data ?? []
    rows.push(...got)
    if (got.length < size) return { rows, error: null }
  }
  return { rows, error: { message: `allPages: περισσότερες από ${maxPages} σελίδες` } }
}
