// ═══════════════════════════════════════════════════════════════════════════
// Η ΕΙΣΑΓΩΓΗ ΚΙΝΗΣΕΩΝ ΣΤΟΝ «ΙΔΙΟΚΤΗΤΗ+» (απόφαση ιδιοκτήτη 24/11/2026)
// ─────────────────────────────────────────────────────────────────────────
// Ο ιδιώτης δεν έχει τον επαγγελματικό τρόπο (ημερολόγιο άρθρων, ισοζύγιο).
// Η αντιστοίχιση δεν ρωτά ούτε τρόπο ούτε πακέτο: παίρνει κινήσεις και
// ανεξόφλητα ενοίκια και τα χωρίζει σε τρία. Όσα ταίριαξαν με βεβαιότητα
// μπαίνουν με ένα «Καταχώρηση όλων (N)»· τα υπόλοιπα μένουν για απόφαση.
// Τρέξε: npx tsx lib/accounting/bankImportOwner.test.ts
// ═══════════════════════════════════════════════════════════════════════════
import { readBankCsv, planImport, type ExpectedRent } from './bankImport'
import { hasFeature } from '@/lib/billing/entitlements'

let passed = 0, failed = 0
function ok(name: string, cond: boolean) { if (cond) { passed++ } else { failed++; console.log('  ✗ ' + name) } }

// Λογαριασμός ιδιοκτήτη, ιδιώτης: κανένας επαγγελματικός τρόπος πουθενά.
ok('ο «Ιδιοκτήτης+» ιδιώτης έχει την εισαγωγή', hasFeature({ plan: 'owner', profileType: 'individual' }, 'bank_import'))
ok('ο «Ιδιοκτήτης+» ιδιώτης δεν παίρνει το ημερολόγιο άρθρων', !hasFeature({ plan: 'owner', profileType: 'individual' }, 'accounting_journal'))

// Ένα διαμέρισμα με ενοίκιο 450,00, τέσσερις ανεξόφλητοι μήνες με προθεσμία την 5η.
const rents: ExpectedRent[] = [9, 10, 11, 12].map(m => ({
  id: `r${m}`, label: `μήνας ${m}`, amount: 450, dueDate: `2026-${String(m).padStart(2, '0')}-05`,
}))
const csv = [
  'Ημερομηνία;Περιγραφή;Ποσό',
  '06/09/2026;ΚΑΤΑΘΕΣΗ ΕΝΟΙΚΙΟΥ ΣΕΠΤ;450,00',
  '05/10/2026;ΚΑΤΑΘΕΣΗ ΕΝΟΙΚΙΟΥ ΟΚΤ;450,00',
  '04/11/2026;ΚΑΤΑΘΕΣΗ ΕΝΟΙΚΙΟΥ ΝΟΕ;450,00',
  '20/12/2026;ΜΕΤΑΦΟΡΑ ΑΠΟ ΤΡΙΤΟ;450,00',
  '12/11/2026;ΔΕΗ ΛΟΓΑΡΙΑΣΜΟΣ;-38,50',
  '15/11/2026;ΕΠΙΣΤΡΟΦΗ ΕΓΓΥΗΣΗΣ;1200,00',
].join('\n')
const { txns } = readBankCsv(csv)
const plan = planImport(txns, rents)

// ── Βέβαια: ποσό ίσο και ημερομηνία μέσα σε πέντε ημέρες ───────────────────
ok('τρία ενοίκια ταίριαξαν με βεβαιότητα', plan.sure.length === 3)
ok('τα βέβαια είναι Σεπτέμβριος, Οκτώβριος, Νοέμβριος',
  plan.sure.map(m => m.rentId).join(',') === 'r9,r10,r11')
ok('κάθε βέβαιο κρατά την ημερομηνία της τράπεζας',
  plan.sure.map(m => m.txn.date).join(',') === '2026-09-06,2026-10-05,2026-11-04')

// ── Για απόφαση: ίδιο ποσό, μακριά από την προθεσμία ──────────────────────
ok('ο Δεκέμβριος (15 ημέρες μετά) μένει για απόφαση', plan.decide.length === 1 && plan.decide[0].rentId === 'r12')
ok('η χρέωση είναι πρόταση δαπάνης, όχι αυτόματη', plan.expenses.length === 1 && plan.expenses[0].amount === 38.5)
ok('η πίστωση 1.200,00 δεν ταιριάζει πουθενά', plan.unmatched.length === 1 && plan.unmatched[0].amount === 1200)
ok('καμία κίνηση δεν χάνεται και καμία δεν μετρά δύο φορές',
  plan.sure.length + plan.decide.length + plan.expenses.length + plan.unmatched.length === txns.length)

// ── Τίποτα βέβαιο: το κουμπί δεν έχει τι να καταχωρήσει ───────────────────
{
  const none = planImport(readBankCsv('Ημερομηνία;Περιγραφή;Ποσό\n20/12/2026;ΜΕΤΑΦΟΡΑ;450,00').txns, rents)
  ok('χωρίς βέβαιο ταίριασμα: μηδέν βέβαια', none.sure.length === 0)
  ok('χωρίς βέβαιο ταίριασμα: η κίνηση μένει για απόφαση', none.decide.length === 1)
}

console.log(`bankImport (Ιδιοκτήτης+) — ${passed} passed, ${failed} failed (σύνολο ${passed + failed})`)
if (failed > 0) { process.exit(1) }
console.log('όλα πέρασαν')
