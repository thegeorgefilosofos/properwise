const flat = (s: string): string =>
  s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/ς/g, 'σ').trim();

/**
 * Η κατηγορία του 4Δ2 από τον τύπο ακινήτου της εφαρμογής. Ο τύπος έχει δύο
 * μορφές στη βάση: κλειδί του οδηγού (`apartment`, `parking`) ή ελληνική
 * ετικέτα από παλιές εγγραφές («Κατοικία», «Αποθήκη Κτιρίου»). Ό,τι δεν
 * αναγνωρίζεται (μαζί και το «Άλλο») επιστρέφει null.
 */
export function e1PropertyClass(propType: string | null | undefined): E1PropertyClass | null {
  const t = flat(String(propType ?? ''));
  if (!t) return null;
  switch (t) {
    case 'apartment': case 'studio': case 'house': case 'villa': case 'maisonette': return 'home';
    case 'office': case 'shop': case 'warehouse': case 'parking': case 'storage': return 'business';
    case 'land': return 'land';
    case 'industrial': return 'industrial';
    case 'signage': return 'signage';
  }
  // Η σειρά μετράει: η «Αποθήκη πολυκατοικίας» έχει μέσα της «κατοικ» και η
  // «Επαγγελματική στέγη» τελειώνει σε «γη».
  if (/βιομηχανοστασ|εμπορικο κεντρο/.test(t)) return 'industrial';
  if (/επιγραφ/.test(t)) return 'signage';
  if (/οικοπεδ|γηπεδ|αγροτεμαχ|αγροσ|γαι(α|εσ)|(^|\s)γη(\s|\/|$)/.test(t)) return 'land';
  if (/γραφει|καταστημ|αποθηκ|σταθμευσ|γκαραζ|ξενοδοχ|κλινικ|σχολει|κινηματογραφ|θεατρ|επαγγελματικ|βοηθητικ/.test(t)) return 'business';
  if (/κατοικ|διαμερισμ|μεζονετ|στουντιο|βιλα|οικια/.test(t)) return 'home';
  return null;
}

/** Ο κωδικός μιας χρήσης, ή ο λόγος που δεν υπάρχει. */
export type E1Mapping =
  | { ok: true; cls: E1PropertyClass; code: E1Code }
  /** `flagged`: θέλει ανθρώπινη κρίση. Χωρίς σημαία: το έντυπο απλώς δεν έχει γραμμή. */
  | { ok: false; cls: E1PropertyClass | null; reason: string; flagged: boolean };

export const E1_UNKNOWN_TYPE = 'Άγνωστος τύπος ακινήτου: όρισε τον τύπο στο ακίνητο ή συμπλήρωσε τον κωδικό με τον λογιστή.';
export const E1_OWN_USE_HOME = 'Η ιδιοχρησιμοποίηση κατοικίας δεν έχει κωδικό στον πίνακα 4Δ2.';

/** Ο κωδικός του πίνακα 4Δ2 για τύπο ακινήτου και χρήση. Ποτέ σιωπηλά 103. */
export function e1CodeFor(propType: string | null | undefined, use: E1Use): E1Mapping {
  const cls = e1PropertyClass(propType);
  if (!cls) return { ok: false, cls: null, reason: E1_UNKNOWN_TYPE, flagged: true };
  const code = E1_4D2[use][cls];
  if (!code) return { ok: false, cls, reason: E1_OWN_USE_HOME, flagged: false };
  return { ok: true, cls, code };
}
