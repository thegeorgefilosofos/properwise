// Τεστ για την εισαγωγή τραπεζικής κίνησης + αντιστοίχιση (lib/accounting/bankImport.ts).
import { parseBankCsv, readBankCsv, parseAmount, parseDate, matchTransactions, legacyKeyOf, type ExpectedRent } from './bankImport'

let passed = 0, failed = 0
function ok(name: string, cond: boolean) { if (cond) { passed++ } else { failed++; console.log('  ✗ ' + name) } }
const near = (a: number | undefined, b: number, eps = 0.01) => a != null && Math.abs(a - b) <= eps

// ── parseAmount: ελληνικά & διεθνή ──────────────────────────────────────────
ok('1.234,56 → 1234.56', near(parseAmount('1.234,56')!, 1234.56))
ok('-45,00 → -45', near(parseAmount('-45,00')!, -45))
ok('1,234.56 → 1234.56 (διεθνές)', near(parseAmount('1,234.56')!, 1234.56))
ok('€ 800 → 800', near(parseAmount('€ 800')!, 800))
ok('(120,00) → -120 (παρενθέσεις)', near(parseAmount('(120,00)')!, -120))
ok('κενό → null', parseAmount('') === null)
ok('κείμενο → null', parseAmount('abc') === null)

// ── parseDate ───────────────────────────────────────────────────────────────
ok('15/03/2026 → ISO', parseDate('15/03/2026') === '2026-03-15')
ok('2026-03-15 → ISO', parseDate('2026-03-15') === '2026-03-15')
ok('5-3-26 → ISO (2ψήφιο έτος)', parseDate('5-3-26') === '2026-03-05')
ok('άκυρη → κενό', parseDate('foo') === '')

// ── parseBankCsv: διαχωριστικό ; + ποσό ─────────────────────────────────────
{
  const csv = 'Ημερομηνία;Περιγραφή;Ποσό\n05/03/2026;Ενοίκιο Μαρτίου;800,00\n07/03/2026;ΔΕΗ λογαριασμός;-120,50'
  const txns = parseBankCsv(csv)
  ok('2 κινήσεις', txns.length === 2)
  ok('πίστωση 800', near(txns[0].amount, 800))
  ok('χρέωση -120,50', near(txns[1].amount, -120.5))
  ok('ISO ημερομηνία', txns[0].date === '2026-03-05')
  ok('περιγραφή', txns[0].description === 'Ενοίκιο Μαρτίου')
}

// ── parseBankCsv: στήλες χρέωση/πίστωση χωριστά, διαχωριστικό tab ────────────
{
  const csv = 'Date\tDescription\tΧρέωση\tΠίστωση\n01/04/2026\tRent\t\t750,00\n03/04/2026\tInsurance\t60,00\t'
  const txns = parseBankCsv(csv)
  ok('credit → θετικό 750', near(txns[0].amount, 750))
  ok('debit → αρνητικό -60', near(txns[1].amount, -60))
}

// ── parseBankCsv: κόμμα ως διαχωριστικό ΚΑΙ δεκαδικό σε εισαγωγικά ───────────
{
  const csv = 'Ημερομηνία,Περιγραφή,Ποσό\n10/05/2026,"Ενοίκιο, Μάιος","1.000,00"'
  const txns = parseBankCsv(csv)
  ok('quoted πεδία + ποσό', txns.length === 1 && near(txns[0].amount, 1000))
  ok('κόμμα μέσα σε εισαγωγικά διατηρείται', txns[0].description === 'Ενοίκιο, Μάιος')
}

// ── Επικεφαλίδες τραπεζών: η «Ημερομηνία Αξίας» ΔΕΝ είναι ποσό ──────────────
// Το «αξία» ήταν κλειδί ποσού και η αναζήτηση γινόταν με υποσυμβολοσειρά, με
// πρώτη νίκη την πιο αριστερή στήλη: η «Ημερομηνία Αξίας» γινόταν στήλη ποσού,
// καμία γραμμή δεν διαβαζόταν και η οθόνη έλεγε «δεν διαβάστηκε καμία κίνηση».
// Τα δεδομένα είναι συνθετικά.
{
  const r = readBankCsv('Ημερομηνία;Ημερομηνία Αξίας;Περιγραφή;Ποσό;Υπόλοιπο\n05/03/2026;06/03/2026;Ενοίκιο Μαρτίου;800,00;2.300,00\n07/03/2026;07/03/2026;ΔΕΗ;-120,50;2.179,50')
  ok('Ημερομηνία Αξίας: 2 κινήσεις', r.txns.length === 2)
  ok('Ημερομηνία Αξίας: καμία χαμένη γραμμή', r.unreadable === 0)
  ok('Ημερομηνία Αξίας: ποσό από τη στήλη «Ποσό»', near(r.txns[0]?.amount, 800) && near(r.txns[1]?.amount, -120.5))
  ok('Ημερομηνία Αξίας: η ημερομηνία είναι της συναλλαγής', r.txns[0]?.date === '2026-03-05')
  ok('Ημερομηνία Αξίας: περιγραφή', r.txns[0]?.description === 'Ενοίκιο Μαρτίου')
}
{
  const r = readBankCsv('Ημερομηνία;Ημ/νία Αξίας;Αιτιολογία;Ποσό;Υπόλοιπο\n05/03/2026;06/03/2026;Ενοίκιο;800,00;2.300,00\n07/03/2026;07/03/2026;Κοινόχρηστα;-60,00;2.240,00')
  ok('Ημ/νία Αξίας: 2 κινήσεις', r.txns.length === 2 && r.unreadable === 0)
  ok('Ημ/νία Αξίας: ποσά', near(r.txns[0]?.amount, 800) && near(r.txns[1]?.amount, -60))
}
// Μορφή τύπου Πειραιώς: δύο στήλες ημερομηνίας στην αρχή. Το «συναλλαγή» είναι
// και κλειδί περιγραφής: η «Ημ/νία Συναλλαγής» δεν πρέπει να γίνει περιγραφή.
{
  const r = readBankCsv('Ημ/νία Συναλλαγής;Ημ/νία Αξίας;Περιγραφή;Ποσό;Υπόλοιπο\n12/03/2026;13/03/2026;ΕΜΒΑΣΜΑ ΜΙΣΘΩΤΗ;750,00;3.050,00\n14/03/2026;14/03/2026;ΠΛΗΡΩΜΗ ΚΑΡΤΑΣ;-45,00;3.005,00')
  ok('Πειραιώς: 2 κινήσεις', r.txns.length === 2 && r.unreadable === 0)
  ok('Πειραιώς: ποσά', near(r.txns[0]?.amount, 750) && near(r.txns[1]?.amount, -45))
  ok('Πειραιώς: ημερομηνία συναλλαγής', r.txns[0]?.date === '2026-03-12')
  ok('Πειραιώς: περιγραφή από τη στήλη «Περιγραφή»', r.txns[0]?.description === 'ΕΜΒΑΣΜΑ ΜΙΣΘΩΤΗ')
}
// Μορφές με χωριστές στήλες χρέωσης και πίστωσης (τύπου Εθνικής, Eurobank, Alpha).
{
  const r = readBankCsv('Ημερομηνία;Ημερομηνία Αξίας;Αιτιολογία;Χρέωση;Πίστωση;Υπόλοιπο\n01/04/2026;01/04/2026;Ενοίκιο;;750,00;1.750,00\n03/04/2026;03/04/2026;Ασφάλιστρο;60,00;;1.690,00')
  ok('χρέωση/πίστωση με Ημερομηνία Αξίας: 2 κινήσεις', r.txns.length === 2 && r.unreadable === 0)
  ok('χρέωση/πίστωση: πίστωση θετική', near(r.txns[0]?.amount, 750))
  ok('χρέωση/πίστωση: χρέωση αρνητική', near(r.txns[1]?.amount, -60))
}
{
  const r = readBankCsv('Ημ/νία Συναλλαγής;Ημ/νία Αξίας;Περιγραφή;Ποσό Χρέωσης;Ποσό Πίστωσης;Υπόλοιπο\n01/04/2026;02/04/2026;Ενοίκιο;;750,00;1.750,00\n03/04/2026;03/04/2026;Ασφάλιστρο;60,00;;1.690,00')
  ok('«Ποσό Χρέωσης/Πίστωσης»: 2 κινήσεις', r.txns.length === 2 && r.unreadable === 0)
  ok('«Ποσό Πίστωσης» θετικό', near(r.txns[0]?.amount, 750))
  ok('«Ποσό Χρέωσης» αρνητικό', near(r.txns[1]?.amount, -60))
}
// Αγγλικά: «Value Date».
{
  const r = readBankCsv('Date,Value Date,Description,Amount,Balance\n2026-03-05,2026-03-06,Rent March,800.00,2300.00\n2026-03-07,2026-03-07,Power bill,-120.50,2179.50')
  ok('Value Date: 2 κινήσεις', r.txns.length === 2 && r.unreadable === 0)
  ok('Value Date: ποσά', near(r.txns[0]?.amount, 800) && near(r.txns[1]?.amount, -120.5))
  ok('Value Date: ημερομηνία', r.txns[0]?.date === '2026-03-05')
}
{
  const r = readBankCsv('Value Date;Transaction Date;Details;Debit;Credit;Balance\n06/03/2026;05/03/2026;Rent;;800,00;2.300,00\n07/03/2026;07/03/2026;Insurance;60,00;;2.240,00')
  ok('Value Date πρώτη: 2 κινήσεις', r.txns.length === 2 && r.unreadable === 0)
  ok('Value Date πρώτη: προτιμάται η ημερομηνία συναλλαγής', r.txns[0]?.date === '2026-03-05')
  ok('Value Date πρώτη: χρέωση/πίστωση', near(r.txns[0]?.amount, 800) && near(r.txns[1]?.amount, -60))
}
// Το υπόλοιπο δεν είναι ποτέ ποσό κίνησης.
{
  const r = readBankCsv('Ημερομηνία;Περιγραφή;Υπόλοιπο\n05/03/2026;Ενοίκιο;2.300,00')
  ok('μόνο «Υπόλοιπο»: καμία κίνηση', r.txns.length === 0 && r.unreadable === 1)
  const b = readBankCsv('Date;Description;Balance;Amount\n2026-03-05;Rent;2300.00;800.00')
  ok('«Balance» πριν από «Amount»: ποσό από το Amount', near(b.txns[0]?.amount, 800))
}
// Επικεφαλίδες σε κεφαλαία χωρίς τόνους, όπως τις βγάζουν πολλά συστήματα.
{
  const r = readBankCsv('ΗΜΕΡΟΜΗΝΙΑ;ΗΜΕΡΟΜΗΝΙΑ ΑΞΙΑΣ;ΠΕΡΙΓΡΑΦΗ;ΠΟΣΟ\n05/03/2026;06/03/2026;ΕΝΟΙΚΙΟ;800,00')
  ok('κεφαλαία χωρίς τόνους: κίνηση', r.txns.length === 1 && near(r.txns[0]?.amount, 800))
  ok('κεφαλαία χωρίς τόνους: περιγραφή', r.txns[0]?.description === 'ΕΝΟΙΚΙΟ')
}
// «Ποσό Συναλλαγής» χωρίς στήλη περιγραφής: είναι ποσό, όχι περιγραφή.
{
  const r = readBankCsv('Ημερομηνία;Ποσό Συναλλαγής\n05/03/2026;800,00')
  ok('«Ποσό Συναλλαγής»: στήλη ποσού', r.txns.length === 1 && near(r.txns[0]?.amount, 800))
}
// Η μόνη «Αξία» χωρίς ημερομηνία μένει στήλη ποσού.
{
  const r = readBankCsv('Ημερομηνία;Περιγραφή;Αξία\n05/03/2026;Ενοίκιο;800,00')
  ok('«Αξία» σκέτη: στήλη ποσού', r.txns.length === 1 && near(r.txns[0]?.amount, 800))
}

// Η στήλη ημερομηνίας μπαίνει στο αποτύπωμα v2: η επιλογή της είναι συμβόλαιο.
// Με «Value Date» ή «Booking Date» δίπλα σε ημερομηνία συναλλαγής, νικά πάντα
// η συναλλαγή. Αν αλλάξει αυτό, αλλάζουν τα αποτυπώματα σε κάθε επανεισαγωγή.
{
  const r = readBankCsv('Value Date;Booking Date;Description;Amount\n06/03/2026;05/03/2026;Rent;800,00')
  ok('Value Date πριν από Booking Date: ημερομηνία κράτησης', r.txns[0]?.date === '2026-03-05')
  const g = readBankCsv('Ημ/νία Αξίας;Ημερομηνία;Περιγραφή;Ποσό\n06/03/2026;05/03/2026;Ενοίκιο;800,00')
  ok('Ημ/νία Αξίας πρώτη: ημερομηνία συναλλαγής', g.txns[0]?.date === '2026-03-05')
}
// Περιγραφή με λέξη χρημάτων στο όνομα: είναι περιγραφή όταν δεν υπάρχει καλύτερη.
{
  const r = readBankCsv('Ημερομηνία;Αιτιολογία Χρέωσης;Ποσό;Υπόλοιπο\n05/03/2026;ΠΛΗΡΩΜΗ ΔΕΗ;-84,50;1.200,00')
  ok('«Αιτιολογία Χρέωσης»: περιγραφή', r.txns[0]?.description === 'ΠΛΗΡΩΜΗ ΔΕΗ')
  ok('«Αιτιολογία Χρέωσης»: ποσό από το «Ποσό»', near(r.txns[0]?.amount, -84.5))
  const b = readBankCsv('Ημερομηνία;Περιγραφή Πίστωσης;Χρέωση;Πίστωση\n05/03/2026;ΕΜΒΑΣΜΑ;;750,00')
  ok('«Περιγραφή Πίστωσης»: περιγραφή', b.txns[0]?.description === 'ΕΜΒΑΣΜΑ')
  ok('«Περιγραφή Πίστωσης»: η πίστωση από τη στήλη «Πίστωση»', near(b.txns[0]?.amount, 750))
  const p = readBankCsv('Ημερομηνία;Αιτιολογία;Αιτιολογία Χρέωσης;Ποσό\n05/03/2026;ΔΕΗ;ΠΑΓΙΑ ΕΝΤΟΛΗ;-84,50')
  ok('καθαρή «Αιτιολογία» προτιμάται', p.txns[0]?.description === 'ΔΕΗ')
}

// ── Αντιστοίχιση ενοικίων ───────────────────────────────────────────────────
{
  const csv = 'Ημερομηνία;Περιγραφή;Ποσό\n03/03/2026;Κατάθεση ενοικίου;800,00\n20/03/2026;Super market;-45,00\n02/04/2026;Ενοίκιο;800,00'
  const txns = parseBankCsv(csv)
  const expected: ExpectedRent[] = [
    { id: 'mar', label: 'Μάρτιος', amount: 800, dueDate: '2026-03-01' },
    { id: 'apr', label: 'Απρίλιος', amount: 800, dueDate: '2026-04-01' },
  ]
  const res = matchTransactions(txns, expected)
  ok('2 ενοίκια ταιριάζουν', res.rentMatches.length === 2)
  ok('Μάρτιος high confidence (≤5 μέρες)', res.rentMatches.find(m => m.rentId === 'mar')?.confidence === 'high')
  ok('η χρέωση super market → πρόταση εξόδου', res.expenseSuggestions.some(e => near(e.amount, 45)))
  ok('κάθε κίνηση μία φορά', res.rentMatches.length + res.expenseSuggestions.length + res.unmatched.length === txns.length)
}

// ── Δεν αντιστοιχεί λάθος ποσό ───────────────────────────────────────────────
{
  const txns = parseBankCsv('Ημερομηνία;Περιγραφή;Ποσό\n03/03/2026;Κάτι;500,00')
  const res = matchTransactions(txns, [{ id: 'x', label: 'X', amount: 800, dueDate: '2026-03-01' }])
  ok('ποσό εκτός ανοχής δεν ταιριάζει', res.rentMatches.length === 0)
  ok('η αταίριαστη πίστωση μένει unmatched', res.unmatched.length === 1)
}

// ── Ίδιο ποσό εκτός χρονικού παραθύρου δεν ταιριάζει ────────────────────────
{
  const txns = parseBankCsv('Ημερομηνία;Περιγραφή;Ποσό\n01/06/2026;Ενοίκιο;800,00')
  const res = matchTransactions(txns, [{ id: 'jan', label: 'Ιαν', amount: 800, dueDate: '2026-01-01' }], 20)
  ok('εκτός 20 ημερών δεν ταιριάζει', res.rentMatches.length === 0)
}

// ── Αποτύπωμα: δύο ίδιες αναλήψεις είναι ΔΥΟ κινήσεις ───────────────────────
{
  const line = '12/03/2026;ΑΝΑΛΗΨΗ ΑΤΜ 1234;-50,00'
  const txns = parseBankCsv(`Ημερομηνία;Περιγραφή;Ποσό\n${line}\n${line}`)
  ok('δύο ίδιες γραμμές μένουν δύο κινήσεις', txns.length === 2)
  ok('με διαφορετικό αποτύπωμα', txns[0].key !== txns[1].key)
  ok('το παλιό αποτύπωμα τις έσβηνε', legacyKeyOf(txns[0]) === legacyKeyOf(txns[1]))
}

// ── Αποτύπωμα: το υπόλοιπο της γραμμής ξεχωρίζει τις κινήσεις ───────────────
{
  const csv = 'Ημερομηνία;Περιγραφή;Ποσό;Υπόλοιπο\n12/03/2026;ΑΝΑΛΗΨΗ ΑΤΜ;-50,00;1.200,00\n12/03/2026;ΑΝΑΛΗΨΗ ΑΤΜ;-50,00;1.150,00'
  const txns = parseBankCsv(csv)
  ok('διαφορετικό υπόλοιπο → διαφορετικό αποτύπωμα', txns[0].key !== txns[1].key)
}

// ── Αποτύπωμα: σταθερό στην ίδια εξαγωγή, ώστε να πιάνει τα διπλότυπα ───────
{
  const csv = 'Ημερομηνία;Περιγραφή;Ποσό\n12/03/2026;ΑΝΑΛΗΨΗ ΑΤΜ;-50,00\n12/03/2026;ΑΝΑΛΗΨΗ ΑΤΜ;-50,00\n15/03/2026;Ενοίκιο;800,00'
  const a = parseBankCsv(csv).map(t => t.key)
  const b = parseBankCsv(csv).map(t => t.key)
  ok('δεύτερη ανάγνωση δίνει τα ίδια αποτυπώματα', a.join('#') === b.join('#'))
  ok('τρία μοναδικά αποτυπώματα', new Set(a).size === 3)
  // Ενα κενό παραπάνω στο τέλος της γραμμής δεν κάνει νέα κίνηση.
  const c = parseBankCsv(csv.split('\n').map(l => l + ' ').join('\n')).map(t => t.key)
  ok('τα κενά στα άκρα δεν αλλάζουν αποτύπωμα', a.join('#') === c.join('#'))
}

// ── Το παλιό αποτύπωμα διαβάζεται όπως γράφτηκε στη βάση ────────────────────
{
  const t = parseBankCsv('Ημερομηνία;Περιγραφή;Ποσό\n05/03/2026;Ενοίκιο Μαρτίου;800,00')[0]
  ok('παλιό κλειδί = ημερομηνία|ποσό|περιγραφή', legacyKeyOf(t) === '2026-03-05|800|Ενοίκιο Μαρτίου')
  ok('νέο κλειδί χωριστής μορφής', t.key.startsWith('v2|') && t.key !== legacyKeyOf(t))
}

console.log(`bankImport.ts — ${passed} passed, ${failed} failed (σύνολο ${passed + failed})`)
if (failed > 0) { process.exit(1) }
console.log('όλα πέρασαν')
