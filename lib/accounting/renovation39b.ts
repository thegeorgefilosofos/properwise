// ΤΟ ΣΦΑΛΜΑ. Οκτώ σημεία της εφαρμογής (οδηγός, βάση γνώσης, Συμβουλευτική,
// σχέδιο ακινήτου, μοχλοί αγοράς, δάνεια, Νόα) έγραφαν «μείωση 40% της
// επιλέξιμης δαπάνης, όριο 16.000€ στη δαπάνη, μέγιστο όφελος 6.400€». Αυτός
// ήταν ο κανόνας του αρχικού άρθρου 39Β (ν.4646/2019), για δαπάνες 2020 έως
// 2022. Μια παλαιότερη «διόρθωση» (f17c1e77) τον επανέφερε πάνω στο σωστό
// κείμενο, που έλεγε 16.000€ σε πέντε έτη· ο ιδιοκτήτης διάβαζε όφελος
// δυόμισι φορές ΜΙΚΡΟΤΕΡΟ από αυτό που δικαιούται.
//
// ΤΙ ΙΣΧΥΕΙ ΚΑΙ ΑΠΟ ΠΟΥ.
//   · ν.5073/2023: αντικατέστησε το άρθρο 39Β από 1.1.2024. Η μείωση του φόρου
//     ΙΣΟΥΤΑΙ με την επιλέξιμη δαπάνη (100%), έως 16.000€ συνολικά για όλα τα
//     έτη, κατανεμημένη ισόποσα σε πέντε έτη και όχι πάνω από τον φόρο κάθε έτους.
//   · ΚΥΑ Α.1153/2025 (ΦΕΚ Β΄ 5933/05.11.2025): εφαρμοστική, με παράταση για
//     δαπάνες από 01.01.2024 έως 31.12.2026. Ηλεκτρονική πληρωμή, παραστατικά
//     στο ΑΦΜ του ιδιοκτήτη, πάροχοι με φορολογική κατοικία ή μόνιμη
//     εγκατάσταση στην Ελλάδα, υλικά έως το 1/3 της αξίας των υπηρεσιών. Η ίδια
//     δαπάνη δεν εκπίπτει ταυτόχρονα ως επιχειρηματική δαπάνη.
//   · Διατύπωση της ΔΕΔ 264/2026: «Το ανώτατο συνολικό ποσό των επιλέξιμων
//     δαπανών και της μείωσης του φόρου … 16.000 ευρώ, για όλα τα έτη».
//   Επιβεβαιώθηκε με αναζήτηση στις 01.10.2026 (taxheaven: Α.1153/2025, ΠΟΜΙΔΑ,
//   e-nomothesia «παράταση ισχύος της διάταξης και για το 2026»).
//
// ΟΤΑΝ ΑΛΛΑΞΕΙ ΞΑΝΑ. Αλλάζει εδώ και στο data/accounting-sources.json
// (`renovation_39b`). Κάθε κείμενο της εφαρμογής διαβάζει τα ποσά από εδώ.
// ═══════════════════════════════════════════════════════════════════════════
import { cents } from '../core/money';

/** Ανώτατο ποσό, ΤΑΥΤΟΧΡΟΝΑ επιλέξιμης δαπάνης και μείωσης φόρου, για όλα τα έτη. */
export const RENO_39B_CAP = 16000;
/** Έτη στα οποία κατανέμεται ισόποσα η μείωση. */
export const RENO_39B_YEARS = 5;
/** Το πολύ ανά έτος: 16.000€ / 5 = 3.200€. Ποτέ πάνω από τον φόρο του έτους. */
export const RENO_39B_PER_YEAR = RENO_39B_CAP / RENO_39B_YEARS;
/** Τα υλικά μετρούν έως αυτό το κλάσμα της αξίας των υπηρεσιών. */
export const RENO_39B_MATERIALS_SHARE = 1 / 3;
/** Παράθυρο δαπανών: από… έως… (ΚΥΑ Α.1153/2025), στη γραφή της οθόνης (ηη/μμ/εεεε, όπως το `grDate`). */
export const RENO_39B_FROM = '01/01/2024';
export const RENO_39B_TO = '31/12/2026';
/** Η νομική βάση, όπως γράφεται σε κάθε κείμενο που την επικαλείται. */
export const RENO_39B_LAW = 'άρθρο 39Β ΚΦΕ (ν.4172/2013), όπως αντικαταστάθηκε με τον ν.5073/2023';
export const RENO_39B_KYA = 'ΚΥΑ Α.1153/2025 (ΦΕΚ Β΄ 5933/05.11.2025)';
/**
 * Ο ΠΑΛΙΟΣ κανόνας, μόνο για σύγκριση: το αρχικό άρθρο 39Β (ν.4646/2019), για
 * δαπάνες 2020 έως 2022, έδινε μείωση 40% της επιλέξιμης δαπάνης. Με όριο
 * δαπάνης 16.000€ το όφελος έφτανε το πολύ τα 6.400€. Το κυκλοφορεί ακόμη ο
 * κόσμος· οδηγός και περιεχόμενο το διαψεύδουν από εδώ, όχι με δικό τους αριθμό.
 */
export const RENO_39B_OLD_RATE = 0.4;

export interface RenovationCredit {
  /** Υλικά που μετρούν, μετά το όριο του 1/3 των υπηρεσιών. */
  materialsCounted: number;
  /** Επιλέξιμη δαπάνη: υπηρεσίες + υλικά που μετρούν, ΠΡΙΝ το ανώτατο όριο. */
  eligible: number;
  /** Συνολική μείωση φόρου: ίση με την επιλέξιμη δαπάνη, έως 16.000€. */
  total: number;
  /** Μείωση ανά έτος, στα πέντε έτη, ΠΡΙΝ το όριο του φόρου κάθε έτους. */
  perYear: number;
  /**
   * Η μείωση που πράγματι δίνεται κάθε έτος: `perYear`, κομμένη στον φόρο του
   * έτους. Υπάρχει μόνο όταν δόθηκαν οι φόροι των ετών (`yearTaxes`).
   */
  byYear?: number[];
  /** Το άθροισμα του `byYear`: όσο πράγματι μειώνεται ο φόρος στα πέντε έτη. */
  applied?: number;
}

const pos = (n: number | null | undefined) => Math.max(0, Number.isFinite(n as number) ? (n as number) : 0);

/**
 * Πόσο μειώνεται ο φόρος για μια ανακαίνιση. Τα ποσά είναι δαπάνες που
 * πληρώθηκαν ηλεκτρονικά και τιμολογήθηκαν στο ΑΦΜ του ιδιοκτήτη.
 *
 * `renovationCredit({ services: 9000, materials: 5000 })` → υλικά 3.000,
 * επιλέξιμη 12.000, μείωση 12.000, 2.400 τον χρόνο.
 */
export function renovationCredit(i: { services: number; materials: number; yearTaxes?: readonly number[] }): RenovationCredit {
  const services = pos(i.services);
  const materialsCounted = cents(Math.min(pos(i.materials), services * RENO_39B_MATERIALS_SHARE));
  const eligible = cents(services + materialsCounted);
  const total = Math.min(eligible, RENO_39B_CAP);
  const perYear = cents(total / RENO_39B_YEARS);
  if (!i.yearTaxes) return { materialsCounted, eligible, total, perYear };
  const byYear = i.yearTaxes.slice(0, RENO_39B_YEARS).map(t => renovationYearReduction(perYear, t));
  return { materialsCounted, eligible, total, perYear, byYear, applied: cents(byYear.reduce((a, b) => a + b, 0)) };
}

/**
 * Η μείωση ΕΝΟΣ έτους: το ετήσιο μερίδιο, όχι πάνω από τον φόρο του έτους.
 *
 * ΤΟ ΣΦΑΛΜΑ. Ο οδηγός έγραφε «όχι πάνω από τον φόρο του έτους» και η
 * συνάρτηση δεν δεχόταν καν τον φόρο: έβγαζε δαπάνη διά πέντε, το πολύ 3.200€,
 * και ο ιδιοκτήτης με φόρο 1.500€ διάβαζε μείωση 3.200€. Ο κανόνας ήταν
 * κείμενο, όχι αριθμός που κόβεται. Φόρος μηδέν σημαίνει μείωση μηδέν· ό,τι
 * περισσεύει δεν επιστρέφεται.
 *
 * `renovationYearReduction(3200, 1500)` → 1.500.
 */
export function renovationYearReduction(perYear: number, yearTax: number | null | undefined): number {
  return cents(Math.min(pos(perYear), pos(yearTax)));
}
