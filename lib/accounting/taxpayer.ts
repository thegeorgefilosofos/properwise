// Η κλίμακα των ενοικίων είναι προοδευτική στο ΣΥΝΟΛΟ του ΕΝΟΣ φορολογούμενου
// (Ε1). Η Λογιστική έτρεχε την ενοποίηση σε ΟΛΑ τα ακίνητα του λογαριασμού. Για
// τον ιδιώτη αυτό είναι σωστό: ένας λογαριασμός, ένας φορολογούμενος. Ο
// επαγγελματίας διαχειριστής όμως κρατά στον ίδιο λογαριασμό ακίνητα πολλών
// ιδιοκτητών, συνδεδεμένα ο καθένας με την καρτέλα «Ιδιοκτήτης» του
// Πελατολογίου. Δύο ιδιοκτήτες με 12.000€ ο καθένας έβγαιναν ένας με 24.000€:
// το δεύτερο δωδεκάρι ανέβαινε στο κλιμάκιο του 25% και του 35% και ο φόρος
// κάθε ιδιοκτήτη φαινόταν μεγαλύτερος απ' όσο θα του έβγαζε η ΑΑΔΕ.
//
// ΜΟΝΟ Ο ΤΥΠΟΣ «ΙΔΙΟΚΤΗΤΗΣ» ΧΩΡΙΖΕΙ. Το `client_id` ενός ακινήτου μπορεί να
// δείχνει και σε «Πελάτη» (επισκέπτη) ή σε «Υποψήφιο»: αυτοί δεν είναι
// φορολογούμενοι του ακινήτου και ο διαχωρισμός με αυτούς θα έκοβε τον φόρο
// του ίδιου ανθρώπου στα δύο — δηλαδή θα τον έδειχνε ΜΙΚΡΟΤΕΡΟ. Ακίνητο χωρίς
// σύνδεση ή με σύνδεση σε άλλο τύπο ανήκει στον κάτοχο του λογαριασμού.
// ═══════════════════════════════════════════════════════════════════════════

/** Κλειδί για τα ακίνητα του ίδιου του κατόχου του λογαριασμού. */
export const ACCOUNT_HOLDER = '__self__'

export interface TaxpayerProperty { id: string; client_id?: string | null }

/** Σε ποιον φορολογούμενο ανήκει το ακίνητο. */
export function taxpayerOf(p: TaxpayerProperty, ownerClientIds: ReadonlySet<string>): string {
  return p.client_id && ownerClientIds.has(p.client_id) ? p.client_id : ACCOUNT_HOLDER
}

/**
 * Τα ακίνητα του ΙΔΙΟΥ φορολογούμενου με το `propertyId`.
 *
 * `ownerClientIds === null` σημαίνει «ένας φορολογούμενος»: ο ιδιώτης, ή
 * λογαριασμός που δεν διαβάστηκε το Πελατολόγιό του. Τότε επιστρέφονται όλα,
 * όπως πριν.
 */
export function sameTaxpayer<T extends TaxpayerProperty>(
  props: readonly T[], propertyId: string, ownerClientIds: ReadonlySet<string> | null,
): T[] {
  if (!ownerClientIds || ownerClientIds.size === 0) return [...props]
  const current = props.find(p => p.id === propertyId)
  const key = current ? taxpayerOf(current, ownerClientIds) : ACCOUNT_HOLDER
  return props.filter(p => taxpayerOf(p, ownerClientIds) === key)
}
