// Ο ΒΑΘΜΟΛΟΓΗΤΗΣ, ΜΕ ΓΡΑΜΜΕΝΕΣ ΑΠΑΝΤΗΣΕΙΣ
// ─────────────────────────────────────────────────────────────────────────
// Ο βαθμολογητής κρίνει αν ένα ποσοστό ορθότητας λέει αλήθεια. Αν διαβάζει
// λάθος μια ημερομηνία ή αφήνει να περάσει ένα «ο βοηθός σου», το ποσοστό
// ανεβαίνει χωρίς η Νόα να έγινε καλύτερη. Εδώ δοκιμάζεται χωρίς μοντέλο.
// ═══════════════════════════════════════════════════════════════════════════
import { extractDates, mentionsDate, hasPhrase, gradeAnswer, identityChecks, type Expectation } from './evalGrade';

let pass = 0, fail = 0;
const ok = (n: string, c: boolean) => { if (c) pass++; else { fail++; console.error('✗ ' + n) } };

// ── ΗΜΕΡΟΜΗΝΙΕΣ ────────────────────────────────────────────────────────────
{
  const d = extractDates('Λήγει 30/10/2026, η επόμενη 30.11.2026 και η τελευταία στις 26 Φεβρουαρίου 2027.');
  ok('διαβάζει «30/10/2026»', d.includes('2026-10-30'));
  ok('διαβάζει «30.11.2026»', d.includes('2026-11-30'));
  ok('διαβάζει «26 Φεβρουαρίου 2027»', d.includes('2027-02-26'));
  ok('διαβάζει ISO', extractDates('ημερομηνία 2027-07-01').includes('2027-07-01'));
  ok('διαβάζει «15 Ιουλίου» χωρίς έτος', extractDates('ως τις 15 Ιουλίου').includes('--07-15'));
  ok('διαβάζει «22/6»', extractDates('έως 22/6').includes('--06-22'));
  ok('διαβάζει «1η Ιουλίου 2027»', extractDates('από την 1η Ιουλίου 2027').includes('2027-07-01'));
  ok('διαβάζει «20 Μαΐου» με τόνο και διαλυτικά', extractDates('στις 20 Μαΐου').includes('--05-20'));
  ok('διαβάζει κεφαλαία «31 ΜΑΡΤΙΟΥ»', extractDates('31 ΜΑΡΤΙΟΥ 2026').includes('2026-03-31'));
  // Ποσά δεν είναι ημερομηνίες.
  ok('το «1.075» δεν είναι ημερομηνία', extractDates('δόση 1.075€').length === 0);
  ok('το «12.000» δεν είναι ημερομηνία', extractDates('έως 12.000€').length === 0);
  ok('το «10,58» δεν είναι ημερομηνία', extractDates('10,58€ ο μήνας').length === 0);
  ok('το «45 τ.μ.» δεν είναι ημερομηνία', extractDates('45 τετραγωνικά').length === 0);
  ok('άκυρη μέρα απορρίπτεται', extractDates('32/13/2026').length === 0);
  ok('ταιριάζει χωρίς έτος', mentionsDate(['--10-30'], '2026-10-30'));
  ok('δεν ταιριάζει άλλο έτος', !mentionsDate(['2025-10-30'], '2026-10-30'));
}

// ── ΦΡΑΣΕΙΣ ─────────────────────────────────────────────────────────────────
ok('φράση χωρίς τόνους και πεζά', hasPhrase('Ρώτα τον ΛΟΓΙΣΤΉ σου.', { label: 'λογιστής', any: ['λογιστ'] }));
ok('εναλλακτική αρκεί μία', hasPhrase('Δεν έχω φύλο.', { label: 'φύλο', any: ['χωρις φυλο', 'δεν εχω φυλο'] }));
ok('απούσα φράση', !hasPhrase('Ο φόρος είναι 900€.', { label: 'λογιστής', any: ['λογιστ'] }));

// ── ΤΑΥΤΟΤΗΤΑ ────────────────────────────────────────────────────────────────
const failing = (t: string) => identityChecks(t).filter(c => !c.ok).map(c => c.name);
ok('καθαρή απάντηση', failing('Είμαι η Νόα. Δεν είμαι σίγουρο, ρώτα τον λογιστή σου.').length === 0);
ok('«είμαι σίγουρη» πιάνεται', failing('Ναι, είμαι σίγουρη για το ποσό.').includes('χωρίς φύλο'));
ok('«είμαι έτοιμος» πιάνεται', failing('Είμαι έτοιμος να βοηθήσω.').includes('χωρίς φύλο'));
ok('«δεν είμαι σίγουρος» πιάνεται', failing('Δεν είμαι σίγουρος.').includes('χωρίς φύλο'));
ok('«ο βοηθός σου» πιάνεται', failing('Είμαι ο βοηθός σου.').includes('ταυτότητα'));
ok('«βοηθός» ως ουσιαστικό πιάνεται', failing('Ως βοηθός της εφαρμογής, απαντώ.').includes('όχι «βοηθός»'));
ok('«δωρεάν Νόα» πιάνεται', failing('Η Νόα είναι δωρεάν.').includes('ταυτότητα'));
ok('το ρήμα «βοηθώ» περνά', failing('Σε βοηθώ με χαρά, με βοήθεια από τα δεδομένα σου.').length === 0);
ok('ο δωρεάν «Ιδιοκτήτης» χωρίς τη Νόα περνά', failing('Ο δωρεάν «Ιδιοκτήτης» είναι χωρίς τη Νόα.').length === 0);
ok('ο χρήστης μπορεί να είναι «σίγουρος»', failing('Αν είσαι σίγουρος για το ενοίκιο, το γράφουμε.').length === 0);

// ── Η ΚΡΙΣΗ ──────────────────────────────────────────────────────────────────
{
  const e: Expectation = {
    amounts: [{ value: 10.58, tolerance: 0.01, label: 'δόση' }, { value: 8, tolerance: 0, label: 'δόσεις' }],
    wrongAmounts: [7.06],
    required: [{ label: 'λογιστής', any: ['λογιστ'] }],
    forbidden: [{ label: 'δώδεκα δόσεις', any: ['12 δοσεις'] }],
  };
  ok('όλα σωστά: σωστό', gradeAnswer(e, 'Σε 8 δόσεις των 10,58€. Επιβεβαίωσε με τον λογιστή σου.').verdict === 'pass');
  ok('ανοχή στο λεπτό: 10,59 περνά', gradeAnswer(e, 'Σε 8 δόσεις των 10,59€, ρώτα τον λογιστή.').verdict === 'pass');
  ok('ανοχή στο λεπτό: 10,60 δεν περνά', gradeAnswer(e, 'Σε 8 δόσεις των 10,60€, ρώτα τον λογιστή.').verdict === 'fail');
  ok('λείπει ποσό: λάθος', gradeAnswer(e, 'Σε δόσεις των 10,58€, ρώτα τον λογιστή.').verdict === 'fail');
  ok('λείπει φράση: λάθος', gradeAnswer(e, 'Σε 8 δόσεις των 10,58€.').verdict === 'fail');
  ok('απαγορευμένη φράση: λάθος', gradeAnswer(e, 'Σε 8 δόσεις των 10,58€ αντί για 12 δόσεις. Λογιστής.').verdict === 'fail');
  ok('σωστό και γνωστό λάθος μαζί: διφορούμενο',
    gradeAnswer(e, 'Σε 8 δόσεις των 10,58€ ή 12 των 7,06€. Λογιστής.').verdict === 'ambiguous');
  ok('ταυτότητα ρίχνει και σωστό ποσό',
    gradeAnswer(e, 'Ως βοηθός σου: 8 δόσεις των 10,58€, ρώτα τον λογιστή.').verdict === 'fail');
  const g = gradeAnswer(e, 'Σε 8 δόσεις των 10,60€, ρώτα τον λογιστή.');
  ok('ο λόγος της αποτυχίας γράφεται', g.checks.some(c => !c.ok && c.name === 'ποσό: δόση'));
  const d = gradeAnswer({ dates: ['2026-10-30'] }, 'Η 8η δόση λήγει στις 30 Οκτωβρίου 2026.');
  ok('ημερομηνία: σωστό', d.verdict === 'pass');
  ok('ημερομηνία: άλλη μέρα λάθος', gradeAnswer({ dates: ['2026-10-30'] }, 'Λήγει 31/10/2026.').verdict === 'fail');
  ok('ποσοστό χωρίς ανοχή', gradeAnswer({ amounts: [{ value: 40, tolerance: 0, label: 'όριο' }] }, 'Έως 40% του εισοδήματος.').verdict === 'pass');
  ok('ποσοστό: το 50 δεν είναι 40', gradeAnswer({ amounts: [{ value: 40, tolerance: 0, label: 'όριο' }] }, 'Έως 50%.').verdict === 'fail');
}

console.log(fail === 0 ? `✓ evalGrade: ${pass} έλεγχοι πέρασαν` : `✗ evalGrade: ${fail} απέτυχαν από ${pass + fail}`);
if (fail > 0) process.exit(1);
