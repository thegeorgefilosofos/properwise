// ═══════════════════════════════════════════════════════════════════════════
// Προτεινόμενες ερωτήσεις — «ρώτα για ΤΑ ΔΙΚΑ ΣΟΥ νούμερα»
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΠΡΟΒΛΗΜΑ
// Η Νόα άνοιγε με γενικές ερωτήσεις τύπου «Πώς φορολογείται το ενοίκιο;».
// Αυτό είναι ερώτηση για μηχανή αναζήτησης. Ο χρήστης το σκέφτεται μία φορά,
// παίρνει μια απάντηση που θα έβρισκε και αλλού και δεν ξαναγυρνά — γιατί
// τίποτα δεν του θύμισε ότι Νόα βλέπει ΤΑ ΔΙΚΑ ΤΟΥ δεδομένα.
//
// Η ΑΛΛΑΓΗ
// Κάθε πρόταση αναφέρεται σε δικό του νούμερο ή σε δική του κατάσταση:
// «Πόσο μου μένει καθαρά από τα 700€ του ακινήτου «Διαμέρισμα Κυψέλης»;».
// Αν λείπουν τα δεδομένα, δεν επινοούμε νούμερα: γυρνάμε σε προτάσεις που
// ΟΔΗΓΟΥΝ στη συμπλήρωση («Τι χρειάζεσαι για να μου πεις τον φόρο μου;»).
//
// ΚΑΝΟΝΕΣ
//  • Ποτέ νούμερο που δεν υπάρχει. Καμία «τυπική τιμή αγοράς» σαν να είναι δική του.
//  • Πάντα δεύτερο πρόσωπο και κτητικό: «σου», «σου μένει», «τα δικά σου».
//  • Μέγιστο 4 προτάσεις: πάνω από αυτό γίνεται μενού, όχι πρόσκληση.
//  • Σειρά προτεραιότητας: επείγον → χρήμα → φόρος → βελτίωση.
//
// ΤΟ ΟΝΟΜΑ ΤΟΥ ΑΚΙΝΗΤΟΥ ΔΕΝ ΚΛΙΝΕΤΑΙ. Είναι ό,τι έγραψε ο χρήστης, συνήθως
// «Διαμέρισμα/Μονοκατοικία + τόπος» και κολλημένο σε άρθρο έβγαζε «του
// Διαμέρισμα Κυψέλης». Μπαίνει σε εισαγωγικά μετά από το «ακίνητο», που κλίνεται.
//
// Καθαρή λογική, χωρίς React/Supabase, ώστε να ελέγχεται με tests.
// ═══════════════════════════════════════════════════════════════════════════

import { ASSISTANT_NAME } from './identity';
import { fe } from '../core/format';
import { navLabel } from '../nav/labels';

export interface OpenerContext {
  /** Όνομα του επιλεγμένου ακινήτου (π.χ. «Διαμέρισμα Κυψέλης»). */
  propertyName?: string;
  /** Μηνιαίο μίσθωμα σε ευρώ, όπως το ξέρει η εφαρμογή. */
  monthlyRent?: number | null;
  /** Αξία ακινήτου σε ευρώ. */
  propertyValue?: number | null;
  /** Δαπάνες του τρέχοντος έτους σε ευρώ. */
  expensesYtd?: number | null;
  /** Ανοιχτά στοιχεία της καρτέλας «Εκκρεμότητες» (checklist). Μόνο αυτά. */
  openTasks?: number;
  /** Ληξιπρόθεσμο ενοίκιο σε ευρώ. */
  overdueRent?: number | null;
  /** Έχει καταχωρημένο δάνειο. */
  hasLoan?: boolean;
  /** Βραχυχρόνια μίσθωση. */
  isShortTerm?: boolean;
  /** Πλήθος ακινήτων του χρήστη. */
  propertyCount?: number;
}

const MAX = 4;

/**
 * Ευρώ σε ελληνική μορφή. Ήταν «χωρίς άσκοπα δεκαδικά» — δηλαδή ακριβώς τα
 * «έξυπνα» δεκαδικά που η εφαρμογή έχει καταργήσει: ο βοηθός έλεγε «450€» για
 * το ίδιο ποσό που η καρτέλα δίπλα του έγραφε «450,00€».
 */
export const eur = fe;

/** Θετικός αριθμός με νόημα; (το 0 και το null δεν είναι δεδομένο) */
const has = (n: number | null | undefined): n is number => typeof n === 'number' && Number.isFinite(n) && n > 0;

/** Προτάσεις όσο ΔΕΝ έχουν φορτώσει ακόμη τα δεδομένα.
 *
 *  Κρίσιμη διάκριση: «δεν ξέρω ακόμη» ≠ «δεν έχεις τίποτα». Ο χρήστης με τρία
 *  χρόνια δαπάνες που ανοίγει τη συνομιλία δεν πρέπει να διαβάσει «μόλις
 *  καταχωρήσεις τα πρώτα στοιχεία…» επειδή δεν γύρισε ακόμη το ερώτημα. */
const LOADING_OPENERS = [
  'Τι εκκρεμεί στο ακίνητό μου αυτή τη στιγμή;',
  'Πόσο μου μένει καθαρά από το ενοίκιο;',
  'Πόσο φόρο θα πληρώσω φέτος;',
];

/**
 * Οι προτάσεις εκκίνησης για τον συγκεκριμένο χρήστη και ακίνητο.
 *
 * Επιστρέφει το πολύ MAX ερωτήσεις, με σειρά προτεραιότητας. Κάθε ερώτηση που
 * περιέχει νούμερο, το παίρνει από τα δεδομένα — ποτέ από εκτίμηση.
 *
 * `null` σημαίνει «τα δεδομένα δεν έχουν φορτώσει», όχι «δεν υπάρχουν δεδομένα».
 */
export function suggestedOpeners(ctx: OpenerContext | null = {}): string[] {
  if (ctx === null) return [...LOADING_OPENERS];
  const out: string[] = [];
  const name = (ctx.propertyName || '').trim();
  const forProp = name ? ` στο ακίνητο «${name}»` : '';

  // 1. ΕΠΕΙΓΟΝ — ό,τι κοστίζει τώρα ή έχει προθεσμία.
  if (has(ctx.overdueRent)) {
    out.push(`Μου χρωστάει ${eur(ctx.overdueRent)} ενοίκιο· τι κάνω;`);
  }
  // Ο ΑΡΙΘΜΟΣ ΛΕΕΙ ΠΟΙΑ ΛΙΣΤΑ ΜΕΤΡΑ. Σκέτο «3 εκκρεμότητες» διαβαζόταν δίπλα σε
  // «4 εκκρεμότητες» των ταμειακών και «4 σε σειρά προθεσμίας» της ατζέντας,
  // στην ίδια οθόνη. Μετρά μόνο την καρτέλα του μενού, οπότε την ονομάζει.
  if ((ctx.openTasks ?? 0) > 0) {
    const n = ctx.openTasks as number;
    const tab = `στην καρτέλα «${navLabel('checklist')}»`;
    out.push(n === 1 ? `Τι έχω ανοιχτό ${tab} και πότε λήγει;` : `Έχω ${n} ανοιχτά ${tab}· ποιο είναι το πιο επείγον;`);
  }

  // 2. ΧΡΗΜΑ — το νούμερο που τον απασχολεί πραγματικά.
  if (has(ctx.monthlyRent)) {
    out.push(`Από τα ${eur(ctx.monthlyRent)} τον μήνα, πόσο μου μένει καθαρά;`);
  }
  if (has(ctx.expensesYtd)) {
    out.push(`Ξόδεψα ${eur(ctx.expensesYtd)} φέτος${forProp}· πού πήγαν;`);
  }

  // 3. ΦΟΡΟΣ & ΑΠΟΔΟΣΗ — ο λόγος που έψαξε λύση.
  if (has(ctx.monthlyRent)) {
    out.push('Πόσο φόρο θα πληρώσω φέτος για τα δικά μου ενοίκια;');
  }
  if (has(ctx.monthlyRent) && has(ctx.propertyValue)) {
    out.push(`Τι απόδοση βγάζει${forProp ? forProp.replace(' στο ', ' το ') : ' το ακίνητό μου'} με τα σημερινά νούμερα;`);
  }
  if (ctx.hasLoan) {
    out.push('Συμφέρει να ρίξω κεφάλαιο στο δάνειό μου ή να το κρατήσω;');
  }
  if (ctx.isShortTerm) {
    // Ερώτηση που απαντιέται από τις καταχωρημένες διαμονές, όχι πρόταση τιμής:
    // η τιμολόγηση βραχυχρόνιας στηρίζεται σε εμπειρικούς κανόνες (δεύτερο κύμα).
    out.push('Πόσα εισέπραξα από διαμονές φέτος και πόσα δηλώνω;');
  }
  if ((ctx.propertyCount ?? 0) > 1) {
    out.push('Ποιο από τα ακίνητά μου αποδίδει καλύτερα;');
  }

  // 4. ΧΩΡΙΣ ΔΕΔΟΜΕΝΑ — δεν επινοούμε νούμερα· δείχνουμε τι λείπει.
  // Αυτές μπαίνουν ΜΟΝΟ αν δεν βρέθηκε αρκετό πραγματικό υλικό, ώστε ο νέος
  // χρήστης να δει διαδρομή αντί για άδεια οθόνη.
  if (out.length < MAX) {
    const fallbacks: string[] = [];
    if (!has(ctx.monthlyRent)) fallbacks.push('Τι χρειάζεσαι από μένα για να μου πεις πόσο φόρο θα πληρώσω;');
    if (!has(ctx.expensesYtd)) fallbacks.push('Πώς καταχωρώ μια δαπάνη με μια φωτογραφία;');
    if (!has(ctx.propertyValue)) fallbacks.push('Τι στοιχεία λείπουν από το ακίνητό μου;');
    fallbacks.push('Τι μπορείς να κάνεις με τα δικά μου δεδομένα;');
    for (const f of fallbacks) { if (out.length >= MAX) break; out.push(f); }
  }

  return out.slice(0, MAX);
}

/**
 * Ο χαιρετισμός: λέει τι ΞΕΡΕΙ η Νόα, όχι τι είναι.
 * «Ρώτησέ με οτιδήποτε» δεν λέει τίποτα· «βλέπω τα νούμερα του Χ» λέει τα πάντα.
 *
 * ΣΥΣΤΗΝΕΤΑΙ ΟΣΟ ΔΕΝ ΥΠΑΡΧΕΙ ΤΙΠΟΤΑ ΝΑ ΠΕΙ, ΜΕΤΑ ΜΙΛΑ ΣΥΝΤΟΜΑ. Η γραμμή
 * έγραφε κάθε μέρα «Γεια σου! Είμαι Νόα. Βλέπω … Ρώτα με για τα δικά σου
 * δεδομένα και νούμερα.», τρεις προτάσεις σύστασης σε οθόνη εργασίας. Όποιος
 * έχει ήδη καταχωρήσει ενοίκιο ή δαπάνες έχει δει την εφαρμογή· του αρκεί μία
 * γραμμή που λέει τι μπορεί να ρωτήσει. Η πλήρης σύσταση μένει για το άδειο
 * ακίνητο, εκεί όπου εξηγεί τι χρειάζεται. Κριτήριο τα δεδομένα και όχι σημαία
 * στη συσκευή: ίδια απάντηση σε διακομιστή και περιηγητή, σε κάθε συσκευή.
 */
export function greeting(assistantName: string = ASSISTANT_NAME, ctx: OpenerContext | null = {}, formal = false): string {
  // Ο πληθυντικός ευγενείας πρέπει να είναι ΟΛΟΚΛΗΡΟΣ. Μεικτό «Γεια σου …
  // Ρωτήστε με» ακούγεται χειρότερα από το να μην υπήρχε καθόλου η ρύθμιση.
  const hi = formal ? 'Γεια σας' : 'Γεια σου';
  const you = formal ? 'Ρωτήστε με' : 'Ρώτα με';
  const your = formal ? 'σας' : 'σου';
  // «Στοιχεία», όχι «δεδομένα και νούμερα»: τα νούμερα είναι δεδομένα. Και η
  // Νόα διαβάζει λογαριασμούς, συμβόλαια και ημερομηνίες, όχι μόνο ποσά.
  const yours = formal ? 'τα δικά σας στοιχεία' : 'τα δικά σου στοιχεία';

  // Δεν έχουν φορτώσει ακόμη τα δεδομένα: δεν λέμε ούτε «βλέπω», ούτε «δεν έχεις».
  if (ctx === null) {
    return `${hi}. Είμαι ${assistantName}. Κοιτάζω τα στοιχεία ${your}…`;
  }

  const name = (ctx.propertyName || '').trim();
  const many = (ctx.propertyCount ?? 0) > 1;

  const scope = many
    ? `των ${ctx.propertyCount} ακινήτων ${your}`
    : name ? `του ακινήτου «${name}»` : `του ακινήτου ${your}`;

  const knows: string[] = [];
  if (has(ctx.monthlyRent)) knows.push('τα ενοίκια');
  if (has(ctx.expensesYtd)) knows.push('τις δαπάνες');
  if (ctx.hasLoan) knows.push('το δάνειο');
  if ((ctx.openTasks ?? 0) > 0) knows.push('τις εκκρεμότητες');

  if (knows.length === 0) {
    const enter = formal ? 'καταχωρήσετε' : 'καταχωρήσεις';
    const first = formal ? 'να καταχωρήσετε' : 'να καταχωρήσεις';
    return `${hi}. Είμαι ${assistantName}. Μόλις ${enter} τα πρώτα στοιχεία ${scope}, θα απαντώ με βάση αυτά. ${you} τι ${first} πρώτα.`;
  }

  const list = knows.length === 1 ? knows[0] : `${knows.slice(0, -1).join(', ')} και ${knows[knows.length - 1]}`;
  return `${hi}. Είμαι ${assistantName}. Βλέπω ${list} ${scope}. ${you} για ${yours}.`;
}
