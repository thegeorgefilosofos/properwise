import { sendMerchantAlert, type MerchantAlert } from '@/lib/billing/merchantAlert';

export const CREDIT_ALERT_EVERY_MS = 6 * 60 * 60 * 1000;

export const CREDIT_ALERT: MerchantAlert = {
  subject: 'PROPERWISE | Τελείωσε το υπόλοιπο στον πάροχο AI: η Νόα δεν απαντά',
  text: [
    'Ο πάροχος AI (Anthropic) απέρριψε ερώτηση πελάτη επειδή το υπόλοιπο του λογαριασμού τελείωσε.',
    '',
    'Ως να μπει υπόλοιπο, η Νόα, η σάρωση εγγράφων και ο καθημερινός έλεγχος επιτοκίων δεν δουλεύουν.',
    'Οι πελάτες βλέπουν μήνυμα βλάβης και η ερώτηση δεν τους χρεώνεται.',
    '',
    'Τι κάνεις: console.anthropic.com · Billing · αγορά υπολοίπου. Ενεργοποίησε και την αυτόματη αναπλήρωση.',
  ].join('\n'),
};

/**
 * Φτιάχνει έναν αποστολέα με δικό του όριο. Στέλνει αν δεν έστειλε τις
 * τελευταίες έξι ώρες και δεν πετά ποτέ: η ειδοποίηση δεν επιτρέπεται να
 * αλλάξει την απάντηση προς τον πελάτη.
 *
 * @param send Δίνεται ως όρισμα ώστε ο έλεγχος να μη χτυπά δίκτυο.
 */
export function makeCreditAlerter(
  send: (a: MerchantAlert, key: string | undefined) => Promise<boolean> = sendMerchantAlert,
) {
  let lastSent = -Infinity;
  return async (apiKey: string | undefined, now: number = Date.now()): Promise<boolean> => {
    if (now - lastSent < CREDIT_ALERT_EVERY_MS) return false;
    lastSent = now;
    return send(CREDIT_ALERT, apiKey).catch(() => false);
  };
}

/** Ο αποστολέας της διαδρομής της Νόας. */
export const alertOutOfCredit = makeCreditAlerter();
