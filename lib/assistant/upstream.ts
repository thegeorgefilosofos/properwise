/**
 * Πόσο περιμένουμε τον πάροχο πριν κόψουμε το αίτημα.
 *
 * ΤΟ ΝΟΥΜΕΡΟ ΔΕΝ ΕΙΝΑΙ ΑΥΘΑΙΡΕΤΟ: ΕΙΝΑΙ Η ΥΠΟΜΟΝΗ ΠΟΥ ΕΧΕΙ ΗΔΗ Ο ΠΕΛΑΤΗΣ. Δύο
 * καλούντες της ίδιας διαδρομής κόβουν μόνοι τους στα σαράντα πέντε
 * δευτερόλεπτα (scanDoc.ts:191, TabTenantMoney.tsx:657), δύο στα τριάντα
 * (PropertyAssistant.tsx:1308, inventory/ItemFormModal.tsx:119) και η
 * συνομιλία δεν κόβει καθόλου. Πάνω από σαράντα πέντε δευτερόλεπτα δεν υπάρχει
 * καλών που να ακούει ακόμη: ο διακομιστής θα δούλευε για κανέναν.
 *
 * ΠΙΟ ΚΑΤΩ ΔΕΝ ΠΑΕΙ. Το ταβάνι εξόδου της διαδρομής είναι 2.000 tokens
 * (`max_tokens` στο route.tsx) πάνω σε system prompt ~33.000 tokens: χωρίς ροή,
 * μια πλήρης απάντηση θέλει κανονικά δεκάδες δευτερόλεπτα. Μικρότερο όριο δεν
 * θα έκοβε βλάβες, θα έκοβε ΣΩΣΤΕΣ απαντήσεις.
 *
 * ΚΑΙ ΑΦΗΝΕΙ ΠΕΡΙΘΩΡΙΟ. Με `maxDuration = 60` στη διαδρομή μένουν δεκαπέντε
 * δευτερόλεπτα μετά το κόψιμο για την επιστροφή της χρέωσης (ένα RPC) και για
 * την απάντηση σφάλματος. Χωρίς αυτό το περιθώριο η πλατφόρμα θα σκότωνε τη
 * συνάρτηση ΠΡΙΝ επιστραφεί η μονάδα — δηλαδή το χρονικό όριο θα προκαλούσε
 * ακριβώς τη ζημιά που ήρθε να αποτρέψει.
 */
export const UPSTREAM_TIMEOUT_MS = 45_000;

/** Μια αποτυχία, όπως τη βλέπει ο χρήστης και όπως τη μετράει η χρέωση. */
export interface UpstreamFailure {
  /** Τι διαβάζει ο χρήστης. Ελληνικά, χωρίς ορολογία API. */
  message: string;
  /** Με τι κωδικό απαντά η ΔΙΚΗ ΜΑΣ διαδρομή — όχι με τον κωδικό του παρόχου. */
  status: number;
  /** Αν επιστρέφεται και η μονάδα της κοινής δεξαμενής (δηλαδή αν δεν ξοδεύτηκε χρήμα). */
  pool: boolean;
}

/**
 * 401/403: το κλειδί δεν έγινε δεκτό.
 *
 * ΤΟ ΟΝΟΜΑ ΤΗΣ ΜΕΤΑΒΛΗΤΗΣ ΜΕΝΕΙ ΜΕΣΑ ΣΤΟ ΜΗΝΥΜΑ ΕΠΙΤΗΔΕΣ: τρεις πελάτες
 * ψάχνουν ακριβώς αυτό το λεκτικό για να δείξουν το `noKeyNotice()` αντί για
 * τεχνικό κείμενο (PropertyAssistant.tsx:1227, scanDoc.ts:208,
 * LoanDocScan.tsx:216). Είναι κατάσταση ρύθμισης, όχι σφάλμα του χρήστη.
 */
export const KEY_FAILURE: UpstreamFailure = {
  message: 'Το κλειδί σύνδεσης με τον πάροχο (ANTHROPIC_API_KEY) δεν έγινε δεκτό.',
  status: 500,
  pool: true,
};

/**
 * 413 από τον πάροχο: το αρχείο πέρασε το δικό μας όριο αλλά όχι το δικό του.
 * Ο κωδικός ΜΕΝΕΙ 413 γιατί ο πελάτης της σάρωσης τον διαβάζει ονομαστικά
 * (scanDoc.ts:203) και δίνει τη μόνη χρήσιμη οδηγία: μικρότερο αρχείο.
 */
export const TOO_LARGE_FAILURE: UpstreamFailure = {
  message: 'Το αρχείο είναι πολύ μεγάλο για τον πάροχο. Δοκίμασε μικρότερη φωτογραφία ή PDF.',
  status: 413,
  pool: true,
};

/** 429 του παρόχου: συμφόρηση δική ΜΑΣ προς αυτόν. Ποτέ 429 προς τον πελάτη. */
export const BUSY_FAILURE: UpstreamFailure = {
  message: 'Πολλά αιτήματα προς τον πάροχο αυτή τη στιγμή. Δοκίμασε ξανά σε λίγο.',
  status: 503,
  pool: true,
};

/** 5xx του παρόχου, μαζί με το 529 «overloaded» που δεν είναι πρότυπο HTTP. */
export const DOWN_FAILURE: UpstreamFailure = {
  message: 'Ο πάροχος δεν απαντά αυτή τη στιγμή. Δοκίμασε ξανά σε λίγο.',
  status: 503,
  pool: true,
};

/**
 * Καθε άλλο 4xx: ο πάροχος απέρριψε το αίτημα πριν παραγάγει οτιδήποτε.
 *
 * ΤΟ ΚΕΙΜΕΝΟ ΔΕΝ ΛΕΕΙ «ΔΙΑΤΥΠΩΣΕ ΤΗΝ ΕΡΩΤΗΣΗ ΑΛΛΙΩΣ», ΚΑΙ ΤΟ ΝΟΥΜΕΡΟ ΕΞΗΓΕΙ
 * ΓΙΑΤΙ. Η διαδρομή έχει ΕΝΝΙΑ σημεία κλήσης σε οκτώ αρχεία· μόνο το ΕΝΑ
 * (PropertyAssistant.tsx:1211) στέλνει πληκτρολογημένη ερώτηση. Τα άλλα οκτώ
 * στέλνουν φωτογραφία, PDF ή επικολλημένο κείμενο, όπου η αιτία του 400 είναι
 * σχεδόν πάντα το αρχείο: ο πάροχος κόβει τη ΜΕΜΟΝΩΜΕΝΗ εικόνα πολύ πριν από
 * το δικό μας όριο σώματος των 12 MB. «Διατύπωσέ την αλλιώς» θα ήταν οδηγία
 * που οκτώ στους εννιά καλούντες δεν μπορούν να ακολουθήσουν.
 */
export const REJECTED_FAILURE: UpstreamFailure = {
  message: 'Ο πάροχος δεν δέχτηκε το αίτημα όπως στάλθηκε. Αν έστειλες φωτογραφία ή PDF, δοκίμασε μικρότερο ή καθαρότερο αρχείο.',
  status: 502,
  pool: true,
};

/**
 * Το δικό μας χρονικό όριο χτύπησε.
 *
 * Η ΔΕΞΑΜΕΝΗ ΔΕΝ ΓΥΡΙΖΕΙ: ο πάροχος δούλευε σαράντα πέντε δευτερόλεπτα, άρα
 * κατά πάσα πιθανότητα παρήγαγε tokens που θα χρεωθούν. Ο χρήστης δεν πήρε
 * τίποτα, οπότε το πακέτο του γυρίζει· τα χρήματα όμως φύγανε.
 */
export const TIMEOUT_FAILURE: UpstreamFailure = {
  message: 'Ο πάροχος άργησε να απαντήσει και το αίτημα σταμάτησε. Δοκίμασε ξανά.',
  status: 504,
  pool: false,
};

/** Το αίτημα δεν έφυγε ή δεν έφτασε: τίποτα δεν παρήχθη, γυρίζουν και τα δύο. */
export const NETWORK_FAILURE: UpstreamFailure = {
  message: 'Δεν υπάρχει σύνδεση με τον πάροχο αυτή τη στιγμή. Δοκίμασε ξανά σε λίγο.',
  status: 502,
  pool: true,
};

/**
 * Απάντηση 200 με σώμα που δεν είναι JSON.
 *
 * Ο πάροχος απάντησε κανονικά, άρα χρεώθηκε: το πακέτο γυρίζει, η δεξαμενή όχι.
 */
export const UNREADABLE_FAILURE: UpstreamFailure = {
  message: 'Η απάντηση του παρόχου δεν διαβάζεται. Δοκίμασε ξανά.',
  status: 502,
  pool: false,
};

/**
 * Τι απαντά η διαδρομή μας για τον κωδικό που έδωσε ο πάροχος.
 *
 * ΚΑΝΕΝΑΣ ΚΩΔΙΚΟΣ ΔΕΝ ΠΕΡΝΑΕΙ ΑΥΤΟΥΣΙΟΣ εκτός από το 413, που έχει την ίδια
 * σημασία και στις δύο πλευρές («μίκρυνε το αρχείο»). Τα υπόλοιπα μεταφράζονται
 * σε κωδικό που περιγράφει ΤΗ ΔΙΚΗ ΜΑΣ κατάσταση προς τον πελάτη.
 */
export function upstreamFailure(status: number): UpstreamFailure {
  if (status === 401 || status === 403) return KEY_FAILURE;
  if (status === 413) return TOO_LARGE_FAILURE;
  if (status === 429) return BUSY_FAILURE;
  if (status >= 500) return DOWN_FAILURE;
  return REJECTED_FAILURE;
}
