// τρίτεκνοι, αναπηρία, ασφάλιση) και παρέλειπε τη μείωση 50% του 2026 για κύρια
// κατοικία σε μικρό οικισμό. Ο ιδιοκτήτης στο χωριό έβλεπε ΔΙΠΛΑΣΙΟ φόρο από
