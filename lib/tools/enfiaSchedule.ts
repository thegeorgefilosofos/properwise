// ΟΙ ΔΟΣΕΙΣ ΤΟΥ ΕΝΦΙΑ, ΜΕ ΗΜΕΡΟΜΗΝΙΑ Η ΚΑΘΕΜΙΑ
// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΕΛΕΙΠΕ. Ο δημόσιος υπολογιστής έβγαζε δύο νούμερα: το ετήσιο και το
// «ανά μήνα». Το δεύτερο ήταν διαίρεση διά δώδεκα και τίποτα άλλο — δεν έλεγε
// ΠΟΤΕ πληρώνεται. Ο ιδιοκτήτης που ρωτά «πόσο ΕΝΦΙΑ θα πληρώσω» ρωτά, μία
// ανάσα μετά, «και πότε»: το ποσό μπαίνει σε προϋπολογισμό μόνο αν ξέρει σε
// ποιον μήνα πέφτει.
//
// ΑΠΟ ΠΟΥ ΒΓΑΙΝΟΥΝ ΟΙ ΗΜΕΡΟΜΗΝΙΕΣ ΚΑΙ ΓΙΑΤΙ ΔΕΝ ΕΠΙΝΟΕΙΤΑΙ ΚΑΜΙΑ.
// Το φορολογικό ημερολόγιο (lib/tax/greekTaxCalendar.ts) ορίζει ήδη τρία
// γεγονότα ΕΝΦΙΑ με πηγή: την έκδοση του εκκαθαριστικού, την 1η δόση στο τέλος
// Μαρτίου και την τελευταία στο τέλος Φεβρουαρίου του επόμενου έτους. Ο κανόνας
// που τα ενώνει είναι γραμμένος εκεί, στο ίδιο σχόλιο: μηνιαίες δόσεις, την
// τελευταία εργάσιμη κάθε μήνα. Δώδεκα μήνες από τον Μάρτιο ως τον Φεβρουάριο,
// δηλαδή ακριβώς δώδεκα δόσεις, με πρώτη και τελευταία αυτές που ήδη ξέρει το
// ημερολόγιο. Καμία ενδιάμεση ημερομηνία δεν μαντεύεται: όλες προκύπτουν από
// την ΙΔΙΑ συνάρτηση `lastWorkingDayOfMonth`, που μεταθέτει αργίες και
// Σαββατοκύριακα όπως και οι δύο άκρες.
//
// ΟΙ ΗΜΕΡΟΜΗΝΙΕΣ ΕΙΝΑΙ ΤΥΠΙΚΕΣ, ΟΧΙ ΘΕΣΜΟΘΕΤΗΜΕΝΕΣ. Το ημερολόγιο τις σημειώνει
// `announced` — ανακοινώνονται κάθε χρόνο με απόφαση. Ο πίνακας το λέει στην
// οθόνη με τα ίδια λόγια που το λέει και μέσα στην εφαρμογή· ένα εργαλείο που
// τυπώνει τυπική ημερομηνία σαν προθεσμία νόμου κάνει ζημιά.
//
// ΤΑ ΣΕΝΤΣ ΚΛΕΙΝΟΥΝ. Δώδεκα ίσες δόσεις σπάνια διαιρούνται ακριβώς: 180,28 διά
// δώδεκα δίνει 15,0233…. Αν στρογγυλοποιηθεί κάθε δόση χωριστά, το άθροισμα
// δεν είναι το ετήσιο και ο πίνακας αυτοδιαψεύδεται μπροστά στον αναγνώστη. Οι
// έντεκα πρώτες κόβονται ΠΡΟΣ ΤΑ ΚΑΤΩ στο λεπτό και η τελευταία παίρνει τη
// διαφορά, οπότε το άθροισμα ισούται ΠΑΝΤΑ με το ετήσιο.
//
// ΚΟΨΙΜΟ ΠΡΟΣ ΤΑ ΚΑΤΩ ΚΑΙ ΟΧΙ ΣΤΡΟΓΓΥΛΟΠΟΙΗΣΗ, ΓΙΑ ΕΝΑΝ ΛΟΓΟ ΠΟΥ ΤΟΝ ΒΡΗΚΕ ΤΟ
// ΤΕΣΤ. Με στρογγυλοποίηση, οι έντεκα πρώτες μπορούν να ξεπεράσουν το σύνολο
// και η δωδέκατη να βγει ΑΡΝΗΤΙΚΗ (ετήσιο 0,07 ⇒ 11 × 0,01 = 0,11 ⇒ −0,04).
// Κομμένες προς τα κάτω, το άθροισμα των έντεκα δεν ξεπερνά ποτέ το ετήσιο και
// η τελευταία είναι πάντα η μεγαλύτερη — κανόνας που εξηγείται σε μία γραμμή.
// ═══════════════════════════════════════════════════════════════════════════
import { lastWorkingDayOfMonth } from '@/lib/tax/greekTaxCalendar'
import { monthGen } from '@/lib/core/months'
import { roundHalfUp } from '../core/money';

/**
 * Πόσες δόσεις το πολύ: Μάρτιος έως Φεβρουάριο του επόμενου έτους.
 *
 * ΕΚΚΡΕΜΕΙ (13.10.2026): ΟΙ ΔΟΣΕΙΣ ΤΟΥ ΕΝΦΙΑ 2026 ΜΕΝΟΥΝ ΩΣ ΕΧΟΥΝ ώσπου να
 * επιβεβαιωθεί επίσημη πηγή (απόφαση ΑΑΔΕ ή ΦΕΚ) για το πλήθος τους. Εντολή του
 * ιδιοκτήτη: καμία αλλαγή χωρίς αυτήν. Το 12 είναι το ανώτατο· για μικρό ποσό
 * οι δόσεις λιγοστεύουν (`ENFIA_MIN_INSTALMENT`).
 */
export const ENFIA_INSTALMENTS = 12

/**
 * ΚΑΜΙΑ ΔΟΣΗ ΚΑΤΩ ΑΠΟ 10€ (απόφαση ιδιοκτήτη 20.10.2026).
 *
 * ΤΟ ΣΦΑΛΜΑ, ΟΠΩΣ ΗΤΑΝ. Το ετήσιο μοιραζόταν πάντα σε δώδεκα, για οποιοδήποτε
 * ποσό: 67,20€ έβγαιναν 12 × 5,60€, δόσεις που δεν υπάρχουν στο εκκαθαριστικό.
 * Ο κανόνας του νόμου «κάθε δόση δεν μπορεί να είναι μικρότερη από 10 ευρώ»
 * ισχύει και για τον ΕΝΦΙΑ: taxheaven, «Τροπολογία για μειώσεις ΕΝΦΙΑ και
 * καταβολή δόσεων» (https://www.taxheaven.gr/news/59285/tropologia-gia-meiwseis-enfia-kai-katabolh-dosewn:
 * «Παραμένει η πρόβλεψη ότι κάθε δόση δεν μπορεί να είναι μικρότερη από 10
 * ευρώ»)· ΥΠΕΘΟΟ (https://minfin.gov.gr/katatethike-sti-vouli-i-tropologia-gia-pliromi-tou-enfia-se-11-doseis/)·
 * ΑΑΔΕ (https://www.aade.gr/en/greeks-abroad-non-residents/property-taxation/unified-tax-ownership-real-estate-e9-enfia)·
 * gov.gr (https://www.gov.gr/en/sdg/residence/purchasing-and-selling-of-immovable-property/taxation-for-possession-of-real-estate-property/uniform-real-estate-property-tax-enfia).
 * ΔΕΝ είναι το ελάχιστο 30€ της πάγιας ρύθμισης (24 δόσεις, έντοκη): άλλος κανόνας.
 */
export const ENFIA_MIN_INSTALMENT = 10

/**
 * Το πλήθος των δόσεων για αυτό το ετήσιο: όσες χωρούν με τουλάχιστον
 * `ENFIA_MIN_INSTALMENT` η καθεμία, έως `ENFIA_INSTALMENTS` και τουλάχιστον
 * μία. 67,20€ → 6, 27,44€ → 2, 9€ → 1, 120€ → 12. Μετρά σε λεπτά, ώστε το
 * δυαδικό δεκαδικό να μη βγάλει 11 εκεί που χωρούν ακριβώς 12.
 */
export function enfiaInstalmentCount(annual: number): number {
  if (!(annual > 0)) return 0
  const fits = Math.floor(Math.round(annual * 100) / (ENFIA_MIN_INSTALMENT * 100))
  return Math.max(1, Math.min(ENFIA_INSTALMENTS, fits))
}
/** Ο μήνας της πρώτης δόσης, με αρίθμηση του JavaScript (0 = Ιανουάριος). */
const FIRST_MONTH = 2

export interface EnfiaInstalment {
  /** 1 έως 12, όπως τη λέει το εκκαθαριστικό. */
  no: number
  /** YYYY-MM-DD, μετατεθειμένη σε εργάσιμη. */
  date: string
  /** «31 Μαρτίου 2026» — για ανάγνωση, όχι για υπολογισμό. */
  label: string
  amount: number
}

const cents = (n: number) => roundHalfUp(n, 2)
/** Προς τα κάτω στο λεπτό. Το `+1e-9` σβήνει το σφάλμα του δυαδικού δεκαδικού
 *  (85,5 × 100 δίνει 8549,999… και το κόψιμο θα έβγαζε 85,49). */
const centsDown = (n: number) => Math.floor(n * 100 + 1e-9) / 100

/**
 * Η ημερομηνία ΟΛΟΓΡΑΦΩΣ, με τον μήνα σε γενική: «14 Αυγούστου 2026».
 *
 * Λεγόταν `grDate`, όπως και η αριθμητική «14/08/2026» που ζει στο
 * lib/core/format. Ίδιο όνομα, άλλη έξοδος, σε δύο αρχεία: όποιος έγραφε
 * `grDate(x)` δεν μπορούσε να ξέρει τι θα δει ο χρήστης χωρίς να ανοίξει το
 * αρχείο. Το όνομα λέει τώρα τη διαφορά.
 */
export function grDateLong(isoDate: string): string {
  const [y, m, d] = isoDate.split('-').map(Number)
  return `${d} ${monthGen(m - 1)} ${y}`
}

/**
 * Οι δόσεις ενός ετήσιου ΕΝΦΙΑ, με ημερομηνία και ποσό: έως δώδεκα, καμία
 * κάτω από `ENFIA_MIN_INSTALMENT` (εκτός από τη μία, όταν το ετήσιο δεν φτάνει
 * ούτε για αυτήν). Οι δόσεις είναι μηνιαίες από την πρώτη, τον Μάρτιο· με
 * λιγότερες από δώδεκα, η τελευταία λήγει νωρίτερα από τον Φεβρουάριο. Ο
 * κανόνας των λεπτών μένει ο ίδιος: οι πρώτες κόβονται προς τα κάτω και η
 * τελευταία παίρνει τη διαφορά.
 *
 * @param annual το ετήσιο ποσό όπως το υπολόγισε το lib/billing/enfia.ts
 * @param year   το έτος του εκκαθαριστικού· οι δόσεις 11 και 12 πέφτουν στο επόμενο
 */
export function enfiaInstalments(annual: number, year: number): EnfiaInstalment[] {
  const n = enfiaInstalmentCount(annual)
  if (!n) return []
  const each = centsDown(annual / n)
  const out: EnfiaInstalment[] = []
  for (let i = 0; i < n; i++) {
    const m = FIRST_MONTH + i
    const date = lastWorkingDayOfMonth(year + Math.floor(m / 12), m % 12)
    const last = i === n - 1
    out.push({
      no: i + 1,
      date,
      label: grDateLong(date),
      amount: last ? cents(annual - each * (n - 1)) : each,
    })
  }
  return out
}
