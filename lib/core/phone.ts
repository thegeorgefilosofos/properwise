// Ο ΑΡΙΘΜΟΣ ΕΡΧΕΤΑΙ ΟΠΩΣ ΤΟΝ ΕΓΡΑΨΕ ΑΝΘΡΩΠΟΣ: «694 123 4567», «0030 6941234567»,
// «+30 694-123-4567». Το `wa.me` θέλει μόνο ψηφία με τον κωδικό χώρας μπροστά·
// ένα σταθερό (21…) δεν έχει WhatsApp και ένα κενό στη μέση στέλνει τον λογιστή
// σε σελίδα σφάλματος, όχι στη συνομιλία.
//
// ΜΟΝΟ ΕΛΛΗΝΙΚΑ ΚΙΝΗΤΑ (69 + 8 ψηφία). Ξένος αριθμός ή σταθερό επιστρέφει `null`:
// τότε το κανάλι απλώς δεν προσφέρεται, αντί να ανοίξει συνομιλία με λάθος άνθρωπο.
// ═══════════════════════════════════════════════════════════════════════════

/** Ελληνικό κινητό σε E.164 χωρίς «+» (π.χ. `306941234567`), αλλιώς `null`. */
export function grMobileDigits(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const s = raw.trim();
  // Γράμματα σημαίνουν ότι δεν είναι αριθμός («καλέστε μετά τις 5»).
  if (/[a-zα-ωά-ώ]/i.test(s)) return null;
  let d = s.replace(/[\s\-().\/]/g, '');
  if (d.startsWith('+')) d = d.slice(1);
  else if (d.startsWith('00')) d = d.slice(2);
  if (!/^\d+$/.test(d)) return null;
  if (d.length === 10) d = `30${d}`;
  return /^3069\d{8}$/.test(d) ? d : null;
}

/** Το ίδιο, με «+» μπροστά (για `sms:` και για ανάγνωση). */
export function grMobileE164(raw: string | null | undefined): string | null {
  const d = grMobileDigits(raw);
  return d ? `+${d}` : null;
}
