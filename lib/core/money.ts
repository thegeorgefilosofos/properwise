// ═══════════════════════════════════════════════════════════════════════════
// ΣΤΡΟΓΓΥΛΟΠΟΙΗΣΗ ΣΤΟ ΛΕΠΤΟ — ΜΙΑ ΦΟΡΑ, ΜΕ ΔΗΛΩΜΕΝΗ ΣΥΜΠΕΡΙΦΟΡΑ ΣΤΟ NaN
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΕΥΡΗΜΑ. Το `Math.round(n * 100) / 100` ήταν γραμμένο δεκαεπτά φορές ως
// τοπικός βοηθός, με τρία ΔΙΑΦΟΡΕΤΙΚΑ ονόματα (`cents`, `round2`, `r2`) και —
// αυτό είναι το σοβαρό — τρεις διαφορετικές συμπεριφορές όταν η είσοδος δεν
// είναι αριθμός:
//
//     Math.round(n * 100) / 100                              NaN  →  NaN
//     Math.round((Number.isFinite(n) ? n : 0) * 100) / 100    NaN  →  0
//     Math.round((Number(n) || 0) * 100) / 100                NaN  →  0, «12» → 12
//
// Δηλαδή η ίδια πράξη, στο ίδιο νούμερο, έδινε άλλο αποτέλεσμα ανάλογα με το
// ποιο αρχείο την έκανε. Και τα δύο δεν είναι λάθος από μόνα τους — είναι
// λάθος να μην ξέρεις ποιο ισχύει.
//
// ΠΟΙΟ ΕΙΝΑΙ ΤΟ ΣΩΣΤΟ ΕΞΑΡΤΑΤΑΙ ΑΠΟ ΤΟ ΕΡΩΤΗΜΑ:
//
//   • Αν το NaN σημαίνει «κάτι έσπασε πιο πάνω», το μηδέν το ΚΡΥΒΕΙ. Ο χρήστης
//     δεν βλέπει σφάλμα· βλέπει έναν φόρο που λείπει μια δαπάνη και τον
//     δηλώνει. Εκεί το NaN πρέπει να ταξιδέψει, ώστε η οθόνη να δείξει «—».
//   • Αν το κενό σημαίνει πραγματικά «δεν υπάρχει ποσό» (προαιρετικό πεδίο που
//     δεν συμπληρώθηκε), τότε το μηδέν είναι η σωστή απάντηση και όχι κρύψιμο.
//
// Δύο συναρτήσεις λοιπόν, με ονόματα που λένε ποιο ερώτημα απαντούν. Καμία
// τρίτη: η μετατροπή συμβολοσειράς σε αριθμό ανήκει στο `lib/core/numInput`,
// όχι σε συνάρτηση στρογγυλοποίησης.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * ΤΟ ΜΙΣΟ ΛΕΠΤΟ ΠΑΕΙ ΠΑΝΤΑ ΣΤΟ ΑΜΕΣΩΣ ΜΕΓΑΛΥΤΕΡΟ (απόφαση ιδιοκτήτη,
 * 02.10.2026: «το 18,295 θα γίνει 18,30»).
 *
 * ΓΙΑΤΙ ΧΡΕΙΑΖΕΤΑΙ ΣΥΝΑΡΤΗΣΗ. Το `Math.round(n * 100) / 100` ΔΕΝ το κάνει: το
 * 563,925 αποθηκεύεται ως 563,92499999999995, το επί 100 δίνει
 * 56392,49999999999 και η στρογγυλοποίηση πέφτει στο 563,92. Ο φόρος
 * 2.255,70 × 25% έβγαινε έτσι ένα λεπτό κάτω. Η διόρθωση: πρώτα κόβεται ο
 * θόρυβος της αναπαράστασης (15 σημαντικά ψηφία, όσα κρατά με ακρίβεια ένας
 * double) και μετά στρογγυλεύεται το μισό προς τα πάνω. Τα αρνητικά
 * στρογγυλεύονται συμμετρικά, μακριά από το μηδέν: η επιστροφή −18,295
 * γράφεται −18,30, όσο και η χρέωση 18,295 γράφεται 18,30.
 */
export function roundHalfUp(n: number, dp = 2): number {
  if (!Number.isFinite(n)) return n;
  const f = 10 ** dp;
  const r = Math.round(Number((Math.abs(n) * f).toPrecision(15))) / f;
  return n < 0 && r !== 0 ? -r : r;
}

/**
 * Στρογγυλοποίηση στο λεπτό. Μη πεπερασμένη είσοδος περνά ΩΣ ΕΧΕΙ (NaN → NaN),
 * ώστε ένα σφάλμα πιο πάνω να φτάσει ορατό στην οθόνη αντί να γίνει μηδέν.
 */
export const cents = (n: number): number => roundHalfUp(n, 2);

/**
 * Ίδιο, αλλά η απούσα ή άκυρη τιμή μετριέται ως μηδέν.
 *
 * Χρησιμοποιείται ΜΟΝΟ όπου το «δεν δόθηκε» σημαίνει όντως «μηδέν ευρώ»:
 * προαιρετικό ποσό, αθροιστής που ξεκινά κενός, μερίδιο που δεν ορίστηκε.
 * Ποτέ σε αποτέλεσμα υπολογισμού, γιατί εκεί το μηδέν είναι ψέμα.
 */
export const centsOr0 = (n: number | null | undefined): number =>
  Number.isFinite(n as number) ? roundHalfUp(n as number, 2) : 0;
