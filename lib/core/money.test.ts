// Τα παραδείγματα είναι εκείνα που έπεφταν κάτω με το `Math.round(n * 100) / 100`
// επειδή ο double αποθηκεύει το ,xx5 ελάχιστα κάτω από το μισό.
// ═══════════════════════════════════════════════════════════════════════════
import { roundHalfUp, cents, centsOr0 } from './money';
import { fe, fn, fp } from './format';

let pass = 0, fail = 0;
function eq(name: string, got: unknown, want: unknown) {
  if (Object.is(got, want) || got === want) pass++;
  else { fail++; console.error(`✗ ${name}\n   got  ${String(got)}\n   want ${String(want)}`); }
}

eq('18,295 → 18,30 (το παράδειγμα του ιδιοκτήτη)', cents(18.295), 18.3);
eq('563,925 → 563,93 (25% του 2.255,70)', cents(2255.70 * 0.25), 563.93);
eq('1,005 → 1,01', cents(1.005), 1.01);
eq('1,004 → 1,00', cents(1.004), 1);
eq('0,1 + 0,2 → 0,30', cents(0.1 + 0.2), 0.3);
eq('αρνητικό συμμετρικά: −18,295 → −18,30', cents(-18.295), -18.3);
eq('κανένα −0', Object.is(cents(-0.004), 0), true);
eq('NaN περνά ως έχει', Number.isNaN(cents(NaN)), true);
eq('centsOr0: NaN → 0', centsOr0(NaN), 0);
eq('centsOr0: 563,925 → 563,93', centsOr0(563.925), 563.93);
eq('ακέραια: 2,5 → 3', roundHalfUp(2.5, 0), 3);
eq('μεγάλο ποσό: 1.234.567,895 → 1.234.567,90', cents(1234567.895), 1234567.9);

// Η οθόνη γράφει ό,τι λέει ο κανόνας, όχι ό,τι αποφασίζει το toLocaleString.
eq('fe: 1.800 + 563,925 → 2.363,93€', fe(1800 + 2255.70 * 0.25), '2.363,93€');
eq('fe: 18,295 → 18,30€', fe(18.295), '18,30€');
eq('fp: 4,125% → 4,13%', fp(4.125), '4,13%');
eq('fn: 2,5 χωρίς δεκαδικά → 3', fn(2.5), '3');

console.log(fail === 0 ? `✓ money: ${pass} έλεγχοι πέρασαν` : `✗ money: ${fail} απέτυχαν από ${pass + fail}`);
if (fail > 0) process.exit(1);
