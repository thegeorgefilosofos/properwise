// ─────────────────────────────────────────────────────────────────────────
// ΓΙΑΤΙ ΥΠΑΡΧΕΙ. Στις ροές εισόδου/εξόδου ΘΕΛΟΥΜΕ να πεθάνει όλη η κατάσταση
// του πελάτη: η συνεδρία του Supabase, οι μνήμες, τα δεδομένα τρίτων. Ο κανόνας
// @next/next/no-location-assign-relative-destination προτείνει router.push, που
// όμως κάνει SPA πλοήγηση και ΑΦΗΝΕΙ την κατάσταση ζωντανή — λάθος για logout ή
// για απώλεια συνεδρίας. Αυτή η σκόπιμη σκληρή πλοήγηση ζει ΜΙΑ φορά, εδώ.
//
// Ο κανόνας χτυπά ΜΟΝΟ στατικές, σχετικές διαδρομές γραμμένες στο σημείο της
// κλήσης· περνώντας τη διαδρομή ως όρισμα, το κάθε σημείο κλήσης μένει καθαρό
// ΚΑΙ ειλικρινές — δεν κρύβει την πρόθεση πίσω από `router.push`. Ως `assign`
// και όχι ανάθεση στο `href`: ίδια συμπεριφορά, αλλά ο μεταγλωττιστής του React
// δεν το διαβάζει ως μεταβολή εξωτερικής τιμής.
// ═══════════════════════════════════════════════════════════════════════════

// ΠΡΙΝ ΦΥΓΕΙ, ΣΒΗΝΕΙ ΟΣΑ ΘΑ ΤΗ ΣΤΑΜΑΤΟΥΣΑΝ. Οποιος κρατά μη αποθηκευμένη
// κατάσταση με ερώτηση `beforeunload` (π.χ. τα προσχέδια σάρωσης του Φακέλου)
// γράφεται εδώ. Η σκληρή πλοήγηση έρχεται ΜΕΤΑ από αποσύνδεση ή διαγραφή: ένα
// «Ακύρωση» σε εκείνη τη στιγμή θα κρατούσε δεδομένα στην οθόνη χωρίς
// συνεδρία. Γι' αυτό η ερώτηση δεν επιτρέπεται να τη σταματήσει.
const beforeLeave = new Set<() => void>();

/** Γράφει κάτι που πρέπει να σβήσει πριν από κάθε σκληρή πλοήγηση. */
export function onHardNavigate(fn: () => void): () => void {
  beforeLeave.add(fn);
  return () => { beforeLeave.delete(fn); };
}

/** Πλήρες reload προς `path` — για ροές auth όπου η κατάσταση πρέπει να σβήσει. */
export function hardNavigate(path: string): void {
  for (const fn of beforeLeave) { try { fn(); } catch { /* η πλοήγηση προηγείται */ } }
  window.location.assign(path);
}
