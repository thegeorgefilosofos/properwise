// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ ΠΟΥ ΚΛΕΙΝΕΙ (02.10.2026). Τρία σημεία έφτιαχναν τις δόσεις δανείου
// με `new Date(έτος, μήνας + i + 1, μέρα)`. Για έναρξη 31 Αυγούστου η δόση του
// Σεπτεμβρίου γινόταν «31 Σεπτεμβρίου», που ο JavaScript μετατρέπει σε 1
// Οκτωβρίου: δύο δόσεις τον Οκτώβριο, καμία τον Σεπτέμβριο. Το ίδιο κάθε
// Φεβρουάριο για έναρξη 29 ως 31 του μήνα.
//
// Η πρόσθεση μηνών με κλείδωμα στην τελευταία ημέρα του μήνα είναι γραμμένη μία
// φορά, στο `lib/loans/progress` (`addMonths`). Εδώ μόνο η σειρά: η δόση i
// μετριέται ΠΑΝΤΑ από την έναρξη, ώστε μια κλειδωμένη 30ή να μη μείνει 30ή και
// στους μήνες με 31 ημέρες.
// ═══════════════════════════════════════════════════════════════════════════
import { addMonths } from '@/lib/loans/progress'

/** Η ημερομηνία της δόσης `i` (η 1η είναι ένας μήνας μετά την έναρξη), ή `null`
 *  όταν η έναρξη δεν είναι «YYYY-MM-DD». */
export function instalmentDate(startIso: string, i: number): string | null {
  return addMonths(startIso, i)
}

/** Οι ημερομηνίες των δόσεων 1 ως `count`. Κενός πίνακας για άκυρη έναρξη. */
export function instalmentDates(startIso: string, count: number): string[] {
  const out: string[] = []
  for (let i = 1; i <= count; i++) {
    const d = instalmentDate(startIso, i)
    if (!d) return []
    out.push(d)
  }
  return out
}
