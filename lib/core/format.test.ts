// npx tsx lib/core/format.test.ts
//
// ΓΙΑΤΙ ΓΡΑΦΤΗΚΕ. Το lib/core/format.ts είναι το σημείο απ' όπου περνά ΚΑΘΕ
// ευρώ που βλέπει ο χρήστης — οθόνη, PDF, email, εξαγωγή στον λογιστή. Οι
// κανόνες του έργου γι' αυτό είναι ρητοί και απόλυτοι:
//
//     ΠΑΝΤΑ δύο δεκαδικά. Ποτέ παύλα σε θέση τιμής. Καμία συντομογραφία.
//
//     Και το σύμβολο γράφεται ΚΟΛΛΗΤΑ στο τελευταίο ψηφίο: «1.234,56€».
//
// Και είναι κανόνες που έχουν ΗΔΗ σπάσει στο παρελθόν: τέσσερις τοπικοί
// μορφοποιητές έκοβαν τα δεκαδικά και τρεις χώριζαν το ποσό από το σύμβολο με
// κενό. Εκατόν σαράντα ένα γραμμές, χωρίς έναν έλεγχο.
import {
  fe, feRate, fp, fn, feOr, fpOr, DASH, ABSENT, ABSENT_DATE, ABSENT_SHORT, isBlankMetric, grUpper,
} from './format'

let pass = 0, fail = 0
function ok(name: string, cond: boolean) { if (cond) pass++; else { fail++; console.error('✗ ' + name) } }
function eq(name: string, got: unknown, want: unknown) {
  const g = JSON.stringify(got), w = JSON.stringify(want)
  if (g === w) pass++; else { fail++; console.error(`✗ ${name}\n   got  ${g}\n   want ${w}`) }
}

// ═══ ΔΥΟ ΔΕΚΑΔΙΚΑ, ΠΑΝΤΑ ═══════════════════════════════════════════════════
eq('ακέραιο παίρνει δεκαδικά', fe(1250), '1.250,00€')
eq('ένα δεκαδικό γίνεται δύο', fe(1250.5), '1.250,50€')
eq('τρία δεκαδικά στρογγυλοποιούνται σε δύο', fe(1250.567), '1.250,57€')
eq('μηδέν', fe(0), '0,00€')
eq('αρνητικό', fe(-84.5), '-84,50€')
eq('λεπτά μόνο', fe(0.07), '0,07€')
{
  let bad = ''
  for (const n of [0, 1, 9.9, 99.999, 1000, 123456.789, -0.005, 1e6]) {
    if (!/,\d{2}€$/.test(fe(n))) bad = String(n)
  }
  eq('ΚΑΘΕ ποσό τελειώνει σε δύο δεκαδικά και ευρώ', bad, '')
}

// ═══ ΤΟ ΕΥΡΩ ΑΚΟΥΜΠΑ ΤΟ ΤΕΛΕΥΤΑΙΟ ΨΗΦΙΟ ══════════════════════════════════
// ΤΟ ΑΡΧΕΙΟ ΕΓΡΑΦΕ ΠΡΙΝ ΤΟ ΑΝΤΙΘΕΤΟ, ΚΑΙ ΓΡΑΦΕΤΑΙ ΓΙΑΤΙ. Η προηγούμενη μορφή
// ήταν «1.250,00\u00A0€»: άθραυστο κενό, ώστε το σύμβολο να μην πέφτει μόνο
// του στην επόμενη γραμμή σε στενή στήλη. Το κενό λύνει πράγματι το σπάσιμο —
// αλλά η επιλογή είναι δική μας κι έγινε το αντίστροφο: κανένα κενό. Χωρίς
// κενό δεν υπάρχει σημείο να σπάσει η γραμμή, οπότε η αρχική ανησυχία φεύγει
// μαζί με τον χαρακτήρα.
//
// ΚΑΙ ΤΑ ΔΥΟ ΚΕΝΑ ΑΠΑΓΟΡΕΥΟΝΤΑΙ. Το κανονικό U+0020 σπάει γραμμή, το άθραυστο
// U+00A0 δεν σπάει — αλλά κανένα από τα δύο δεν πρέπει να εμφανιστεί, αλλιώς
// δύο ποσά δίπλα δίπλα γράφονται αλλιώς το καθένα.
{
  let bad = ''
  for (const n of [5, 1250, -3.5, 0, 123456.789]) if (/[\u0020\u00A0]€/.test(fe(n))) bad = String(n)
  eq('κανένα κενό πριν το ευρώ, ούτε κανονικό ούτε άθραυστο', bad, '')
  ok('το σύμβολο ακουμπά το ψηφίο', /\d€$/.test(fe(1250)))
  ok('και στο feRate επίσης', /\d€$/.test(feRate(0.145)))
}

// ═══ ΔΙΑΧΩΡΙΣΤΙΚΟ ΧΙΛΙΑΔΩΝ, ΕΛΛΗΝΙΚΑ ══════════════════════════════════════
ok('τελεία για χιλιάδες, κόμμα για δεκαδικά', fe(1234567.89).startsWith('1.234.567,89'))
ok('κάτω από χίλια δεν παίρνει διαχωριστικό', !fe(999.99).includes('.'))

// ═══ ΧΑΛΑΣΜΕΝΗ ΕΙΣΟΔΟΣ ΔΕΝ ΓΡΑΦΕΙ «NaN €» ═════════════════════════════════
// Ένα «NaN €» στην οθόνη είναι χειρότερο από κενό: μοιάζει με ποσό.
{
  let bad = ''
  for (const v of [NaN, Infinity, -Infinity]) {
    const out = fe(v as number)
    if (/NaN|Infinity/.test(out)) bad += out + ' '
  }
  eq('NaN και άπειρο δεν φτάνουν ποτέ στην οθόνη', bad, '')
}

// ═══ ΠΟΣΟΣΤΑ ═══════════════════════════════════════════════════════════════
ok('το ποσοστό έχει σύμβολο', fp(12.3).includes('%'))
eq('το ποσοστό κρατά δύο δεκαδικά', fp(12.345).replace(/[^0-9,]/g, ''), '12,35')
ok('χαλασμένο ποσοστό δεν γράφει NaN', !/NaN/.test(fp(NaN)))

// ═══ ΑΡΙΘΜΟΙ ═══════════════════════════════════════════════════════════════
eq('ακέραιος χωρίς δεκαδικά όταν δεν ζητηθούν', fn(1234), '1.234')
eq('με δεκαδικά όταν ζητηθούν', fn(1234.5, 2), '1.234,50')
ok('χαλασμένος αριθμός δεν γράφει NaN', !/NaN/.test(fn(NaN)))

// ═══ Η ΑΠΟΥΣΙΑ ΛΕΓΕΤΑΙ ΜΕ ΛΕΞΕΙΣ, ΟΧΙ ΜΕ ΠΑΥΛΑ ═══════════════════════════
// Ο κανόνας του έργου: καμία παύλα σε θέση τιμής. Μια παύλα δεν λέει αν το
// στοιχείο λείπει, αν είναι μηδέν, ή αν κάτι χάλασε.
{
  ok('η απουσία είναι ελληνική φράση, όχι παύλα', /[α-ωΑ-Ω]/.test(ABSENT) && !/^[—–-]+$/.test(ABSENT))
  ok('και για ημερομηνία', /[α-ωΑ-Ω]/.test(ABSENT_DATE))
  ok('και στη σύντομη μορφή', /[α-ωΑ-Ω]/.test(ABSENT_SHORT))
  // ΤΟ ΚΕΝΟ ΠΟΣΟ ΓΡΑΦΕΤΑΙ «0,00€», ΚΑΙ ΕΙΝΑΙ ΣΩΣΤΟ.
  // Οι φράσεις απουσίας είναι για κενό ΚΕΙΜΕΝΟ (κατάσταση, όροφος, σημείωση).
  // Ένα κενό ΠΟΣΟ σημαίνει «δεν έχει καταγραφεί τίποτα», που σε ευρώ είναι
  // μηδέν — και το μηδέν στοιχίζεται σε στήλη, ενώ μια φράση όχι.
  eq('κενό ποσό → μηδέν, όχι παύλα', feOr(null), fe(0))
  eq('κενό ποσοστό → μηδέν', fpOr(undefined), fp(0))
  eq('υπαρκτό ποσό → κανονική μορφοποίηση', feOr(12), fe(12))
  eq('το μηδέν συμπεριφέρεται όπως το κενό, εσκεμμένα', feOr(0), fe(0))
}

// ═══ isBlankMetric: ΤΙ ΜΕΤΡΑΕΙ ΩΣ ΚΕΝΟ ════════════════════════════════════
{
  ok('η φράση απουσίας είναι κενή μετρική', isBlankMetric(ABSENT))
  ok('η παύλα επίσης', isBlankMetric(DASH))
  ok('το κενό κείμενο επίσης', isBlankMetric(''))
  // Το μηδενικό ποσό ΕΙΝΑΙ κενή μετρική, εσκεμμένα: «μετρήσαμε και δεν υπάρχει
  // τίποτα». Ένα πλακίδιο «0,00€» δίπλα σε τρία άλλα μηδενικά δεν λέει τίποτα.
  ok('μηδενικό ποσό μετράει ως κενό', isBlankMetric(fe(0)))
  ok('και το σκέτο μηδέν', isBlankMetric('0'))
  // Αλλά ένα μηδενικό ΔΙΠΛΑ σε νούμερο είναι απάντηση.
  ok('κείμενο με μη μηδενικά ψηφία δεν είναι κενό', !isBlankMetric(fe(1250)))
  ok('απάντηση σε λέξεις δεν είναι κενή', !isBlankMetric('Ενεργό') && !isBlankMetric('Ελεύθερο'))
}

// ═══ ΣΥΝΕΠΕΙΑ ΜΕΤΑΞΥ ΤΩΝ ΜΟΡΦΟΠΟΙΗΤΩΝ ════════════════════════════════════
// Δύο μορφοποιητές που δίνουν άλλο αποτέλεσμα για το ίδιο ποσό είναι ακριβώς
// το σφάλμα που έφερε αυτό το αρχείο σε ύπαρξη.
{
  let bad = ''
  for (const n of [0, 7.5, 1250, 99999.994]) if (feOr(n) !== fe(n)) bad = String(n)
  eq('feOr και fe συμφωνούν σε κάθε υπαρκτό ποσό', bad, '')
}

// ═══ ΚΕΦΑΛΑΙΑ: Ο ΤΟΝΟΣ ΦΕΥΓΕΙ, ΤΑ ΔΙΑΛΥΤΙΚΑ ΜΕΝΟΥΝ ΟΠΟΥ ΧΡΕΙΑΖΟΝΤΑΙ ══════
// Ο κανόνας δεν είναι «σβήσε ό,τι βρεις πάνω από το γράμμα». Τα διαλυτικά
// χωρίζουν δίφθογγο που αλλιώς διαβάζεται αλλιώς — «ΜΑΪΟΥ», όχι «ΜΑΙΟΥ», που
// θα διαβαζόταν «ΜΕΟΥ». Το «ωι» όμως ΔΕΝ είναι δίφθογγος, οπότε το «πρωί»
// γίνεται «ΠΡΩΙ» και τίποτα δεν μπαίνει από πάνω.
{
  eq('τόνος: φεύγει', grUpper('Στοιχεία ακινήτου'), 'ΣΤΟΙΧΕΙΑ ΑΚΙΝΗΤΟΥ')
  eq('τόνος σε δύο λέξεις', grUpper('Χαρτοφυλάκιό μου'), 'ΧΑΡΤΟΦΥΛΑΚΙΟ ΜΟΥ')
  eq('διαλυτικά: μένουν', grUpper('αϋπνία'), 'ΑΫΠΝΙΑ')
  eq('διαλυτικά χωρίς τόνο', grUpper('κοροϊδεύω'), 'ΚΟΡΟΪΔΕΥΩ')
  // Το «ΐ» κουβαλά ΚΑΙ τόνο ΚΑΙ διαλυτικά: χάνει τον έναν, κρατά τα άλλα.
  eq('τόνος και διαλυτικά μαζί', grUpper('Μαΐου'), 'ΜΑΪΟΥ')
  eq('και σε ρήμα', grUpper('ταΐζω'), 'ΤΑΪΖΩ')
  // Χωρίς δίφθογγο δεν μπαίνουν διαλυτικά: «ΠΡΩΪ» θα ήταν λάθος.
  eq('όπου δεν υπάρχει δίφθογγος, μόνο ο τόνος φεύγει', grUpper('πρωί'), 'ΠΡΩΙ')
  eq('η δίφθογγος «αι» μένει δίφθογγος', grUpper('νεράιδα'), 'ΝΕΡΑΙΔΑ')
  eq('τελικό σίγμα', grUpper('ιδιοκτήτης'), 'ΙΔΙΟΚΤΗΤΗΣ')
  // Το ωμό toUpperCase() κρατά τον τόνο: αυτός είναι ο λόγος που υπάρχει η grUpper.
  ok('το toUpperCase() της JavaScript ΔΕΝ αρκεί', 'Στοιχεία'.toUpperCase() !== grUpper('Στοιχεία'))
}

console.log(fail === 0 ? `✓ format: ${pass} έλεγχοι πέρασαν` : `✗ format: ${fail} απέτυχαν από ${pass + fail}`)
if (fail > 0) process.exit(1)
