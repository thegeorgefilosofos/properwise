// ΤΟ ΠΟΣΟ ΟΠΩΣ ΑΚΟΥΓΕΤΑΙ. Η ελληνική γραμματική των αριθμών έχει τρεις
// παγίδες που ένας απλός πίνακας λέξεων θα έχανε: το γένος των χιλιάδων
// (θηλυκό), το «εκατό» που γίνεται «εκατόν» όταν ακολουθεί αριθμός και ο
// ενικός «ένα λεπτό». Κλειδώνονται εδώ.
import { greekNumberWords, spokenEuro } from './spokenAmount';

let pass = 0, fail = 0;
const ok = (n: string, c: boolean) => { if (c) pass++; else { fail++; console.error('✗ ' + n + ' → ' + JSON.stringify(n)); } };
const is = (n: number, w: string) => ok(`${n}: «${w}» (βγήκε «${greekNumberWords(n)}»)`, greekNumberWords(n) === w);

is(0, 'μηδέν');
is(1, 'ένα');
is(13, 'δεκατρία');
is(21, 'είκοσι ένα');
is(100, 'εκατό');
is(101, 'εκατόν ένα');
is(234, 'διακόσια τριάντα τέσσερα');
is(1000, 'χίλια');
is(1100, 'χίλια εκατό');
is(1234, 'χίλια διακόσια τριάντα τέσσερα');
is(2000, 'δύο χιλιάδες');
is(3000, 'τρεις χιλιάδες');
is(13000, 'δεκατρείς χιλιάδες');
is(21000, 'είκοσι μία χιλιάδες');
is(24000, 'είκοσι τέσσερις χιλιάδες');
is(100000, 'εκατό χιλιάδες');
is(200000, 'διακόσιες χιλιάδες');
is(1000000, 'ένα εκατομμύριο');
is(2300000, 'δύο εκατομμύρια τριακόσιες χιλιάδες');
ok('θηλυκό στις μονάδες', greekNumberWords(3, 'f') === 'τρεις' && greekNumberWords(1, 'f') === 'μία');

ok('ευρώ και λεπτά', spokenEuro(1234.56) === 'χίλια διακόσια τριάντα τέσσερα ευρώ και πενήντα έξι λεπτά');
ok('στρογγυλά ευρώ, χωρίς λεπτά', spokenEuro(4500) === 'τέσσερις χιλιάδες πεντακόσια ευρώ');
ok('ένα λεπτό στον ενικό', spokenEuro(3.01) === 'τρία ευρώ και ένα λεπτό');
ok('μόνο λεπτά', spokenEuro(0.5) === 'πενήντα λεπτά');
ok('μηδέν', spokenEuro(0) === 'μηδέν ευρώ');
ok('αρνητικό', spokenEuro(-12.3) === 'μείον δώδεκα ευρώ και τριάντα λεπτά');
ok('στρογγύλευση στο λεπτό όπως στην οθόνη', spokenEuro(9.999) === 'δέκα ευρώ');
ok('αρνητικό που στρογγυλεύει στο μηδέν: χωρίς «μείον»', spokenEuro(-0.001) === 'μηδέν ευρώ');
ok('μη αριθμός: κενό', spokenEuro(Number.NaN) === '');

console.log(`${pass} πέρασαν, ${fail} απέτυχαν`);
if (fail) process.exit(1);
