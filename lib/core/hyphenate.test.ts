// ═══════════════════════════════════════════════════════════════════════════
// Ο ΕΛΛΗΝΙΚΟΣ ΣΥΛΛΑΒΙΣΜΟΣ, ΕΛΕΓΜΕΝΟΣ ΣΤΟΥΣ ΚΑΝΟΝΕΣ ΤΟΥ ΣΧΟΛΕΙΟΥ
//
// ΓΙΑΤΙ ΘΕΛΕΙ ΕΛΕΓΧΟ ΚΑΙ ΜΑΛΙΣΤΑ ΑΥΣΤΗΡΟ. Το αποτέλεσμα τυπώνεται σε
// δημοσιευμένο νομικό κείμενο. Ενα «ή-ρθε» ή ένα «άνθ-ρωπος» δεν σκάει
// πουθενά: απλώς ο επισκέπτης που διαβάζει τους Ορους διαβάζει κάτι που
// φαίνεται ερασιτεχνικό, ακριβώς στη σελίδα που ζητά εμπιστοσύνη.
//
// ΤΑ ΠΑΡΑΔΕΙΓΜΑΤΑ ΕΙΝΑΙ ΤΑ ΚΑΝΟΝΙΚΑ ΤΗΣ ΓΡΑΜΜΑΤΙΚΗΣ, γιατί εκεί κρίνεται ο
// κανόνας: «λά-σπη» έναντι «θάρ-ρος» είναι όλη η διαφορά του δεύτερου κανόνα.
// ═══════════════════════════════════════════════════════════════════════════
import { syllables, hyphenateWord, hyphenate, SHY } from './hyphenate';

let pass = 0, fail = 0;
const ok = (name: string, cond: boolean) => { if (cond) { pass++ } else { fail++; console.error('✗ ' + name) } };
const eq = (name: string, got: unknown, want: unknown) => {
  const g = JSON.stringify(got), w = JSON.stringify(want);
  if (g === w) { pass++ } else { fail++; console.error(`✗ ${name}\n   got  ${g}\n   want ${w}`) }
};
/** Ο συλλαβισμός γραμμένος με παύλες, για να διαβάζεται ο έλεγχος. */
const s = (w: string) => syllables(w).join('-');

// ── ΚΑΝΟΝΑΣ 1: ΕΝΑ ΣΥΜΦΩΝΟ ΠΑΕΙ ΜΕ ΤΟ ΕΠΟΜΕΝΟ ΦΩΝΗΕΝ ────────────────────
eq('καλός', s('καλός'), 'κα-λός');
eq('πατέρας', s('πατέρας'), 'πα-τέ-ρας');
eq('όνομα', s('όνομα'), 'ό-νο-μα');

// ── ΚΑΝΟΝΑΣ 2: ΔΥΟ ΣΥΜΦΩΝΑ, ΚΑΙ ΤΟ ΕΡΩΤΗΜΑ ΕΙΝΑΙ ΑΝ ΑΡΧΙΖΟΥΝ ΛΕΞΗ ──────
// «σπ» αρχίζει λέξη (σπίτι) → πάει μπροστά.  «ρρ» δεν αρχίζει → χωρίζεται.
eq('λάσπη', s('λάσπη'), 'λά-σπη');
eq('έθνος', s('έθνος'), 'έ-θνος');
eq('θάρρος', s('θάρρος'), 'θάρ-ρος');
eq('άλλος', s('άλλος'), 'άλ-λος');
eq('κόσμος', s('κόσμος'), 'κό-σμος');
eq('ήρθε', s('ήρθε'), 'ήρ-θε');

// ── ΚΑΝΟΝΑΣ 3: ΤΡΙΑ ΣΥΜΦΩΝΑ, ΚΡΙΝΟΥΝ ΤΑ ΔΥΟ ΠΡΩΤΑ ──────────────────────
// «θρ» αρχίζει λέξη (θρόνος) → «άν-θρω-πος», με το «ν» πίσω.
eq('άνθρωπος', s('άνθρωπος'), 'άν-θρω-πος');
// «σχ» αρχίζει λέξη (σχολείο) → όλα μπροστά.
eq('αισχρός', s('αισχρός'), 'αι-σχρός');
eq('εκστρατεία', s('εκστρατεία'), 'εκ-στρα-τεί-α');

// ── ΚΑΝΟΝΑΣ 4: ΤΑ ΔΙΨΗΦΑ ΣΥΜΦΩΝΑ ΔΕΝ ΧΩΡΙΖΟΝΤΑΙ ────────────────────────
eq('μπαίνω', s('μπαίνω'), 'μπαί-νω');
eq('πέντε', s('πέντε'), 'πέ-ντε');
eq('τζάκι', s('τζάκι'), 'τζά-κι');
eq('κορίτσι', s('κορίτσι'), 'κο-ρί-τσι');
eq('αγκάθι', s('αγκάθι'), 'α-γκά-θι');

// ── ΚΑΝΟΝΑΣ 5: ΔΙΨΗΦΑ ΦΩΝΗΕΝΤΑ ΚΑΙ ΔΙΦΘΟΓΓΟΙ ───────────────────────────
eq('παιδί', s('παιδί'), 'παι-δί');
eq('είναι', s('είναι'), 'εί-ναι');
eq('ουρανός', s('ουρανός'), 'ου-ρα-νός');
eq('αυτός', s('αυτός'), 'αυ-τός');
eq('ευρώ', s('ευρώ'), 'ευ-ρώ');

// ── ΚΑΝΟΝΑΣ 6: ΣΥΝΙΖΗΣΗ — ΤΟ ΑΤΟΝΟ «ι» ΔΕΝ ΚΑΝΕΙ ΔΙΚΗ ΤΟΥ ΣΥΛΛΑΒΗ ─────
eq('χρόνια', s('χρόνια'), 'χρό-νια');
eq('δικαιώματα', s('δικαιώματα'), 'δι-και-ώ-μα-τα');

// ── ΟΤΑΝ ΤΟ ΔΙΨΗΦΟ ΔΕΝ ΕΙΝΑΙ ΔΙΨΗΦΟ ────────────────────────────────────
// ΔΥΟ ΣΗΜΑΔΙΑ ΤΟ ΣΠΑΝΕ, ΚΑΙ ΤΑ ΔΥΟ ΕΙΝΑΙ ΤΥΠΩΜΕΝΑ ΣΤΗ ΛΕΞΗ. Ο τόνος στο
// ΠΡΩΤΟ φωνήεν λέει ότι διαβάζονται χωριστά· τα διαλυτικά υπάρχουν ακριβώς
// γι' αυτόν τον λόγο. Χωρίς τους δύο ελέγχους, ο «γάιδαρος» θα γινόταν
// «γάι-δα-ρος» και η «πρωτεΐνη» «πρω-τεΐ-νη».
eq('τόνος στο πρώτο φωνήεν', s('γάιδαρος'), 'γά-ι-δα-ρος');
eq('διαλυτικά', s('πρωτεΐνη'), 'πρω-τε-ΐ-νη');
eq('και το «Μάιος»', s('Μάιος'), 'Μά-ι-ος');

// ── ΛΕΞΕΙΣ ΠΟΥ ΟΝΤΩΣ ΥΠΑΡΧΟΥΝ ΣΤΙΣ ΣΕΛΙΔΕΣ ─────────────────────────────
eq('δεδομένα', s('δεδομένα'), 'δε-δο-μέ-να');
eq('επεξεργασία', s('επεξεργασία'), 'ε-πε-ξερ-γα-σί-α');
eq('υποχρεώσεις', s('υποχρεώσεις'), 'υ-πο-χρε-ώ-σεις');
eq('φορολογικός', s('φορολογικός'), 'φο-ρο-λο-γι-κός');
eq('ακίνητο', s('ακίνητο'), 'α-κί-νη-το');
eq('συνδρομή', s('συνδρομή'), 'συν-δρο-μή');
eq('κρυπτογράφηση', s('κρυπτογράφηση'), 'κρυ-πτο-γρά-φη-ση');

// ═══ ΤΟ ΜΑΛΑΚΟ ΕΝΩΤΙΚΟ ΚΑΙ ΟΙ ΤΥΠΟΓΡΑΦΙΚΟΙ ΚΑΝΟΝΕΣ ══════════════════════
// ΔΕΝ ΣΠΑΜΕ ΜΙΚΡΕΣ ΛΕΞΕΙΣ. Κάτω από έξι γράμματα δεν κερδίζεται πλάτος.
eq('τρίλεξη λέξη μένει ανέπαφη', hyphenateWord('καλός'), 'καλός');
eq('ούτε το «ευρώ»', hyphenateWord('ευρώ'), 'ευρώ');

// ΟΥΤΕ ΑΦΗΝΟΥΜΕ ΕΝΑ ΓΡΑΜΜΑ ΣΤΗΝ ΑΚΡΗ. Το «ό-νομα» θα άφηνε το «ό» μόνο του
// στο τέλος της γραμμής, που είναι ακριβώς ό,τι δεν κάνει καμία σοβαρή
// τυπογραφία· η πρώτη τομή πέφτει.
{
  const h = hyphenateWord('υποχρεώσεις');
  ok('η πρώτη τομή με ένα γράμμα δεν μπαίνει', !h.startsWith('υ' + SHY));
  ok('αλλά οι υπόλοιπες μπαίνουν', h.includes(SHY));
  eq('και το κείμενο μένει ίδιο χωρίς τα ενωτικά', h.split(SHY).join(''), 'υποχρεώσεις');
}

// ═══ ΤΙ ΔΕΝ ΑΓΓΙΖΕΤΑΙ ═══════════════════════════════════════════════════
// Ο,τι δεν είναι ελληνικά γράμματα μένει όπως είναι: ονόματα υπηρεσιών,
// διευθύνσεις, αριθμοί νόμων, συντομογραφίες.
eq('λατινικά', hyphenateWord('PROPERWISE'), 'PROPERWISE');
eq('διεύθυνση', hyphenate('privacy@properwise.gr'), 'privacy@properwise.gr');
eq('αριθμός νόμου', hyphenate('ν.5246/2025'), 'ν.5246/2025');
eq('συντομογραφία', hyphenate('GDPR'), 'GDPR');
eq('ΑΦΜ κεφαλαία', hyphenate('ΑΦΜ'), 'ΑΦΜ');

// ═══ ΤΟ ΕΛΛΗΝΙΚΟ ΑΡΚΤΙΚΟΛΕΞΟ ΔΕΝ ΣΠΑΕΙ ════════════════════════════════════
// Ο έλεγχος του «ΑΦΜ» από πάνω περνούσε για λάθος λόγο: τρία γράμματα είναι
// κάτω από το MIN_WORD, άρα δεν έφτανε ποτέ στον κανόνα. Μόλις το αρκτικόλεξο
// είχε έξι γράμματα, ο συλλαβιστής το έκοβε σαν να ήταν λέξη — «ΕΛ-ΣΤΑΤ» μέσα
// στη σημείωση αναπροσαρμογής, «ΔΕΔ-ΔΗΕ» στους λογαριασμούς ρεύματος. Τα
// κεφαλαία της έμφασης έπαθαν το ίδιο: ένα «ΠΡΟΣΟΧΗ» κομμένο στο τέλος της
// γραμμής χάνει τη δουλειά για την οποία γράφτηκε με κεφαλαία.
eq('ΕΛΣΤΑΤ', hyphenate('ΕΛΣΤΑΤ'), 'ΕΛΣΤΑΤ');
eq('ΔΕΔΔΗΕ', hyphenate('ΔΕΔΔΗΕ'), 'ΔΕΔΔΗΕ');
eq('ΕΓΔΙΧ', hyphenate('ΕΓΔΙΧ'), 'ΕΓΔΙΧ');
eq('έμφαση σε κεφαλαία', hyphenate('ΠΡΟΣΟΧΗ'), 'ΠΡΟΣΟΧΗ');
eq('κεφαλαία με τόνο', hyphenate('ΆΡΘΡΟ'), 'ΆΡΘΡΟ');
// Το αρκτικόλεξο μένει ακέραιο ΜΕΣΑ στην πρόταση, ενώ γύρω του συλλαβίζεται
// κανονικά: ο κανόνας κοιτάζει τη λέξη, όχι ολόκληρο το κείμενο.
{
  const out = hyphenate('βάσει Δείκτη Τιμών Καταναλωτή (ΕΛΣΤΑΤ), εφόσον προβλέπεται');
  ok('το αρκτικόλεξο ακέραιο μέσα στην πρόταση', out.includes('(ΕΛΣΤΑΤ)'));
  ok('κι οι γύρω λέξεις συλλαβισμένες', out.includes(SHY));
}

// ═══ ΤΟ ΚΕΙΜΕΝΟ ΕΠΙΣΤΡΕΦΕΤΑΙ ΑΝΕΠΑΦΟ, ΜΕ ΜΟΝΗ ΠΡΟΣΘΗΚΗ ΤΟ ΑΟΡΑΤΟ ══════
// Ο πιο σημαντικός έλεγχος όλου του αρχείου: ό,τι κι αν κάνει ο συλλαβισμός,
// αφαιρώντας τα μαλακά ενωτικά πρέπει να προκύπτει ΤΟ ΙΔΙΟ κείμενο. Αλλιώς
// μια νομική πρόταση αλλάζει σιωπηλά.
{
  const src = 'Υπεύθυνος επεξεργασίας των δεδομένων που περιγράφονται εδώ είναι ο '
    + 'φορέας λειτουργίας του PROPERWISE (στο εξής «εμείς»). Γράψε μας στο '
    + 'privacy@properwise.gr, κατά τον ν.5246/2025 και τον Καν. ΕΕ 2016/679.';
  const out = hyphenate(src);
  eq('χωρίς τα ενωτικά, το ίδιο ακριβώς κείμενο', out.split(SHY).join(''), src);
  ok('και μπήκαν ενωτικά', out.includes(SHY));
  ok('η διεύθυνση δεν πειράχτηκε', out.includes('privacy@properwise.gr'));
  ok('ούτε ο αριθμός του νόμου', out.includes('ν.5246/2025'));
  ok('ούτε το λατινικό όνομα', out.includes('PROPERWISE'));
}

// ΚΑΙ ΤΟ ΚΕΝΟ ΚΕΙΜΕΝΟ ΔΕΝ ΣΚΑΕΙ.
eq('κενό', hyphenate(''), '');
eq('μόνο κενά', hyphenate('   '), '   ');

console.log(fail === 0 ? `✓ hyphenate: ${pass} έλεγχοι πέρασαν` : `✗ hyphenate: ${fail} απέτυχαν από ${pass + fail}`);
if (fail > 0) process.exit(1);
