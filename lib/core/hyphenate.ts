// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΠΡΟΒΛΗΜΑ, ΜΕΤΡΗΜΕΝΟ. Οι νομικές σελίδες στοιχίζονται πλήρως, όπως κάθε
// σύμβαση. Χωρίς συλλαβισμό όμως η πλήρης στοίχιση δεν κλείνει τη γραμμή
// σπάζοντας λέξη: την κλείνει ΤΕΝΤΩΝΟΝΤΑΣ τα κενά. Σε 195 κενά της σελίδας
// «Ποιοι είμαστε», στα 1440, μετρήθηκαν διάμεσο 5,5 · p90 14 · μέγιστο 16,9,
// όταν το φυσικό κενό της Inter στα 15 είναι περίπου 4,2. Δηλαδή ποτάμια.
//
// ΚΑΙ ΤΟ `hyphens: auto` ΔΕΝ ΤΟ ΛΥΝΕΙ. Ζητά λεξικό συλλαβισμού από τον
// περιηγητή. Μετρημένο με `lang="el"`: ΙΔΙΑ ακριβώς νούμερα, ώς το δέκατο —
// καμία λέξη δεν έσπασε. Και δεν είναι ζήτημα ενός περιηγητή: το αν υπάρχει
// ελληνικό λεξικό εξαρτάται από έκδοση, πλατφόρμα και το αν έχει κατέβει, άρα
// η στοίχιση του κειμένου μας θα ήταν λοταρία ανά συσκευή.
//
// Η ΛΥΣΗ ΕΙΝΑΙ ΝΑ ΜΗΝ ΡΩΤΑΜΕ ΤΟΝ ΠΕΡΙΗΓΗΤΗ. Τα ελληνικά, σε αντίθεση με τα
// αγγλικά, συλλαβίζονται ΜΕ ΚΑΝΟΝΕΣ και όχι με λεξικό: οι κανόνες είναι αυτοί
// που διδάσκονται στο σχολείο και δεν έχουν εξαιρέσεις ανά λέξη. Τους
// εφαρμόζουμε εδώ και εμφυτεύουμε ΜΑΛΑΚΟ ΕΝΩΤΙΚΟ (U+00AD) στα σημεία τομής.
// Το μαλακό ενωτικό είναι αόρατο· γίνεται «-» ΜΟΝΟ αν ο περιηγητής χρειαστεί
// να σπάσει εκεί. Δουλεύει σε κάθε μηχανή, σε κάθε έκδοση, στο χαρτί.
//
// ΟΙ ΚΑΝΟΝΕΣ ΠΟΥ ΕΦΑΡΜΟΖΟΝΤΑΙ
//   1. Ενα σύμφωνο ανάμεσα σε δύο φωνήεντα πάει με το ΕΠΟΜΕΝΟ:  κα-λός
//   2. Δύο σύμφωνα: αν αρχίζει ελληνική λέξη από αυτά, πάνε ΜΑΖΙ με το
//      επόμενο φωνήεν (λά-σπη, έ-θνος)· αλλιώς χωρίζονται (θάρ-ρος, άν-θος)
//   3. Τρία ή περισσότερα: αν τα ΔΥΟ ΠΡΩΤΑ αρχίζουν λέξη, όλα πάνε μπροστά
//      (αι-σχρός)· αλλιώς το πρώτο μένει πίσω (άν-θρω-πος)
//   4. Τα δίψηφα σύμφωνα (μπ, ντ, γκ, τσ, τζ) δεν χωρίζονται ποτέ
//   5. Τα δίψηφα φωνήεντα και οι δίφθογγοι (αι, ει, οι, υι, ου, αυ, ευ, ηυ)
//      δεν χωρίζονται
//   6. Οι συνιζήσεις (ια, ιο, ιε, ιω μετά από σύμφωνο) μένουν μία συλλαβή:
//      χρό-νια, όχι χρό-νι-α
//
// ΚΑΙ ΔΥΟ ΤΥΠΟΓΡΑΦΙΚΟΙ ΚΑΝΟΝΕΣ ΠΑΝΩ ΑΠΟ ΑΥΤΟΥΣ. Δεν σπάμε αφήνοντας ένα ή δύο
// γράμματα μόνα τους στην άκρη της γραμμής, γιατί το κέρδος σε πλάτος είναι
// μηδενικό και το μάτι σκοντάφτει· και δεν αγγίζουμε λέξεις κάτω από έξι
// γράμματα, που δεν έχουν τι να προσφέρουν σπασμένες.
// ═══════════════════════════════════════════════════════════════════════════

/** Το μαλακό ενωτικό: αόρατο, εκτός αν χρειαστεί να σπάσει η γραμμή εκεί. */
export const SHY = '­';

const VOWELS = 'αάεέηήιίϊΐοόυύϋΰωώ';
const isVowel = (c: string) => VOWELS.includes(c.toLowerCase());

/** Ελληνικό γράμμα — κεφαλαίο ή πεζό, με ή χωρίς τόνο. */
const isGreek = (c: string) => /[Ͱ-Ͽἀ-῿]/.test(c);

/**
 * ΤΑ ΣΥΜΠΛΕΓΜΑΤΑ ΑΠΟ ΤΑ ΟΠΟΙΑ ΑΡΧΙΖΕΙ ΕΛΛΗΝΙΚΗ ΛΕΞΗ.
 *
 * Είναι ο πίνακας που κρίνει τον δεύτερο κανόνα: «βλ» αρχίζει λέξη (βλέπω),
 * άρα «θά-βλα»· «ρθ» δεν αρχίζει, άρα «ήρ-θε». Ο κατάλογος είναι κλειστός και
 * γραμμένος ρητά — δεν παράγεται από ευρετικό, γιατί μια ευρετική που πέφτει
 * έξω δίνει «ή-ρθε» σε δημοσιευμένο νομικό κείμενο.
 */
const CLUSTERS = new Set([
  'βγ', 'βδ', 'βλ', 'βρ',
  'γδ', 'γκ', 'γλ', 'γν', 'γρ',
  'δρ',
  'θλ', 'θν', 'θρ',
  'κβ', 'κλ', 'κν', 'κρ', 'κτ',
  'μν', 'μπ',
  'ντ',
  'πλ', 'πν', 'πρ', 'πτ',
  'σβ', 'σγ', 'σθ', 'σκ', 'σλ', 'σμ', 'σν', 'σπ', 'στ', 'σφ', 'σχ',
  'τζ', 'τλ', 'τμ', 'τρ', 'τσ',
  'φθ', 'φκ', 'φλ', 'φρ', 'φτ', 'φχ',
  'χλ', 'χν', 'χρ', 'χτ',
]);

/** Δίψηφα φωνήεντα και δίφθογγοι: μία συλλαβή, ποτέ χωρισμένα. */
const DIGRAPH_VOWELS = new Set(['αι', 'ει', 'οι', 'υι', 'ου', 'αυ', 'ευ', 'ηυ']);

/** Το φωνήεν χωρίς τόνο και χωρίς διαλυτικά, για να αναγνωρίζεται το δίψηφο. */
const BARE: Record<string, string> = {
  'ά': 'α', 'έ': 'ε', 'ή': 'η', 'ί': 'ι', 'ό': 'ο', 'ύ': 'υ', 'ώ': 'ω',
  'ϊ': 'ι', 'ϋ': 'υ', 'ΐ': 'ι', 'ΰ': 'υ',
};
const bare = (c: string) => BARE[c] ?? c;
/** Τόνος στο ΠΡΩΤΟ φωνήεν σπάει το δίψηφο: «γά-ι-δα-ρος», όχι «γάι-δα-ρος». */
const isAccented = (c: string) => 'άέήίόύώΐΰ'.includes(c);
/** Τα διαλυτικά υπάρχουν ακριβώς για να δηλώσουν ότι ΔΕΝ είναι δίψηφο. */
const hasDiaeresis = (c: string) => 'ϊϋΐΰ'.includes(c);

/**
 * Δίψηφο φωνήεν ή δίφθογγος;
 *
 * ΤΟ ΣΦΑΛΜΑ ΠΟΥ ΤΟ ΓΕΝΝΗΣΕ: ο κατάλογος κρατούσε μόνο άτονες μορφές («αι»),
 * ενώ στα ελληνικά ο τόνος του δίψηφου πέφτει στο ΔΕΥΤΕΡΟ φωνήεν («μπαίνω»,
 * «είναι»). Ετσι το «αί» δεν αναγνωριζόταν και έβγαινε «μπα-ί-νω».
 */
const isDigraph = (a: string, b: string) =>
  !isAccented(a) && !hasDiaeresis(b) && DIGRAPH_VOWELS.has(bare(a) + bare(b));

/**
 * Συνίζηση: το άτονο «ι» πριν από φωνήεν διαβάζεται μαζί του σε μία συλλαβή —
 * «χρό-νια», όχι «χρό-νι-α». Ισχύει μόνο για ΑΤΟΝΟ «ι»· το τονισμένο κρατά τη
 * δική του συλλαβή («βι-ο-λί» έναντι «κα-ρδιά»).
 *
 * ΚΑΙ ΘΕΛΕΙ ΣΥΜΦΩΝΟ ΑΠΟ ΠΡΙΝ. Το «Μάιος» το έδειξε: εκεί το «ι» ακολουθεί
 * ΦΩΝΗΕΝ, οπότε δεν έχει σύμφωνο να «κολλήσει» και διαβάζεται χωριστά —
 * «Μά-ι-ος», όχι «Μά-ιος». Χωρίς τον όρο, κάθε «ιο» και «ια» μετά από φωνήεν
 * γινόταν λάθος μία συλλαβή.
 */
const isSynizesis = (a: string, b: string, afterConsonant: boolean) =>
  afterConsonant && (a === 'ι' || a === 'υ') && 'αάεέοόωώυύ'.includes(b);

/**
 * Σπάει μία ΛΕΞΗ σε συλλαβές. Δέχεται μόνο γράμματα· ο καλών φροντίζει να μην
 * της δώσει σημεία στίξης ή αριθμούς.
 */
export function syllables(word: string): string[] {
  const w = word;
  if (w.length < 2) return [w];

  // ── Ομαδοποίηση σε πυρήνες φωνηέντων και συμφωνικά συμπλέγματα ────────────
  type Chunk = { text: string; vowel: boolean };
  const chunks: Chunk[] = [];
  let i = 0;
  while (i < w.length) {
    const c = w[i];
    if (isVowel(c)) {
      let group = c;
      // Δίψηφο, δίφθογγος ή συνίζηση — ΜΟΝΟ πάνω σε ΜΟΝΟ γράμμα. Το «αι» του
      // «δικαιώματα» είναι ήδη δίψηφο· αν του επιτραπεί να ρουφήξει και το
      // «ώ», βγαίνει «δι-καιώ-μα-τα» αντί για «δι-και-ώ-μα-τα».
      if (i + 1 < w.length && isVowel(w[i + 1])) {
        const a = c.toLowerCase(), b = w[i + 1].toLowerCase();
        const afterConsonant = i > 0 && !isVowel(w[i - 1]);
        if (isDigraph(a, b) || isSynizesis(a, b, afterConsonant)) group += w[i + 1];
      }
      chunks.push({ text: group, vowel: true });
      i += group.length;
    } else {
      let group = '';
      while (i < w.length && !isVowel(w[i])) { group += w[i]; i++; }
      chunks.push({ text: group, vowel: false });
    }
  }

  // ── Μοίρασμα των συμφώνων ανάμεσα στους πυρήνες ───────────────────────────
  const parts: string[] = [];
  let current = '';
  let hasNucleus = false;
  for (let k = 0; k < chunks.length; k++) {
    const ch = chunks[k];
    if (ch.vowel) {
      // ΧΑΣΜΩΔΙΑ: δύο πυρήνες φωνηέντων χωρίς σύμφωνο ανάμεσα είναι ΔΥΟ
      // συλλαβές. Χωρίς αυτό, το «σί»+«α» έμενε στην ίδια συλλαβή επειδή δεν
      // υπήρχε σύμφωνο να τα χωρίσει — «ε-πε-ξερ-γα-σία» αντί για «…σί-α».
      if (hasNucleus) { parts.push(current); current = ''; }
      current += ch.text;
      hasNucleus = true;
      continue;
    }

    // Σύμφωνα πριν από τον πρώτο πυρήνα ή στο τέλος της λέξης: μένουν κολλητά.
    const isLast = k === chunks.length - 1;
    if (!current || isLast) { current += ch.text; continue; }

    const cons = ch.text;
    const low = cons.toLowerCase();
    let keepBack: string;   // όσα μένουν στην προηγούμενη συλλαβή
    if (cons.length === 1) {
      keepBack = '';                                   // κανόνας 1
    } else if (cons.length === 2) {
      keepBack = CLUSTERS.has(low) ? '' : cons[0];     // κανόνας 2
    } else {
      keepBack = CLUSTERS.has(low.slice(0, 2)) ? '' : cons[0];   // κανόνας 3
    }
    current += keepBack;
    parts.push(current);
    current = cons.slice(keepBack.length);
    hasNucleus = false;
  }
  if (current) parts.push(current);
  return parts.length ? parts : [w];
}

/** Δεν σπάμε λέξη κάτω από τόσα γράμματα: δεν κερδίζει πλάτος, μόνο θόρυβο. */
const MIN_WORD = 6;
/** Ούτε αφήνουμε λιγότερα από τόσα γράμματα στην άκρη της γραμμής. */
const MIN_EDGE = 2;

/**
 * Βάζει μαλακά ενωτικά σε ΜΙΑ λέξη, στα σημεία που επιτρέπει ο συλλαβισμός
 * ΚΑΙ η τυπογραφία. Λέξη με λατινικά, ψηφία ή σύμβολα επιστρέφεται ανέπαφη:
 * «properwise.gr», «5246/2025» και «GDPR» δεν συλλαβίζονται. Ούτε το ελληνικό
 * αρκτικόλεξο: «ΕΛΣΤΑΤ» έβγαινε «ΕΛ-ΣΤΑΤ» και «ΔΕΔΔΗΕ» έβγαινε «ΔΕΔ-ΔΗΕ»,
 * επειδή ο κανόνας κοίταζε μόνο το αλφάβητο κι όχι τα κεφαλαία.
 */
/**
 * ΚΕΦΑΛΑΙΑ ΑΠΟ ΤΗΝ ΑΡΧΗ ΩΣ ΤΟ ΤΕΛΟΣ: ΔΕΝ ΕΙΝΑΙ ΛΕΞΗ, ΔΕΝ ΣΥΛΛΑΒΙΖΕΤΑΙ.
 * Πιάνει τα δύο πράγματα που γράφονται έτσι — τα δύο θέλουν το ίδιο:
 *   · Το αρκτικόλεξο. «ΕΛΣΤΑΤ» δεν έχει συλλαβές να σπάσει — είναι έξι αρχικά.
 *   · Τα κεφαλαία της έμφασης. Ενα «ΠΡΟΣΟΧΗ» που κόβεται στο τέλος της γραμμής
 *     χάνει ακριβώς αυτό για το οποίο γράφτηκε με κεφαλαία.
 * Ο έλεγχος γράφεται με ρητό εύρος γραμμάτων κι όχι με `toUpperCase()`, γιατί
 * το δεύτερο αλλάζει τους τόνους κατά περίπτωση κι εξαρτάται από τοπικές
 * ρυθμίσεις — δηλαδή θα έδινε άλλο αποτέλεσμα σε άλλη μηχανή.
 */
const ALL_CAPS = /^[Α-ΩΆΈΉΊΌΎΏΪΫ]+$/;

export function hyphenateWord(word: string): string {
  if (word.length < MIN_WORD) return word;
  if (ALL_CAPS.test(word)) return word;
  if (![...word].every(isGreek)) return word;

  const syl = syllables(word);
  if (syl.length < 2) return word;

  let out = '';
  let before = 0;
  for (let k = 0; k < syl.length; k++) {
    out += syl[k];
    before += syl[k].length;
    const after = word.length - before;
    const last = k === syl.length - 1;
    if (!last && before >= MIN_EDGE && after >= MIN_EDGE) out += SHY;
  }
  return out;
}

/**
 * Βάζει μαλακά ενωτικά σε ολόκληρο κείμενο, λέξη προς λέξη.
 *
 * ΤΑ ΟΡΙΑ ΤΩΝ ΛΕΞΕΩΝ ΚΡΑΤΙΟΥΝΤΑΙ ΑΥΤΟΥΣΙΑ. Το κείμενο επιστρέφεται με τα ίδια
 * κενά, την ίδια στίξη και τους ίδιους αριθμούς· αλλάζουν μόνο τα ελληνικά
 * γράμματα, με μόνη προσθήκη έναν αόρατο χαρακτήρα.
 */
export function hyphenate(text: string): string {
  return text.replace(/[Ͱ-Ͽἀ-῿]+/g, hyphenateWord);
}
