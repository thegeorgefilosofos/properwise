/** Το μαλακό ενωτικό: αόρατο, εκτός αν χρειαστεί να σπάσει η γραμμή εκεί. */
export const SHY = '­';

const VOWELS = 'αάεέηήιίϊΐοόυύϋΰωώ';
const isVowel = (c: string) => VOWELS.includes(c.toLowerCase());

/** Ελληνικό γράμμα — κεφαλαίο ή πεζό, με ή χωρίς τόνο. */
const isGreek = (c: string) => /[Ͱ-Ͽἀ-῿]/.test(c);

/**
 * ΤΑ ΣΥΜΠΛΕΓΜΑΤΑ ΑΠΟ ΤΑ ΟΠΟΙΑ ΑΡΧΙΖΕΙ ΕΛΛΗΝΙΚΗ ΛΕΞΗ.
 *
 * Είναι ο πίνακας που κρίνει τον δεύτερο κανόνα: «βλ» αρχίζει λέξη (βλέπω),
 * άρα «θά-βλα»· «ρθ» δεν αρχίζει, άρα «ήρ-θε». Ο κατάλογος είναι κλειστός και
 * γραμμένος ρητά — δεν παράγεται από ευρετικό, γιατί μια ευρετική που πέφτει
 * έξω δίνει «ή-ρθε» σε δημοσιευμένο νομικό κείμενο.
 */
const CLUSTERS = new Set([
  'βγ', 'βδ', 'βλ', 'βρ',
  'γδ', 'γκ', 'γλ', 'γν', 'γρ',
  'δρ',
  'θλ', 'θν', 'θρ',
  'κβ', 'κλ', 'κν', 'κρ', 'κτ',
  'μν', 'μπ',
  'ντ',
  'πλ', 'πν', 'πρ', 'πτ',
  'σβ', 'σγ', 'σθ', 'σκ', 'σλ', 'σμ', 'σν', 'σπ', 'στ', 'σφ', 'σχ',
  'τζ', 'τλ', 'τμ', 'τρ', 'τσ',
  'φθ', 'φκ', 'φλ', 'φρ', 'φτ', 'φχ',
  'χλ', 'χν', 'χρ', 'χτ',
]);

/** Δίψηφα φωνήεντα και δίφθογγοι: μία συλλαβή, ποτέ χωρισμένα. */
const DIGRAPH_VOWELS = new Set(['αι', 'ει', 'οι', 'υι', 'ου', 'αυ', 'ευ', 'ηυ']);

/** Το φωνήεν χωρίς τόνο και χωρίς διαλυτικά, για να αναγνωρίζεται το δίψηφο. */
const BARE: Record<string, string> = {
  'ά': 'α', 'έ': 'ε', 'ή': 'η', 'ί': 'ι', 'ό': 'ο', 'ύ': 'υ', 'ώ': 'ω',
  'ϊ': 'ι', 'ϋ': 'υ', 'ΐ': 'ι', 'ΰ': 'υ',
};
const bare = (c: string) => BARE[c] ?? c;
/** Τόνος στο ΠΡΩΤΟ φωνήεν σπάει το δίψηφο: «γά-ι-δα-ρος», όχι «γάι-δα-ρος». */
const isAccented = (c: string) => 'άέήίόύώΐΰ'.includes(c);
/** Τα διαλυτικά υπάρχουν ακριβώς για να δηλώσουν ότι ΔΕΝ είναι δίψηφο. */
const hasDiaeresis = (c: string) => 'ϊϋΐΰ'.includes(c);

/**
 * Δίψηφο φωνήεν ή δίφθογγος;
 *
 * ΤΟ ΣΦΑΛΜΑ ΠΟΥ ΤΟ ΓΕΝΝΗΣΕ: ο κατάλογος κρατούσε μόνο άτονες μορφές («αι»),
 * ενώ στα ελληνικά ο τόνος του δίψηφου πέφτει στο ΔΕΥΤΕΡΟ φωνήεν («μπαίνω»,
 * «είναι»). Ετσι το «αί» δεν αναγνωριζόταν και έβγαινε «μπα-ί-νω».
 */
const isDigraph = (a: string, b: string) =>
  !isAccented(a) && !hasDiaeresis(b) && DIGRAPH_VOWELS.has(bare(a) + bare(b));

/**
 * Συνίζηση: το άτονο «ι» πριν από φωνήεν διαβάζεται μαζί του σε μία συλλαβή —
 * «χρό-νια», όχι «χρό-νι-α». Ισχύει μόνο για ΑΤΟΝΟ «ι»· το τονισμένο κρατά τη
 * δική του συλλαβή («βι-ο-λί» έναντι «κα-ρδιά»).
 *
 * ΚΑΙ ΘΕΛΕΙ ΣΥΜΦΩΝΟ ΑΠΟ ΠΡΙΝ. Το «Μάιος» το έδειξε: εκεί το «ι» ακολουθεί
 * ΦΩΝΗΕΝ, οπότε δεν έχει σύμφωνο να «κολλήσει» και διαβάζεται χωριστά —
 * «Μά-ι-ος», όχι «Μά-ιος». Χωρίς τον όρο, κάθε «ιο» και «ια» μετά από φωνήεν
 * γινόταν λάθος μία συλλαβή.
 */
const isSynizesis = (a: string, b: string, afterConsonant: boolean) =>
  afterConsonant && (a === 'ι' || a === 'υ') && 'αάεέοόωώυύ'.includes(b);

/**
 * Σπάει μία ΛΕΞΗ σε συλλαβές. Δέχεται μόνο γράμματα· ο καλών φροντίζει να μην
 * της δώσει σημεία στίξης ή αριθμούς.
 */
export function syllables(word: string): string[] {
  const w = word;
  if (w.length < 2) return [w];

  // ── Ομαδοποίηση σε πυρήνες φωνηέντων και συμφωνικά συμπλέγματα ────────────
  type Chunk = { text: string; vowel: boolean };
  const chunks: Chunk[] = [];
  let i = 0;
  while (i < w.length) {
    const c = w[i];
    if (isVowel(c)) {
      let group = c;
      // Δίψηφο, δίφθογγος ή συνίζηση — ΜΟΝΟ πάνω σε ΜΟΝΟ γράμμα. Το «αι» του
      // «δικαιώματα» είναι ήδη δίψηφο· αν του επιτραπεί να ρουφήξει και το
      // «ώ», βγαίνει «δι-καιώ-μα-τα» αντί για «δι-και-ώ-μα-τα».
      if (i + 1 < w.length && isVowel(w[i + 1])) {
        const a = c.toLowerCase(), b = w[i + 1].toLowerCase();
        const afterConsonant = i > 0 && !isVowel(w[i - 1]);
        if (isDigraph(a, b)) group += w[i + 1];
        else if (isSynizesis(a, b, afterConsonant)) {
          group += w[i + 1];
          // ΣΥΝΙΖΗΣΗ ΜΠΡΟΣΤΑ ΑΠΟ ΔΙΨΗΦΟ: «μη-νιαί-ου», όχι «μη-νια-ί-ου». Το
          // «ι» κολλούσε στο «α» και άφηνε το «ί» του «αί» ορφανό, οπότε στην
          // αρχική έβγαινε «μηνια-ίου» (01.10.2026). Τα τρία είναι μία συλλαβή.
          if (i + 2 < w.length && isDigraph(b, w[i + 2].toLowerCase())) group += w[i + 2];
        }
      }
      chunks.push({ text: group, vowel: true });
      i += group.length;
    } else {
      let group = '';
      while (i < w.length && !isVowel(w[i])) { group += w[i]; i++; }
      chunks.push({ text: group, vowel: false });
    }
  }

  // ── Μοίρασμα των συμφώνων ανάμεσα στους πυρήνες ───────────────────────────
  const parts: string[] = [];
  let current = '';
  let hasNucleus = false;
  for (let k = 0; k < chunks.length; k++) {
    const ch = chunks[k];
    if (ch.vowel) {
      // ΧΑΣΜΩΔΙΑ: δύο πυρήνες φωνηέντων χωρίς σύμφωνο ανάμεσα είναι ΔΥΟ
      // συλλαβές. Χωρίς αυτό, το «σί»+«α» έμενε στην ίδια συλλαβή επειδή δεν
      // υπήρχε σύμφωνο να τα χωρίσει — «ε-πε-ξερ-γα-σία» αντί για «…σί-α».
      if (hasNucleus) { parts.push(current); current = ''; }
      current += ch.text;
      hasNucleus = true;
      continue;
    }

    // Σύμφωνα πριν από τον πρώτο πυρήνα ή στο τέλος της λέξης: μένουν κολλητά.
    const isLast = k === chunks.length - 1;
    if (!current || isLast) { current += ch.text; continue; }

    const cons = ch.text;
    const low = cons.toLowerCase();
    let keepBack: string;   // όσα μένουν στην προηγούμενη συλλαβή
    if (cons.length === 1) {
      keepBack = '';                                   // κανόνας 1
    } else if (cons.length === 2) {
      keepBack = CLUSTERS.has(low) ? '' : cons[0];     // κανόνας 2
    } else {
      keepBack = CLUSTERS.has(low.slice(0, 2)) ? '' : cons[0];   // κανόνας 3
    }
    current += keepBack;
    parts.push(current);
    current = cons.slice(keepBack.length);
    hasNucleus = false;
  }
  if (current) parts.push(current);
  return parts.length ? parts : [w];
}

/** Δεν σπάμε λέξη κάτω από τόσα γράμματα: δεν κερδίζει πλάτος, μόνο θόρυβο. */
const MIN_WORD = 6;
/**
 * Ούτε αφήνουμε λιγότερα από τόσα γράμματα στην άκρη της γραμμής.
 *
 * ΑΣΥΜΜΕΤΡΑ, ΓΙΑΤΙ ΤΟ ΜΑΤΙ ΔΙΑΒΑΖΕΙ ΑΣΥΜΜΕΤΡΑ. Αριστερά αρκούν δύο: το «κα-»
 * στο τέλος της γραμμής προαναγγέλλει λέξη, όπως κάθε ελληνικό βιβλίο. Δεξιά
 * όμως η συλλαβή των δύο γραμμάτων κατεβαίνει ΜΟΝΗ στην αρχή της επόμενης
 * γραμμής και διαβάζεται ως λέξη: «ανάλο- / γα.», «Φρανκφούρ- / τη»,
 * «εγγρα- / φή.», «δωρε- / άν» (οπτικός έλεγχος, 01.10.2026, στα 360). Το
 * κέρδος σε πλάτος από δύο γράμματα είναι αμελητέο, το κόστος στην ανάγνωση
 * όχι. Τρία γράμματα και πάνω στη νέα γραμμή.
 */
const MIN_LEFT = 2;
const MIN_RIGHT = 3;

/**
 * Βάζει μαλακά ενωτικά σε ΜΙΑ λέξη, στα σημεία που επιτρέπει ο συλλαβισμός
 * ΚΑΙ η τυπογραφία. Λέξη με λατινικά, ψηφία ή σύμβολα επιστρέφεται ανέπαφη:
 * «properwise.gr», «5246/2025» και «GDPR» δεν συλλαβίζονται. Ούτε το ελληνικό
 * αρκτικόλεξο: «ΕΛΣΤΑΤ» έβγαινε «ΕΛ-ΣΤΑΤ» και «ΔΕΔΔΗΕ» έβγαινε «ΔΕΔ-ΔΗΕ»,
 * επειδή ο κανόνας κοίταζε μόνο το αλφάβητο κι όχι τα κεφαλαία.
 */
/**
 * ΚΕΦΑΛΑΙΑ ΑΠΟ ΤΗΝ ΑΡΧΗ ΩΣ ΤΟ ΤΕΛΟΣ: ΔΕΝ ΕΙΝΑΙ ΛΕΞΗ, ΔΕΝ ΣΥΛΛΑΒΙΖΕΤΑΙ.
 * Πιάνει τα δύο πράγματα που γράφονται έτσι — τα δύο θέλουν το ίδιο:
 *   · Το αρκτικόλεξο. «ΕΛΣΤΑΤ» δεν έχει συλλαβές να σπάσει — είναι έξι αρχικά.
 *   · Τα κεφαλαία της έμφασης. Ενα «ΠΡΟΣΟΧΗ» που κόβεται στο τέλος της γραμμής
 *     χάνει ακριβώς αυτό για το οποίο γράφτηκε με κεφαλαία.
 * Ο έλεγχος γράφεται με ρητό εύρος γραμμάτων κι όχι με `toUpperCase()`, γιατί
 * το δεύτερο αλλάζει τους τόνους κατά περίπτωση κι εξαρτάται από τοπικές
 * ρυθμίσεις — δηλαδή θα έδινε άλλο αποτέλεσμα σε άλλη μηχανή.
 */
// Γραμμένο σε κωδικά σημεία κι όχι σε γράμματα, για δύο λόγους. Πρώτον, ο
// φύλακας των τονισμένων κεφαλαίων —σωστά— κοκκινίζει κάθε τονισμένο κεφαλαίο
// που βλέπει σε αρχείο· εδώ δεν είναι κείμενο προς ανάγνωση, είναι το σύνολο
// των χαρακτήρων που ΑΝΑΓΝΩΡΙΖΟΥΜΕ. Δεύτερον, τα Ά και Ό ξεχωρίζουν με το μάτι
// από τα άτονα μόνο σε καλή γραμματοσειρά: γραμμένα ως αριθμοί δεν χάνονται σε
// καμία αντιγραφή.
//   0391-03A9 Α ως Ω · 0386 Ά · 0388-038A Έ Ή Ί · 038C Ό · 038E-038F Ύ Ώ
//   03AA-03AB Ϊ Ϋ
const ALL_CAPS = /^[\u0391-\u03A9\u0386\u0388-\u038A\u038C\u038E\u038F\u03AA\u03AB]+$/;

export function hyphenateWord(word: string, minWord = MIN_WORD, minRight = MIN_RIGHT): string {
  if (word.length < Math.max(MIN_WORD, minWord)) return word;
  if (ALL_CAPS.test(word)) return word;
  if (![...word].every(isGreek)) return word;

  const syl = syllables(word);
  if (syl.length < 2) return word;

  let out = '';
  let before = 0;
  for (let k = 0; k < syl.length; k++) {
    out += syl[k];
    before += syl[k].length;
    const after = word.length - before;
    const last = k === syl.length - 1;
    if (!last && before >= MIN_LEFT && after >= Math.max(MIN_RIGHT, minRight)) out += SHY;
  }
  return out;
}

/** Ελληνικό κεφαλαίο, με ή χωρίς τόνο (σε κωδικά σημεία, βλ. ALL_CAPS). */
const CAP_INITIAL = /^[\u0386\u0388-\u038A\u038C\u038E\u038F\u0391-\u03A9\u03AA\u03AB]/;
/**
 * Τι κλείνει πρόταση, ώστε το κεφαλαίο που ακολουθεί να είναι αρχή πρότασης κι
 * όχι όνομα. Το «;» είναι και το ελληνικό ερωτηματικό (U+037E).
 */
const SENTENCE_END = /[.!?;\u037e\u2026\n]/;
/** Ό,τι στέκεται ανάμεσα στο τέλος της πρότασης και στην επόμενη λέξη. */
const OPENERS = /[\s\u00a0\u202f\u00ab"\u201c\u2018'([]/;

/**
 * ΚΥΡΙΟ ΟΝΟΜΑ ΜΕΣΑ ΣΤΗΝ ΠΡΟΤΑΣΗ: ΔΕΝ ΚΟΒΕΤΑΙ. «στη Φρανκφούρ- / τη» έκοβε
 * το όνομα του τόπου που ο αναγνώστης ήρθε να μάθει. Κεφαλαίο αρχικό ΠΟΥ ΔΕΝ
 * ακολουθεί τέλος πρότασης είναι όνομα (πόλη, υπηρεσία, «Κώδικας Φορολογίας»).
 * Η αρχή της πρότασης («Υπολογίζεται …») συλλαβίζεται κανονικά. Η αρχή του
 * κειμένου μετρά ως αρχή πρότασης: δεν ξέρουμε τι ήταν πριν.
 */
function isNameAt(text: string, offset: number, word: string): boolean {
  if (!CAP_INITIAL.test(word)) return false;
  for (let i = offset - 1; i >= 0; i--) {
    const c = text[i];
    if (OPENERS.test(c)) continue;
    return !SENTENCE_END.test(c);
  }
  return false;
}

/**
 * Η ΤΕΛΕΥΤΑΙΑ ΓΡΑΜΜΗ ΔΕΝ ΞΕΚΙΝΑ ΜΕ ΘΡΑΥΣΜΑ. Η τελευταία λέξη της παραγράφου
 * κόβεται μόνο αν στην τελευταία γραμμή κατεβαίνουν τουλάχιστον πέντε
 * γράμματα («μακρο- / χρόνια.»)· ποτέ «εγγρα- / φή.», «δεδομέ- / να.».
 *
 * ΓΙΑΤΙ ΟΧΙ «ΠΟΤΕ». Δοκιμάστηκε και η τελευταία λέξη εντελώς ακέραιη. Σε
 * στενή κάρτα (αρχική, 360) η «μακροχρόνια.» κατέβηκε ολόκληρη και η γραμμή
 * από πάνω άνοιξε κενό 3,4em· το ίδιο στις απαντήσεις των συχνών (2,5em). Η
 * ορφανή συλλαβή ήταν το πρόβλημα, όχι το ενωτικό· το TeX κάνει το ίδιο
 * (`\finalhyphendemerits`): ακριβό, όχι απαγορευμένο.
 */
const LAST_MIN_RIGHT = 5;

/** Μένει γράμμα ή ψηφίο ως το τέλος; Αν όχι, η λέξη είναι η τελευταία. */
const TAIL_HAS_WORD = /[\p{L}\p{N}]/u;

export type HyphenateOptions = {
  /**
   * Η ΤΕΛΕΥΤΑΙΑ ΛΕΞΗ ΤΗΣ ΠΑΡΑΓΡΑΦΟΥ ΔΕΝ ΑΦΗΝΕΙ ΘΡΑΥΣΜΑ. Κομμένη στη μικρή της
   * συλλαβή, αφήνει μόνη στην τελευταία γραμμή μισή λέξη («εγγρα- / φή.»): η
   * πιο ορφανή ορφανή που υπάρχει (βλ. LAST_MIN_RIGHT). Ο καλών ξέρει αν το
   * κείμενο κλείνει παράγραφο (Hyphen.tsx, typeset.ts)· το κείμενο όχι.
   */
  keepLast?: boolean;
  /**
   * ΜΟΝΟ ΟΙ ΜΑΚΡΙΕΣ ΛΕΞΕΙΣ. Στο έντονο (`<strong>`) η λέξη είναι αυτό που
   * σαρώνει το μάτι και δεν κόβεται ελαφρά («Ένω-σης» στο «Ποιοι είμαστε»).
   * Ολόκληρο όμως το έντονο αδιάσπαστο, σε στήλη 330, άνοιγε κενά 1,8em
   * («Το   κρυπτογραφημένο   αντίγραφο», 01.10.2026). Το έντονο ζητά οκτώ
   * γράμματα (Hyphen.tsx, typeset.ts): εκεί η λέξη που δεν κόβεται αρχίζει να
   * κοστίζει ορατό κενό στη στήλη του κινητού.
   */
  minWord?: number;
};

/**
 * Βάζει μαλακά ενωτικά σε ολόκληρο κείμενο, λέξη προς λέξη.
 *
 * ΤΑ ΟΡΙΑ ΤΩΝ ΛΕΞΕΩΝ ΚΡΑΤΙΟΥΝΤΑΙ ΑΥΤΟΥΣΙΑ. Το κείμενο επιστρέφεται με τα ίδια
 * κενά, την ίδια στίξη και τους ίδιους αριθμούς· αλλάζουν μόνο τα ελληνικά
 * γράμματα, με μόνη προσθήκη έναν αόρατο χαρακτήρα.
 */
export function hyphenate(text: string, opts: HyphenateOptions = {}): string {
  return text.replace(/[\u0370-\u03FF\u1F00-\u1FFF]+/g, (word: string, offset: number) => {
    if (isNameAt(text, offset, word)) return word;
    if (opts.keepLast && !TAIL_HAS_WORD.test(text.slice(offset + word.length))) return hyphenateWord(word, opts.minWord, LAST_MIN_RIGHT);
    return hyphenateWord(word, opts.minWord);
  });
}

/**
 * ΟΙ ΠΑΡΑΠΟΜΠΕΣ ΜΕΝΟΥΝ ΟΛΟΚΛΗΡΕΣ (`bindRefs`).
 *
 * ΤΙ ΥΠΗΡΧΕ. Ο προκάτοχος (`breakCitations`) έβαζε σημείο αλλαγής ΜΕΤΑ την
 * κάθετο: «ν.4223/» στο τέλος της γραμμής και «2013» στην αρχή της επόμενης.
 * Εκλεινε την τρύπα της στοίχισης, αλλά η παραπομπή διαβαζόταν σπασμένη, σαν
 * δύο αριθμοί· και όποιος την αντέγραφε για να τη βρει στο ΦΕΚ έπαιρνε τα
 * μισά (οπτικός έλεγχος, 01.10.2026).
 *
 * ΤΩΡΑ Η ΑΛΛΑΓΗ ΓΡΑΜΜΗΣ ΠΕΦΤΕΙ ΠΡΙΝ ΑΠΟ ΤΟ «ν.», ΟΧΙ ΜΕΣΑ ΣΤΟΝ ΑΡΙΘΜΟ. Το
 * «ν.5219/2025» χωρίς κενό είναι ήδη μία λέξη· τα κενά ΜΕΣΑ σε μία αναφορά
 * γίνονται αδιάσπαστα, ώστε ο δείκτης να μη μένει ορφανός στο τέλος γραμμής:
 *   · «ν. 5246/2025», «παρ. 3», «άρθρο 39», «ΦΕΚ Β΄» → U+00A0
 *   · «15 / 25 / 35 / 45%» → στενά αδιάσπαστα κενά (U+202F) γύρω από την
 *     κάθετο: μένει ενιαίο ΚΑΙ κονταίνει
 *   · «30 ημέρες», «12 μήνες» → ο αριθμός δεν χωρίζεται από τη μονάδα του
 *   · «15% ως 45%» → το «ως» δεν τελειώνει γραμμή, πάει με το «45%»
 *
 * ΚΑΙ ΟΧΙ ΠΑΡΑΠΑΝΩ, ΜΕΤΡΗΜΕΝΟ. Πρώτη γραφή έδενε και ολόκληρο το «ΦΕΚ Β΄
 * 5590/17.09.2026» και ολόκληρο το «10% ή 20%». Στις πηγές του οδηγού ΕΝΦΙΑ
 * στα 360 (στήλη ~40 χαρακτήρων) έβγαλε κενά 2,1em και 2,4em εκεί που πριν
 * ήταν 1,1em: είκοσι πέντε χαρακτήρες χωρίς σημείο κοπής δεν χωρούν σε γραμμή
 * σαράντα χωρίς να τεντώσουν την από πάνω. Ο αριθμός του ΦΕΚ μπορεί να
 * κατέβει μόνος του· ο αριθμός νόμου και το έτος του όχι.
 *
 * ΞΕΧΩΡΙΣΤΟ ΑΠΟ ΤΟ `hyphenate`, που υπόσχεται ότι προσθέτει ΜΟΝΟ μαλακά
 * ενωτικά (hyphenate.test.ts). Τρέχει ΠΡΙΝ από αυτό: η «ημέρες» συλλαβισμένη
 * δεν θα ταίριαζε πια στον κανόνα της μονάδας.
 */
const NB = '\u00a0';
const NNB = '\u202f';
const REF_RULES: Array<[RegExp, string]> = [
  // «ν. 5246», «Ν. 4223», «παρ. 3», «αρ. 7», «άρθρο 39», «άρθρου 210», «ΦΕΚ Β΄».
  // Lookbehind, ώστε το «μεν. 5» (λέξη που τελειώνει σε «ν.») να μη δεθεί.
  [/(?<!\p{L})(ν\.|Ν\.|παρ\.|αρ\.|άρθρο|άρθρου|άρθρα|ΦΕΚ|ΚΥΑ)[ \t]+(?=[\dΑ-Ω])/gu, `$1${NB}`],
  // «15 / 25 / 35 / 45%»: κάθετος ανάμεσα σε ποσοστά ή αριθμούς
  [/(\d%?) \/ (?=\d)/g, `$1${NNB}/${NNB}`],
  // «15% ως 45%», «10% έως 20%», «10% ή 20%»
  [/(\d%) (ως|έως|ή) (?=\d)/g, `$1 $2${NB}`],
  // Ο αριθμός με τη μονάδα του χρόνου
  [/(\d) (?=(?:ημέρες|ημέρα|ημερών|μέρες|μήνες|μήνα|μηνών|έτη|ετών|χρόνια|χρόνο|ώρες|ώρα|εβδομάδες|εργάσιμες)(?!\p{L}))/gu, `$1${NB}`],
];

export function bindRefs(text: string): string {
  let out = text;
  for (const [re, to] of REF_RULES) out = out.replace(re, to);
  return out;
}
