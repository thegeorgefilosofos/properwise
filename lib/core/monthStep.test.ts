// ΔΟΣΕΙΣ ΣΤΙΣ 29 ΩΣ 31 ΤΟΥ ΜΗΝΑ (02.10.2026).
//
// Πριν: `new Date(έτος, μήνας + i + 1, μέρα)` για έναρξη 31.8.2026 έδινε 1.10
// αντί για 30.9 και δύο δόσεις τον Οκτώβριο. Τώρα κάθε δόση μετριέται από την
// έναρξη με κλείδωμα στο τέλος του μήνα.
//
// Τρέξε: npx tsx lib/core/monthStep.test.ts
// ═══════════════════════════════════════════════════════════════════════════
import { instalmentDate, instalmentDates } from './monthStep'

let pass = 0, fail = 0
const ok = (n: string, c: boolean) => { if (c) pass++; else { fail++; console.error('✗ ' + n) } }
const eq = (n: string, a: unknown, b: unknown) => {
  const same = JSON.stringify(a) === JSON.stringify(b)
  ok(`${n}: ${JSON.stringify(a)} ${same ? '=' : '≠'} ${JSON.stringify(b)}`, same)
}

eq('έναρξη 31.8.2026, επτά δόσεις', instalmentDates('2026-08-31', 7), [
  '2026-09-30', '2026-10-31', '2026-11-30', '2026-12-31', '2027-01-31', '2027-02-28', '2027-03-31',
])
// Η κλειδωμένη μέρα δεν «κολλάει»: μετά τις 28.2 ξαναγυρίζει στις 31.
eq('έναρξη 31.1, Φεβρουάριος και Μάρτιος', instalmentDates('2027-01-31', 2), ['2027-02-28', '2027-03-31'])
eq('δίσεκτο έτος', instalmentDate('2028-01-30', 1), '2028-02-29')
eq('συνηθισμένη μέρα', instalmentDates('2026-08-05', 3), ['2026-09-05', '2026-10-05', '2026-11-05'])
eq('πέρασμα έτους', instalmentDate('2026-12-15', 1), '2027-01-15')
eq('άκυρη έναρξη', instalmentDates('χθες', 3), [])
ok('καμία ημερομηνία δεν ξεφεύγει από τον μήνα της', instalmentDates('2026-01-31', 60).every((d, i) => {
  const m = (0 + i + 1) % 12
  return Number(d.slice(5, 7)) === m + 1
}))

// Το παλιό σφάλμα, για να φαίνεται τι διορθώθηκε: ο τύπος έδινε 1 Οκτωβρίου.
const old = new Date(2026, 7 + 0 + 1, 31)
ok('ο παλιός τύπος υπερχείλιζε (αναφορά)', old.getMonth() === 9 && old.getDate() === 1)

console.log(`\nmonthStep.ts — ${pass} passed, ${fail} failed`)
if (fail) process.exit(1)
