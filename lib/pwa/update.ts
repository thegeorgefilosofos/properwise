/** Πόση ώρα στο παρασκήνιο κάνει την επιστροφή «νέο ξεκίνημα». */
export const AWAY_MS = 10 * 60_000;

/** Κάθε πόσο ρωτά όσο είναι ανοιχτή μπροστά του. */
export const POLL_MS = 30 * 60_000;

/** Ποτέ δύο ερωτήσεις πιο κοντά από αυτό (γρήγορα πήγαινε-έλα στην εφαρμογή). */
export const MIN_GAP_MS = 60_000;

export type UpdateAction = 'none' | 'reload' | 'offer';

/**
 * Τι γίνεται μόλις μάθουμε ποιο build τρέχει ο διακομιστής.
 *
 * @param mine    Το build αυτού του κώδικα.
 * @param live    Το build του διακομιστή (`null` αν η ερώτηση απέτυχε).
 * @param awayMs  Πόση ώρα ήταν στο παρασκήνιο πριν από αυτόν τον έλεγχο (0 αν δεν ήταν).
 * @param busy    Γράφει κάτι ή έχει ανοιχτό παράθυρο.
 */
export function decideUpdate(mine: string, live: string | null, awayMs: number, busy: boolean): UpdateAction {
  // Τοπική ανάπτυξη ή άγνωστο build: τίποτα να συγκριθεί.
  if (!live || !mine || mine === 'dev' || live === 'dev') return 'none';
  if (live === mine) return 'none';
  return awayMs >= AWAY_MS && !busy ? 'reload' : 'offer';
}
