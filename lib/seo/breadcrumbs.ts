// `SITE + path` (lib/core/site.ts), ο ίδιος host με το canonical και τον χάρτη.
// Η αρχική γράφεται ως σκέτο `SITE`, όπως στο canonical και στον χάρτη της.
//
// ΚΑΘΕ ΚΡΙΚΟΣ ΕΧΕΙ ΣΕΛΙΔΑ. Η Google ζητά `item` σε κάθε κρίκο εκτός από τον
// τελευταίο· εδώ το έχουν όλοι. Κρίκος χωρίς δική του σελίδα (π.χ. ένας
// «Υπολογισμοί» χωρίς σελίδα-κόμβο) δεν μπαίνει: θα έδειχνε στο κενό.
