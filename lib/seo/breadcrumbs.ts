import { SITE } from '@/lib/core/site'

/** Ένας κρίκος: το όνομα όπως το διαβάζει ο άνθρωπος και η διαδρομή της σελίδας του. */
export interface Crumb { name: string; path: string }

/** Ο πρώτος κρίκος κάθε διαδρομής. */
export const HOME_CRUMB: Crumb = { name: 'Αρχική', path: '/' }

/** Η απόλυτη διεύθυνση ενός κρίκου, με τον κανονικό host. */
export const crumbUrl = (path: string): string => (path === '/' ? SITE : SITE + path)

/**
 * Ο κόμβος `BreadcrumbList` για το `@graph` μιας σελίδας. Η διαδρομή ξεκινά
 * πάντα από την αρχική: όποιος τη δώσει χωρίς αυτήν, την παίρνει μπροστά.
 */
export function breadcrumbJsonLd(trail: readonly Crumb[]) {
  const full = trail[0]?.path === '/' ? trail : [HOME_CRUMB, ...trail]
  return {
    '@type': 'BreadcrumbList',
    itemListElement: full.map((c, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name: c.name,
      item: crumbUrl(c.path),
    })),
  }
}
