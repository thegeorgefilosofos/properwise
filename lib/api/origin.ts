// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΜΕΤΡΗΘΗΚΕ. `grep -ril csrf` σε ολόκληρο το αποθετήριο: ΜΗΔΕΝ αρχεία. Και
// η χειρότερη διαδρομή το έλεγε δομικά: το `app/api/account/delete/route.ts`
// δήλωνε `export async function POST()` — χωρίς παράμετρο αιτήματος, δηλαδή
// έλεγχος προέλευσης ήταν ΑΔΥΝΑΤΟΣ, όχι ξεχασμένος.
//
// Η διαδρομή σβήνει κάθε γραμμή του λογαριασμού, ακυρώνει τη συνδρομή και
// διαγράφει τον ίδιο τον χρήστη. Χωρίς σώμα, χωρίς επικεφαλίδα, χωρίς τίποτα:
// μια ξένη σελίδα με `<form method="post">` προς αυτή τη διεύθυνση αρκούσε.
//
// ── ΤΟ SameSite ΔΕΝ ΕΙΝΑΙ Η ΑΠΑΝΤΗΣΗ, ΕΙΝΑΙ ΤΟ ΔΕΥΤΕΡΟ ΔΙΧΤΥ ────────────
// Τα cookies του παρόχου ταυτότητας γράφονται `Lax`, οπότε ο σημερινός
// περιηγητής ΔΕΝ τα στέλνει σε διασταυρούμενη υποβολή φόρμας. Ομως αυτή η
// άμυνα δεν ζει σε καμία γραμμή του αποθετηρίου: είναι προεπιλογή βιβλιοθήκης
// σε cookie που δεν γράφουμε εμείς. Αλλάζει με αναβάθμιση, με μια ρύθμιση, ή
// με έναν περιηγητή που δεν την εφαρμόζει. Ο έλεγχος προέλευσης είναι δικός
// μας κώδικας, ελεγμένος από τεστ και από φύλακα.
//
// ── ΠΩΣ ΒΡΙΣΚΟΝΤΑΙ ΟΙ ΕΠΙΤΡΕΠΤΕΣ ΠΡΟΕΛΕΥΣΕΙΣ ΧΩΡΙΣ ΚΑΡΦΩΜΕΝΟ DOMAIN ─────
// Το αίτημα ξέρει μόνο του πού απευθύνεται: το `x-forwarded-host` το γράφει ο
// αντιστροφέας του Vercel, το `host` ο περιηγητής στην τοπική ανάπτυξη.
// Δεκτή είναι η προέλευση που ταιριάζει με ΑΥΤΟΝ τον υπολογιστή. Ετσι
// δουλεύει το `localhost:3000`, δουλεύει κάθε preview deployment με το δικό
// του τυχαίο υποτομέα και δεν υπάρχει τιμή να ξεχαστεί σε καμία ρύθμιση.
//
// Δεύτερη δεκτή προέλευση, η κανονική διεύθυνση του lib/core/site.ts: αν
// μπροστά μπει CDN που ξαναγράφει το `host`, ο έλεγχος δεν πέφτει στο κενό.
//
// ΤΟ `x-forwarded-host` ΕΙΝΑΙ ΕΜΠΙΣΤΟΣΥΝΗ ΣΤΟΝ ΑΝΤΙΣΤΡΟΦΕΑ, ΚΑΙ ΓΡΑΦΕΤΑΙ:
// όποιος μπορεί να γράψει κεφαλίδες μπορεί να ταιριάξει το `Origin` του με ένα
// `x-forwarded-host` δικής του επιλογής. ΔΕΝ είναι παράκαμψη CSRF —μια ξένη
// σελίδα δεν γράφει κεφαλίδες· όποιος τις γράφει δεν κουβαλά το cookie του
// θύματος— αλλά αν κάποτε μπει δεύτερος αντιστροφέας μπροστά, εδώ κοιτάς.
//
// ── ΚΑΙ ΟΤΑΝ ΛΕΙΠΕΙ ΤΟ «Origin» ─────────────────────────────────────────
// Ο περιηγητής στέλνει `Origin` σε ΚΑΘΕ αίτημα που δεν είναι GET ή HEAD. Και
// στις τέσσερις διαδρομές που φυλάει αυτός ο έλεγχος ο μόνος καλών είναι
// δικός μας κώδικας `fetch`. Οταν λοιπόν λείπει, δεύτερη ευκαιρία δίνει το
// `sec-fetch-site: same-origin`, που το γράφει ο ίδιος ο περιηγητής και δεν
// μπορεί να το πλαστογραφήσει σελίδα.
//
// ΤΟ ΚΛΕΙΣΤΟ ΕΙΝΑΙ ΕΠΙΛΟΓΗ, ΚΑΙ ΕΧΕΙ ΚΟΣΤΟΣ: ένας μελλοντικός πελάτης εκτός
// περιηγητή (εφαρμογή κινητού, σενάριο) θα παίρνει 403 ώσπου να αποκτήσει
// δικό του τρόπο ταυτοποίησης. Το αντίθετο —«δεν ξέρω, άρα πέρασε»— είναι
// ακριβώς η πόρτα που ήρθαμε να κλείσουμε.
//
// ΤΑ WEBHOOK ΔΕΝ ΠΕΡΝΟΥΝ ΑΠΟ ΕΔΩ. Το `/api/billing/lemon` και το
// `/api/inbound` έρχονται από άλλον διακομιστή, χωρίς περιηγητή και χωρίς
// `Origin`: ο έλεγχός τους είναι η υπογραφή του σώματος. Ενας έλεγχος
// προέλευσης εκεί θα απέρριπτε ΚΑΘΕ γνήσια πληρωμή. Το ίδιο ισχύει για το
// `/api/push`, που το φωνάζει η δική μας βάση με το κοινό μυστικό.
// ═══════════════════════════════════════════════════════════════════════════

import { SITE_HOST } from '@/lib/core/site';

/** Η απάντηση προς τα έξω. Ιδια για κάθε αιτία, ώστε να μη διδάσκει τίποτα. */
export const ORIGIN_DENIED = 'Το αίτημα δεν έγινε από την εφαρμογή.';

/** Ο,τι ξέρει η διαδρομή για τις κεφαλίδες: όνομα σε πεζά, τιμή ή τίποτα. */
export type HeaderBag = { get(name: string): string | null };

/** Ο υπολογιστής στον οποίο απευθύνεται το αίτημα, όπως τον βλέπει ο διακομιστής. */
export function targetHost(headers: HeaderBag): string {
  const forwarded = (headers.get('x-forwarded-host') || '').trim();
  const direct = (headers.get('host') || '').trim();
  // ΠΡΟΤΕΡΑΙΟΤΗΤΑ ΣΤΟ ΠΡΟΩΘΗΜΕΝΟ. Στο Vercel το `host` είναι ο εσωτερικός
  // υπολογιστής της συνάρτησης· η δημόσια διεύθυνση ζει μόνο εκεί.
  return (forwarded || direct).toLowerCase();
}

/** Ο υπολογιστής μιας προέλευσης, ή κενό όταν δεν είναι καν διεύθυνση. */
function hostOfOrigin(origin: string): string {
  try {
    return new URL(origin).host.toLowerCase();
  } catch {
    // Το «null» που στέλνει ένα απομονωμένο πλαίσιο φτάνει εδώ και μένει έξω.
    return '';
  }
}

/**
 * Ηρθε το αίτημα από τη ΔΙΚΗ μας σελίδα;
 *
 * @param headers Οι κεφαλίδες του αιτήματος.
 * @param canonicalHost Η κανονική διεύθυνση του ιστότοπου, χωρίς πρωτόκολλο.
 */
export function sameOrigin(headers: HeaderBag, canonicalHost: string = SITE_HOST): boolean {
  const origin = (headers.get('origin') || '').trim();
  if (origin) {
    const from = hostOfOrigin(origin);
    if (!from) return false;
    const target = targetHost(headers);
    return from === target || from === canonicalHost.trim().toLowerCase();
  }
  const site = (headers.get('sec-fetch-site') || '').trim().toLowerCase();
  return site === 'same-origin';
}
