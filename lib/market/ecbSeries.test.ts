// ΚΑΘΕ ΕΤΙΚΕΤΑ ΣΤΗ ΣΩΣΤΗ ΣΕΙΡΑ ΤΗΣ ΕΚΤ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ. Το «Μέσο νέο στεγαστικό» διάβαζε τη σειρά MIR.M.GR.B.A2C.F…N, που
// είναι το κυμαινόμενο ή σταθερό έως 1 έτος. Ο υπολογιστής στεγαστικού έβαζε
// αυτή την τιμή στο πεδίο «Σταθερό επιτόκιο» και η σελίδα την έγραφε ως μέσο
// όρο. Η ετικέτα και η σειρά ζούσαν σε δύο διπλανές γραμμές χωρίς τίποτα να τις
// δένει· και το «Μέσο υφιστάμενο στεγαστικό» έδειχνε σε σειρά νέων χορηγήσεων.
//
// Ο ΠΙΝΑΚΑΣ ΑΠΟ ΚΑΤΩ ΕΙΝΑΙ Ο ΚΑΤΑΛΟΓΟΣ ΤΗΣ ΕΚΤ, ΟΧΙ Ο ΚΩΔΙΚΑΣ. Στις νέες
// χορηγήσεις το πέμπτο πεδίο του κλειδιού MIR (MATURITY_NOT_IRATE) είναι η
// αρχική περίοδος σταθερού επιτοκίου. Οι σημασίες είναι κατά τον κατάλογο
// CL_MATURITY_ORIG, ανεπιβεβαίωτες στο Data Portal: η Κατευθυντήρια Γραμμή
// ΕΚΤ/2005/4 ορίζει τα A (σύνολο), F (έως ένα έτος) και K (πάνω από ένα έτος).
// Οι τίτλοι των σειρών δεν διαβάστηκαν (το data-api.ecb.europa.eu δίνει 403
// στο περιβάλλον ανάπτυξης) και δεν παρατίθενται εδώ ως αυτολεξεί.
//   A  σύνολο
//   F  κυμαινόμενο ή σταθερό έως 1 έτος
//   K  σταθερό πάνω από 1 έτος
//   I  σταθερό πάνω από 1 και έως 5 έτη
// Το δέκατο πεδίο: N νέες χορηγήσεις, O υπόλοιπα.
//
// ΟΙ A ΚΑΙ K ΔΕΝ ΕΧΟΥΝ ΤΡΟΦΟΔΟΤΗΘΕΙ ΑΚΟΜΗ. Οι F και I γράφονται ήδη στον πίνακα
// market_rates για την Ελλάδα. Την ύπαρξη των A και K την επιβεβαιώνει η πρώτη
// τροφοδοσία μετά την ανάπτυξη, με το SELECT του provenance στο PR.
//
// Οι κωδικοί των τριών σειρών του στεγαστικού είναι αυτοί που όρισε ο
// ιδιοκτήτης στο αίτημα P0 της 13/10/2026.
// ═══════════════════════════════════════════════════════════════════════════
import { ECB_SERIES, seriesPage, type MarketKey } from '@/lib/market/ecb';

let pass = 0; const fail: string[] = [];
const eq = (what: string, got: unknown, want: unknown) => {
  if (JSON.stringify(got) === JSON.stringify(want)) { pass++; return; }
  fail.push(`${what}\n    περίμενα: ${JSON.stringify(want)}\n    πήρα:     ${JSON.stringify(got)}`);
};

/** Η ετικέτα που αντιστοιχεί σε κάθε περίοδο σταθερού επιτοκίου της ΕΚΤ. */
const LABEL_OF_IRF: Record<string, string> = {
  A: 'Μέσο επιτόκιο νέων στεγαστικών',
  F: 'Κυμαινόμενο ή σταθερό έως 1 έτος',
  K: 'Σταθερό πάνω από 1 έτος',
  I: 'Σταθερό πάνω από 1 και έως 5 έτη',
};
/** Η βάση μέτρησης που αντιστοιχεί στο δέκατο πεδίο. */
const BASIS_OF_COVERAGE: Record<string, string> = { N: 'νέες χορηγήσεις', O: 'υπόλοιπα δανείων' };

// ── 1. ΤΟ ΑΙΤΗΜΑ: ΚΑΘΕ ΚΛΕΙΔΙ ΣΕ ΜΙΑ ΣΥΓΚΕΚΡΙΜΕΝΗ ΣΕΙΡΑ ─────────────────────
const WANT: [MarketKey, string][] = [
  ['bog_housing_new',      'MIR.M.GR.B.A2C.A.R.A.2250.EUR.N'],
  ['bog_housing_floating', 'MIR.M.GR.B.A2C.F.R.A.2250.EUR.N'],
  ['bog_housing_fixed',    'MIR.M.GR.B.A2C.K.R.A.2250.EUR.N'],
  // Το όνομα του κλειδιού είναι η στήλη του πίνακα· η σειρά δεν άλλαξε.
  ['bog_housing_stock',    'MIR.M.GR.B.A2C.I.R.A.2250.EUR.N'],
];
for (const [key, id] of WANT) {
  const spec = ECB_SERIES.find(s => s.key === key);
  eq(`${key}: υπάρχει στον κατάλογο`, !!spec, true);
  if (!spec) continue;
  eq(`${key}: μία υποψήφια, χωρίς εφεδρεία`, spec.candidates.length, 1);
  eq(`${key}: η σειρά`, spec.candidates.map(c => `${c.flow}.${c.series}`), [id]);
  eq(`${key}: η σελίδα επαλήθευσης δείχνει στην ίδια σειρά`,
    spec.candidates.map(seriesPage), [`https://data.ecb.europa.eu/data/datasets/MIR/${id}`]);
}

// ── 2. ΚΑΘΕ ΣΕΙΡΑ MIR ΤΟΥ ΚΑΤΑΛΟΓΟΥ: Η ΕΤΙΚΕΤΑ ΒΓΑΙΝΕΙ ΑΠΟ ΤΟΝ ΚΩΔΙΚΟ ─────────
// Γενικός έλεγχος, ώστε μια σειρά που θα προστεθεί αύριο να μη γλιτώνει.
const mir = ECB_SERIES.filter(s => s.candidates.some(c => c.flow === 'MIR'));
eq('ο κατάλογος έχει τις τέσσερις σειρές του στεγαστικού', mir.map(s => s.key).sort(), WANT.map(w => w[0]).sort());
for (const spec of mir) {
  for (const c of spec.candidates) {
    const f = c.series.split('.');
    eq(`${spec.key}: δέκα πεδία`, f.length, 10);
    eq(`${spec.key}: μηνιαία, Ελλάδα, στεγαστικά νοικοκυριών, επιτόκιο`,
      [f[0], f[1], f[2], f[3], f[5], f[6], f[7], f[8]], ['M', 'GR', 'B', 'A2C', 'R', 'A', '2250', 'EUR']);
    eq(`${spec.key}: η ετικέτα είναι της περιόδου «${f[4]}»`, spec.label, LABEL_OF_IRF[f[4]] ?? `άγνωστη περίοδος ${f[4]}`);
    eq(`${spec.key}: η βάση είναι του πεδίου «${f[9]}»`, c.basis, BASIS_OF_COVERAGE[f[9]] ?? `άγνωστο πεδίο ${f[9]}`);
  }
}

// ── 3. ΤΟ ΣΤΑΘΕΡΟ ΔΕΝ ΠΕΦΤΕΙ ΠΟΤΕ ΣΕ ΑΛΛΗ ΠΕΡΙΟΔΟ ────────────────────────────
// Μια εφεδρεία στο F, στο A ή στο I θα ξανάφερνε ακριβώς το λάθος του P0: τιμή
// άλλης περιόδου στο πεδίο «Σταθερό επιτόκιο», με σωστή μορφή.
const fixed = ECB_SERIES.find(s => s.key === 'bog_housing_fixed');
eq('το σταθερό δεν έχει υποψήφια F, A ή I',
  (fixed?.candidates ?? []).filter(c => ['F', 'A', 'I'].includes(c.series.split('.')[4])).map(c => c.series), []);
const all = mir.flatMap(s => s.candidates.map(c => c.series));
eq('καμία σειρά δεν μοιράζεται σε δύο ετικέτες', new Set(all).size, all.length);

if (fail.length) { console.error(`\n✗ ecb σειρές: ${fail.length} αποτυχίες\n`); for (const f of fail) console.error('  ' + f); process.exit(1); }
console.log(`✓ ecb σειρές: ${pass} έλεγχοι πέρασαν`);
