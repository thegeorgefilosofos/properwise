// ─────────────────────────────────────────────────────────────────────────
// Το ημερολόγιο της εφαρμογής έλεγε «Ληξιπρόθεσμο» για ΚΑΘΕ ανοιχτό γεγονός με
// περασμένη ημερομηνία. Για προθεσμία (δόση, λογαριασμός, δήλωση) αυτό ισχύει.
// Για τις υπενθυμίσεις λήξης ΠΕΑ (lib/calendar/onceOnDay.ts) δεν ισχύει: δεν
// πληρώνονται και δεν υποβάλλονται. Η «Το ΠΕΑ λήγει σε 90 ημέρες» του Μαρτίου
// έβγαινε τον Μάιο στη λίστα των ληξιπρόθεσμων, δίπλα σε απλήρωτο ΕΝΦΙΑ.
// Τα email ήδη δεν το έλεγαν (`remindsAs`)· η οθόνη το έλεγε.
//
// ΤΡΕΙΣ ΚΑΤΑΣΤΑΣΕΙΣ για ανοιχτό γεγονός με περασμένη ημερομηνία:
//   · `overdue`: προθεσμία που δεν έκλεισε. «Ληξιπρόθεσμο».
//   · `expired`: η ημέρα λήξης του ΠΕΑ (`pea:expiry:0`). Δεν οφείλεται τίποτα,
//     αλλά το πιστοποιητικό δεν ισχύει πια. «Έληξε».
//   · `passed`: υπενθύμιση που έκανε τη δουλειά της (90 και 30 ημέρες πριν).
//     Καμία ένδειξη, μόνο η ημερομηνία.
//
// ΠΩΣ ΜΠΑΙΝΕΙ ΝΕΟ ΕΙΔΟΣ. Ό,τι δεν πρέπει να λέγεται ποτέ «ληξιπρόθεσμο» μπαίνει
// με ΜΙΑ γραμμή στο `NEVER_OVERDUE`. Υποψήφιες: οι δόσεις φόρου εισοδήματος
// (`tax:income-instalment-*`), που τα email ήδη δεν τις λένε ληξιπρόθεσμες
// (`reminderOccurrences` στο lib/calendar/recurrence.ts) γιατί η εφαρμογή δεν
// ξέρει αν ο χρήστης χρωστά φόρο. Χωρίς αυτή τη γραμμή, η δόση που ο χρήστης
// άγγιξε και ο συγχρονισμός δεν σβήνει θα έλεγε στην οθόνη «Ληξιπρόθεσμο».
// ═══════════════════════════════════════════════════════════════════════════
import { onceOnDay, PEA_SOURCE_PREFIX } from './onceOnDay';

type Sourced = { source?: string | null };

/** Τα είδη που, όταν περάσει η μέρα τους, δεν είναι ποτέ «ληξιπρόθεσμα». */
export const NEVER_OVERDUE: ReadonlyArray<(e: Sourced) => boolean> = [
  onceOnDay,
];

/** Η πηγή της γραμμής της ίδιας της λήξης του ΠΕΑ (`peaSource(0)` στο lib/property/peaExpiry.ts). */
export const PEA_EXPIRY_DAY_SOURCE = `${PEA_SOURCE_PREFIX}0`;

export type PastState = 'overdue' | 'expired' | 'passed';

/** Η ένδειξη κάθε κατάστασης. Το `passed` δεν παίρνει λέξη στην κάρτα, μόνο στην εξαγωγή. */
export const PAST_LABEL: Record<PastState, string> = {
  overdue: 'Ληξιπρόθεσμο',
  expired: 'Έληξε',
  passed: 'Πέρασε',
};

/**
 * Η κατάσταση ανοιχτού γεγονότος που η ημερομηνία του πέρασε, ή `null` όταν
 * δεν πέρασε ή όταν έκλεισε (πληρώθηκε, ακυρώθηκε, είναι σε εξέλιξη).
 * @param today η σημερινή ημέρα Αθήνας, `YYYY-MM-DD`.
 */
export function pastState(
  e: Sourced & { status: string; event_date: string }, today: string,
): PastState | null {
  if (e.status !== 'pending' || !(e.event_date < today)) return null;
  if (e.source === PEA_EXPIRY_DAY_SOURCE) return 'expired';
  if (NEVER_OVERDUE.some(p => p(e))) return 'passed';
  return 'overdue';
}
