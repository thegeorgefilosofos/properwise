// Οι προθεσμίες γράφονται ανά ακίνητο (`tax:<id>` σε κάθε ακίνητο), γιατί
// ανά ακίνητο τις δείχνουν το Ημερολόγιο, η Επισκόπηση και οι Εκκρεμότητες.
// Ο ΕΝΦΙΑ όμως είναι ΕΝΑ εκκαθαριστικό και το Ε1 ΜΙΑ δήλωση ανά φορολογούμενο.
// Με δύο διαμερίσματα και αυτόματο συγχρονισμό, το «ΕΝΦΙΑ, 8η δόση» θα έφτανε
// δύο φορές στο email, δύο στο push και δύο στο ημερολόγιο του κινητού, με το
// όνομα του ακινήτου δίπλα, σαν να ήταν δύο πληρωμές.
//
// Ο ΚΑΝΟΝΑΣ. Ανάμεσα σε ΑΝΟΙΧΤΑ γεγονότα του ίδιου λογαριασμού, η ίδια πηγή
// `tax:<id>` είναι μία προθεσμία. Μένει το γεγονός με το μικρότερο
// αναγνωριστικό: σταθερή επιλογή, ώστε το uid της συνδρομής και το μητρώο
// απεσταλμένων των email να βλέπουν το ίδιο γεγονός κάθε μέρα.
//
// ΧΩΡΙΣ ΕΙΣΑΓΩΓΕΣ, ΣΚΟΠΙΜΑ. Το διαβάζουν και η εφαρμογή (lib/calendar/deadlines,
// για συνδρομή και push) και η συνάρτηση άκρου send-reminders, που τρέχει σε
// Deno και δεν λύνει τα ψευδώνυμα `@/…`. Ενας κανόνας, ένα αρχείο, δύο
// περιβάλλοντα.
// ═══════════════════════════════════════════════════════════════════════════

export interface TaxCopy {
  id: string;
  source?: string | null;
}

export interface TaxOnce<T> {
  /** Τα γεγονότα, με μία μόνο γραμμή ανά θεσμική προθεσμία. */
  kept: T[];
  /** Οι πηγές `tax:<id>` που βρέθηκαν σε περισσότερα από ένα γεγονότα. */
  shared: Set<string>;
}

const isTax = (source: string | null | undefined): source is string =>
  typeof source === 'string' && source.startsWith('tax:');

/**
 * Μία γραμμή ανά θεσμική προθεσμία. Τα υπόλοιπα γεγονότα περνούν όπως ήταν και
 * με την ίδια σειρά. Ο καλών περνά ΜΟΝΟ ανοιχτά γεγονότα: το κλειστό το κρίνει
 * ο ίδιος, με τον δικό του κανόνα.
 */
export function oneTaxCopy<T extends TaxCopy>(events: readonly T[]): TaxOnce<T> {
  const best = new Map<string, T>();
  const count = new Map<string, number>();
  for (const e of events) {
    if (!isTax(e.source)) continue;
    count.set(e.source, (count.get(e.source) || 0) + 1);
    const cur = best.get(e.source);
    if (!cur || e.id < cur.id) best.set(e.source, e);
  }
  const shared = new Set([...count].filter(([, n]) => n > 1).map(([s]) => s));
  const kept = events.filter(e => !isTax(e.source) || best.get(e.source) === e);
  return { kept, shared };
}
