/** Το πρόθεμα της πηγής των υπενθυμίσεων λήξης ΠΕΑ (lib/property/peaExpiry.ts). */
export const PEA_SOURCE_PREFIX = 'pea:expiry:';

const ONCE_ON_DAY_PREFIXES: readonly string[] = [PEA_SOURCE_PREFIX];

/** Η υπενθύμιση είναι ειδοποίηση μιας ημέρας, όχι προθεσμία. */
export function onceOnDay(e: { source?: string | null }): boolean {
  const s = e.source ?? '';
  return ONCE_ON_DAY_PREFIXES.some(p => s.startsWith(p));
}

/**
 * Δέχεται το γεγονός αυτό το είδος υπενθύμισης; (`7days`, `3days`, `1day`,
 * `today`, `overdue`). Οι προθεσμίες όλα· οι ειδοποιήσεις μιας ημέρας μόνο `today`.
 */
export function remindsAs(e: { source?: string | null }, type: string): boolean {
  return !onceOnDay(e) || type === 'today';
}

/** Παίρνει σύνδεσμο «Πλήρωσα»; Μόνο ό,τι μπορεί να πληρωθεί ή να κλείσει ως προθεσμία. */
export function payableReminder(e: { source?: string | null }): boolean {
  return !onceOnDay(e);
}
