// Το Ημερολόγιο έδειχνε κάτω από το πλέγμα δύο λίστες με τα ίδια γεγονότα
// («Επόμενα από σήμερα» και «Γεγονότα») και πάνω από αυτό το πλαίσιο λήξης
// συμβολαίων, με το ίδιο ασφαλιστήριο τρίτη φορά. Μένει μία λίστα: της ημέρας
// που διάλεξε ο χρήστης στο πλέγμα, αλλιώς του μήνα που βλέπει. Το «από
// σήμερα» ζει στην «Ατζέντα», που είναι φτιαγμένη γι' αυτό.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Τα γεγονότα της λίστας. Ημέρα άλλου μήνα (ο χρήστης άλλαξε μήνα με τα βέλη)
 * δεν μετρά: η λίστα ακολουθεί πάντα τον μήνα που φαίνεται. Άδεια ημέρα δίνει
 * άδεια λίστα και όχι τον μήνα, για να μη μοιάζει ότι το πάτημα δεν έπιασε.
 */
export function belowGrid<E extends { event_date: string }>(
  monthEvents: readonly E[], picked: string | null, monthPrefix: string,
): { day: string | null; events: E[] } {
  if (picked && picked.startsWith(`${monthPrefix}-`)) {
    return { day: picked, events: monthEvents.filter(e => e.event_date === picked) }
  }
  return { day: null, events: [...monthEvents] }
}
