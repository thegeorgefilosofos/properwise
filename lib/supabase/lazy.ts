// Ο ΠΕΛΑΤΗΣ ΤΗΣ ΒΑΣΗΣ, ΜΕΤΑ ΤΟ ΠΡΩΤΟ ΣΧΕΔΙΑΣΜΑ ΤΗΣ ΟΘΟΝΗΣ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΜΕΤΡΗΜΕΝΟ ΠΡΟΒΛΗΜΑ. Το `@supabase/supabase-js` είναι ένα κομμάτι 222 KB
// (57,5 KB στο καλώδιο) που περιέχει realtime, storage, functions και
// postgrest. Ο κατασκευαστής του `SupabaseClient` φτιάχνει ΚΑΙ ΤΟΥΣ ΠΕΝΤΕ
// υποπελάτες, οπότε κανένας bundler δεν μπορεί να πετάξει όσους δεν
// χρησιμοποιούνται.
//
// Οι σελίδες σύνδεσης, εγγραφής, ταμείου και επαναφοράς κωδικού χρησιμοποιούν
// ΜΟΝΟ `auth.*`. Με στατική εισαγωγή, το κομμάτι έμπαινε ως `<script async>`
// στο ίδιο το HTML: ο επισκέπτης κατέβαζε realtime και storage για να πατήσει
// «Σύνδεση». Στη σελίδα εγγραφής αυτό ήταν το 25% όλου του JavaScript.
//
// ΤΙ ΑΛΛΑΖΕΙ ΚΑΙ ΤΙ ΟΧΙ. Ο πελάτης είναι ο ΙΔΙΟΣ — ίδιο `createBrowserClient`,
// ίδια μορφή cookie, ίδια συνεδρία. Αλλάζει μόνο ΠΟΤΕ φορτώνεται: μετά το
// πρώτο σχεδίασμα, όχι πριν. Καμία σελίδα δεν δείχνει δεδομένα βάσης στο
// πρώτο καρέ, οπότε δεν υπάρχει τίποτα να περιμένει ο χρήστης.
//
// ΔΕΝ ΑΛΛΑΖΕΙ Η ΜΟΡΦΗ ΤΟΥ COOKIE. Η εναλλακτική —σκέτο `@supabase/auth-js`
// αντί για `@supabase/ssr`— θα έκοβε ακόμη περισσότερα, αλλά το `ssr` παράγει
// τη μορφή cookie που διαβάζουν το lib/supabase/server.ts και το proxy.ts.
// Απόκλιση εκεί σημαίνει σιωπηλή απώλεια συνεδρίας σε ΟΛΗ την εφαρμογή και
// δεν ανταλλάσσεται με kilobytes.
//
// ΠΟΥ ΔΕΝ ΧΡΗΣΙΜΟΠΟΙΕΙΤΑΙ. Ο πίνακας ελέγχου κρατά τη στατική εισαγωγή: εκεί
// ο πελάτης χρειάζεται αμέσως, σε δεκάδες σημεία και μια αναβολή θα πρόσθετε
// καθυστέρηση χωρίς να γλιτώνει τίποτα — το κομμάτι κατεβαίνει έτσι κι αλλιώς.
// ═══════════════════════════════════════════════════════════════════════════
import type { createClient } from './client';

type Client = ReturnType<typeof createClient>;

/**
 * Ο πελάτης, φορτωμένος κατ' απαίτηση.
 *
 * ΕΝΑ ΑΝΤΙΓΡΑΦΟ ΑΝΑ ΚΛΗΣΗ, ΟΠΩΣ ΚΑΙ ΠΡΙΝ: το `createClient()` φτιάχνει
 * καινούριο πελάτη σε κάθε κλήση και ο κώδικας που καλεί το ξέρει. Αν εδώ
 * κρατούσαμε ένα κοινό αντικείμενο, θα άλλαζε σιωπηλά η συμπεριφορά σε κάθε
 * σημείο κλήσης — άλλο πρόβλημα, όχι λύση.
 */
export async function authClient(): Promise<Client> {
  const { createClient } = await import('./client');
  return createClient();
}

// ═══ ΧΩΡΙΣ COOKIE ΣΥΝΕΔΡΙΑΣ, ΚΑΝΕΝΑ ΦΟΡΤΩΜΑ ═════════════════════════════════
// Η εγγραφή και η σύνδεση ρωτούν στο πρώτο καρέ «είναι ήδη συνδεδεμένος;» και
// για να το ρωτήσουν κατέβαζαν ΟΛΟ τον πελάτη, περίπου 45 KB στο καλώδιο, τον
// μισό JavaScript της σελίδας πέρα από το React. Ο επισκέπτης της εγγραφής
// όμως, σχεδόν πάντα, δεν έχει λογαριασμό: η απάντηση ήταν γνωστή εκ των
// προτέρων και το κόστος πληρωνόταν για το τίποτα.
//
// Η συνεδρία του browser ζει στο cookie `sb-<έργο>-auth-token` (ή κομματιασμένο
// σε `.0`, `.1`, …), όπως το γράφει το `@supabase/ssr`, χωρίς `httpOnly`.
// Χωρίς αυτό το `getUser()` απαντά πάντα «κανένας χρήστης». Η μόνη άλλη πηγή
// συνεδρίας είναι η επιστροφή από την Google ή από σύνδεσμο email: εκεί η
// διεύθυνση φέρνει `code`, `access_token`, `token_hash`, `error` ή `oauth` και
// ο πελάτης πρέπει να φορτώσει για να κάνει την ανταλλαγή. Σε αυτές τις
// περιπτώσεις η απάντηση είναι πάντα «ίσως» και όλα γίνονται όπως πριν.

const SESSION_COOKIE = /(?:^|;\s*)sb-[^=;]*-auth-token/
const SESSION_IN_URL = /[?&#](?:code|access_token|token_hash|error|oauth)=/

/**
 * Μπορεί να υπάρχει συνεδρία; `false` μόνο όταν είναι βέβαιο ότι δεν υπάρχει.
 * Χωρίς ορίσματα διαβάζει τον browser· έξω από browser απαντά «ίσως».
 */
export function mayHaveSession(cookie?: string, url?: string): boolean {
  if (cookie === undefined) {
    if (typeof document === 'undefined') return true
    cookie = document.cookie
  }
  url ??= typeof location === 'undefined' ? '' : location.search + location.hash
  return SESSION_COOKIE.test(cookie) || SESSION_IN_URL.test(url)
}
