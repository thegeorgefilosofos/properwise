/** Οι έμποροι που ξέρει ο κώδικας. Το αναγνωριστικό, όχι το εμπορικό όνομα. */
export type MerchantId = 'lemon' | 'creem';

/**
 * Το εμπορικό όνομα κάθε εμπόρου, όπως το ξέρει ο κόσμος και όπως γράφεται σε
 * νομικό κείμενο. ΤΟ ΜΟΝΟ ΣΗΜΕΙΟ ΤΟΥ ΑΠΟΘΕΤΗΡΙΟΥ ΠΟΥ ΤΟ ΓΡΑΦΕΙ ΚΥΡΙΟΛΕΚΤΙΚΑ:
 * ο φύλακας `scripts/guard-billing-claims.mjs` κόβει κάθε άλλη αναγραφή.
 */
// ΤΟ ΟΝΟΜΑ ΤΟ ΔΙΝΕΙ Η ΘΥΡΑ ΠΟΥ ΕΙΣΠΡΑΤΤΕΙ, ΚΑΙ ΤΟ ΠΑΙΡΝΕΙ ΑΠΟ ΕΔΩ. Τα νομικά
// κείμενα ζητούν `merchant(env).name`: έτσι το όνομα στη σελίδα και ο πάροχος
// που χρεώνει είναι κυριολεκτικά το ίδιο αντικείμενο, όχι δύο τιμές που
// «τυχαίνει» να συμφωνούν.
export const MERCHANT_NAMES: Readonly<Record<MerchantId, string>> = {
  lemon: 'Lemon Squeezy',
  creem: 'Creem',
};

/** Το όνομα της μεταβλητής που διαλέγει έμπορο. */
export const PROVIDER_ENV = 'MERCHANT_PROVIDER';

/** Ο προεπιλεγμένος: ό,τι τρέχει σήμερα στην παραγωγή. */
export const DEFAULT_MERCHANT: MerchantId = 'lemon';

/** Τα ονόματα που δέχεται η μεταβλητή, για μηνύματα σφάλματος. */
export const KNOWN_MERCHANTS = Object.keys(MERCHANT_NAMES) as MerchantId[];

/**
 * Ποιος έμπορος ισχύει σε αυτή την εγκατάσταση.
 *
 * ΑΓΝΩΣΤΟ ΟΝΟΜΑ ΔΕΝ ΠΕΦΤΕΙ ΣΙΩΠΗΛΑ ΣΤΟΝ ΠΡΟΕΠΙΛΕΓΜΕΝΟ. Ενα τυπογραφικό στη
 * μεταβλητή θα σήμαινε ότι η εφαρμογή χρεώνει από άλλον πάροχο απ' ό,τι
 * νομίζει όποιος τη ρύθμισε. Πετά, ώστε να φανεί στο πρώτο κιόλας αίτημα.
 *
 * @param env το περιβάλλον, ρητά, ώστε οι σουίτες να μην πειράζουν τη διεργασία
 */
export function merchantId(env: Record<string, string | undefined> = process.env): MerchantId {
  const raw = (env[PROVIDER_ENV] || '').trim().toLowerCase();
  if (!raw) return DEFAULT_MERCHANT;
  if (!Object.prototype.hasOwnProperty.call(MERCHANT_NAMES, raw)) {
    throw new Error(
      `Η ${PROVIDER_ENV} λέει «${raw}», που δεν είναι πάροχος που ξέρουμε. `
      + `Δεκτά: ${KNOWN_MERCHANTS.join(', ')}.`,
    );
  }
  return raw as MerchantId;
}
