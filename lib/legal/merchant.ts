/** Ο πωλητής που δηλώνεται στον αγοραστή όταν ο έμπορος είναι merchant of record. */
export interface MorSeller {
  /** Το όνομα του πωλητή όπως το διαβάζει ο αγοραστής (το εμπορικό όνομα του εμπόρου). */
  readonly name: string;
  /** Οι όροι του εμπόρου για τον αγοραστή: επίσημη σελίδα, https. */
  readonly buyerTermsUrl: string;
}

/**
 * Ποιοι έμποροι είναι merchant of record και με ποια στοιχεία. `null`: ο
 * έμπορος δεν πουλά στο δικό του όνομα, οπότε πωλητής είναι ο φορέας και
 * ισχύει η ταυτότητα του lib/legal/identity.ts.
 */
export const MOR_SELLERS: Readonly<Record<MerchantId, MorSeller | null>> = {
  creem: {
    name: MERCHANT_NAMES.creem,
    // Πηγή: https://www.creem.io/buyer-terms (Buyer Terms of Service, επίσημη
    // σελίδα του εμπόρου· τη δείχνει ο κατάλογος των σελίδων του creem.io).
    buyerTermsUrl: 'https://www.creem.io/buyer-terms',
  },
};

/** Είναι δηλωμένος ο πωλητής ώστε να τον δει ο αγοραστής πριν πληρώσει; */
export function morSellerDisclosed(s: MorSeller | null | undefined): s is MorSeller {
  return !!s && !!s.name.trim() && /^https:\/\/\S+$/.test(s.buyerTermsUrl.trim());
}
