// ΕΔΩ ΚΡΙΝΕΤΑΙ ΑΝ ΤΑ ΝΟΜΙΚΑ ΚΕΙΜΕΝΑ ΛΕΝΕ ΤΗΝ ΑΛΗΘΕΙΑ.
// Το σφάλμα που γεννά αυτό το αρχείο: ο κώδικας απέκτησε ζωντανό κουμπί
// πληρωμής και πέντε επιφάνειες συνέχισαν να γράφουν «η χρέωση δεν έχει
// ενεργοποιηθεί». Ο έλεγχος δεν ρωτά «τι λέει η σελίδα» — ρωτά αν οι δύο
// καταστάσεις είναι όντως δύο και αν διαλέγονται από τη ΣΩΣΤΗ συνθήκη.
import { billingWords } from './billingWords'
import { merchant } from '../billing/merchant'
import { subprocessors, activeSubprocessors, plannedSubprocessors } from './subprocessors'
import { MERCHANT_NAMES, KNOWN_MERCHANTS, merchantId, PROVIDER_ENV } from './merchant'
import { TRIAL_DAYS, PLANS } from '../billing/plans'

let pass = 0, fail = 0
const ok = (n: string, c: boolean) => { if (c) pass++; else { fail++; console.error('✗ ' + n) } }

/** Ο έμπορος αυτού του περιβάλλοντος, ονομαστικά. */
const mor = (env: Record<string, string | undefined>) => MERCHANT_NAMES[merchantId(env)]

/** Η ΙΔΙΑ συνθήκη με το κουμπί του ταμείου, από τη θύρα και όχι από πάροχο. */
const checkoutIsLive = (env: Record<string, string | undefined>) => merchant(env).isLive(env)

// Ο ΕΜΠΟΡΟΣ, ΖΩΝΤΑΝΟΣ, ΜΕ ΟΛΟΚΛΗΡΟ ΤΟΝ ΧΑΡΤΗ. Ο έμπορος πουλά μόνο με και τα
// οκτώ ζεύγη (τέσσερα πακέτα σε δύο κύκλους): με ένα λιγότερο το ταμείο μένει
// κλειστό και η σουίτα θα δοκίμαζε μόνο την κλειστή κατάσταση, δύο φορές.
const PRODUCTS = 'p1:solo:monthly,p2:solo:annual,p3:owner:monthly,p4:owner:annual,'
  + 'p5:agency:monthly,p6:agency:annual,p7:office:monthly,p8:office:annual'
const LIVE = {
  [PROVIDER_ENV]: 'creem',
  CREEM_API_KEY: 'κλειδί',
  CREEM_PRODUCTS: PRODUCTS,
  CREEM_WEBHOOK_SECRET: 'μυστικό',
}
const DARK = {}
// Ο ΙΔΙΟΣ ΕΜΠΟΡΟΣ ΧΩΡΙΣ ΜΕΤΑΒΛΗΤΗ ΕΠΙΛΟΓΗΣ. Ο προεπιλεγμένος πρέπει να
// διαβάζει τα ίδια κλειδιά: αλλιώς μια εγκατάσταση που ξέχασε το
// MERCHANT_PROVIDER θα έμενε με κλειστό ταμείο και ανοιχτά κλειδιά.
const LIVE_2 = {
  CREEM_API_KEY: 'κλειδί',
  CREEM_PRODUCTS: PRODUCTS,
}

// ── Η ΣΥΝΘΗΚΗ ─────────────────────────────────────────────────────────────
ok('με τη ρύθμιση πλήρη, το ταμείο είναι ζωντανό', checkoutIsLive(LIVE))
ok('χωρίς ρύθμιση, δεν είναι', !checkoutIsLive(DARK))
// ΤΟ ΜΙΣΟ ΕΙΝΑΙ ΧΕΙΡΟΤΕΡΟ ΑΠΟ ΤΟ ΤΙΠΟΤΑ και γι' αυτό μετράνε όλα: με
// ζωντανό ταμείο και ξεχασμένο χάρτη προϊόντων, ο πελάτης πληρώνει και ο
// webhook απαντά σφάλμα σε κάθε γεγονός: χρεωμένος, χωρίς πακέτο.
ok('χωρίς χάρτη προϊόντων δεν μετράει ως ζωντανό ταμείο',
  !checkoutIsLive({ ...LIVE, CREEM_PRODUCTS: '' }))
ok('χωρίς κλειδί API δεν μετράει', !checkoutIsLive({ ...LIVE, CREEM_API_KEY: '' }))
ok('χάρτης με ζεύγος που λείπει δεν μετράει',
  !checkoutIsLive({ ...LIVE, CREEM_PRODUCTS: PRODUCTS.replace(',p8:office:annual', '') }))

// ── ΟΙ ΔΥΟ ΚΑΤΑΣΤΑΣΕΙΣ ΕΙΝΑΙ ΟΝΤΩΣ ΔΥΟ ────────────────────────────────────
{
  const live = billingWords(LIVE), dark = billingWords(DARK)
  ok('η σημαία ακολουθεί το ταμείο', live.live === true && dark.live === false)
  const keys = ['chargingToday', 'afterTrial', 'afterTrialShort', 'cardData', 'compMonths', 'howWeArePaid', 'paymentMethodAsked', 'moneyBack', 'firstCharge', 'contractSteps', 'planChange', 'subscriptionPlace', 'renewal', 'merchantRow'] as const
  // Αν μια φράση είναι ίδια και στις δύο καταστάσεις, τότε η μία από τις δύο
  // λέει ψέματα — και δεν θα το έπιανε κανείς, γιατί «υπάρχει διατύπωση».
  for (const k of keys) ok(`η «${k}» διαφέρει ανά κατάσταση`, live[k] !== dark[k])

  ok('όταν χρεώνουμε, δεν λέμε ότι δεν χρεώνουμε',
    !live.chargingToday.includes('δεν έχει ενεργοποιηθεί') && !live.cardData.includes('δεν έχει ενεργοποιηθεί'))
  ok('όταν ΔΕΝ χρεώνουμε, το λέμε', dark.chargingToday.includes('δεν έχει ενεργοποιηθεί'))
  ok('ο έμπορος ονομάζεται όταν χρεώνει', live.chargingToday.includes(mor(LIVE)))
  // Καμία φράση δεν μένει κενή: μια κενή πρόταση σε νομικό κείμενο είναι
  // παράλειψη ενημέρωσης, όχι συντομία.
  for (const k of keys) ok(`καμία κενή φράση: ${k}`, live[k].length > 20 && dark[k].length > 20)

  // Ο ΣΤΟΧΟΣ ΤΩΝ ΣΥΝΕΡΓΑΤΩΝ ΜΕΤΡΑ ΣΥΝΔΡΟΜΗΤΕΣ: χωρίς ταμείο το λέμε, με ταμείο σιωπούμε.
  ok('χωρίς χρέωση, ο στόχος των συνεργατών λέει από πότε ισχύει', !!dark.partnerTarget && dark.partnerTarget.includes('συνδρομητές'))
  ok('με χρέωση, καμία επιφύλαξη', live.partnerTarget === null)

  // Η ΕΙΔΟΠΟΙΗΣΗ ΤΟΥ ΤΙΜΟΚΑΤΑΛΟΓΟΥ ΥΠΑΡΧΕΙ ΜΟΝΟ ΟΣΟ ΔΕΝ ΑΓΟΡΑΖΕΤΑΙ ΤΙΠΟΤΑ.
  ok('χωρίς χρέωση, ο τιμοκατάλογος λέει ότι δεν αγοράζεται ακόμη', !!dark.pricingNotice && dark.pricingNotice.body.includes('χωρίς χρέωση'))
  ok('με χρέωση, καμία ειδοποίηση', live.pricingNotice === null)

  // ΤΑ ΔΕΔΟΜΕΝΑ ΜΕΤΑ ΤΗ ΣΥΝΔΡΟΜΗ: ΤΟ ΔΙΑΣΤΗΜΑ ΤΗΣ ΣΥΝΤΟΜΗΣ ΑΠΑΝΤΗΣΗΣ ΕΙΝΑΙ
  // ΤΟ ΙΔΙΟ ΜΕ ΤΗΣ ΠΟΛΙΤΙΚΗΣ. Χωρίς ταμείο ο καθαρισμός δεν τρέχει, άρα καμία
  // απειλή διαγραφής σε ημέρες· με ταμείο, ο αριθμός της βάσης.
  // ΑΠΟ 25.09.2026 Η ΔΙΑΤΗΡΗΣΗ ΔΕΝ ΕΞΑΡΤΑΤΑΙ ΑΠΟ ΤΟ ΤΑΜΕΙΟ. Ο λογαριασμός χωρίς
  // συνδρομή συνεχίζει στο δωρεάν πακέτο και μένει ώσπου να τον διαγράψει ο
  // ίδιος· η σύντομη απάντηση είναι η ίδια και στις δύο καταστάσεις, επίτηδες.
  ok('η σύντομη διατήρηση είναι ίδια με ή χωρίς ταμείο', live.lapsedRetentionShort === dark.lapsedRetentionShort)
  ok('και δεν απειλεί διαγραφή σε ημέρες', !/\d+ ημέρες/.test(live.lapsedRetentionShort) && live.lapsedRetentionShort.includes('δωρεάν πακέτο'))
  // ΤΟ ΠΛΑΙΣΙΟ ΤΟΥ ΠΑΚΕΤΟΥ ΣΤΗΝ ΕΓΓΡΑΦΗ: με ταμείο λέει τον κύκλο (null),
  // χωρίς ταμείο δεν γράφει «Ετήσια χρέωση» δίπλα σε περιγραφή που λέει «καμία».
  ok('χωρίς χρέωση, η εγγραφή δεν μιλά για κύκλο χρέωσης', !!dark.signupPlanTerms && dark.signupPlanTerms.includes('Χωρίς χρέωση'))
  ok('με χρέωση, η εγγραφή δείχνει τον κύκλο', live.signupPlanTerms === null)
}

// ── ΤΟ ΜΟΝΤΕΛΟ ΤΩΝ ΧΡΗΜΑΤΩΝ, ΓΡΑΜΜΕΝΟ ΚΑΙ ΚΑΡΦΩΜΕΝΟ ─────────────────────
// Καθε πρόταση εδώ αντιστοιχεί σε κάτι που ΚΑΝΕΙ ο κώδικας. Οταν άλλαξε το
// μοντέλο, τα κείμενα έμειναν πίσω και έλεγαν το ακριβώς αντίθετο: «δεν
// ζητείται μέσο πληρωμής» δίπλα σε μια διαδρομή που ζητά κάρτα την τρίτη
// οθόνη. Οι έλεγχοι είναι λεξιλογικοί επίτηδες — ό,τι υπόσχεται ένα νομικό
// κείμενο δεν επιτρέπεται να αλλάξει κατά λάθος.
{
  const live = billingWords(LIVE), dark = billingWords(DARK)

  // Η ΔΟΚΙΜΗ ΔΕΝ ΖΗΤΑ ΚΑΡΤΑ, Η ΣΥΝΔΡΟΜΗ ΧΡΕΩΝΕΤΑΙ ΣΤΗΝ ΑΓΟΡΑ (απόφαση 27.09.2026).
  // Ο έμπορος δεν έχει δοκιμή στα προϊόντα του: η πρώτη χρέωση φεύγει την
  // ημέρα της αγοράς. Ενα κείμενο που υπόσχεται «31η ημέρα» είναι ψέμα.
  ok('η ζωντανή διατύπωση λέει ότι η δοκιμή δεν ζητά κάρτα',
    live.afterTrial.includes('χωρίς κάρτα'))
  ok('και ότι η χρέωση γίνεται τη στιγμή της αγοράς',
    live.afterTrial.includes('τη στιγμή της αγοράς'))
  for (const [name, w] of [['afterTrial', live.afterTrial], ['afterTrialShort', live.afterTrialShort],
    ['withdrawal', live.withdrawal], ['firstCharge', live.firstCharge], ['paymentMethodAsked', live.paymentMethodAsked],
    ['withdrawal (ανενεργή)', dark.withdrawal]] as const) {
    ok(`το ${name} δεν υπόσχεται χρέωση την ${TRIAL_DAYS + 1}η ημέρα`, !w.includes(`${TRIAL_DAYS + 1}η`))
  }
  ok('το μέσο πληρωμής ζητείται μετά την επιβεβαίωση του email',
    live.paymentMethodAsked.includes('επιβεβαίωση του email'))
  ok('η σύντομη μορφή λέει πότε γίνεται η χρέωση',
    live.firstCharge.includes('τη στιγμή της αγοράς'))
  ok('και χωρίς ταμείο δεν υπόσχεται καμία χρέωση',
    dark.firstCharge.includes('δεν έχει ενεργοποιηθεί'))
  // ΚΑΜΙΑ ΔΗΛΩΣΗ ΠΟΥ ΔΕΝ ΖΗΤΕΙΤΑΙ ΠΟΥΘΕΝΑ. Το ταμείο δεν ρωτά για «άμεση
  // έναρξη της παροχής»· η επιστροφή είναι ολόκληρη και δεν τη χρειάζεται.
  ok('η υπαναχώρηση δεν επικαλείται δήλωση που δεν ζητείται',
    !live.withdrawal.includes('δηλώσεις ρητά'))
  ok('και λέει ποιος εκτελεί την επιστροφή',
    live.withdrawal.includes('εξέδωσε το παραστατικό'))

  // Η ΕΓΓΥΗΣΗ ΤΩΝ 14 ΗΜΕΡΩΝ ΑΠΟ ΤΗΝ ΠΡΩΤΗ ΧΡΕΩΣΗ.
  // Οι 14 ημέρες του νόμου μετρούν από τη σύναψη, δηλαδή λήγουν δεκαέξι
  // ημέρες πριν φύγει το πρώτο ευρώ. Χωρίς αυτή τη δέσμευση, ο πελάτης
  // πληρώνει την 31η ημέρα χωρίς κανένα δικαίωμα επιστροφής.
  for (const [name, w] of [['ζωντανή', live.withdrawal], ['ανενεργή', dark.withdrawal]] as const) {
    ok(`η ${name} υπαναχώρηση αναφέρει την εγγύηση από την πρώτη χρέωση`,
      w.includes('14 ημέρες από την πρώτη χρέωση'))
  }
  ok('η ζωντανή εγγύηση επιστρέφει ολόκληρο το ποσό',
    live.withdrawal.includes('επιστρέφουμε ολόκληρο το ποσό'))
  // ΜΙΑ ΠΡΟΤΑΣΗ, ΔΥΟ ΘΕΣΕΙΣ. Ο τιμοκατάλογος τη δείχνει στα ψιλά γράμματα και
  // οι Οροι μέσα στην υπαναχώρηση: γραμμένη δύο φορές, θα απέκλινε.
  ok('η σύντομη εγγύηση ζει μέσα στην παράγραφο της υπαναχώρησης',
    live.withdrawal.includes(live.moneyBack) && dark.withdrawal.includes(dark.moneyBack))
  ok('και λέει από πότε μετρούν οι 14 ημέρες', live.withdrawal.includes('από τότε μετρούν οι 14 ημέρες'))

  // Η ΑΝΕΝΕΡΓΗ ΚΑΤΑΣΤΑΣΗ ΜΕΝΕΙ ΑΝΕΝΕΡΓΗ, χωρίς να υπόσχεται χρεώσεις.
  ok('χωρίς ταμείο, καμία υπόσχεση για χρέωση',
    dark.afterTrial.includes('δεν έχει ενεργοποιηθεί'))
  // ΑΝΑΝΕΩΣΗ, ΑΛΛΑΓΗ ΠΑΚΕΤΟΥ ΚΑΙ ΚΑΡΤΑ ΜΙΛΟΥΝ ΣΤΟΝ ΧΡΟΝΟ ΤΟΥΣ. Οι Οροι τα έγραφαν
  // στον ενεστώτα δίπλα σε παράγραφο που έλεγε ότι σήμερα δεν χρεώνεται τίποτα.
  for (const k of ['subscriptionPlace', 'renewal'] as const)
    ok(`χωρίς ταμείο, το «${k}» μιλά για όταν ενεργοποιηθεί η χρέωση`, dark[k].startsWith('Όταν ενεργοποιηθεί'))
  ok('χωρίς ταμείο, η αλλαγή πακέτου δεν κοστίζει σήμερα', dark.planChange.includes('σήμερα η αλλαγή δεν κοστίζει'))
  // ΚΑΙ Η ΥΠΑΝΑΧΩΡΗΣΗ ΔΕΝ ΠΕΡΙΓΡΑΦΕΙ ΠΕΡΙΠΤΩΣΗ ΠΟΥ ΔΕΝ ΥΠΑΡΧΕΙ: σε συνδρομή
  // «πλήρης εκτέλεση εντός 14 ημερών» δεν συμβαίνει ποτέ.
  ok('η υπαναχώρηση δεν μιλά για πλήρη εκτέλεση', !live.withdrawal.includes('πλήρη εκτέλεση') && !dark.withdrawal.includes('πλήρη εκτέλεση'))
  ok('χωρίς ταμείο, η υπαναχώρηση δεν κοστίζει τίποτα', dark.withdrawal.includes('δεν οφείλεις τίποτα'))

  // ── Ο ΛΟΓΑΡΙΑΣΜΟΣ ΧΩΡΙΣ ΣΥΝΔΡΟΜΗ ΔΕΝ ΜΕΝΕΙ ΓΙΑ ΠΑΝΤΑ ─────────────────
  // Η πολιτική σβήνει δεδομένα, άρα η ενημέρωση δεν είναι διακοσμητική: το
  // άρθρο 13§2 στοιχείο α΄ GDPR ζητά να λέγεται ΤΟ ΔΙΑΣΤΗΜΑ, όχι ότι
  // «κάποτε διαγράφονται». Και τα δύο κείμενα, το μακρύ και το σύντομο, το
  // λένε με τον ίδιο αριθμό: γραμμένος δύο φορές, θα απέκλινε.
  // ΑΠΟ 25.09.2026: χωρίς συνδρομή ο λογαριασμός ΣΥΝΕΧΙΖΕΙ στο δωρεάν πακέτο.
  // Και τα δύο κείμενα το λένε με το όνομα του πακέτου και κανένα δεν απειλεί
  // με διαγραφή, γιατί το χρονόμετρο της διαγραφής αφαιρέθηκε από τη βάση.
  for (const [name, w] of [['μακρύ', live.afterTrial], ['σύντομο', live.afterTrialShort]] as const) {
    ok(`το ${name} κείμενο λέει ότι συνεχίζεις στο δωρεάν πακέτο`, w.includes(`«${PLANS.free.name}»`))
    // «δεν διαγράφονται» (τα ακίνητα πέρα από το πρώτο) είναι υπόσχεση, όχι απειλή.
    ok(`και δεν απειλεί με διαγραφή`, !/(?<!δεν )διαγράφ/.test(w))
  }
  ok('η πολιτική διατήρησης δεν σβήνει λογαριασμό επειδή δεν πληρώνει', live.lapsedRetention.includes('Δεν διαγράφεται αυτόματα'))
  // ΚΑΙ ΟΤΑΝ ΔΕΝ ΥΠΑΡΧΕΙ ΤΑΜΕΙΟ, ΔΕΝ ΑΠΕΙΛΕΙΤΑΙ ΚΑΝΕΙΣ. Το «δεν πλήρωσες»
  // όταν δεν υπάρχει τρόπος να πληρώσεις είναι δικό μας κενό: ο σαρωτής δεν
  // τρέχει (φρένο στη βάση) και το κείμενο δεν επιτρέπεται να λέει άλλα.
  ok('χωρίς ταμείο, καμία απειλή διαγραφής',
    !/διαγράφ|διαγραφή/.test(dark.afterTrialShort))

  // Η ΣΥΝΤΟΜΗ ΜΟΡΦΗ ΓΡΑΦΤΗΚΕ ΓΙΑ ΤΟ ΜΕΤΡΟ ΤΩΝ ΣΥΧΝΩΝ ΕΡΩΤΗΣΕΩΝ: δύο γραμμές
  // στα 1044px, δηλαδή ώς περίπου 280 χαρακτήρες. Πάνω από αυτό ξαναγίνεται
  // η παράγραφος που ήρθε να αντικαταστήσει.
  for (const [name, w] of [['ζωντανή', live.afterTrialShort], ['ανενεργή', dark.afterTrialShort]] as const) {
    ok(`η ${name} σύντομη μορφή μένει στο μέτρο της απάντησης (${w.length})`, w.length <= 300)
  }
}

// ── ΤΟ ΜΗΤΡΩΟ ΥΠΕΡΓΟΛΑΒΩΝ ΑΚΟΛΟΥΘΕΙ ──────────────────────────────────────
// Είναι μηχαναγνώσιμο δημοσιευμένο έγγραφο του άρθρου 28 GDPR: ένα `false`
// εκεί δεν είναι σχόλιο, είναι δήλωση προς το υποκείμενο.
{
  const merchantOf = (env: Record<string, string | undefined>) =>
    subprocessors(env).find(s => s.name === mor(env))!
  ok('με ζωντανό ταμείο ο πάροχος πληρωμών είναι ενεργός', merchantOf(LIVE).active === true)
  ok('χωρίς ταμείο δεν είναι', merchantOf(DARK).active === false)
  ok('και μετακινείται ανάμεσα στους δύο καταλόγους',
    activeSubprocessors(LIVE).some(s => s.name === mor(LIVE))
    && plannedSubprocessors(DARK).some(s => s.name === mor(DARK)))
  ok('η αιτιολόγηση του παρόχου δανείζεται τη μία διατύπωση',
    merchantOf(DARK).purpose.includes(billingWords(DARK).merchantRow)
    && merchantOf(LIVE).purpose.includes(billingWords(LIVE).merchantRow))
  // Η ΓΡΑΜΜΗ ΤΟΥ ΕΜΠΟΡΟΥ ΔΕΝ ΜΙΛΑ ΓΙΑ «ΤΟΝ ΠΑΡΟΧΟ ΠΛΗΡΩΜΩΝ»: ο πάροχος είναι
  // ο ίδιος και η τρίτη πρόσωπη αναφορά διαβαζόταν σαν να υπάρχει κι άλλος.
  ok('η γραμμή του εμπόρου δεν αναφέρεται στον εαυτό της ως τρίτο',
    !merchantOf(DARK).purpose.includes('ο πάροχος πληρωμών'))
  // Οι υπόλοιποι πάροχοι δεν παρασύρονται από τη μεταβλητή της χρέωσης.
  const others = (env: Record<string, string | undefined>) =>
    subprocessors(env).filter(s => s.name !== mor(env)).map(s => `${s.name}:${s.active}`).join()
  ok('κανένας άλλος πάροχος δεν αλλάζει κατάσταση', others(LIVE) === others(DARK))
}

// ── ΑΛΛΑΖΕΙ Ο ΕΜΠΟΡΟΣ, ΑΛΛΑΖΟΥΝ ΚΑΙ ΤΑ ΚΕΙΜΕΝΑ ───────────────────────────
// ΤΟ ΣΦΑΛΜΑ ΠΟΥ ΓΕΝΝΑ ΑΥΤΗ ΤΗΝ ΕΝΟΤΗΤΑ. Το όνομα του εμπόρου ήταν σταθερά, ενώ
// ο κώδικας είχε ήδη δύο εμπόρους και μεταβλητή που διαλέγει ποιος εισπράττει.
// Την ημέρα που η μεταβλητή γύριζε, η Πολιτική απορρήτου, οι Οροι και το
// μητρώο υπεργολάβων θα ονόμαζαν τον προηγούμενο: θα δήλωναν στο υποκείμενο
// ως εκτελούντα την επεξεργασία εταιρεία που δεν αγγίζει τα δεδομένα του.
{
  ok('χωρίς μεταβλητή ισχύει ο προεπιλεγμένος (creem)', merchantId(DARK) === 'creem')
  ok('η μεταβλητή διαλέγει ρητά τον ίδιο', merchantId(LIVE) === 'creem')
  ok('κεφαλαία και κενά δεν χαλούν το όνομα',
    merchantId({ [PROVIDER_ENV]: '  CREEM ' }) === 'creem')

  // ΑΓΝΩΣΤΟ ΟΝΟΜΑ ΠΕΤΑ. Σιωπηλή πτώση στον προεπιλεγμένο θα σήμαινε ότι η
  // εφαρμογή χρεώνει από άλλον πάροχο απ' ό,τι νομίζει όποιος τη ρύθμισε.
  let threw = ''
  try { merchantId({ [PROVIDER_ENV]: 'stripe' }) } catch (e) { threw = String(e) }
  ok('άγνωστο όνομα δεν πέφτει σιωπηλά στον προεπιλεγμένο', threw.includes(PROVIDER_ENV))
  // ΚΑΙ Ο ΠΑΛΙΟΣ ΠΑΡΟΧΟΣ ΕΙΝΑΙ ΠΛΕΟΝ ΑΓΝΩΣΤΟΣ. Ο κώδικάς του αφαιρέθηκε· μια
  // ξεχασμένη μεταβλητή στον Vercel πρέπει να σκάσει, όχι να χρεώνει άλλος.
  let threwOld = ''
  try { merchantId({ [PROVIDER_ENV]: 'lemon' }) } catch (e) { threwOld = String(e) }
  ok('ο αφαιρεμένος πάροχος δεν επιλέγεται πια', threwOld.includes(PROVIDER_ENV))

  // ΞΕΝΑ ΟΝΟΜΑΤΑ, ΠΕΖΑ: ο φύλακας των ισχυρισμών κόβει το όνομα άλλου
  // παρόχου γραμμένο κυριολεκτικά, ακόμη και σε σουίτα.
  const FOREIGN = /stripe|paddle|lemon/i
  const others: string[] = KNOWN_MERCHANTS.filter(id => id !== 'creem').map(id => MERCHANT_NAMES[id])
  const w2 = billingWords(LIVE_2)
  ok('ο έμπορος είναι ζωντανός και χωρίς μεταβλητή επιλογής', w2.live === true)
  ok('τα λόγια ονομάζουν αυτόν που εισπράττει',
    w2.chargingToday.includes(MERCHANT_NAMES.creem) && w2.cardData.includes(MERCHANT_NAMES.creem))
  ok('και ΔΕΝ ονομάζουν άλλον πάροχο',
    !FOREIGN.test(w2.chargingToday) && !FOREIGN.test(w2.cardData)
    && others.every(o => !w2.chargingToday.includes(o) && !w2.cardData.includes(o)))

  const reg2 = subprocessors(LIVE_2)
  ok('το μητρώο υπεργολάβων γράφει τον ίδιο έμπορο',
    reg2.some(s => s.name === MERCHANT_NAMES.creem && s.active))
  ok('και δεν γράφει άλλον πάροχο πληρωμών',
    !reg2.some(s => FOREIGN.test(s.name) || others.includes(s.name)))
}

console.log(fail === 0 ? `✓ billingWords: ${pass} έλεγχοι πέρασαν` : `✗ billingWords: ${fail} απέτυχαν από ${pass + fail}`)
if (fail > 0) process.exit(1)
