// ─────────────────────────────────────────────────────────────────────────
// Ο κατάλογος των εκτελούντων την επεξεργασία ήταν γραμμένος ΔΥΟ φορές: μία
// στην Πολιτική απορρήτου και μία στη σελίδα «Ποιοι είμαστε». Και οι δύο
// γραμμένες με το χέρι, από διαφορετικό πέρασμα, με διαφορετικό περιεχόμενο:
// η μία ανέφερε ειδοποιήσεις κινητού που η άλλη δεν ανέφερε και η μία έλεγε
// ότι οι γραμματοσειρές δεν φεύγουν πλέον στη Google ενώ η ίδια σελίδα, τριάντα
// γραμμές πιο κάτω, έλεγε ότι φεύγουν.
//
// ΔΕΝ ΕΙΝΑΙ ΘΕΜΑ ΤΑΞΗΣ. Ο κατάλογος υπεργολάβων είναι νομικό κείμενο: το
// άρθρο 28 GDPR απαιτεί να είναι επίκαιρος και το άρθρο 30 να τηρείται αρχείο.
// Δύο κατάλογοι που διαφωνούν σημαίνει ότι τουλάχιστον ο ένας είναι λάθος και
// ο χρήστης δεν έχει τρόπο να ξέρει ποιος.
//
// Ο κατάλογος ζει εδώ. Οι δύο σελίδες τον ΔΙΑΒΑΖΟΥΝ. Όποιος προσθέσει πάροχο
// τον προσθέτει μία φορά και εμφανίζεται και στα δύο κείμενα την ίδια στιγμή.
//
// ΤΙ ΣΗΜΑΙΝΕΙ `active: false`. Ότι ο πάροχος ΔΕΝ επεξεργάζεται δεδομένα σήμερα.
// Μένει γραμμένος γιατί είναι σχεδιασμένος και ο χρήστης έχει δικαίωμα να
// ξέρει τι έρχεται πριν έρθει — όχι να το ανακαλύψει μετά.
//
// ── ΚΑΙ ΓΙΑΤΙ Ο ΠΑΡΟΧΟΣ ΠΛΗΡΩΜΩΝ ΔΕΝ ΓΡΑΦΕΤΑΙ ΜΕ ΤΟ ΧΕΡΙ ────────────────
// Η γραμμή του εμπόρου έλεγε καρφωτά `active: false` με το κείμενο
// «σήμερα δεν γίνεται καμία επεξεργασία στοιχείων κάρτας». Την ίδια στιγμή ο
// κώδικας απέκτησε ζωντανό κουμπί «Πληρωμή με κάρτα». Το μητρώο είναι
// ΜΗΧΑΝΑΓΝΩΣΙΜΟ δημοσιευμένο έγγραφο του άρθρου 28 GDPR: ένα `false` εκεί δεν
// είναι σχόλιο, είναι δήλωση προς το υποκείμενο.
//
// Η κατάστασή του βγαίνει τώρα από την ΙΔΙΑ συνθήκη που δείχνει το κουμπί και
// γι' αυτό ο κατάλογος είναι ΣΥΝΑΡΤΗΣΗ και όχι σταθερά: μια σταθερά θα έπρεπε
// να θυμηθεί κάποιος να την αλλάξει.
// ═══════════════════════════════════════════════════════════════════════════

export interface Subprocessor {
  /** Το εμπορικό όνομα, όπως το ξέρει ο κόσμος. */
  name: string;
  /** Τι κάνει για εμάς, με τα λόγια του χρήστη. */
  purpose: string;
  /**
   * Η ίδια δουλειά σε τρεις ως πέντε λέξεις, για τη γραμμή των σχεδιασμένων
   * παρόχων στη σελίδα εμπιστοσύνης: εκεί λέγεται ΤΙ έρχεται, όχι ΠΟΙΟΣ, γιατί
   * ένας πάροχος που δεν αγγίζει ακόμη κανένα δεδομένο δεν χρειάζεται όνομα σε
   * δημόσια σελίδα προϊόντος. Τα ονόματα μένουν στην Πολιτική απορρήτου.
   */
  short: string;
  /** Πού γίνεται η επεξεργασία. Κρίνει αν χρειάζονται Τυποποιημένες Ρήτρες. */
  where: string;
  /** Επεξεργάζεται δεδομένα ΣΗΜΕΡΑ; */
  active: boolean;
  /**
   * Ο ΡΟΛΟΣ ΚΑΤΑ GDPR, ΟΧΙ ΚΑΘΕ ΠΑΡΟΧΟΣ ΕΙΝΑΙ ΕΚΤΕΛΩΝ. Η Πολιτική απορρήτου
   * έγραφε ότι όλοι «ενεργούν για λογαριασμό μας», ενώ το μητρώο
   * (docs/compliance/subprocessors.md) καταγράφει τη Google ως αυτοτελή
   * υπεύθυνο και τον έμπορο ως υπεύθυνο για το ταμείο και τα φορολογικά.
   */
  role: SubprocessorRole;
  /** Το νομικό πρόσωπο με το οποίο συμβαλλόμαστε, όπως το γράφει το μητρώο. */
  entity: string | null;
}

