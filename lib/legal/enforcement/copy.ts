/** Το πλήθος του κανόνα· για άγνωστο καθεστώς «15 ή 5 εργάσιμες ημέρες». */
function spanOf(ids: string[]): string {
  const counts = ids.map(id => rule(id).params.count!);
  const unit = rule(ids[0]).params.unit!;
  if (counts.length > 1 && counts[0] !== counts[1]) return `${counts.join(' ή ')} ${unitWord(2, unit, 'acc')}`;
  return fmtCount(counts[0], unit);
}

