type Case = 'acc' | 'gen';

/** «15 εργάσιμες ημέρες», «45 ημέρες», «7 μήνες»· γενική: «3 μηνών». */
const UNIT_WORDS = {
  calendar: { one: { acc: 'ημέρα', gen: 'ημέρας' }, many: { acc: 'ημέρες', gen: 'ημερών' } },
  working: { one: { acc: 'εργάσιμη ημέρα', gen: 'εργάσιμης ημέρας' }, many: { acc: 'εργάσιμες ημέρες', gen: 'εργάσιμων ημερών' } },
  months: { one: { acc: 'μήνα', gen: 'μήνα' }, many: { acc: 'μήνες', gen: 'μηνών' } },
} as const;
const unitWord = (n: number, unit: keyof typeof UNIT_WORDS, c: Case): string => UNIT_WORDS[unit][n === 1 ? 'one' : 'many'][c];

export function fmtCount(n: number, unit: 'calendar' | 'working' | 'months', c: Case = 'acc'): string {
  // Αδιάσπαστο κενό: ο αριθμός δεν μένει στο τέλος της γραμμής χωρίς τη μονάδα του.
  return `${n}\u00a0${unitWord(n, unit, c)}`;
}

/** Ο αριθμός και η μονάδα του κανόνα, όπως τον γράφει ο νόμος. */
export function ruleSpan(id: string, c: Case = 'acc'): string {
  const p = rule(id).params;
  if (p.count == null || !p.unit) throw new Error(`enforcement/copy: ο κανόνας «${id}» δεν έχει πλήθος και μονάδα`);
  return fmtCount(p.count, p.unit, c);
}
const ruleTo = (id: string, c: Case = 'acc'): string => {
  const p = rule(id).params;
  return fmtCount(p.countTo!, p.unit!, c);
};
const rulePct = (id: string): string => fpRate(rule(id).params.percent!);
const ruleDate = (id: string): string => grDate(rule(id).params.date!);

/** Πλήρης ανάγνωση για αναγνώστες οθόνης: «Τρίτη 23 Φεβρουαρίου 2027». */
const WEEKDAYS = ['Κυριακή', 'Δευτέρα', 'Τρίτη', 'Τετάρτη', 'Πέμπτη', 'Παρασκευή', 'Σάββατο'] as const;
export function longDate(iso: string): string {
  const [y, m, d] = iso.split('-').map(Number);
  const wd = new Date(Date.UTC(y, m - 1, d)).getUTCDay();
  return `${WEEKDAYS[wd]} ${d} ${MONTHS_GEN[m - 1]} ${y}`;
}

/** «σε 21 ημέρες», «αύριο», «σήμερα», «πριν από 3 ημέρες»· ποτέ αντίστροφη μέτρηση σε μεγάλα ψηφία. */
export function relDays(iso: string, today: string): string {
  const n = Math.round((Date.parse(iso) - Date.parse(today)) / 86400000);
  if (n === 0) return 'σήμερα';
  if (n === 1) return 'αύριο';
  if (n > 1) return `σε ${fmtCount(n, 'calendar')}`;
  return `πριν από ${fmtCount(-n, 'calendar')}`;
}

