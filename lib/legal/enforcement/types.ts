// Τύποι του μητρώου κανόνων της Προστασίας ιδιοκτήτη. Χωριστό αρχείο ώστε το
// sources.ts (παραγόμενο από τις πηγές) να μη χρειάζεται να εισάγει το rules.ts.

/** Μία πηγή κανόνα. */
export type RuleSource = {
  /**
   * 'official': το κείμενο του ΦΕΚ. 'independent': άλλος εκδότης που
   * αναδημοσιεύει ή κωδικοποιεί τη διάταξη. Ο κανόνας εμφανίζεται μόνο με
   * τουλάχιστον μία από την καθεμιά.
   */
  kind: 'official' | 'independent';
  title: string;
  url: string;
  /** Το PDF του επίσημου κειμένου, όταν η `url` είναι η σελίδα του νόμου. */
  fileUrl?: string;
  /** Αυτούσια τμήματα του κειμένου, με τη σειρά που εμφανίζονται. */
  excerpt: readonly string[];
  /** Στιγμιότυπο του κειμένου της πηγής, μέσα στο αποθετήριο. */
  snapshot: string;
  /** Πότε κατέβηκε και αντιπαραβλήθηκε (ISO). */
  checkedAt: string;
};

/** Το καθεστώς του ΚΠολΔ για την εκτέλεση, κατά το άρθρο 126 §7 ν. 5221/2025. */
export type Regime = 'new' | 'old';

/**
 * Υπογραφή δικηγόρου. ΚΕΝΗ σήμερα. Γεμίζει ΜΟΝΟ όταν ο δικηγόρος υπογράψει τον
 * κατάλογο ελέγχου για ΑΥΤΗ την έκδοση του κανόνα. Ο φύλακας κόβει εγγραφή χωρίς
 * όνομα ή ημερομηνία και κάθε ανάθεση έξω από το rules.ts.
 */
export type LawyerReview = {
  /** Ψευδώνυμο ή κωδικός· το ονοματεπώνυμο και ο ΑΜ μένουν σε ιδιωτικό αρχείο. */
  reviewer: string;
  /** ISO. */
  reviewedAt: string;
  /** Πρέπει να ισούται με το `version` του κανόνα. */
  version: number;
};

export type RuleParams = {
  /** Πλήθος μονάδων (ημέρες, εργάσιμες ή μήνες). */
  count?: number;
  /** Δεύτερο όριο για παράθυρο (π.χ. έως 8 μήνες). */
  countTo?: number;
  unit?: 'calendar' | 'working' | 'months';
  /** Ποσοστό, όπου ο κανόνας γράφει ποσοστό. */
  percent?: number;
  /** Η τιμή πριν από την τροποποίηση, όπου η οθόνη τη χρειάζεται (π.χ. 72 → 120 δόσεις). */
  was?: number;
  /** Σταθερή ημερομηνία του νόμου (ISO). */
  date?: string;
};

export type LegalRule = {
  id: string;
  /** +1 σε κάθε ουσιαστική αλλαγή· η υπογραφή δικηγόρου δένεται με την έκδοση. */
  version: number;
  /** Τίτλος όπως τον λέει ο χρήστης. */
  label: string;
  /** Η διάταξη, π.χ. «ΚΠολΔ 938 §4». */
  provision: string;
  /** Ο νόμος που δίνει το ισχύον κείμενο, με ΦΕΚ. */
  amendedBy: string;
  /** Σε ποιο καθεστώς επιταγής ισχύει· 'any' όταν δεν εξαρτάται. */
  regime: Regime | 'any';
  params: RuleParams;
  /**
   * 'verified': επαληθεύτηκε σε δύο πηγές (επίσημη και ανεξάρτητη).
   * 'withheld': δεν επαληθεύτηκε· η μηχανή δεν βγάζει ποτέ ημερομηνία από αυτόν.
   */
  status: 'verified' | 'withheld';
  /** Ποιος έκανε την αντιπαραβολή. Ομάδα, όχι πρόσωπο και όχι δικηγόρος. */
  verifier: 'properwise-team' | null;
  sources: readonly RuleSource[];
  /** Γιατί δεν εμφανίζεται (μόνο για 'withheld'). */
  withheldReason?: string;
  /** Ανοιχτά ερμηνευτικά ερωτήματα· όσο υπάρχουν, το αποτέλεσμα είναι εύρος. */
  ambiguities: readonly string[];
  validFrom: string;
  validTo: string | null;
  lawyerReviewed: LawyerReview | null;
};
