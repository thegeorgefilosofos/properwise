// έβλεπε ποτέ την ενημέρωση που αποφασίστηκε για όλους.
//
// ΜΟΝΟ ΣΤΙΣ ΕΚΔΟΣΕΙΣ ΤΗΣ (`FIRM_NOTICE_POLICIES`). Η 2026-11-05 την έφερε και η
