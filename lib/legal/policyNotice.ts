/** Η έκδοση είναι ημερομηνία ISO, άρα συγκρίνεται ως κείμενο. */
function sawAtLeast(meta: PolicyMeta | null | undefined, seenLocally: string | null, version: string): boolean {
  const atLeast = (v: unknown) => typeof v === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(v) && v >= version
  return atLeast(seenLocally) || atLeast(meta?.policy_notice_seen) || atLeast(meta?.consent_policy_version)
}

/** Είδε ήδη την ενημέρωση του νομικού ελέγχου (2026-11-09) ή νεότερη; */
export function sawLegalReview(meta: PolicyMeta | null | undefined, seenLocally: string | null): boolean {
  return sawAtLeast(meta, seenLocally, LEGAL_REVIEW_VERSION)
}

/** Είδε ήδη την ενημέρωση των αντιγράφων ασφαλείας (2026-11-11) ή νεότερη; */
export function sawBackups(meta: PolicyMeta | null | undefined, seenLocally: string | null): boolean {
  return sawAtLeast(meta, seenLocally, BACKUP_VERSION)
}

/** Είδε ήδη την ενημέρωση της μαζικής καταχώρησης (2026-11-10) ή νεότερη; */
export function sawBulkImport(meta: PolicyMeta | null | undefined, seenLocally: string | null): boolean {
  return sawAtLeast(meta, seenLocally, BULK_VERSION)
}

export interface PolicyNoticeCopy {
  /** Η μία γραμμή που φαίνεται. */
  short: string
  /** Η πρώτη πρόταση του «Τι άλλαξε». */
  headline: string
  /** Τι άλλαξε, χωρίς ψηφία. */
  summary: string
  /** Ο σύνδεσμος στο κείμενο που άλλαξε. */
  href: '/terms' | '/privacy'
  hrefLabel: string
}

/** Τα κείμενα της ειδοποίησης για τον συγκεκριμένο χρήστη. */
export function policyNoticeCopy(meta: PolicyMeta | null | undefined, seenLocally: string | null): PolicyNoticeCopy {
  const privacy = { short: 'Νέα Πολιτική απορρήτου.', headline: 'Ενημερώσαμε την Πολιτική απορρήτου.', href: '/privacy', hrefLabel: 'Δες την Πολιτική απορρήτου' } as const
  if (sawBackups(meta, seenLocally)) return {
    ...privacy,
    summary: `Η Πολιτική απορρήτου λέει πλέον ότι ${KEEP_COPY_ADDITION}`,
  }
  if (sawBulkImport(meta, seenLocally)) return {
    ...privacy,
    summary: `Η Πολιτική απορρήτου λέει πλέον ότι ${BACKUP_ADDITION} Λέει επίσης ότι ${KEEP_COPY_ADDITION}`,
  }
  if (sawLegalReview(meta, seenLocally)) return {
    ...privacy,
    summary: `Η Πολιτική απορρήτου λέει πλέον ότι ${BULK_ADDITION} Λέει επίσης ότι ${BACKUP_ADDITION} Ακόμη, λέει ότι ${KEEP_COPY_ADDITION}`,
  }
  return {
    short: POLICY_NOTICE_SHORT,
    headline: 'Ενημερώσαμε τους Όρους και την Πολιτική απορρήτου.',
    summary: `${LEGAL_REVIEW_SUMMARY} Λέει επίσης ότι ${BULK_ADDITION} Ακόμη, λέει ότι ${BACKUP_ADDITION} Τέλος, λέει ότι ${KEEP_COPY_ADDITION}`,
    href: '/terms', hrefLabel: 'Δες τους Όρους',
  }
}

