// Ο ΚΩΔΙΚΟΣ ΕΠΑΛΗΘΕΥΣΗΣ ΟΠΩΣ ΤΟΝ ΠΛΗΚΤΡΟΛΟΓΕΙ ΑΝΘΡΩΠΟΣ ΜΕ ΕΛΛΗΝΙΚΟ ΠΛΗΚΤΡΟΛΟΓΙΟ
// ─────────────────────────────────────────────────────────────────────────
// Η γεννήτρια (lib/documents/issue.ts) γράφει `PO-ΕΕΜΜΗΗ-XXXXXXXX`: λατινικό
// PO, ημερομηνία σε ψηφία και οκτώ σύμβολα από αλφάβητο χωρίς 0/O και 1/I/L.
// Ο κωδικός όμως διαβάζεται από χαρτί και γράφεται με το χέρι:
//
// - Με ελληνικό πληκτρολόγιο το «PO» βγαίνει «ΡΟ», ελληνικό ρο και όμικρον.
//   Φαίνεται ίδιο και δεν ταιριάζει ποτέ: η σελίδα έλεγε «δεν βρέθηκε» για
//   γνήσιο έγγραφο. Το ίδιο για κάθε κεφαλαίο που μοιάζει με λατινικό.
// - Στη γραμματοσειρά του πεδίου το O μοιάζει με 0: «P0-…».
//
// Διορθώνεται ΜΟΝΟ ό,τι δεν μπορεί να σημαίνει κάτι άλλο: το πρόθεμα και το
// O στο τμήμα της ημερομηνίας, που είναι μόνο ψηφία. Στο τυχαίο τμήμα δεν
// υπάρχουν ούτε 0 ούτε O, άρα ό,τι γράφτηκε εκεί μένει όπως είναι και απλώς
// δεν θα βρεθεί.
// ═══════════════════════════════════════════════════════════════════════════

import { grUpper } from '@/lib/core/format';

/** Ελληνικά κεφαλαία που γράφονται ίδια με λατινικά. */
const LOOKALIKE: Record<string, string> = {
  Α: 'A', Β: 'B', Ε: 'E', Ζ: 'Z', Η: 'H', Ι: 'I', Κ: 'K', Μ: 'M',
  Ν: 'N', Ο: 'O', Ρ: 'P', Τ: 'T', Υ: 'Y', Χ: 'X',
};

/** Ο κωδικός όπως τον αναζητά η βάση. */
export function normalizeVerifyCode(raw: string): string {
  const latin = [...grUpper(raw.replace(/\s+/g, ''))].map(c => LOOKALIKE[c] ?? c).join('');
  const m = /^P[O0]-?([0-9O]{6})-?(.*)$/.exec(latin);
  if (!m) return latin;
  const date = m[1].replace(/O/g, '0');
  return m[2] ? `PO-${date}-${m[2]}` : `PO-${date}`;
}

/**
 * ΤΟ ΑΠΟΤΥΠΩΜΑ ΟΠΩΣ ΤΟ ΔΙΑΒΑΖΕΙ ΑΝΘΡΩΠΟΣ, ΙΔΙΟ ΣΤΟ ΧΑΡΤΙ ΚΑΙ ΣΤΗΝ /verify.
 *
 * Το μητρώο κρατά ολόκληρο το sha256 (64 δεκαεξαδικά, 20261007100000). Για
 * σύγκριση με το μάτι τυπώνονται τα πρώτα 16, κεφαλαία, σε τετράδες:
 * «3F2A 9C10 B7E4 0D55». Το PDF και η σελίδα περνούν από ΑΥΤΗ τη συνάρτηση,
 * ώστε να μη γίνει ποτέ η μία γραφή άλλη από την άλλη.
 *
 * Ό,τι δεν είναι sha256 (οι παλιές γραμμές με checksum του περιηγητή) δίνει
 * κενό: εκεί δεν υπάρχει αποτύπωμα του διακομιστή για να συγκριθεί.
 */
export function fingerprintLabel(checksum: string | null | undefined): string {
  const hex = (checksum ?? '').trim().toLowerCase();
  if (!/^[0-9a-f]{64}$/.test(hex)) return '';
  return (grUpper(hex.slice(0, 16)).match(/.{4}/g) ?? []).join(' ');
}
