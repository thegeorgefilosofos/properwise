// ασφάλειας διαβάζουν από εδώ, δεν ξαναγράφουν ημερομηνία.
// ═══════════════════════════════════════════════════════════════════════════
export interface AsOf {
  /** Τι μετριέται, όπως το λέει η οθόνη. */
  label: string;
  /** Πότε το είδε άνθρωπος στην πηγή (ISO). `null` = δεν έχει ελεγχθεί με ημερομηνία. */
  checkedAt: string | null;
  /** Η περίοδος των τιμών, όταν διαφέρει από την ημέρα ελέγχου («Οκτώβριος 2026»). */
  period?: string;
  /** Το όνομα της πηγής, όπως γράφεται στην οθόνη. */
  source: string;
  url?: string;
  /** Μετά από πόσες ημέρες η τιμή θεωρείται παλιά και δεν κατατάσσεται. */
  maxAgeDays?: number;
}

