/** Η εγγραφή ενός παρόχου, ή μια εγγραφή που λέει ότι δεν έχει ημερομηνία ελέγχου. */
export function telecomAsOf(provider: string, providerLabel?: string): AsOf {
  return TELECOM_FACTS[provider] ?? {
    label: `Προγράμματα ${providerLabel || provider}`, checkedAt: null, source: 'σελίδα του παρόχου',
  };
}

/** «05/10/2026». */
export function asOfDate(iso: string | null | undefined): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso ?? '');
  return m ? `${m[3]}/${m[2]}/${m[1]}` : '';
}

/**
 * Η γραμμή που γράφει κάθε οθόνη δίπλα σε τιμή ή όριο, με τις ίδιες λέξεις:
 * «Τελευταία ενημέρωση 05/10/2026 · Πηγή: ΡΑΑΕΥ, energycost.gr». Χωρίς
 * ημερομηνία ελέγχου το λέει: δεν δανείζεται ημερομηνία.
 */
export function asOfLine(f: AsOf): string {
  const when = f.checkedAt
    ? `Τελευταία ενημέρωση ${asOfDate(f.checkedAt)}`
    : 'Χωρίς ημερομηνία ελέγχου, επιβεβαίωσε στην πηγή';
  return `${when} · Πηγή: ${f.source}`;
}
