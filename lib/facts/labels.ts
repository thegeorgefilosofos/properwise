/**
 * ΤΟ ΟΝΟΜΑ ΜΙΑΣ ΔΟΣΗΣ ΦΟΡΟΥ, ΙΔΙΟ ΜΕ ΤΟ ΗΜΕΡΟΛΟΓΙΟ ΤΟΥ ΝΟΜΟΥ (αξιολόγηση 2, Χ3).
 * Η ατζέντα διαβάζει τον τίτλο του `lib/tax/greekTaxCalendar` («ΕΝΦΙΑ, 9η δόση»)
 * και η πρόβλεψη 12 μηνών, στην ίδια οθόνη, έγραφε «ΕΝΦΙΑ 9/12». Εδώ ο ίδιος
 * κανόνας με το ημερολόγιο: μία δόση, η δωδέκατη «τελευταία», η τελευταία
 * μικρότερου πλήθους «n-οστή και τελευταία». Ο έλεγχος στο forecast12.test
 * συγκρίνει με το ημερολόγιο λέξη προς λέξη.
 */
export function instalmentTitle(name: string, no: number, count: number): string {
  if (count === 1) return `${name}, πληρωμή σε μία δόση`;
  if (no === 12) return `${name}, τελευταία δόση`;
  if (no === count) return `${name}, ${no}η και τελευταία δόση`;
  return `${name}, ${no}η δόση`;
}
