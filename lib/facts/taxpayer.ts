export { sameTaxpayer, taxpayerOf, ACCOUNT_HOLDER } from '@/lib/accounting/taxpayer';

/**
 * Το εύρος του φορολογούμενου για το `sameTaxpayer` / `taxpayerRentSources`.
 *
 * @param profileType ο τύπος λογαριασμού
 * @param owners οι καρτέλες «Ιδιοκτήτης»· `null` όταν δεν διαβάστηκαν
 * @returns `null` για τον ιδιώτη (ένας φορολογούμενος), αλλιώς η λίστα, κενή
 *   όταν δεν διαβάστηκε: τότε δεν ενώνεται τίποτα.
 */
export function taxpayerScope(
  profileType: string | null | undefined, owners: ReadonlySet<string> | null | undefined,
): ReadonlySet<string> | null {
  if (profileType !== 'professional') return null;
  return owners ?? new Set<string>();
}
