// Ποιο κείμενο ΔΕΝ είναι παράγραφος για τον στοιχειοθέτη (lib/ui/typeset.ts).
//
// Το κενό που κλείνει: η γραμμή «ΠΡΑΣΙΝΟ · 0,129€ ανά κιλοβατώρα · Χωρίς πάγιο ·
// Τιμή Αυγούστου 2026 · Χωρίς δέσμευση» της σύγκρισης ρεύματος στοιχιζόταν πέρα
// πέρα σε tablet μέσα από το Instagram και τα κενά ανάμεσα στα κομμάτια
// άνοιγαν σε τρύπες (04.10.2026).
// ═══════════════════════════════════════════════════════════════════════════
import { isFactsLine } from './typeset';

let pass = 0, fail = 0;
const ok = (name: string, cond: boolean) => { if (cond) pass++; else { fail++; console.error(`✗ ${name}`); } };

ok('γραμμή στοιχείων τιμολογίου', isFactsLine('ΠΡΑΣΙΝΟ · 0,129€ ανά κιλοβατώρα · Χωρίς πάγιο · Τιμή Αυγούστου 2026 · Χωρίς δέσμευση'));
ok('δύο τελείες στο μέσο αρκούν', isFactsLine('ΜΠΛΕ · Πάγιο 3,50€ · Δέσμευση 12 μήνες'));
ok('πρόταση με μία τελεία στο μέσο μένει παράγραφος', !isFactsLine('Το δάνειο θέλει 742,12€ τον μήνα · μέσα στο όριο του 50% του εισοδήματος.'));
ok('κανονική παράγραφος μένει παράγραφος', !isFactsLine('Οι κρατήσεις μοιράζονται ισομερώς στους δώδεκα μήνες. Το τέλος είναι 8€ τη διανυκτέρευση.'));
ok('τελεία χωρίς κενά δεν μετρά', !isFactsLine('α·β·γ·δ'));

console.log(fail ? `✗ στοιχειοθέτης: ${fail} αποτυγχάνουν` : `✓ στοιχειοθέτης: ${pass} περνούν`);
if (fail) process.exit(1);
