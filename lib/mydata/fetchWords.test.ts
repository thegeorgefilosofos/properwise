// Η άντληση γίνεται μόνο όταν την ξεκινά ο λογιστής. Ο έλεγχος του βίντεο
// βρήκε στην κάρτα του πελάτη «μπορεί να φέρνει αυτόματα τα παραστατικά σου»:
// κείμενο του παλιού σχεδίου που επιβίωσε την απόφαση. Εδώ σαρώνονται τα
// ΚΕΙΜΕΝΑ (όχι τα σχόλια) κάθε αρχείου που δείχνει κάτι για το myDATA.
//
// ΤΙ ΜΕΝΕΙ ΕΠΙΤΡΕΠΤΟ. Η «αυτόματη καταχώρηση» είναι άλλο πράγμα: παραστατικό
// που ήδη έφερε ο λογιστής μπαίνει στις δαπάνες χωρίς πάτημα και αναιρείται.
// Απαγορεύεται το «αυτόματα» δίπλα σε λέξη άντλησης, όχι δίπλα σε καταχώρηση.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync, readdirSync } from 'node:fs';
import { clientSyncedLine } from './status';

let fails = 0;
const ok = (name: string, cond: boolean) => { if (!cond) { fails++; console.error('✗', name); } else console.log('✓', name); };

const FILES = [
  ...readdirSync('lib/mydata').filter(f => f.endsWith('.ts') && !f.endsWith('.test.ts')).map(f => `lib/mydata/${f}`),
  'lib/legal/mydataJoint.ts',
  'app/accountant/workspace/MydataCard.tsx',
  ...readdirSync('app/dashboard/components').filter(f => /^Mydata.*\.tsx$/.test(f)).map(f => `app/dashboard/components/${f}`),
];

/** Τα κείμενα ενός αρχείου: ό,τι είναι μέσα σε εισαγωγικά ή σε JSX, χωρίς σχόλια. */
function visibleText(src: string): string {
  return src
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/(^|[^:'"`])\/\/.*$/gm, '$1');
}

// «αυτόματα» μέχρι τρεις λέξεις πριν ή μετά από ρήμα άντλησης.
const FETCH = '(?:φέρν|φέρει|φέρουμε|άντλ|αντλ|συγχρον|λήψ|λαμβάν|έρχοντ|ενημερών)';
const FORBIDDEN = new RegExp(
  `κάθε νύχτα|απόψε|νυχτεριν|κάθε βράδυ|` +
  `${FETCH}\\S*(?:\\s+\\S+){0,3}?\\s+αυτόματ|αυτόματ\\S*(?:\\s+\\S+){0,3}?\\s+${FETCH}`, 'i');

ok('ο κανόνας πιάνει το κείμενο που βρήκε το βίντεο', FORBIDDEN.test('Ο λογιστής σου μπορεί να φέρνει αυτόματα τα παραστατικά σου από το myDATA.'));
ok('ο κανόνας πιάνει «αυτόματη άντληση»', FORBIDDEN.test('Γίνεται αυτόματη άντληση κάθε μέρα'));
ok('ο κανόνας πιάνει «απόψε»', FORBIDDEN.test('Θα ξαναδοκιμάσουμε απόψε'));
ok('η αυτόματη καταχώρηση μένει επιτρεπτή', !FORBIDDEN.test('Καταχωρήθηκαν αυτόματα · 3') && !FORBIDDEN.test('Αναίρεσες αυτόματη καταχώρηση'));
ok('τα σχόλια δεν μετρούν', !FORBIDDEN.test(visibleText('// ο νυχτερινός συγχρονισμός\nconst a = 1')));

for (const f of FILES) {
  const hit = visibleText(readFileSync(f, 'utf8')).match(FORBIDDEN);
  ok(`Ε2: ${f} χωρίς υπόσχεση αυτόματης ή νυχτερινής άντλησης${hit ? ` (βρέθηκε «${hit[0]}»)` : ''}`, !hit);
}

ok('η γραμμή του πελάτη: «Τελευταία άντληση από τον λογιστή: dd/mm/yyyy»',
  clientSyncedLine('2026-11-23T01:10:00Z') === 'Τελευταία άντληση από τον λογιστή: 23/11/2026');
ok('γύρω από τα μεσάνυχτα μετρά η ώρα Αθήνας', clientSyncedLine('2026-11-22T22:30:00Z') === 'Τελευταία άντληση από τον λογιστή: 23/11/2026');

if (fails) { console.error(`\n${fails} απέτυχαν`); process.exit(1); }
