// ═══════════════════════════════════════════════════════════════════════════
// scopedUpload — ΜΙΑ υλοποίηση για ανέβασμα αρχείου σε φάκελο του ίδιου του
// χρήστη. Κάθε μονοπάτι ξεκινά με το uid («<auth.uid()>/…»), ώστε οι πολιτικές
// αποθήκευσης να μπορούν να απομονώνουν τα αρχεία ανά χρήστη με
// `(storage.foldername(name))[1] = auth.uid()::text`.
//
// Χωρίς αυτό, τα δημόσια buckets (avatars, inventory-photos) είχαν επίπεδα
// μονοπάτια και η μόνη δυνατή προστασία ήταν «ανά bucket», δηλαδή κάθε
// συνδεδεμένος χρήστης μπορούσε να σβήσει το αρχείο άλλου.
//
// ── ΚΑΙ ΓΙΑΤΙ ΤΟ ΠΡΟΘΕΜΑ ΔΕΝ ΑΡΚΕΙ ΑΠΟ ΜΟΝΟ ΤΟΥ ──────────────────────────
// ΟΛΗ η απομόνωση στηρίζεται σε μία υπόθεση: ότι το πρώτο κομμάτι του
// μονοπατιού είναι το uid. Το `${user.id}/${relPath}` την κρατά μόνο όσο το
// `relPath` δεν περιέχει «..». Ενα «../<άλλο uid>/x.jpg» βγάζει
// «<uid>/../<άλλο uid>/x.jpg» και, αν το επίπεδο αποθήκευσης κανονικοποιήσει
// το μονοπάτι, το αρχείο προσγειώνεται στον φάκελο ΑΛΛΟΥ χρήστη — με την
// πολιτική RLS να το εγκρίνει, γιατί κοιτά το μονοπάτι που της δόθηκε.
//
// ΔΕΝ ΕΙΝΑΙ ΘΕΩΡΗΤΙΚΟ. Απο τα τρία σημεία που καλούν αυτή τη συνάρτηση, τα δύο
// φτιάχνουν το μονοπάτι με το `uploadPath()` (που καθαρίζει το όνομα) και το
// τρίτο —τα αρχεία επαφών— το έγραφε με το χέρι, παίρνοντας την ΚΑΤΑΛΗΞΗ ωμή
// από το `file.name.split('.').pop()`. Η κατάληξη είναι κείμενο που διαλέγει ο
// χρήστης όταν ονομάζει το αρχείο του.
//
// Η ΑΜΥΝΑ ΜΠΑΙΝΕΙ ΕΔΩ ΚΑΙ ΟΧΙ ΣΤΑ ΣΗΜΕΙΑ ΚΛΗΣΗΣ. Αυτή η συνάρτηση υπάρχει
// ακριβώς για να εγγυάται την απομόνωση· μια εγγύηση που εξαρτάται από το αν
// θυμήθηκε ο καθένας να καθαρίσει την είσοδό του δεν είναι εγγύηση. Το
// τέταρτο σημείο κλήσης, αύριο, δεν θα ξέρει τίποτα από όλα αυτά.
// ═══════════════════════════════════════════════════════════════════════════
import type { SupabaseClient } from '@supabase/supabase-js';

export interface ScopedUploadResult {
  /** Πλήρες μονοπάτι με το πρόθεμα του χρήστη — χρειάζεται για getPublicUrl/remove. */
  path: string;
  error: { message: string } | null;
}

/** Το μήνυμα απόρριψης, σε ένα σημείο ώστε να το ελέγχει και ο έλεγχος. */
export const ESCAPE_MSG = 'Μη έγκυρο όνομα αρχείου.';

/**
 * Το σχετικό μονοπάτι, καθαρισμένο ώστε να μην μπορεί να βγει από τον φάκελο
 * του χρήστη — ή `null` αν δεν σώζεται.
 *
 * ΤΟ ΠΟΣΟΣΤΙΑΙΟ ΑΠΟΚΩΔΙΚΟΠΟΙΕΙΤΑΙ ΠΡΩΤΑ. Το «%2e%2e%2f» είναι «../» για κάθε
 * επίπεδο που αποκωδικοποιεί διευθύνσεις· ένας έλεγχος που ψάχνει σκέτες
 * τελείες δεν το βλέπει. Οταν η αποκωδικοποίηση αποτύχει (σπασμένο ποσοστό),
 * το μονοπάτι απορρίπτεται: ένα όνομα που δεν διαβάζεται δεν ανεβαίνει.
 */
export function safeRelPath(relPath: string): string | null {
  let s = String(relPath ?? '');
  // Δύο περάσματα: το «%252e» γίνεται «%2e» στο πρώτο και «.» στο δεύτερο.
  for (let i = 0; i < 2; i++) {
    try { const d = decodeURIComponent(s); if (d === s) break; s = d; } catch { return null; }
  }
  // Η ανάστροφη κάθετος είναι διαχωριστικό σε Windows και σε αρκετούς πελάτες.
  const parts = s.split(/[/\\]/);
  const clean: string[] = [];
  for (const raw of parts) {
    const seg = raw.trim();
    if (seg === '' || seg === '.') continue;      // «a//b» και «a/./b» ισοπεδώνονται
    if (seg === '..') return null;                // ανάβαση: δεν καθαρίζεται, απορρίπτεται
    // Χαρακτήρες ελέγχου και NUL δεν έχουν θέση σε όνομα αντικειμένου.
    if (/[\u0000-\u001f\u007f]/.test(seg)) return null;
    clean.push(seg);
  }
  return clean.length ? clean.join('/') : null;
}

/**
 * Ανεβάζει το αρχείο στο `<uid>/<relPath>` του bucket.
 * @param relPath μονοπάτι ΧΩΡΙΣ το uid (π.χ. «contacts/1712.jpg»)
 */
export async function uploadUserScoped(
  supabase: SupabaseClient,
  bucket: string,
  relPath: string,
  file: File,
  opts?: { upsert?: boolean; contentType?: string },
): Promise<ScopedUploadResult> {
  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return { path: '', error: { message: 'Χρειάζεται σύνδεση για το ανέβασμα αρχείου.' } };
  const rel = safeRelPath(relPath);
  if (!rel) return { path: '', error: { message: ESCAPE_MSG } };
  const path = `${user.id}/${rel}`;
  const { error } = await supabase.storage.from(bucket).upload(path, file, opts);
  return { path, error: error ? { message: error.message } : null };
}
