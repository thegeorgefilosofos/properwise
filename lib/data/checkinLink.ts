// ΗΤΑΝ ΓΡΑΜΜΕΝΟΣ ΔΥΟ ΦΟΡΕΣ, ΜΕ ΤΑ ΙΔΙΑ ΔΥΟ ΣΦΑΛΜΑΤΑ. Η καρτέλα Πελατών κι ο
// βοηθός έφτιαχναν κι οι δύο το ίδιο `upsert` κι έχτιζαν κι οι δύο τη
// διεύθυνση με το χέρι — άρα κάθε διόρθωση έπρεπε να γίνει δύο φορές κι μία
// από τις δύο θα ξεχνιόταν.
//
// ── ΠΡΩΤΟ: Η ΔΙΕΥΘΥΝΣΗ ΔΕΝ ΒΓΑΙΝΕΙ ΑΠΟ ΤΟΝ ΠΕΡΙΗΓΗΤΗ ──────────────────────
// Ηταν `window.location.origin + '/checkin/' + token`. Ο σύνδεσμος όμως ΦΕΥΓΕΙ
// σε επισκέπτη, σε WhatsApp ή Viber. Ο ιδιοκτήτης που δούλευε από διεύθυνση
// προεπισκόπησης έστελνε διεύθυνση προεπισκόπησης — κι οι προεπισκοπήσεις
// σβήνονται. Ο επισκέπτης πατούσε κι δεν άνοιγε τίποτα.
//
// ── ΔΕΥΤΕΡΟ: ΤΟ ΞΑΝΑΑΝΤΙΓΡΑΜΜΕΝΟ ΗΤΑΝ ΗΔΗ ΝΕΚΡΟ ───────────────────────────
// Η στήλη `expires_at` γεννιέται `now() + 90 ημέρες` κι οι συναρτήσεις της
// βάσης αρνούνται ληγμένο κουπόνι. Το `upsert` όμως, σε σύγκρουση, γύριζε το
// ΥΠΑΡΧΟΝ κουπόνι χωρίς να αγγίξει τη λήξη του. Ενας πελάτης του περασμένου
// καλοκαιριού που ξαναρχόταν φέτος έπαιρνε σύνδεσμο ληγμένο πριν καν σταλεί:
// η οθόνη έλεγε «Ο σύνδεσμος αντιγράφηκε» κι ο επισκέπτης έβλεπε κενή σελίδα.
//
// Η ΑΝΤΙΓΡΑΦΗ ΕΙΝΑΙ ΡΗΤΗ ΠΡΑΞΗ, ΑΡΑ ΡΗΤΗ ΑΝΑΝΕΩΣΗ. Οταν ο ιδιοκτήτης πατά
// «Αντιγραφή συνδέσμου» δηλώνει ότι τον στέλνει ΤΩΡΑ. Το παράθυρο των ενενήντα
// ημερών ξεκινά από εκείνη τη στιγμή — όχι από την πρώτη φορά που άνοιξε την
// καρτέλα του πελάτη πέρσι.
// ═══════════════════════════════════════════════════════════════════════════
import type { SupabaseClient } from '@supabase/supabase-js';
import type { DbError } from '@/lib/supabase/writeResult';
import { siteUrl } from '@/lib/core/site';

const TABLE = 'checkin_links';

export type Db = SupabaseClient;

/** Ποσο ζει ο σύνδεσμος από τη στιγμή που δίνεται. Ιδιο με το `default` της στήλης. */
export const LIFETIME_DAYS = 90;

const DAY = 86_400_000;

/** Η διεύθυνση που πάει στον επισκέπτη. Κενό όταν δεν υπάρχει κουπόνι. */
export const checkinUrl = (token: string | null | undefined): string =>
  token ? siteUrl(`/checkin/${token}`) : '';

/** Ως πότε ισχύει ένας σύνδεσμος που δίνεται τώρα. */
export const expiryFrom = (now: Date): string =>
  new Date(now.getTime() + LIFETIME_DAYS * DAY).toISOString();

/**
 * Ο σύνδεσμος αυτού του πελάτη, γεννημένος ή ανανεωμένος.
 *
 * Επιστρέφει τον χτίστη του PostgREST, όχι το αποτέλεσμα: κάθε οθόνη κρατά τον
 * δικό της χειρισμό σφάλματος —`savedData` στην καρτέλα, `must` στον βοηθό—
 * όπως σε όλο το `lib/data`.
 */
export function issue(
  db: Db, userId: string, clientId: string, propertyId: string | null, now: Date,
): PromiseLike<{ data: { token: string } | null; error: DbError | null }> {
  return db.from(TABLE)
    .upsert({
      user_id: userId, client_id: clientId, property_id: propertyId,
      active: true, expires_at: expiryFrom(now),
    }, { onConflict: 'user_id,client_id' })
    .select('token').maybeSingle();
}
