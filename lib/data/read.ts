// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΧΗΜΑ ΤΟΥ ΣΦΑΛΜΑΤΟΣ. Το PostgREST απαντά πάντα `{ data, error }`. Οταν το
// ερώτημα αποτύχει — δίκτυο, δικαίωμα, ορθογραφικό σε όνομα στήλης — το `data`
// είναι `null`. Ο κώδικας που γράφει
//
//     const { data } = await db.from('expenses').select(…)
//     return (data || []) as T[]
//
// μετατρέπει την αποτυχία σε άδεια λίστα: την ΙΔΙΑ απάντηση με το «δεν έχεις
// καταχωρήσει τίποτα». Καμία εξαίρεση, κανένα μήνυμα, καμία ένδειξη. Το σχήμα
// ήταν γραμμένο ογδόντα εννέα φορές, σε σαράντα ένα αρχεία.
//
// ── ΤΙ ΑΛΛΑΖΕΙ ΕΔΩ ΚΑΙ ΤΙ ΟΧΙ ───────────────────────────────────────────
// ΔΕΝ γίνεται κάθε ανάγνωση θορυβώδης. Σε πολλά σημεία η άδεια λίστα ΕΙΝΑΙ η
// σωστή απάντηση και μια εξαίρεση εκεί θα έριχνε οθόνη για κάτι που δεν
// ενοχλεί κανέναν.
//
// Αυτό που αλλάζει είναι ΠΟΥ ΓΡΑΦΕΤΑΙ Η ΑΠΟΦΑΣΗ. Το `const { data } = await`
// δεν λέει «αποφάσισα να αγνοήσω το σφάλμα»· λέει «δεν το σκέφτηκα». Το
// `rows(…)` λέει το πρώτο, μία φορά, με το όνομά του — και δίπλα του υπάρχει
// πάντα το `read(…)` για όποιον χρειάζεται το σφάλμα.
//
// Ετσι κάθε αναγνώστης του στρώματος δεδομένων γίνεται ΜΙΑ γραμμή, το ερώτημα
// χτίζεται σε ένα σημείο και η εκδοχή «με το σφάλμα ορατό» δεν είναι πια
// δεύτερη υλοποίηση που μπορεί να αποκλίνει: είναι η ίδια, χωρίς την απόρριψη.
// ═══════════════════════════════════════════════════════════════════════════

import type { DbError } from '@/lib/supabase/writeResult';

/** Οτι επιστρέφει το PostgREST. Χαλαρό επίτηδες: το χτίσιμο το κάνει ο καλών. */
export type Query = PromiseLike<{ data: unknown; error: DbError | null }>;

export interface ReadResult<T> { rows: T[]; error: DbError | null }
export interface ReadOneResult<T> { row: T | null; error: DbError | null }

/** Λίστα, με το σφάλμα της ορατό. */
export async function read<T>(q: Query): Promise<ReadResult<T>> {
  const { data, error } = await q;
  return { rows: (data || []) as T[], error: error ?? null };
}

/** Μία γραμμή (`maybeSingle`/`single`), με το σφάλμα της ορατό. */
export async function readOne<T>(q: Query): Promise<ReadOneResult<T>> {
  const { data, error } = await q;
  return { row: (data ?? null) as T | null, error: error ?? null };
}

/**
 * Η λίστα ΧΩΡΙΣ το σφάλμα της.
 *
 * Η απόρριψη είναι ρητή και έχει όνομα. Οπου το άδειο γίνεται ΠΟΣΟ — φόρος,
 * Ε2, ταμειακή θέση — ο καλών οφείλει να χρησιμοποιήσει το `read` και να
 * δείξει την αποτυχία, όχι αυτό.
 */
export async function rows<T>(q: Query): Promise<T[]> {
  return (await read<T>(q)).rows;
}

/** Η μία γραμμή χωρίς το σφάλμα της. Ιδια σύμβαση με το `rows`. */
export async function row<T>(q: Query): Promise<T | null> {
  return (await readOne<T>(q)).row;
}

// ── ΟΛΕΣ ΟΙ ΓΡΑΜΜΕΣ, ΣΕ ΣΕΛΙΔΕΣ ─────────────────────────────────────────────
// Το PostgREST επιστρέφει το πολύ 1.000 γραμμές ανά αίτημα και δεν λέει ότι
// έκοψε. Για λίστες που αθροίζονται σε ΠΟΣΟ (καθολικό δαπανών → Λογιστική,
// Ε2, απόδοση) ή που διασχίζονται ολόκληρες (συσκευές ειδοποιήσεων), μια
// κομμένη λίστα είναι λάθος αριθμός ή χρήστες χωρίς ειδοποίηση (έλεγχος
// κλίμακας 10/11/2026). Η σελίδα είναι μικρότερη από το όριο, ώστε η γεμάτη
// σελίδα να σημαίνει πάντα «υπάρχει κι άλλη». Το `page(from, to)` χτίζει νέο
// ερώτημα κάθε φορά, με σταθερή ταξινόμηση που τελειώνει σε μοναδικό κλειδί.

export const PAGE_SIZE = 500;

export async function readAll<T>(
  page: (from: number, to: number) => Query, size = PAGE_SIZE, maxPages = 10_000,
): Promise<ReadResult<T>> {
  const out: T[] = [];
  for (let i = 0; i < maxPages; i++) {
    const from = i * size;
    const { rows: got, error } = await read<T>(page(from, from + size - 1));
    if (error) return { rows: out, error };
    out.push(...got);
    if (got.length < size) return { rows: out, error: null };
  }
  return { rows: out, error: { message: `readAll: περισσότερες από ${maxPages} σελίδες` } as DbError };
}
