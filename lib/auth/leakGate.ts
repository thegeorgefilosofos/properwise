/** Πόσο περιμένει η υποβολή, φόρτωμα και δίκτυο μαζί, πριν προχωρήσει. */
export const SUBMIT_TIMEOUT_MS = 2000

/**
 * `true` μόνο όταν η υπηρεσία απάντησε «βρέθηκε». Αλλιώς η υποβολή προχωρά.
 * Δεν απορρίπτεται ποτέ: αρχείο που δεν φόρτωσε (εκτός δικτύου) δίνει `false`.
 * Ο χρονοδιακόπτης δεν καθαρίζεται επίτηδες: όταν λήξει, ξαναλύνει μια
 * υπόσχεση που έχει ήδη κριθεί και δεν κάνει τίποτα. Κάθε byte εδώ μετρά.
 */
export function leakedAtSubmit(password: string, timeoutMs = SUBMIT_TIMEOUT_MS): Promise<boolean> {
  const until = Date.now() + timeoutMs
  return Promise.race([
    import('./leakedPassword').then(m => m.leakedForSubmit(password, until), () => false),
    new Promise<false>(r => setTimeout(r, timeoutMs, false)),
  ])
}
