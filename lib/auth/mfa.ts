// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΜΕΤΡΗΘΗΚΕ. `grep -rn "aal2|assurance|getAuthenticatorAssuranceLevel" app
// lib supabase` επέστρεψε ΜΗΔΕΝ γραμμές (έξοδος 1). Την ίδια στιγμή η εγγραφή
// συσκευής υπάρχει ολόκληρη στο app/dashboard/components/SecuritySettings.tsx
// — `mfa.enroll`, `mfa.challenge`, `mfa.verify`, `mfa.unenroll` — δηλαδή ο
// χρήστης σαρώνει τον κωδικό QR, βλέπει «Ενεργή» στην οθόνη του λογαριασμού
// και το ιστορικό ασφαλείας γράφει «Ενεργοποίησες την επαλήθευση δύο βημάτων».
//
// Η σύνδεση όμως έκανε `signInWithPassword` και αμέσως μετά
// `router.push('/dashboard')`. Η συνεδρία που γεννιέται εκεί είναι `aal1`:
// ένας κωδικός που διέρρευσε άνοιγε ολόκληρο τον λογαριασμό ΜΕ τον δεύτερο
// παράγοντα δηλωμένο ενεργό. Αυτό είναι χειρότερο από απουσία 2FA — ο χρήστης
// σταματά να προσέχει τον κωδικό του επειδή νομίζει ότι δεν αρκεί.
//
// ── ΤΙ ΛΕΝΕ ΤΑ ΔΥΟ ΕΠΙΠΕΔΑ ──────────────────────────────────────────────
// `currentLevel` είναι το επίπεδο ΤΗΣ ΣΥΝΕΔΡΙΑΣ που κρατά ο χρήστης τώρα.
// `nextLevel` είναι το επίπεδο που ΜΠΟΡΕΙ να φτάσει: γίνεται `aal2` μόνο όταν
// υπάρχει τουλάχιστον ένας επαληθευμένος παράγοντας. Οταν τα δύο διαφέρουν,
// ο χρήστης έχει δηλώσει συσκευή και δεν την έχει δείξει ακόμη σε αυτή τη
// συνεδρία. Αυτή ακριβώς είναι η στιγμή που ζητιέται ο εξαψήφιος κωδικός.
//
// ── ΓΙΑΤΙ ΔΥΟ ΞΕΧΩΡΙΣΤΕΣ ΣΥΝΑΡΤΗΣΕΙΣ ────────────────────────────────────
// Η οθόνη σύνδεσης ρωτά τον πελάτη του περιηγητή, που έχει έτοιμη τη συνεδρία,
// οπότε παίρνει `AssuranceLevels` και τελείωσε.
//
// Ο διαμεσολαβητής ΔΕΝ επιτρέπεται να ρωτήσει τον ίδιο δρόμο. Το
// `getAuthenticatorAssuranceLevel()` χωρίς όρισμα διαβάζει τη συνεδρία ΑΠΟ ΤΟ
// COOKIE, δηλαδή από κάτι που γράφει ο ίδιος ο επισκέπτης: όποιος έχει τον
// κλεμμένο κωδικό μπορεί να συνδεθεί με curl, να πάρει γνήσιο `aal1` διακριτικό
// και να στήσει cookie ΧΩΡΙΣ τον κατάλογο παραγόντων. Τότε το `nextLevel`
// βγαίνει `aal1` και η πόρτα ανοίγει. Γι' αυτό ο διαμεσολαβητής συνδυάζει δύο
// πηγές που ΔΕΝ ελέγχει ο επισκέπτης:
//
//   · τους παράγοντες όπως τους επιστρέφει το `auth.getUser()`, που ρωτά τον
//     διακομιστή ταυτότητας και όχι το cookie·
//   · το `aal` μέσα στο ΥΠΟΓΕΓΡΑΜΜΕΝΟ διακριτικό. Πλαστό διακριτικό δεν περνά
//     το `getUser()`, οπότε όποιο φτάνει ώς εδώ το έχει υπογράψει ο πάροχος.
// ═══════════════════════════════════════════════════════════════════════════

/** Το επίπεδο που σημαίνει «δύο βήματα έγιναν». */
export const AAL2 = 'aal2';

/** Ο,τι επιστρέφει το `mfa.getAuthenticatorAssuranceLevel()` και μας αφορά. */
export interface AssuranceLevels {
  currentLevel: string | null;
  nextLevel: string | null;
}

/** Το σχήμα ενός παράγοντα, όσο χρειάζεται για να κριθεί αν μετράει. */
export interface FactorLike {
  status?: string;
}

/** Το μήνυμα της οθόνης όταν λείπει το δεύτερο βήμα. Γραμμένο μία φορά. */
export const MFA_SAY = {
  ask: 'Καταχώρησε τον εξαψήφιο κωδικό από την εφαρμογή επαλήθευσης.',
  wrong: 'Ο κωδικός δεν είναι σωστός. Δοκίμασε ξανά.',
  stuck: 'Δεν μπορούμε να ολοκληρώσουμε το δεύτερο βήμα αυτή τη στιγμή. Δοκίμασε ξανά σε λίγο.',
} as const;

/**
 * Εχει ο χρήστης παράγοντα που ΕΧΕΙ επαληθευτεί;
 *
 * Οι μισοτελειωμένοι («unverified») δεν μετρούν: γεννιούνται σε κάθε
 * προσπάθεια εγγραφής συσκευής που εγκαταλείφθηκε. Αν μετρούσαν, όποιος
 * άνοιξε την οθόνη εγγραφής και την έκλεισε θα κλειδωνόταν έξω.
 */
export function hasVerifiedFactor(factors: readonly FactorLike[] | null | undefined): boolean {
  return (factors ?? []).some(f => f?.status === 'verified');
}

/**
 * Λείπει το δεύτερο βήμα από ΑΥΤΗ τη συνεδρία;
 *
 * Η απάντηση είναι «ναι» μόνο όταν ο χρήστης ΜΠΟΡΕΙ να φτάσει στο `aal2` και
 * δεν βρίσκεται ήδη εκεί. Καθε άλλη περίπτωση —χωρίς συσκευή, ή με το βήμα
 * ήδη περασμένο— δεν έχει τίποτα να ζητήσει.
 */
export function secondStepPending(levels: AssuranceLevels | null | undefined): boolean {
  if (!levels) return false;
  return levels.nextLevel === AAL2 && levels.currentLevel !== AAL2;
}

/**
 * Το `aal` μέσα στο διακριτικό, χωρίς επαλήθευση υπογραφής.
 *
 * ΓΙΑΤΙ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΜΗΝ ΕΠΑΛΗΘΕΥΕΤΑΙ ΕΔΩ. Ο μόνος καλών είναι ο
 * διαμεσολαβητής και καλεί ΜΕΤΑ το `auth.getUser()`, που έχει ήδη ρωτήσει τον
 * διακομιστή ταυτότητας για το ίδιο διακριτικό. Ενα διακριτικό με πειραγμένο
 * `aal` δεν φτάνει ποτέ εδώ: το `getUser()` το απορρίπτει πρώτο.
 *
 * Η αποκωδικοποίηση περνά από `TextDecoder` και όχι από σκέτο `atob`. Το
 * φορτίο κουβαλά και `user_metadata`, δηλαδή ελληνικά ονόματα: με σκέτο `atob`
 * το «Δημήτρης» γίνεται σκουπίδια και το `JSON.parse` πετάει — δηλαδή ο
 * έλεγχος θα έσπαγε ΜΟΝΟ για τους χρήστες με ελληνικό όνομα στο προφίλ.
 */
export function aalOfToken(accessToken: string | null | undefined): string | null {
  const parts = (accessToken || '').split('.');
  if (parts.length !== 3) return null;
  try {
    const b64 = parts[1].replace(/-/g, '+').replace(/_/g, '/');
    const padded = b64 + '='.repeat((4 - (b64.length % 4)) % 4);
    const binary = atob(padded);
    const bytes = Uint8Array.from(binary, c => c.charCodeAt(0));
    const claims = JSON.parse(new TextDecoder().decode(bytes)) as { aal?: unknown };
    return typeof claims.aal === 'string' ? claims.aal : null;
  } catch {
    return null;
  }
}

/**
 * Η ετυμηγορία του διαμεσολαβητή: πρέπει να σταλεί πίσω στη σύνδεση;
 *
 * ΚΛΕΙΝΕΙ ΟΤΑΝ ΔΕΝ ΞΕΡΕΙ. Χρήστης με επαληθευμένη συσκευή και διακριτικό που
 * δεν διαβάζεται είναι ακριβώς η μορφή που θα κατασκεύαζε κάποιος για να
 * γλιτώσει το δεύτερο βήμα. Το κόστος του λάθους προς την ασφαλή πλευρά είναι
 * μία επιπλέον καταχώρηση εξαψήφιου κωδικού· προς την άλλη, ολόκληρος ο
 * λογαριασμός.
 */
export function sessionNeedsSecondStep(
  accessToken: string | null | undefined,
  factors: readonly FactorLike[] | null | undefined,
): boolean {
  if (!hasVerifiedFactor(factors)) return false;
  return aalOfToken(accessToken) !== AAL2;
}
