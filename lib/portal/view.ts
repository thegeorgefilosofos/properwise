/**
 * Ο σύνδεσμος πληρωμής γράφεται μόνο αν είναι https. Ο ιδιοκτήτης τον
 * πληκτρολογεί· ένα `javascript:` ή `http:` δεν φτάνει ποτέ σε κουμπί.
 */
export function payLink(link: unknown): string | null {
  return typeof link === 'string' && link.startsWith('https://') ? link : null;
}

/**
 * Ο IBAN σε τετράδες, όπως τυπώνεται στις τράπεζες. Μόνο για ανάγνωση: η
 * αντιγραφή παίρνει την αρχική τιμή. Σπάει σε κενά αντί για τη μέση ενός
 * αριθμού στα 390.
 */
export function groupIban(iban: string): string {
  return iban.replace(/\s+/g, '').replace(/(.{4})(?=.)/g, '$1 ');
}

/** Υπάρχει οφειλή που ζητά ενέργεια; */
export function hasDue(d: { total_due: number; due: readonly unknown[] }): boolean {
  return d.total_due > 0 && d.due.length > 0;
}
