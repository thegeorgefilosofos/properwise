// κλήση αποτύγχανε. Η οθόνη λέει μόνο ό,τι έμαθε: ότι δεν πήρε απάντηση.
//
// ΚΑΙ ΔΕΝ ΣΤΕΛΝΕΙ ΓΙΑ ΝΕΟ ΣΥΝΔΕΣΜΟ ΣΤΟ ΣΦΑΛΜΑ. Αν ο ενοικιαστής ζητήσει νέο
// για ένα στιγμιαίο πρόβλημα, ο ιδιοκτήτης ανακαλεί τον παλιό που δούλευε.
// Πρώτη κίνηση είναι το «Δοκίμασε ξανά», που ξαναρωτά τον ίδιο σύνδεσμο.
// ═══════════════════════════════════════════════════════════════════════════

export type LinkLoad = 'ok' | 'notfound' | 'offline';

/**
 * Η κατάσταση από την απάντηση μιας κλήσης `rpc`. Το `found` κρίνει αν τα
 * δεδομένα που ήρθαν περιγράφουν σύνδεσμο που υπάρχει· εξ ορισμού «ήρθε κάτι».
 */
export function linkLoad(
  r: { data: unknown; error: unknown },
  found: (data: unknown) => boolean = d => d != null,
): LinkLoad {
  if (r.error) return 'offline';
  return found(r.data) ? 'ok' : 'notfound';
}

