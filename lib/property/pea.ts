// σάρωση του πιστοποιητικού, που γράφει την κατηγορία στο ακίνητο. Δύο
// κατάλογοι θα απέκλιναν στο πρώτο «Β+» που θα έγραφε ο ένας με λατινικό Β.
// ═══════════════════════════════════════════════════════════════════════════

/** Οι εννέα κατηγορίες του πιστοποιητικού, με τη γραφή που αποθηκεύεται. */
export const PEA_CLASSES = ['A+', 'A', 'B+', 'B', 'Γ', 'Δ', 'Ε', 'Ζ', 'Η'] as const;

// Η ΓΡΑΦΗ ΤΟΥ ΧΑΡΤΙΟΥ ΔΕΝ ΕΙΝΑΙ ΠΑΝΤΑ Η ΓΡΑΦΗ ΤΗΣ ΒΑΣΗΣ. Τα Α και Β του
// πιστοποιητικού είναι ελληνικά, οι αποθηκευμένες τιμές λατινικές· και η
// ανάγνωση γράφει συχνά το Ε, το Ζ και το Η με λατινικά, ή την ευρωπαϊκή
// κλίμακα C έως G. Αντιστοιχίζονται θέση προς θέση στην ίδια σειρά.
const SAME_LETTER: Record<string, string> = {
  'Α': 'A', 'Β': 'B', 'E': 'Ε', 'Z': 'Ζ', 'H': 'Η',
  'C': 'Γ', 'D': 'Δ', 'F': 'Ζ', 'G': 'Η',
};

/** Η κατηγορία στη γραφή της βάσης, ή κενό όταν δεν είναι μία από τις εννέα. */
export function peaClassOf(raw: string | null | undefined): string {
  const s = String(raw ?? '').trim().toUpperCase().replace(/\s+/g, '');
  const c = s.replace(/[^+]/g, ch => SAME_LETTER[ch] ?? ch);
  return (PEA_CLASSES as readonly string[]).includes(c) ? c : '';
}
