/** Πόσα ψηφία της παροχής ζητά η στήλη 18 του Ε2. */
export const E2_POWER_SUPPLY_DIGITS = 9;

/** Ανώτατο μήκος που δέχεται η βάση (ίδιο με το check της μετανάστευσης). */
export const DIGITS_MAX = 40;

/**
 * Η τιμή του πεδίου όπως αποθηκεύεται: χωρίς κενά, τελείες και παύλες που
 * βάζει ο λογαριασμός για να διαβάζεται. Ό,τι άλλο δεν είναι ψηφίο απορρίπτεται
 * με μήνυμα, δεν σβήνεται σιωπηλά.
 */
export function cleanDigits(raw: string | null | undefined): { value: string | null; error: string | null } {
  const s = String(raw ?? '').replace(/[\s.\-/]/g, '');
  if (!s) return { value: null, error: null };
  if (!/^\d+$/.test(s)) return { value: null, error: 'Μόνο ψηφία.' };
  if (s.length > DIGITS_MAX) return { value: null, error: `Έως ${DIGITS_MAX} ψηφία.` };
  return { value: s, error: null };
}

/** Η στήλη 18: τα πρώτα εννιά ψηφία της αποθηκευμένης παροχής. */
export function e2PowerSupply(stored: string | null | undefined): string {
  const d = String(stored ?? '').replace(/\D/g, '');
  return d.slice(0, E2_POWER_SUPPLY_DIGITS);
}

/**
 * Η παροχή όπως τη γράφει η σάρωση λογαριασμού στη σημείωσή του
 * (lib/billing/documents.ts: «Παροχή: …»). Επιστρέφει μόνο ψηφία, ή null όταν
 * η σημείωση δεν έχει παροχή με τουλάχιστον εννιά ψηφία.
 */
export function powerSupplyFromNote(note: string | null | undefined): string | null {
  const m = /Παροχή:\s*([0-9][0-9\s.\-/]*[0-9])/.exec(String(note ?? ''));
  if (!m) return null;
  const d = m[1].replace(/\D/g, '');
  return d.length >= E2_POWER_SUPPLY_DIGITS && d.length <= DIGITS_MAX ? d : null;
}
