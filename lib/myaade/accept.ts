// Το πλακίδιο δεχόταν PDF ή φωτογραφία, αλλά το πεδίο του «Δοκίμασε άλλο
// αρχείο» μετά από αποτυχία είχε γραμμένο με το χέρι μόνο το PDF. Ο χρήστης
// με σαρωμένο PDF διάβαζε «ανέβασε μια φωτογραφία της σελίδας» και ο
// επιλογέας δεν του έδειχνε φωτογραφίες (12/11/2026). Τώρα και τα δύο πεδία
// παίρνουν το `accept` από εδώ, όπως και ο έλεγχος που διαλέγει τη διαδρομή
// της φωτογραφίας (isPhotoFile), ώστε να μην αποκλίνουν ξανά.
//
// Χωρίς `capture`: στο κινητό ο επιλογέας προσφέρει κάμερα και αρχεία μαζί.
// Με `capture` θα άνοιγε μόνο την κάμερα και το PDF του myAADE δεν θα
// διαλεγόταν. Το HEIC περνά όπου ο περιηγητής το ανοίγει· αλλού το μήνυμα
// της ανάγνωσης λέει να αποθηκευτεί ως JPG (scanDoc.ts: scanPhotoList).
// ═══════════════════════════════════════════════════════════════════════════

/** Οι φωτογραφίες που διαβάζει η μαζική καταχώρηση. */
export const PHOTO_LIST_TYPES = ['image/jpeg', 'image/png', 'image/webp', 'image/heic', 'image/heif'] as const;
/** Οι καταλήξεις τους, για αρχεία χωρίς δηλωμένο τύπο. */
export const PHOTO_LIST_EXT = ['jpg', 'jpeg', 'png', 'webp', 'heic', 'heif'] as const;

/** Το `accept` κάθε πεδίου αρχείου της μαζικής καταχώρησης: το PDF του myAADE ή φωτογραφία του. */
export const MYAADE_ACCEPT = ['application/pdf', '.pdf', ...PHOTO_LIST_TYPES, ...PHOTO_LIST_EXT.map(e => `.${e}`)].join(',');

/** Πάει στη διαδρομή της φωτογραφίας; Με τον τύπο ή, όπου λείπει, με την κατάληξη. */
export const isPhotoFile = (file: { type?: string; name?: string }): boolean => {
  if ((PHOTO_LIST_TYPES as readonly string[]).includes((file.type || '').toLowerCase())) return true;
  const ext = /\.([a-z0-9]+)$/i.exec(file.name || '')?.[1]?.toLowerCase() ?? '';
  return (PHOTO_LIST_EXT as readonly string[]).includes(ext);
};
