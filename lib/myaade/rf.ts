// ═══════════════════════════════════════════════════════════════════════════
// ΤΑΥΤΟΤΗΤΑ ΟΦΕΙΛΗΣ (RF): ΕΛΕΓΧΟΣ ISO 11649
// ─────────────────────────────────────────────────────────────────────────
// Η Ταυτότητα Οφειλής είναι αναφορά πιστωτή κατά ISO 11649: «RF», δύο ψηφία
// ελέγχου και έως 21 αλφαριθμητικά. Ελέγχεται όπως το IBAN: τα τέσσερα πρώτα
// πάνε στο τέλος, τα γράμματα γίνονται αριθμοί (A=10 … Z=35) και το σύνολο
// mod 97 πρέπει να δίνει 1. Ό,τι δεν περνά δεν δείχνεται ως Ταυτότητα Οφειλής:
// μια λάθος αναφορά πληρωμής είναι χειρότερη από καμία.
// ═══════════════════════════════════════════════════════════════════════════

/** Χωρίς κενά, κεφαλαία. */
export const rfCompact = (s: string): string => s.replace(/\s+/g, '').toUpperCase();

/** Ισχύει το ψηφίο ελέγχου της αναφοράς; */
export function isValidRf(raw: string | null | undefined): boolean {
  const s = rfCompact(String(raw ?? ''));
  if (!/^RF\d{2}[0-9A-Z]{1,21}$/.test(s)) return false;
  const moved = s.slice(4) + s.slice(0, 4);
  let rem = 0;
  for (const ch of moved) {
    const v = ch >= 'A' && ch <= 'Z' ? String(ch.charCodeAt(0) - 55) : ch;
    for (const d of v) rem = (rem * 10 + Number(d)) % 97;
  }
  return rem === 1;
}
