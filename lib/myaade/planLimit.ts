/** Πόσα νέα ακίνητα χωρούν. `Infinity` όταν το πακέτο δεν έχει όριο. */
export function freeSlots(limit: number, currentCount: number): number {
  if (!Number.isFinite(limit)) return Infinity;
  return Math.max(0, Math.floor(limit) - currentCount);
}

/**
 * Ποιες νέες γραμμές είναι τσεκαρισμένες στην αρχή: οι πρώτες με τη σειρά της
 * πράξης, όσες χωρούν. Οι υπόλοιπες φαίνονται ξετσεκαρισμένες. Επιστρέφει τους
 * δείκτες των γραμμών «Εκτός πακέτου».
 */
export function overLimit(newRows: readonly number[], slots: number): number[] {
  return Number.isFinite(slots) ? newRows.slice(Math.max(0, slots)) : [];
}

/** Χωρά η επιλογή του χρήστη; Πόσα νέα επέλεξε πάνω από το όριο. */
export function excessOf(selectedNew: number, slots: number): number {
  return Number.isFinite(slots) ? Math.max(0, selectedNew - slots) : 0;
}
