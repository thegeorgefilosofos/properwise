// Τα μηνύματα κινητού έχουν ελληνικό όνομα στο μητρώο· αναγνωρίζονται από το Viber.
const keyOf = (s: Subprocessor) => (s.name.includes('Viber') ? 'mobile' : s.name);
const copyOf = (s: Subprocessor) => (s.role === 'mixed' ? MERCHANT_EN : SUBPROCESSOR_EN[keyOf(s)]);

export const subprocessorNameEn = (s: Subprocessor): string => SUBPROCESSOR_EN[keyOf(s)]?.name ?? s.name;

/** Η ίδια γραμμή με το `subprocessorLine`, στα αγγλικά. Ιδια κατάσταση, ίδια σειρά. */
export function subprocessorLineEn(s: Subprocessor): string {
  const c = copyOf(s);
  let purpose = c?.purpose ?? s.purpose;
  // Οι ίδιες προσθήκες που κάνει το μητρώο ανάλογα με το περιβάλλον.
  if (s.name === 'Sentry' && !s.active) purpose += ' It is switched on only if a key is set, and none is set today.';
  if (s.name === PUSH_SERVICES && !s.active) purpose += ' Not switched on.';
  if (s.name === 'Resend' && inboundDomain(process.env.NEXT_PUBLIC_INBOUND_DOMAIN) !== '') purpose += ' Receiving email: what you forward to your account’s receiving address, so that it can be suggested as expenses; and what you send to our contact addresses.';
  if (s.role === 'mixed') purpose += ` ${billingWordsEn().merchantRow}`;
  const entity = c?.entity ?? (s.entity && !/\p{Script=Greek}/u.test(s.entity) ? s.entity : null);
  return `${subprocessorNameEn(s)} (${c?.where ?? s.where}), ${ROLE_EN[s.role]}.${entity ? ` Legal entity: ${entity.replace(/\.?$/, '.')}` : ''} ${purpose}`;
}

