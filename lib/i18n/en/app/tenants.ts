const f = APP_FMT;
const count = (n: number, one: string, many: string) => `${f.fn(n)} ${n === 1 ? one : many}`;
const days = (n: number) => count(n, 'day', 'days');
const ord = (n: number) => {
  const t = n % 100;
  const s = t >= 11 && t <= 13 ? 'th' : n % 10 === 1 ? 'st' : n % 10 === 2 ? 'nd' : n % 10 === 3 ? 'rd' : 'th';
  return `${n}${s}`;
};
