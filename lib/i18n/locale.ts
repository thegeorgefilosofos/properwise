// ΔΥΟ ΓΛΩΣΣΕΣ ΣΤΗ ΒΙΤΡΙΝΑ, ΜΙΑ ΣΤΗΝ ΕΦΑΡΜΟΓΗ
// ─────────────────────────────────────────────────────────────────────────
// Οι δημόσιες σελίδες (αρχική, τιμές, εργαλεία, οδηγοί, είσοδος, εγγραφή,
// νομικά) υπάρχουν και στα αγγλικά, κάτω από το /en, για τον υποψήφιο
// επενδυτή και τον ξένο ιδιοκτήτη που θέλει να καταλάβει τι είναι το προϊόν.
// Η ίδια η εφαρμογή (/dashboard) μένει ελληνική.
//
// Η ΓΛΩΣΣΑ ΒΓΑΙΝΕΙ ΑΠΟ ΤΗ ΔΙΑΔΡΟΜΗ ΚΑΙ ΜΟΝΟ ΑΠΟ ΑΥΤΗ. Οχι από cookie, όχι
// από το Accept-Language: η ίδια διεύθυνση δίνει πάντα την ίδια γλώσσα, σε
// άνθρωπο και σε μηχανή αναζήτησης. Το cookie θυμάται μόνο την ΕΠΙΛΟΓΗ του
// επισκέπτη, για να τον κρατά στη γλώσσα του όταν ακολουθεί σύνδεσμο.
// ═══════════════════════════════════════════════════════════════════════════

export type Locale = 'el' | 'en';

/** Το πρόθεμα των αγγλικών σελίδων. */
export const EN_PREFIX = '/en';

/** Το cookie της επιλογής γλώσσας («el» ή «en»). Το γράφει ο επιλογέας. */
export const LOCALE_COOKIE = 'pw_lang';

/** Η κεφαλίδα αιτήματος με τη γλώσσα της σελίδας, από το proxy.ts στη ρίζα. */
export const LOCALE_HEADER = 'x-pw-locale';

/**
 * Η κεφαλίδα της διακριτικής πρότασης «View in English»: η αγγλική διαδρομή
 * της ελληνικής σελίδας, όταν ο περιηγητής δεν μιλά ελληνικά και ο
 * επισκέπτης δεν έχει διαλέξει γλώσσα.
 */
export const SUGGEST_HEADER = 'x-pw-suggest-en';

/** Ενας χρόνος: η επιλογή γλώσσας δεν ξεχνιέται σε κάθε επίσκεψη. */
export const LOCALE_COOKIE_MAX_AGE = 60 * 60 * 24 * 365;

export const isEnPath = (path: string): boolean => path === EN_PREFIX || path.startsWith(EN_PREFIX + '/');

// ═══════════════════════════════════════════════════════════════════════════
// ΟΙ ΣΕΛΙΔΕΣ ΤΟΥ ΠΑΡΑΛΗΠΤΗ: ΙΔΙΑ ΔΙΕΥΘΥΝΣΗ, ΓΛΩΣΣΑ ΑΠΟ ΤΟΝ ΑΝΘΡΩΠΟ
// ─────────────────────────────────────────────────────────────────────────
// Η πύλη του ενοικιαστή, τα στοιχεία διαμονής του επισκέπτη, το «Πλήρωσα»,
// η απεγγραφή, η επιβεβαίωση διεύθυνσης, η επαλήθευση εγγράφου και η σελίδα
// χωρίς σύνδεση ανοίγουν από σύνδεσμο που στάλθηκε με email ή SMS. Η
// διεύθυνση δεν αλλάζει (είναι το κλειδί), δεν ευρετηριάζονται ποτέ και
// πολλοί ενοικιαστές και επισκέπτες στην Ελλάδα δεν διαβάζουν ελληνικά.
// Εδώ και μόνο εδώ η γλώσσα βγαίνει από τον άνθρωπο: πρώτα η ρητή επιλογή
// του (cookie `pw_lang`), αλλιώς ο περιηγητής του (αγγλικά μόνο όταν δεν
// μιλά καθόλου ελληνικά). Ο κανόνας «η γλώσσα από τη διαδρομή» μένει για
// κάθε σελίδα που ευρετηριάζεται.
// ═══════════════════════════════════════════════════════════════════════════
const RECIPIENT_EXACT = new Set(['/verify', '/offline']);
const RECIPIENT_PREFIXES = ['/portal/', '/checkin/', '/plirosa/', '/unsubscribe/', '/epivevaiosi-email/', '/verify/'];

/** Σελίδα παραλήπτη συνδέσμου: ίδια διεύθυνση και στις δύο γλώσσες. */
export const isRecipientPath = (path: string): boolean =>
  RECIPIENT_EXACT.has(path) || RECIPIENT_PREFIXES.some(p => path.startsWith(p));

/** Η γλώσσα μιας σελίδας παραλήπτη: η επιλογή του, αλλιώς ο περιηγητής του. */
export function recipientLocale(chosen: string | null | undefined, acceptLanguage: string | null | undefined): Locale {
  if (chosen === 'en' || chosen === 'el') return chosen;
  return browserLacksGreek(acceptLanguage) ? 'en' : 'el';
}

// ═══════════════════════════════════════════════════════════════════════════
// Η ΕΦΑΡΜΟΓΗ: ΙΔΙΑ ΔΙΕΥΘΥΝΣΗ, ΓΛΩΣΣΑ ΑΠΟ ΤΗΝ ΕΠΙΛΟΓΗ ΤΟΥ ΧΡΗΣΤΗ
// ─────────────────────────────────────────────────────────────────────────
// Ο πίνακας (/dashboard) είναι ιδιωτικός και δεν ευρετηριάζεται, οπότε δεν
// χρειάζεται ζεύγος /en: όπως οι σελίδες παραλήπτη, κρατά τη διεύθυνσή του.
// Η γλώσσα του βγαίνει ΜΟΝΟ από τη ρητή επιλογή (cookie `pw_lang`, που
// γράφουν οι Ρυθμίσεις μαζί με το `user_metadata.app_locale` του λογαριασμού).
// ΟΧΙ από τον περιηγητή: πολλοί Ελληνες ιδιοκτήτες έχουν αγγλικό περιηγητή
// και η εφαρμογή τους δεν αλλάζει γλώσσα χωρίς να το ζητήσουν.
// ═══════════════════════════════════════════════════════════════════════════
const APP_PREFIX = '/dashboard';

/** Σελίδα της εφαρμογής: ίδια διεύθυνση και στις δύο γλώσσες. */
export const isAppPath = (path: string): boolean => path === APP_PREFIX || path.startsWith(APP_PREFIX + '/');

/** Η γλώσσα της εφαρμογής: αγγλικά μόνο με ρητή επιλογή, αλλιώς ελληνικά. */
export const appLocale = (chosen: string | null | undefined): Locale => (chosen === 'en' ? 'en' : 'el');

/**
 * Το κλειδί του `user_metadata` με την επιλογή γλώσσας του λογαριασμού.
 * ΟΧΙ σκέτο «locale»: το Supabase αντιγράφει στο ίδιο αντικείμενο τα στοιχεία
 * του παρόχου σύνδεσης και η Google στέλνει δικό της `locale` (τη γλώσσα του
 * λογαριασμού Google). Ελληνας με αγγλικό λογαριασμό Google θα έβλεπε την
 * εφαρμογή στα αγγλικά χωρίς να το ζητήσει.
 */
export const LOCALE_META_KEY = 'app_locale';

/** Η επιλογή γλώσσας που κρατά ο λογαριασμός, ή null αν δεν διάλεξε ποτέ. */
export function metaLocale(meta: Record<string, unknown> | null | undefined): Locale | null {
  const v = meta?.[LOCALE_META_KEY];
  return v === 'en' || v === 'el' ? v : null;
}

// ═══════════════════════════════════════════════════════════════════════════
// Η ΓΛΩΣΣΑ ΤΩΝ ΜΗΝΥΜΑΤΩΝ: EMAIL ΚΑΙ ΕΙΔΟΠΟΙΗΣΕΙΣ ΣΥΣΚΕΥΗΣ
// ─────────────────────────────────────────────────────────────────────────
// Χωριστή από τη γλώσσα της εφαρμογής, γιατί δεν είναι πάντα ίδια: ο Ελληνας
// ιδιοκτήτης που θέλει την εφαρμογή στα ελληνικά αλλά προωθεί τις υπενθυμίσεις
// στον ξένο συνιδιοκτήτη, ή το αντίστροφο. Οσο ο χρήστης δεν έχει διαλέξει,
// τα μηνύματα ακολουθούν τη γλώσσα της εφαρμογής και, χωρίς ούτε αυτή,
// μένουν ελληνικά. Τη διαβάζουν και οι συναρτήσεις άκρης (Deno), γι' αυτό
// αυτό το αρχείο δεν εισάγει τίποτα.
// ═══════════════════════════════════════════════════════════════════════════

/** Το κλειδί του `user_metadata` με τη γλώσσα των email και των ειδοποιήσεων. */
export const MSG_LOCALE_META_KEY = 'msg_locale';

/** Η γλώσσα των μηνυμάτων: η επιλογή της, αλλιώς η γλώσσα της εφαρμογής, αλλιώς ελληνικά. */
export function msgLocale(meta: Record<string, unknown> | null | undefined): Locale {
  const v = meta?.[MSG_LOCALE_META_KEY];
  if (v === 'en' || v === 'el') return v;
  return metaLocale(meta) ?? 'el';
}

export const localeOfPath = (path: string | null | undefined): Locale => (path && isEnPath(path) ? 'en' : 'el');

/** Η μορφή του Open Graph για κάθε γλώσσα. */
export const OG_LOCALE: Record<Locale, string> = { el: 'el_GR', en: 'en_US' };

/** Το όνομα κάθε γλώσσας στη δική της γλώσσα, όπως στον επιλογέα. */
export const LOCALE_NAME: Record<Locale, string> = { el: 'Ελληνικά', en: 'English' };

/** Η σύντομη ετικέτα του κουμπιού: «ΕΛ» και «EN». */
export const LOCALE_SHORT: Record<Locale, string> = { el: 'ΕΛ', en: 'EN' };

/**
 * Αν ο περιηγητής ΔΕΝ μιλά καθόλου ελληνικά. Μόνο τότε η ελληνική σελίδα
 * προτείνει, διακριτικά, την αγγλική της — ποτέ ανακατεύθυνση (οδηγία της
 * Google για σελίδες ανά γλώσσα). Χωρίς κεφαλίδα, όπως οι μηχανές
 * αναζήτησης, δεν προτείνεται τίποτα.
 */
export function browserLacksGreek(acceptLanguage: string | null | undefined): boolean {
  const tags = (acceptLanguage ?? '')
    .split(',')
    .map(part => part.trim().split(';')[0].trim().toLowerCase())
    .filter(t => t && t !== '*');
  if (!tags.length) return false;
  return !tags.some(t => t === 'el' || t.startsWith('el-'));
}
