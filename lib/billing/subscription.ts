// ΓΙΑΤΙ ΞΕΧΩΡΙΣΕ ΑΠΟ ΤΟ «lemon.ts». Οι επτά καταστάσεις μιας συνδρομής, το
// «ποιος δικαιούται τι» και το «σε ποια φάση είναι ο πελάτης» δεν ανήκουν σε
// κανέναν πάροχο: είναι δικοί ΜΑΣ κανόνες και δεν αλλάζουν αν αύριο χρεώνει
// άλλος. Οσο ζούσαν σε αρχείο με το όνομα του παρόχου, η κάρτα χρέωσης του
// πίνακα ελέγχου έπρεπε να εισάγει «lemon» για να ρωτήσει κάτι ουδέτερο.
//
// Ο,τι ΑΛΛΑΖΕΙ με τον πάροχο —τα ονόματα γεγονότων, το σχήμα του webhook, οι
// καταστάσεις με τη δική του ορθογραφία— ζει πίσω από τη θύρα «merchant/». Το
// όριο είναι ακριβώς αυτό: κανόνες εδώ, πρωτόκολλο εκεί.
// ═══════════════════════════════════════════════════════════════════════════
import { PLAN_ORDER, type PlanId, type BillingCycle } from './plans';

/**
 * Οι καταστάσεις συνδρομής της εφαρμογής. Γεννήθηκαν από την τεκμηρίωση του
 * πρώτου εμπόρου και κάθε έμπορος μεταφράζει στις δικές ΤΟΥ μέσα στη θύρα
 * (π.χ. «canceled» και «scheduled_cancel» του Creem σε `cancelled`). Η λίστα
 * δεν επεκτείνεται από εικασία.
 */
export const MOR_STATUSES = [
  'on_trial', 'active', 'paused', 'past_due', 'unpaid', 'cancelled', 'expired',
] as const;

export type MorStatus = (typeof MOR_STATUSES)[number];

export const isMorStatus = (v: unknown): v is MorStatus =>
  typeof v === 'string' && (MOR_STATUSES as readonly string[]).includes(v);

export interface VariantPlan { plan: PlanId; cycle: BillingCycle }

export interface MorSubscription {
  /** Το αναγνωριστικό της συνδρομής στον έμπορο. */
  id: string;
  status: MorStatus;
  variantId: string;
  customerId: string;
  /** Ο λογαριασμός μας, από το `custom_data`. `null` όταν λείπει. */
  userId: string | null;
  /** Πότε ανανεώνεται. Κενό όταν δεν ανανεώνεται. */
  renewsAt: string | null;
  /** Πότε λήγει η πρόσβαση. Γεμάτο σε ακύρωση και σε λήξη. */
  endsAt: string | null;
}

// ── ΠΟΤΕ ΙΣΧΥΕΙ Η ΣΥΝΔΡΟΜΗ ────────────────────────────────────────────────
//
// `on_trial`   δοκιμή σε εξέλιξη — η μόνη δωρεάν περίοδος του προϊόντος.
// `active`     πληρωμένη και ενεργή.
// `past_due`   μια ανανέωση απέτυχε και ο έμπορος ξαναδοκιμάζει την
//              είσπραξη. Η πρόσβαση ΜΕΝΕΙ για `PAST_DUE_GRACE_DAYS` ημέρες
//              από την ΠΡΩΤΗ αποτυχία: το να κλείσει η πόρτα σε πελάτη που
//              απλώς άλλαξε κάρτα είναι χειρότερο από λίγες ημέρες πίστωση.
//              Μετά, ο λογαριασμός πέφτει στο πακέτο χωρίς συνδρομή ώσπου να
//              περάσει η πληρωμή. Ως τις 12/11/2026 η πρόσβαση έμενε χωρίς
//              όριο, όσο ο έμπορος δεν έστελνε «unpaid» (έλεγχος ετοιμότητας
//              πληρωμών 12/11/2026, «Λείπει (κώδικας)» 2).
// `cancelled`  ακυρώθηκε η ΜΕΛΛΟΝΤΙΚΗ χρέωση, αλλά η περίοδος που πληρώθηκε
//              τρέχει ακόμη. Η πρόσβαση ΜΕΝΕΙ ως το `ends_at` και ούτε μέρα
//              παραπάνω. Χωρίς `ends_at` δεν υπάρχει πρόσβαση: δεν εφευρίσκουμε
//              ημερομηνία λήξης για να είμαστε γενναιόδωροι.
// `paused`     η είσπραξη έχει παύσει με τη θέληση του πελάτη. ΔΕΝ δίνει
//              πρόσβαση: το προϊόν δεν έχει δωρεάν βαθμίδα και μια παύση που
//              κρατά τη συνδρομή ανοιχτή θα ήταν ακριβώς αυτό.
// `unpaid`     απέτυχαν και οι τέσσερις προσπάθειες είσπραξης.
// `expired`    τελείωσε.
//
/**
 * ΠΟΣΕΣ ΗΜΕΡΕΣ ΚΡΑΤΑ Η ΠΡΟΣΒΑΣΗ ΜΕΤΑ ΤΗΝ ΠΡΩΤΗ ΑΠΟΤΥΧΗΜΕΝΗ ΧΡΕΩΣΗ.
 *
 * ΕΠΙΛΟΓΗ ΠΡΟΪΟΝΤΟΣ, ΟΧΙ ΚΑΝΟΝΑΣ ΤΟΥ ΕΜΠΟΡΟΥ ΟΥΤΕ ΤΟΥ ΝΟΜΟΥ. Μια εβδομάδα
 * φτάνει για να δει ο πελάτης το email του εμπόρου και να αλλάξει κάρτα, χωρίς
 * να γίνεται η καθυστέρηση δωρεάν μήνας. Αλλάζει μόνο με απόφαση ιδιοκτήτη και
 * ΜΑΖΙ με την `public.past_due_grace_days()` της βάσης: το db-replay ελέγχει
 * ότι οι δύο αριθμοί συμφωνούν.
 */
export const PAST_DUE_GRACE_DAYS = 7;

/**
 * Ως πότε κρατά η πρόσβαση μιας συνδρομής σε καθυστέρηση πληρωμής.
 *
 * `null` όταν δεν ξέρουμε πότε ξεκίνησε η καθυστέρηση: δεν εφευρίσκουμε
 * ημερομηνία για να κόψουμε πρόσβαση.
 */
export function pastDueUntil(since: string | null | undefined): string | null {
  const t = since ? Date.parse(since) : NaN;
  return Number.isFinite(t) ? new Date(t + PAST_DUE_GRACE_DAYS * 86_400_000).toISOString() : null;
}

/**
 * Ισχύει η συνδρομή τη δεδομένη στιγμή;
 *
 * @param sub.pastDueSince Η πρώτη αποτυχημένη χρέωση (`mor_past_due_at`). Μόνο
 *               για το `past_due`· χωρίς αυτήν η χάρη δεν λήγει.
 * @param nowIso Η στιγμή που κρίνεται, σε ISO. Δίνεται από τον καλούντα ώστε ο
 *               έλεγχος να είναι ντετερμινιστικός.
 */
export function isEntitled(
  sub: { status: MorStatus; endsAt: string | null; pastDueSince?: string | null },
  nowIso: string,
): boolean {
  switch (sub.status) {
    case 'on_trial':
    case 'active':
      return true;
    case 'past_due': {
      const until = pastDueUntil(sub.pastDueSince);
      return !until || Date.parse(nowIso) < Date.parse(until);
    }
    case 'cancelled':
      return !!sub.endsAt && nowIso < sub.endsAt;
    case 'paused':
    case 'unpaid':
    case 'expired':
      return false;
  }
}

// ── ΠΩΣ ΛΕΓΕΤΑΙ Η ΚΑΤΑΣΤΑΣΗ ΣΤΟΝ ΑΝΘΡΩΠΟ ──────────────────────────────────
//
// Η ΟΘΟΝΗ ΔΕΝ ΞΑΝΑΓΡΑΦΕΙ ΤΟ ΛΕΞΙΛΟΓΙΟ ΤΟΥ ΕΜΠΟΡΟΥ. Η κάρτα της συνδρομής
// συνέκρινε με συμβολοσειρές γραμμένες με το χέρι· μια αλλαγή παρόχου σημαίνει
// ότι καμία συνθήκη δεν ταιριάζει πια και ο πελάτης με ενεργή συνδρομή βλέπει
// κάρτα που δεν λέει τίποτα — χωρίς κανένα σφάλμα να το εξηγεί.
//
// Η μετάφραση γίνεται ΕΔΩ, δίπλα στη λίστα των καταστάσεων, ώστε μια νέα
// κατάσταση να μη γίνεται δεκτή χωρίς να αποφασιστεί τι λέει στον άνθρωπο.
export type SubPhase =
  /** Δοκιμή σε εξέλιξη. */
  | 'trial'
  /** Πληρωμένη και ενεργή. */
  | 'active'
  /** Μια ανανέωση απέτυχε και ξαναδοκιμάζεται. Η πρόσβαση μένει. */
  | 'retrying'
  /** Τελείωσε, πάγωσε, ή δεν πληρώθηκε ποτέ. */
  | 'lapsed'
  /** Καμία συνδρομή δεν έχει υπάρξει. */
  | 'none';

/**
 * Σε ποια φάση βρίσκεται η συνδρομή, από την κατάσταση που έγραψε ο webhook.
 *
 * ΤΟ `cancelled` ΔΕΝ ΕΙΝΑΙ ΦΑΣΗ ΕΔΩ, ΕΙΝΑΙ ΗΜΕΡΟΜΗΝΙΑ. Ακυρωμένη συνδρομή που
 * τρέχει ως το `ends_at` δεν διαβάζεται από την κατάσταση αλλά από την ίδια την
 * ημερομηνία, που η οθόνη ελέγχει πρώτη.
 */
export function subPhase(status: string): SubPhase {
  if (!isMorStatus(status)) return 'none';
  switch (status) {
    case 'on_trial': return 'trial';
    case 'active': return 'active';
    case 'past_due': return 'retrying';
    case 'cancelled':
    case 'paused':
    case 'unpaid':
    case 'expired': return 'lapsed';
  }
}

