// ΤΟ ΣΦΑΛΜΑ, ΟΠΩΣ ΗΤΑΝ. Ο πίνακας του `enfia.ts` έχει κλειδιά `fourth` (1,02) και
// `fifth_plus` (1,03) και ο νόμος βάζει τον 5ο όροφο στο 1,02, μαζί με τον 4ο.
// Η δημόσια σελίδα το έγραφε σωστά («4ος και 5ος», «6ος και πάνω»). Ο πίνακας
// ελέγχου έγραφε «4ος» και «5ος και άνω»: ο ιδιοκτήτης στον 5ο που διάλεγε τη
// λέξη που τον περιέγραφε έπαιρνε συντελεστή 1,03, δηλαδή 1% παραπάνω ΕΝΦΙΑ
// κτίσματος, σε οθόνη που λέει «ίδιοι συντελεστές με τον νόμο».
//
// Δύο οθόνες είχαν δύο αντίγραφα του ίδιου λεξιλογίου και το ένα απέκλινε. Εδώ
// ζει το μόνο αντίγραφο. Ο τύπος `Record<keyof typeof ENFIA_FLOOR_COEF, …>`
// κάνει σφάλμα μεταγλώττισης κάθε κλειδί που προστίθεται στον πίνακα χωρίς
// ετικέτα. Το `enfiaFloors.test.ts` ελέγχει ότι η ετικέτα κάθε κλειδιού
// περιγράφει ακριβώς τους ορόφους που αντιστοιχίζει σε αυτό η
// `enfiaFloorKeyFromValue`.
// ═══════════════════════════════════════════════════════════════════════════
import type { ENFIA_FLOOR_COEF } from './enfia'

export const ENFIA_FLOOR_LABEL: Record<keyof typeof ENFIA_FLOOR_COEF, string> = {
  basement: 'Υπόγειο',
  ground: 'Ισόγειο',
  first: '1ος όροφος',
  second: '2ος όροφος',
  third: '3ος όροφος',
  fourth: '4ος και 5ος',
  // «άνω», όπως το «26 έτη και άνω» της παλαιότητας που κάθεται στην ίδια σειρά.
  fifth_plus: '6ος και άνω',
}

// ═══ ΔΙΠΛΑ ΣΤΟ ΚΛΕΙΔΙ «ΟΡΟΦΟΣ», ΧΩΡΙΣ ΤΗ ΛΕΞΗ ΔΕΥΤΕΡΗ ΦΟΡΑ (#398) ═══════════
// Στο μενού η ετικέτα στέκει μόνη της και το «2ος όροφος» διαβάζεται σωστά. Στο
// χαρτί της εκτίμησης και στις κάρτες των σειρών μπαίνει όμως δίπλα στο κλειδί
// «Όροφος», οπότε έβγαινε «Όροφος 2ος όροφος». Η σύντομη μορφή ΒΓΑΙΝΕΙ από την
// ετικέτα του μενού, δεν ξαναγράφεται: ένα νέο κλειδί στον πίνακα παίρνει και
// τις δύο από το ίδιο σημείο. Το «Υπόγειο», το «Ισόγειο», το «4ος και 5ος» και
// το «6ος και άνω» δεν έχουν τη λέξη και μένουν ίδια.
export const ENFIA_FLOOR_SHORT = Object.fromEntries(
  (Object.keys(ENFIA_FLOOR_LABEL) as (keyof typeof ENFIA_FLOOR_COEF)[])
    .map(k => [k, ENFIA_FLOOR_LABEL[k].replace(/\s+όροφος$/u, '')]),
) as Record<keyof typeof ENFIA_FLOOR_COEF, string>
