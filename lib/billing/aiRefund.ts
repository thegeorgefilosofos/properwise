// ΓΙΑΤΙ ΜΕ ΚΛΕΙΔΙ ΥΠΗΡΕΣΙΑΣ ΚΑΙ ΟΧΙ ΜΕ ΤΗ ΣΥΝΕΔΡΙΑ ΤΟΥ ΧΡΗΣΤΗ. Η
// `bump_ai_usage` μόνο ΑΥΞΑΝΕΙ, οπότε είναι ακίνδυνο να την καλεί ο ίδιος ο
// χρήστης. Η `refund_ai_usage` ΜΕΙΩΝΕΙ: αν την είχε ο ρόλος `authenticated`,
// ο καθένας θα ζητούσε απάντηση από τη διαδρομή και αμέσως μετά θα καλούσε
// `rpc('refund_ai_usage')` για να μηδενίσει τη χρέωση — δηλαδή απεριόριστος
// βοηθός, δωρεάν, για όλους. Το δικαίωμα εκτέλεσης το έχει ΜΟΝΟ ο
// `service_role` και γι' αυτό η συνάρτηση δέχεται ρητό αναγνωριστικό χρήστη
// αντί να διαβάζει `auth.uid()`.
//
// ΔΕΝ ΠΕΤΑΕΙ ΠΟΤΕ, ΚΑΙ ΑΥΤΟ ΕΙΝΑΙ Η ΠΡΟΔΙΑΓΡΑΦΗ ΤΗΣ. Καλείται πάντα ΜΕΣΑ σε
// χειρισμό σφάλματος: μια εξαίρεση εδώ θα σκέπαζε το αρχικό σφάλμα και ο
// χρήστης θα διάβαζε λάθος αιτία για λάθος πρόβλημα. Οταν αποτύχει, το λέει
// με `false` και το γράφει στα αρχεία καταγραφής.
// ═══════════════════════════════════════════════════════════════════════════

import { createServiceClient } from '@/lib/supabase/service';

/**
 * Το πρόθεμα καταγραφής όταν η επιστροφή δεν έγινε.
 *
 * Γράφεται σε ΕΝΑ σημείο ώστε η αναζήτηση στα αρχεία καταγραφής να βρίσκει
 * ΟΛΕΣ τις χαμένες επιστροφές, όχι τα δύο τρίτα τους.
 */
export const REFUND_LOG = 'η επιστροφή μονάδας AI δεν έγινε:';

/**
 * Γυρίζει πίσω μία ερώτηση στο ημερήσιο και στο μηνιαίο πακέτο του χρήστη.
 *
 * @param userId ποιανού είναι η μονάδα. Το `auth.uid()` δεν υπάρχει εδώ: ο
 *   πελάτης υπηρεσίας δεν έχει συνεδρία, γι' αυτό το όνομα ταξιδεύει ρητά.
 * @param pool αν επιστρέφεται και η μονάδα της κοινής δεξαμενής. Η δεξαμενή
 *   μετράει ΧΡΗΜΑ: μένει χρεωμένη όταν ο πάροχος πιθανότατα παρήγαγε tokens
 *   (χρονικό όριο, σώμα που δεν διαβάζεται).
 * @returns `true` μόνο αν η βάση όντως μείωσε τους μετρητές.
 */
/**
 * Η ΑΠΟΦΑΣΗ, ΧΩΡΙΣΤΑ ΑΠΟ ΤΗ ΜΕΤΑΦΟΡΑ.
 *
 * ΓΙΑΤΙ ΧΩΡΙΣΤΑ. Ο έλεγχος αυτού του αρχείου δοκίμαζε ΑΝΤΙΓΡΑΦΟ της λογικής,
 * γιατί η αληθινή ήταν κλεισμένη γύρω από έναν πελάτη που θέλει κλειδί
 * υπηρεσίας και δίκτυο. Ενας έλεγχος που δοκιμάζει αντίγραφο μένει πράσινος
 * όταν αλλάξει το πρωτότυπο — δηλαδή είναι χειρότερος από κανέναν, γιατί
 * διαβάζεται ως κάλυψη. Η κρίση ζει τώρα σε καθαρή συνάρτηση.
 *
 * ΟΙ ΤΡΕΙΣ ΑΠΑΝΤΗΣΕΙΣ ΔΕΝ ΕΙΝΑΙ Η ΙΔΙΑ. Η συνάρτηση της βάσης απαντά
 * `{"refunded": false, "reason": "no_row"}` όταν δεν βρήκε γραμμή να μειώσει.
 * ΔΕΝ είναι σφάλμα — είναι «δεν έγινε» — ο καλών πρέπει να το ξεχωρίζει
 * γιατί από αυτό κρίνει αν θα διορθώσει τις κεφαλίδες υπολοίπου. Ενα
 * `return !error` θα έλεγε «επιστράφηκε» για μονάδα που ΔΕΝ επιστράφηκε.
 *
 * Το `=== true` είναι αυστηρό επίτηδες: μια απάντηση `"true"` ή `1` δεν
 * αποδεικνύει ότι μειώθηκε μετρητής — αποδεικνύει ότι κάτι άλλαξε στο σχήμα.
 */
export function refundOutcome(res: { data: unknown; error: { message: string } | null }): boolean {
  if (res.error) {
    console.error(REFUND_LOG, res.error.message);
    return false;
  }
  return (res.data as { refunded?: boolean } | null)?.refunded === true;
}

export async function refundAiUsage(userId: string, pool = true): Promise<boolean> {
  try {
    return refundOutcome(await createServiceClient()
      .rpc('refund_ai_usage', { p_uid: userId, p_pool: pool }));
  } catch (err) {
    console.error(REFUND_LOG, err instanceof Error ? err.message : err);
    return false;
  }
}
