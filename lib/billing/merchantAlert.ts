const idOf = (v: unknown): string => {
  if (typeof v === 'string') return v.trim();
  if (v && typeof v === 'object' && typeof (v as { id?: unknown }).id === 'string') return (v as { id: string }).id.trim();
  return '';
};

/**
 * Τι έκανε η εφαρμογή με την επιστροφή ή την αμφισβήτηση.
 *
 *   `revoked`    έκλεισε την πρόσβαση του λογαριασμού που κρατά τη συνδρομή·
 *   `partial`    μερική επιστροφή: η πρόσβαση δεν άλλαξε·
 *   `missing`    λείπει ποσό, νόμισμα ή συναλλαγή: η πρόσβαση δεν άλλαξε·
 *   `basis`      ποσό σε άλλη βάση ή νόμισμα: η πρόσβαση δεν άλλαξε·
 *   `older`      αφορά παλαιότερη χρέωση, όχι την τελευταία πληρωμένη·
 *   `already`    η πρόσβαση είχε ήδη κλείσει από ΑΛΛΗ επιστροφή ή αμφισβήτηση
 *                της ίδιας συνδρομής (π.χ. αμφισβήτηση μετά από επιστροφή)·
 *   `unmatched`  η συνδρομή δεν είναι η καταγεγραμμένη κανενός λογαριασμού·
 *   χωρίς τιμή   το γεγονός δεν έφερε συνδρομή, η πρόσβαση δεν άλλαξε.
 *
 * Ο ΚΑΝΟΝΑΣ (έλεγχος του PR 558, M1): η πρόσβαση κλείνει ΜΟΝΟ όταν η περίπτωση
 * είναι σαφής. Σε κάθε άλλη, αποφασίζει άνθρωπος.
 */
export type RevocationOutcome = 'revoked' | 'partial' | 'missing' | 'basis' | 'older' | 'already' | 'unmatched';

const KEPT = 'Η πρόσβαση ΔΕΝ άλλαξε· αποφάσισε αν πρέπει να κλείσει.';
const OUTCOME_LINE: Record<RevocationOutcome, string> = {
  revoked: 'Η εφαρμογή έκλεισε ήδη την πρόσβαση: ο λογαριασμός συνεχίζει στο πακέτο χωρίς συνδρομή. Η συνδρομή στον έμπορο ΔΕΝ ακυρώθηκε.',
  partial: `Μερική επιστροφή. ${KEPT}`,
  missing: `Το γεγονός ήρθε χωρίς ποσό, νόμισμα ή συναλλαγή, οπότε δεν φαίνεται αν είναι ολόκληρη επιστροφή της τελευταίας πληρωμής. ${KEPT}`,
  basis: `Το ποσό είναι σε άλλη βάση ή νόμισμα από την πληρωμή (π.χ. καθαρό απέναντι σε μικτό). ${KEPT}`,
  older: `Αφορά παλαιότερη χρέωση, όχι την τελευταία πληρωμένη περίοδο. ${KEPT}`,
  already: 'Η πρόσβαση είχε ήδη κλείσει από προηγούμενη επιστροφή ή αμφισβήτηση της ίδιας συνδρομής. Τίποτα δεν άλλαξε τώρα· έλεγξε στον πίνακα του εμπόρου αν χρειάζεται κάτι ακόμη για αυτή τη χρέωση.',
  unmatched: 'Η συνδρομή δεν είναι αυτή που έχει καταγράψει κάποιος λογαριασμός της εφαρμογής· η πρόσβαση ΔΕΝ άλλαξε.',
};

/**
 * Το μήνυμα για ένα γεγονός, ή `null` όταν δεν αφορά επιστροφή ή αμφισβήτηση.
 * Καθαρή συνάρτηση: δεν στέλνει τίποτα.
 */
export function alertFor(payload: unknown, outcome?: RevocationOutcome): MerchantAlert | null {
  const p = (payload && typeof payload === 'object' ? payload : {}) as Record<string, unknown>;
  const name = String(p.eventType || '').trim();
  const kind = name.startsWith('refund.') ? 'refund' : name.startsWith('dispute.') ? 'dispute' : null;
  if (!kind) return null;

  const obj = (p.object && typeof p.object === 'object' ? p.object : {}) as Record<string, unknown>;
  const tx = (obj.transaction && typeof obj.transaction === 'object' ? obj.transaction : {}) as Record<string, unknown>;
  const subscription = idOf(obj.subscription) || idOf(tx.subscription);
  const amount = obj.refund_amount ?? obj.amount ?? tx.amount;
  const currency = String(obj.refund_currency ?? obj.currency ?? tx.currency ?? '').toUpperCase();

  const what = kind === 'refund' ? 'Επιστροφή χρημάτων' : 'Αμφισβήτηση πληρωμής';
  const mor = merchant().name;
  const none = 'άγνωστο';
  return {
    subject: `PROPERWISE | ${what} στο ${mor}: ακύρωσε τη συνδρομή`,
    text: [
      `${what} στον πίνακα του ${mor} (${name}).`,
      '',
      `Συνδρομή: ${subscription || none}`,
      `Γεγονός: ${idOf(obj) || none}`,
      `Ποσό: ${typeof amount === 'number' ? `${(amount / 100).toFixed(2)} ${currency}`.trim() : none}`,
      '',
      ...(outcome ? [OUTCOME_LINE[outcome], ''] : []),
      `Τι κάνεις: ${mor} · Subscriptions · η συνδρομή · Cancel.`,
      'Χωρίς ακύρωση, η επόμενη ανανέωση χρεώνει ξανά τον ίδιο πελάτη.',
    ].join('\n'),
  };
}

/**
 * ΝΕΑ ΧΡΕΩΣΗ ΣΕ ΣΥΝΔΡΟΜΗ ΠΟΥ ΕΙΧΕ ΚΛΕΙΣΕΙ ΑΠΟ ΕΠΙΣΤΡΟΦΗ Ή ΑΜΦΙΣΒΗΤΗΣΗ.
 *
 * Η επιστροφή δεν ακυρώνει μόνη της τη συνδρομή στον έμπορο. Αν κανείς δεν
 * την ακύρωσε, η επόμενη ανανέωση χρεώνει ξανά τον ίδιο πελάτη. Ο webhook
 * ανοίγει πάλι το πακέτο, γιατί ο πελάτης πλήρωσε· ο άνθρωπος πρέπει να μάθει
 * ότι η ακύρωση δεν έγινε.
 */
export function rechargedAlert(userId: string, subId: string, late = false): MerchantAlert {
  const mor = merchant().name;
  return {
    subject: late
      ? `PROPERWISE | Πληρωμή στο ${mor} που έφτασε μετά την επιστροφή: έλεγξε τη συνδρομή`
      : `PROPERWISE | Νέα χρέωση στο ${mor} μετά από επιστροφή: έλεγξε τη συνδρομή`,
    text: [
      late
        ? `Ο ${mor} ειδοποίησε με καθυστέρηση για χρέωση που έγινε ΠΡΙΝ από την επιστροφή ή την αμφισβήτηση. Η επιστροφή αφορούσε παλαιότερη χρέωση της ίδιας συνδρομής.`
        : `Ο ${mor} χρέωσε ξανά συνδρομή που είχε κλείσει στην εφαρμογή από επιστροφή χρημάτων ή αμφισβήτηση.`,
      '',
      `Λογαριασμός: ${userId}`,
      `Συνδρομή: ${subId}`,
      '',
      'Η εφαρμογή άνοιξε ξανά το πακέτο, γιατί η πληρωμή πέρασε.',
      `Τι κάνεις: ${mor} · Subscriptions · η συνδρομή. Αν ο πελάτης δεν ήθελε συνέχεια, Cancel και επιστροφή αυτής της χρέωσης.`,
    ].join('\n'),
  };
}

