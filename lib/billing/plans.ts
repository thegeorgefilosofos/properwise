// Το `rank()` του entitlements.ts είναι το `indexOf` αυτού του πίνακα και ΠΡΕΠΕΙ
// να ταυτίζεται με την `public.user_plan_rank`. Παρεμβολή πλάνου εδώ χωρίς
// αντίστοιχο migration μετακινεί κάθε επόμενο επίπεδο κατά ένα — σιωπηλά, με
// αποτέλεσμα ο συνδρομητής «Ιδιοκτήτης» να διαβάζεται ως «Ένα ακίνητο».
// Το `solo` μπήκε μαζί με το 20260805090000_solo_plan.sql.
export const PLAN_ORDER: PlanId[] = ['free', 'solo', 'owner', 'agency', 'office'];

/**
 * Το πακέτο που προτείνουμε σε όποιον δεν έχει διαλέξει ακόμη.
 *
 * Το «Ιδιοκτήτης+»: εκεί υπάρχει περιθώριο να μεγαλώσει το χαρτοφυλάκιο, ενώ ο
 * «Ιδιοκτήτης» είναι τελικός σταθμός για ένα σπίτι. Μία τιμή για την αρχική και
 * για το /paketa, ώστε οι δύο σελίδες τιμών να μην προτείνουν άλλο πακέτο.
 */
export const RECOMMENDED_PLAN: PlanId = 'owner';

/** Το πρώτο πακέτο της κλίμακας που γράφει αυτή τη γραμμή· τα επόμενα την κληρονομούν. */
export function firstPlanWith(line: string): PlanId {
  const id = PLAN_ORDER.find(p => PLANS[p].features.includes(line));
  if (!id) throw new Error(`plans: η γραμμή «${line}» δεν υπάρχει σε κανένα πακέτο`);
  return id;
}

/** Ασφαλής ανάγνωση πλάνου από τυχόν αποθηκευμένο id (fallback: free). */
export function normalizePlan(id: string | null | undefined): PlanId {
  return id === 'solo' || id === 'owner' || id === 'agency' || id === 'office' ? id : 'free';
}

/**
 * Χρεώνεται πραγματικά αυτό το πακέτο;
 *
 * ΔΕΝ ΤΑΥΤΙΖΕΤΑΙ ΜΕ ΤΟ «ΕΝΕΡΓΟ ΕΠΙΠΕΔΟ». Η δοκιμή, οι δωρεάν μήνες και η
 * ιδιότητα Συνεργάτη ανεβάζουν το επίπεδο χωρίς να μπαίνει ευρώ στο ταμείο.
 * Ελέγχεται η ΤΙΜΗ και όχι μια γραμμένη με το χέρι λίστα ονομάτων, ώστε ένα
 * νέο πακέτο να μη χρειάζεται να θυμηθεί κανείς να το προσθέσει εδώ.
 *
 * Ιδιο σύνολο με τη λίστα της `bump_ai_usage` στη βάση.
 */
export function isPayingPlan(id: string | null | undefined): boolean {
  return PLANS[normalizePlan(id)].priceMonthly > 0;
}

// ΤΟ `planLimit` ΕΦΥΓΕ ΚΙ ΑΥΤΟ, ΓΙΑ ΤΟΝ ΙΔΙΟ ΛΟΓΟ ΜΕ ΤΟ `canAddProperty`.
// Επέστρεφε το `maxProperties` του πακέτου και ΜΟΝΟ αυτό: σε χρήστη που είχε
// πληρώσει για επιπλέον ακίνητα έδινε μικρότερο όριο από το πραγματικό. Εμεινε
// πίσω όταν έφυγε το `canAddProperty` και το βρήκε ο φύλακας νεκρών εξαγωγών,
// γιατί το καλούσε μόνο το δικό του τεστ. Η μία απάντηση είναι το
// `propertyLimit` του entitlements.ts.

// ΤΟ `canAddProperty` ΕΦΥΓΕ ΑΠΟ ΕΔΩ.
// Υπήρχε σε δύο αρχεία με το ίδιο όνομα και ΔΙΑΦΟΡΕΤΙΚΗ απάντηση: αυτό εδώ
// κοιτούσε μόνο το πλάνο, ενώ το lib/billing/entitlements.ts μετράει και τα
// ΑΓΟΡΑΣΜΕΝΑ επιπλέον ακίνητα. Δηλαδή σε χρήστη που είχε πληρώσει για παραπάνω,
// αυτό εδώ έλεγε «όχι». Καμία οθόνη δεν το καλούσε — μόνο το ίδιο του το test.
// Η μία απάντηση δίνεται από το `canAddProperty` του entitlements.ts, που
// συμφωνεί με τον έλεγχο `enforce_property_limit` της βάσης.

/** Το μικρότερο πλάνο που χωράει τόσα ακίνητα ΧΩΡΙΣ αγορά επιπλέον. */
export function planForCount(count: number): PlanId {
  for (const id of PLAN_ORDER) if (count <= PLANS[id].maxProperties) return id;
  return 'office';
}

/** Μηνιαίο ισοδύναμο ετήσιας τιμής (για εμφάνιση «X/μήνα με ετήσια»). */
export function annualPerMonth(id: PlanId): number {
  return Math.round((PLANS[id].priceAnnual / 12) * 100) / 100;
}

