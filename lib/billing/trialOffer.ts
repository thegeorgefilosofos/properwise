// ─────────────────────────────────────────────────────────────────────────
// Η αρχική και το /paketa έγραφαν «με τις δυνατότητες του Ιδιοκτήτης+», δηλαδή
// υπόσχονταν σιωπηρά και τις 60 ερωτήσεις του πακέτου. Η δοκιμή όμως έχει
// δικό της πακέτο ερωτήσεων (TRIAL_LIMITS): ο δοκιμαστής χτυπούσε τοίχο στην
// εικοστή πρώτη ερώτηση, αφού του είχαμε πει άλλα. Οι δυνατότητες και το όριο
// λέγονται πλέον μαζί, από τις πηγές τους.
// ═══════════════════════════════════════════════════════════════════════════
import { PLANS, TRIAL_DAYS, type PlanId } from './plans';
import { TRIAL_PLAN, planAtLeast } from './entitlements';
import { TRIAL_LIMITS, TRIAL_SCANS_PER_MONTH } from './aiLimits';
import { ASSISTANT_TO } from '@/lib/assistant/identity';

// Το διπλό «με … με» («ξεκινά με … δοκιμής με τις δυνατότητες») έγινε άνω
// τελεία και απαρίθμηση: πρώτα η δοκιμή και μετά τι περιέχει.
// ΚΑΙ Η ΣΑΡΩΣΗ ΜΕ ΤΟ ΟΡΙΟ ΤΗΣ (03.10.2026): το «όσα έχει ο Ιδιοκτήτης+»
// υπόσχεται σιωπηρά σάρωση χωρίς όριο, ενώ η δοκιμή έχει δικό της ταβάνι.
export const TRIAL_OFFER =
  `Κάθε νέος λογαριασμός ξεκινά με δοκιμή ${TRIAL_DAYS} ημερών: όσα έχει ο «${PLANS[TRIAL_PLAN].name}», ${TRIAL_LIMITS.perMonth} ερωτήσεις ${ASSISTANT_TO} και ${TRIAL_SCANS_PER_MONTH} σαρώσεις τον μήνα.`;

// ═══════════════════════════════════════════════════════════════════════════
// Η ΔΟΚΙΜΗ ΔΕΝ ΕΙΝΑΙ ΤΟ ΠΑΚΕΤΟ ΠΟΥ ΔΙΑΛΕΞΕΣ
// ─────────────────────────────────────────────────────────────────────────
// Τα κουμπιά του «Επαγγελματίας» και του «Επαγγελματίας+» έγραφαν «Ξεκίνα τη
// δοκιμή» και η εγγραφή έδειχνε «Δοκιμή 30 ημερών» δίπλα στο όνομά τους. Η
// δοκιμή όμως δίνει όσα έχει το TRIAL_PLAN και τίποτα πάνω από αυτό: όποιος
// διάλεγε πελατολόγιο και ομάδα δεν τα έβρισκε στη δοκιμή του. Για τα πακέτα
// πάνω από το TRIAL_PLAN το κουμπί λέει μόνο ότι η αρχή είναι δωρεάν και η
// ταμπέλα της εγγραφής λέει σε ποιο πακέτο τρέχει η δοκιμή.
// ═══════════════════════════════════════════════════════════════════════════

/** Αν η δοκιμή δίνει όσα έχει αυτό το πακέτο. */
export const trialCovers = (id: PlanId): boolean => planAtLeast(TRIAL_PLAN, id);

/** Το ρήμα του κουμπιού εγγραφής για ένα πακέτο. */
export const trialCta = (id: PlanId): string =>
  trialCovers(id) ? 'Ξεκίνα τη δοκιμή' : 'Ξεκίνα δωρεάν';
