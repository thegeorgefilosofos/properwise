import { PLANS, TRIAL_DAYS, normalizePlan, isPayingPlan, type PlanId } from './plans';
import { TRIAL_PLAN, planAtLeast } from './entitlements';
import { TRIAL_LIMITS, TRIAL_SCANS_PER_MONTH } from './aiLimits';
import { ASSISTANT_TO } from '@/lib/assistant/identity';

// Το διπλό «με … με» («ξεκινά με … δοκιμής με τις δυνατότητες») έγινε άνω
// τελεία και απαρίθμηση: πρώτα η δοκιμή και μετά τι περιέχει.
// ΚΑΙ Η ΣΑΡΩΣΗ ΜΕ ΤΟ ΟΡΙΟ ΤΗΣ (03.10.2026): το «όσα έχει ο Ιδιοκτήτης+»
// υπόσχεται σιωπηρά σάρωση χωρίς όριο, ενώ η δοκιμή έχει δικό της ταβάνι.
export const TRIAL_OFFER =
  `Κάθε νέος λογαριασμός ξεκινά με δοκιμή ${TRIAL_DAYS} ημερών: όσα έχει ο «${PLANS[TRIAL_PLAN].name}», ${TRIAL_LIMITS.perMonth} ερωτήσεις ${ASSISTANT_TO} και ${TRIAL_SCANS_PER_MONTH} σαρώσεις τον μήνα.`;

// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ ΚΟΥΜΠΙ ΠΡΟΣ ΤΗΝ ΕΓΓΡΑΦΗ ΛΕΕΙ ΟΤΙ ΣΥΜΒΑΙΝΕΙ ΣΤΟ ΠΑΚΕΤΟ ΠΟΥ ΚΟΥΒΑΛΑ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ, ΟΠΩΣ ΗΤΑΝ (έλεγχος κειμένων 06.10.2026). Κάθε «Ξεκίνα δωρεάν»
// της αρχικής οδηγούσε στην εγγραφή, όπου το κουμπί της φόρμας έγραφε
// «Ξεκίνα τη δοκιμή»: όποιος διάλεγε το δωρεάν πακέτο διάβαζε ότι ξεκινά
// δοκιμή. Και στον τιμοκατάλογο ο «Επαγγελματίας» και ο «Επαγγελματίας+»,
// πακέτα με τιμή, έγραφαν «Ξεκίνα δωρεάν», ενώ ο «Ιδιοκτήτης+» δίπλα τους
// έγραφε «Ξεκίνα τη δοκιμή». Τρία λεκτικά, γραμμένα με το χέρι σε επτά σημεία.
//
// Ο ΚΑΝΟΝΑΣ, ΜΙΑ ΦΟΡΑ:
//   · Πακέτο χωρίς τιμή (ή κανένα πακέτο: η εγγραφή χωρίς `?plan=` ανοίγει
//     λογαριασμό στο δωρεάν, βλ. `normalizePlan`)      → «Ξεκίνα δωρεάν».
//   · Πακέτο με τιμή που η δοκιμή το δίνει ολόκληρο     → «Ξεκίνα τη δοκιμή».
//   · Πακέτο με τιμή πάνω από το TRIAL_PLAN ή χωρίς ημέρες δοκιμής →
//     «Κάνε εγγραφή». Η δοκιμή δίνει μόνο όσα έχει το TRIAL_PLAN: όποιος
//     διάλεγε πελατολόγιο και ομάδα δεν τα έβρισκε στη δοκιμή του. Και
//     «δωρεάν» δεν είναι, έχει τιμή. Μένει αυτό που κάνει το πάτημα.
//
// Η κάρτα του τιμοκαταλόγου και το κουμπί της φόρμας ρωτούν την ίδια
// συνάρτηση για το ίδιο πακέτο, οπότε δεν μπορούν να πουν άλλο πράγμα.
// ═══════════════════════════════════════════════════════════════════════════

/** Αν η δοκιμή δίνει όσα έχει αυτό το πακέτο. */
const trialCovers = (id: PlanId): boolean => PLANS[id].trialDays > 0 && planAtLeast(TRIAL_PLAN, id);

/**
 * Το λεκτικό κάθε κουμπιού που οδηγεί στην εγγραφή, για το πακέτο που
 * ταξιδεύει ως `?plan=`. Χωρίς πακέτο, ό,τι ανοίγει η εγγραφή: το δωρεάν.
 */
export function signupCta(plan: PlanId | null = null): string {
  const id = plan ?? normalizePlan(null);
  if (!isPayingPlan(id)) return 'Ξεκίνα δωρεάν';
  return trialCovers(id) ? 'Ξεκίνα τη δοκιμή' : 'Κάνε εγγραφή';
}
