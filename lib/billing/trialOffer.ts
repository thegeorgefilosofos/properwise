// υπόσχονταν σιωπηρά και τις 60 ερωτήσεις του πακέτου. Η δοκιμή όμως έχει
// δικό της πακέτο ερωτήσεων (TRIAL_LIMITS): ο δοκιμαστής χτυπούσε τοίχο στην
// εικοστή πρώτη ερώτηση, αφού του είχαμε πει άλλα. Οι δυνατότητες και το όριο
// λέγονται πλέον μαζί, από τις πηγές τους.
