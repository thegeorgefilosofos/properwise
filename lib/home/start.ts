// «ΑΠΟ ΠΟΥ ΞΕΚΙΝΑΣ» — Ο ΠΙΝΑΚΑΣ ΤΗΣ ΔΟΚΙΜΗΣ, ΣΕ ΚΑΘΑΡΗ ΛΟΓΙΚΗ
// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΛΥΝΕΙ. Ο νέος χρήστης μπαίνει, βλέπει μια οθόνη με μηδενικά και δεν ξέρει
// τι να πατήσει πρώτο. Η ατζέντα (lib/home/agenda.ts) απαντά στο «τι πρέπει να
// κάνω σήμερα» — αλλά όχι στο «τι δεν έχω δει ακόμη».
//
// ΓΙΑΤΙ ΛΙΓΑ ΒΗΜΑΤΑ ΚΑΙ ΟΧΙ ΕΞΙ. Μια λίστα έξι βημάτων διαβάζεται ως αγγαρεία
// και εγκαταλείπεται στο δεύτερο. Τρία ήταν τα ελάχιστα που κάνουν την
// εφαρμογή να δουλέψει: ένα ακίνητο, ένα παραστατικό, οι προθεσμίες στο
// κινητό. Ό,τι άλλο μαθαίνεται μόνο του.
//
// ΚΑΝΕΝΑ ΒΗΜΑ ΔΕΝ ΕΙΝΑΙ ΔΗΛΩΣΗ ΤΟΥ ΧΡΗΣΤΗ. Κάθε «έγινε» βγαίνει από ΠΡΑΓΜΑΤΙΚΑ
// δεδομένα — πλήθος ακινήτων, πλήθος παραστατικών, ένα ημερολόγιο που διάβασε
// τη συνδρομή. Δεν υπάρχει checkbox «το είδα»: θα ήταν πίνακας που λέει
// ψέματα την πρώτη φορά που ο χρήστης σβήσει κάτι.
//
// ΤΟ ΤΡΙΤΟ ΒΗΜΑ ΑΛΛΑΞΕ ΝΟΗΜΑ (20.10.2026). Ηταν «είδε τις προθεσμίες», με σήμα
// τα φορολογικά γεγονότα του ημερολογίου. Αυτά γράφονται πλέον μόνα τους μόλις
// μπει ακίνητο (lib/calendar/taxSync.ts), οπότε το βήμα θα έκλεινε χωρίς να
// κάνει ο χρήστης τίποτα. Ο,τι μένει να κάνει είναι το ένα πάτημα που φέρνει τις
// προθεσμίες στο κινητό του· κλείνει όταν κάποιο ημερολόγιο διαβάσει πράγματι
// τη συνδρομή (`calendar_feed_tokens.last_fetched_at`).
//
// ΚΑΙ ΤΑ ΒΑΣΙΚΑ ΤΟΥ ΑΚΙΝΗΤΟΥ, ΜΕΤΑ ΤΟ ΑΚΙΝΗΤΟ (13/11/2026). Ο οδηγός του νέου
// ακινήτου ρωτά μόνο τύπο, κατάσταση και μίσθωμα, ώστε ο φόρος να φανεί σε
// τέσσερα πατήματα. Διεύθυνση, ΑΤΑΚ, εμβαδόν και ΠΕΑ έγιναν βήμα εδώ: κλείνει
// όταν το ακίνητο έχει διεύθυνση και εμβαδόν, δηλαδή από πραγματικά δεδομένα,
// όχι από δήλωση. Χωρίς ακίνητο δεν έχει τι να ανοίξει, οπότε δεν έχει κουμπί.
//
// ΠΟΤΕ ΦΕΥΓΕΙ. Όταν κλείσουν και τα τρία, ή όταν λήξει η δοκιμή. Και στις δύο
// περιπτώσεις μόνος του, χωρίς να το ζητήσει κανείς: ένας πίνακας υποδοχής που
// μένει για πάντα γίνεται διαφήμιση μέσα στο προϊόν που ήδη πληρώνεται.
// ═══════════════════════════════════════════════════════════════════════════

export interface StartSignals {
  /** Πλήθος ακινήτων του χρήστη. */
  properties: number;
  /** Πλήθος παραστατικών/δαπανών που έχουν καταχωρηθεί. */
  documents: number;
  /** Κάποιο ημερολόγιο (κινητό, Google, Apple) διάβασε τη συνδρομή του. */
  calendarLinked: boolean;
  /** Το ακίνητο που βλέπει έχει διεύθυνση και εμβαδόν. Χωρίς τιμή: όχι. */
  basicsDone?: boolean;
}

export interface StartStep {
  key: 'property' | 'basics' | 'document' | 'deadlines';
  /** Ονοματική φράση, όχι προστακτική — η προστακτική ανήκει στο κουμπί. */
  title: string;
  hint: string;
  done: boolean;
  /** Η καρτέλα ή η ενέργεια που ανοίγει το κουμπί. */
  nav: string;
  /** Το ρήμα του κουμπιού, ένα για κάθε βήμα: λέει τι θα γίνει, όχι «Άνοιγμα». */
  cta: string;
  /** Δεν γίνεται ακόμη (π.χ. τα βασικά χωρίς ακίνητο): χωρίς κουμπί. */
  blocked?: boolean;
}

export interface StartPanelState {
  visible: boolean;
  steps: StartStep[];
  /** Πόσα απομένουν ανοιχτά. */
  open: number;
  daysLeft: number;
  /** Υπάρχει ήδη πραγματικό ακίνητο: το παράδειγμα δεν χρειάζεται πια. */
  hasProperty: boolean;
}

export interface StartInput extends StartSignals {
  /** Ενεργή δοκιμαστική περίοδος; */
  trialActive: boolean;
  /** Ημέρες που απομένουν στη δοκιμή. */
  daysLeft: number;
}

/**
 * Τα τρία βήματα, με τη σειρά που έχουν νόημα: πρώτα υπάρχει ακίνητο, μετά
 * μπαίνει παραστατικό μέσα του και μετά φτάνουν οι προθεσμίες του στο κινητό.
 *
 * Η σειρά ΔΕΝ αλλάζει όταν κάποιο κλείσει. Ένας πίνακας που αναδιατάσσεται
 * μπροστά στα μάτια διαβάζεται ως χαλασμένος, όχι ως έξυπνος.
 */
export function startSteps(sig: StartSignals): StartStep[] {
  const has = sig.properties > 0;
  return [
    {
      key: 'property',
      title: 'Το πρώτο σου ακίνητο',
      hint: 'Τύπος, κατάσταση και μίσθωμα. Ο φόρος βγαίνει αμέσως.',
      done: has,
      nav: 'add',
      cta: 'Προσθήκη',
    },
    {
      key: 'basics',
      title: 'Τα βασικά του ακινήτου',
      hint: 'Διεύθυνση, ΑΤΑΚ, εμβαδόν και ΠΕΑ.',
      done: has && !!sig.basicsDone,
      nav: 'edit-basics',
      cta: 'Συμπλήρωση',
      blocked: !has,
    },
    {
      key: 'document',
      title: 'Ένα παραστατικό, σαρωμένο',
      hint: 'Η δαπάνη καταχωρείται αυτόματα ανά ΑΦΜ και κατηγορία.',
      done: sig.documents > 0,
      nav: 'scan',
      cta: 'Σάρωση',
    },
    {
      key: 'deadlines',
      title: 'Οι προθεσμίες στο κινητό σου',
      hint: 'Σύνδεσε το Ημερολόγιο μία φορά με Google ή Apple.',
      done: sig.calendarLinked,
      nav: 'calendar',
      cta: 'Σύνδεση',
    },
  ];
}

/**
 * Ο πίνακας ολόκληρος.
 *
 * ΤΟ `visible` ΕΙΝΑΙ ΤΟ ΜΟΝΟ ΣΗΜΕΙΟ ΠΟΥ ΑΠΟΦΑΣΙΖΕΙ ΑΝ ΦΑΙΝΕΤΑΙ. Η οθόνη δεν
 * ξαναρωτά «είναι σε δοκιμή;» με δικό της κριτήριο — αλλιώς θα υπήρχαν δύο
 * κανόνες που κάποια στιγμή θα διαφωνούσαν.
 */
export function startPanel(input: StartInput): StartPanelState {
  const steps = startSteps(input);
  const open = steps.filter(s => !s.done).length;
  return {
    visible: input.trialActive && open > 0,
    steps,
    open,
    daysLeft: Math.max(0, input.daysLeft),
    hasProperty: input.properties > 0,
  };
}

/** «24 ημέρες» / «1 ημέρα» — ο αριθμός και η λέξη του, χωρίς παρένθεση. */
export function daysLabel(n: number): string {
  const d = Math.max(0, Math.round(n));
  return `${d} ${d === 1 ? 'ημέρα' : 'ημέρες'}`;
}

/** «2 βήματα ακόμη» / «1 βήμα ακόμη» — η γραμμή της συμπτυγμένης μορφής. */
export function stepsLabel(n: number): string {
  const s = Math.max(0, Math.round(n));
  return `${s} ${s === 1 ? 'βήμα' : 'βήματα'} ακόμη`;
}
