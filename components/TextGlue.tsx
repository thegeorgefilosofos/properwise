/** Η τελευταία λέξη και ό,τι ακολουθεί, σε κουτί που δεν τυλίγει. */
export function GlueTail({ text, children }: { text: string; children?: ReactNode }) {
  if (children == null || children === false) return <>{text}</>;
  const cut = text.lastIndexOf(' ') + 1;
  return (
    <>
      {text.slice(0, cut)}
      <span className="tx-glue" style={{ whiteSpace: 'nowrap' }}>{text.slice(cut)}{children}</span>
    </>
  );
}
