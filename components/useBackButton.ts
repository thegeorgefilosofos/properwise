'use client';

// ═══════════════════════════════════════════════════════════════════════════
// useBackButton: το «Πίσω» του περιηγητή κάνει ό,τι το «Πίσω» της οθόνης
// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΜΕΤΡΗΘΗΚΕ (13/11/2026). Στο τηλέφωνο ο οδηγός του νέου ακινήτου είναι
// φύλλο σε όλη την οθόνη· το φυσικό «Πίσω» του Android ή η χειρονομία του iOS
// έβγαζε τον χρήστη από τον πίνακα ελέγχου, με ό,τι είχε γράψει. Ο χρήστης
// διάβαζε «Πίσω» στο κουμπί και περίμενε το ίδιο από το πλήκτρο.
//
// ΠΩΣ. Το παράθυρο γράφει μία εγγραφή στο ιστορικό όταν ανοίγει, με την ίδια
// διεύθυνση (καμία καρτέλα δεν αλλάζει: useNavHistory διαβάζει το ίδιο hash).
// Το «Πίσω» του περιηγητή την αφαιρεί και καλεί το `onBack` του παραθύρου, που
// αποφασίζει: προηγούμενο βήμα ή κλείσιμο. Αν το παράθυρο μένει ανοιχτό (π.χ.
// πήγε ένα βήμα πίσω ή ο χρήστης είπε «όχι» στο «Να φύγουν οι αλλαγές;»), η
// εγγραφή ξαναμπαίνει με `rearm`. Οταν το παράθυρο κλείνει από μόνο του
// (αποθήκευση, «Ακύρωση»), η εγγραφή του φεύγει ώστε το επόμενο «Πίσω» να
// κάνει ό,τι έκανε πάντα.
//
// ΓΕΓΟΝΟΤΑ ΠΟΥ ΠΡΟΣΓΕΙΩΝΟΝΤΑΙ ΣΕ ΔΙΚΗ ΜΑΣ ΕΓΓΡΑΦΗ ΑΓΝΟΟΥΝΤΑΙ. Το αυστηρό
// mode της React στήνει και ξηλώνει το εφέ δύο φορές· το `history.back()` του
// πρώτου ξηλώματος φτάνει μετά το δεύτερο στήσιμο και προσγειώνεται σε εγγραφή
// του παραθύρου. Δεν είναι «Πίσω» του χρήστη.
// ═══════════════════════════════════════════════════════════════════════════
import { useEffect, useRef } from 'react';

const MARK = '__overlay';

function arm() {
  try { window.history.pushState({ ...(window.history.state ?? {}), [MARK]: true }, '', window.location.href); } catch { /* χωρίς ιστορικό */ }
}

/**
 * @param onBack Καλείται στο «Πίσω» του περιηγητή. Παίρνει `rearm`: το καλεί
 * όταν το παράθυρο ΔΕΝ κλείνει, ώστε το επόμενο «Πίσω» να έρθει πάλι εδώ.
 */
export function useBackButton(onBack: (rearm: () => void) => void, enabled = true): void {
  const ref = useRef(onBack);
  useEffect(() => { ref.current = onBack; });
  useEffect(() => {
    if (!enabled || typeof window === 'undefined') return;
    arm();
    const onPop = (e: PopStateEvent) => {
      if ((e.state as Record<string, unknown> | null)?.[MARK]) return;
      ref.current(arm);
    };
    window.addEventListener('popstate', onPop);
    return () => {
      window.removeEventListener('popstate', onPop);
      // Η εγγραφή μας είναι ακόμη η τρέχουσα: το παράθυρο έκλεισε από μόνο του.
      if ((window.history.state as Record<string, unknown> | null)?.[MARK]) window.history.back();
    };
  }, [enabled]);
}
