'use client';

import { useEffect } from 'react';

// ═══════════════════════════════════════════════════════════════════════════
// Ο,ΤΙ ΑΝΤΙΓΡΑΦΕΙ Ο ΧΡΗΣΤΗΣ ΦΕΥΓΕΙ ΚΑΘΑΡΟ ΑΠΟ ΤΗΝ ΤΥΠΟΓΡΑΦΙΑ ΜΑΣ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ, ΜΕΤΡΗΜΕΝΟ ΣΤΟ ΠΡΑΓΜΑΤΙΚΟ ΠΡΟΧΕΙΡΟ. Η πολιτική απορρήτου έχει 2.916
// μαλακά ενωτικά (U+00AD) — τα βάζει ο συλλαβιστής για να κλείνει η γραμμή κι
// δεξιά. Στην οθόνη είναι αόρατα. Επιλογή όλου του κειμένου κι Control+C
// έδειχνε ότι κι τα 2.916 ΤΑΞΙΔΕΥΟΥΝ: το πρόχειρο κρατούσε «δε­δο­μέ­να».
//
// ΠΟΙΟΝ ΠΛΗΓΩΝΕΙ. Το κείμενο που αντιγράφει κανείς από αυτό το προϊόν είναι
// νομικό ή φορολογικό: όρος σύμβασης προς δικηγόρο, επιφύλαξη προς λογιστή,
// παράγραφος σε δήλωση. Οι αόρατοι χαρακτήρες μπαίνουν μέσα στη λέξη κι μετά
// ζουν στο ξένο έγγραφο: η αναζήτηση εκεί δεν βρίσκει πια τη λέξη, η σύγκριση
// δύο κειμένων δείχνει διαφορές που δεν φαίνονται· ένα πεδίο φόρμας που
// περιμένει καθαρό κείμενο παίρνει σκουπίδια. Ο χρήστης δεν έχει κανέναν τρόπο
// να δει τι κουβαλά.
//
// ΓΙΑΤΙ ΕΔΩ ΚΑΙ ΟΧΙ ΣΤΟΝ ΣΥΛΛΑΒΙΣΤΗ. Τα ενωτικά ΠΡΕΠΕΙ να υπάρχουν στο DOM:
// είναι το μόνο πράγμα που λέει στον περιηγητή πού επιτρέπεται να σπάσει η
// λέξη· χωρίς αυτά η πλήρης στοίχιση τεντώνει τα κενά. Το σφάλμα δεν είναι
// η παρουσία τους στη σελίδα — είναι η διαφυγή τους στο πρόχειρο.
//
// ΚΑΙ ΟΙ ΔΥΟ ΓΕΥΣΕΙΣ ΚΑΘΑΡΙΖΟΝΤΑΙ. Το `text/plain` είναι αυτό που πάει σε
// επεξεργαστή κειμένου κι σε πεδίο φόρμας. Το `text/html` είναι αυτό που πάει
// σε Word κι σε ηλεκτρονικό ταχυδρομείο· κρατά τη μορφοποίηση: αν
// καθαριζόταν μόνο το πρώτο, η επικόλληση σε Word θα κουβαλούσε ακόμη τους
// χαρακτήρες. Γι' αυτό γράφονται ΚΑΙ ΤΑ ΔΥΟ πριν ακυρωθεί το προεπιλεγμένο.
// ═══════════════════════════════════════════════════════════════════════════

/** U+00AD. Δεν το γράφει ποτέ άνθρωπος· μπαίνει μόνο από το lib/core/hyphenate.ts. */
const SHY = /­/g;

export default function CopyPlain() {
  useEffect(() => {
    function onCopy(e: ClipboardEvent) {
      const sel = window.getSelection();
      const text = sel?.toString() ?? '';
      // Καμία επέμβαση όταν δεν υπάρχει τι να καθαριστεί: η προεπιλογή του
      // περιηγητή είναι πάντα καλύτερη από δική μας αναπαραγωγή της.
      if (!text || !SHY.test(text)) return;
      SHY.lastIndex = 0;

      const data = e.clipboardData;
      if (!data) return;

      // Η μορφοποιημένη γεύση χτίζεται από την ΙΔΙΑ την επιλογή, ώστε να μη
      // χαθεί ό,τι κρατά (έντονα, σύνδεσμοι, λίστες).
      let html = '';
      try {
        if (sel && sel.rangeCount > 0) {
          const box = document.createElement('div');
          box.appendChild(sel.getRangeAt(0).cloneContents());
          html = box.innerHTML.replace(SHY, '');
        }
      } catch { html = ''; }

      data.setData('text/plain', text.replace(SHY, ''));
      if (html) data.setData('text/html', html);
      e.preventDefault();
    }

    document.addEventListener('copy', onCopy);
    return () => document.removeEventListener('copy', onCopy);
  }, []);

  return null;
}
