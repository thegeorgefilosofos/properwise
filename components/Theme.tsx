// ΗΤΑΝ ΤΡΙΑ, ΟΧΙ ΕΝΑ. Το `KPIGrid` εδώ, το `KPI` του Δανείου και ένα τρίτο,
// τοπικό, μέσα στην Αξιοποίηση. Και τα τρία ζωγράφιζαν το ίδιο πράγμα:
