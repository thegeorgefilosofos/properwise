import { cloneElement, Fragment, isValidElement, type ReactNode } from 'react';
import { hyphenate } from '@/lib/core/hyphenate';

// ═══════════════════════════════════════════════════════════════════════════
// Ο ΣΥΛΛΑΒΙΣΜΟΣ ΒΓΑΙΝΕΙ ΑΠΟ ΤΙΣ ΤΡΕΙΣ ΝΟΜΙΚΕΣ ΣΕΛΙΔΕΣ ΚΑΙ ΓΙΝΕΤΑΙ ΤΟΥ ΕΡΓΟΥ
// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΥΠΗΡΧΕ. Το `lib/core/hyphenate.ts` εφαρμόζει τους κανόνες της ελληνικής
// γραμματικής και εμφυτεύει μαλακά ενωτικά (U+00AD) στα σημεία τομής. Χτίστηκε
// για τις σελίδες εμπιστοσύνης, όπου το κείμενο κλείνει και δεξιά όπως κάθε
// σύμβαση — και έμεινε ΜΟΝΟ εκεί. Ολο το υπόλοιπο προϊόν έγραφε ριγμένη δεξιά
// άκρη: κάθε επεξήγηση πίσω από ένα ⓘ, κάθε κάρτα του χάρτη πορείας, κάθε
// σημείωση κάτω από αριθμό.
//
// ΓΙΑΤΙ ΕΧΕΙ ΣΗΜΑΣΙΑ ΠΕΡΑ ΑΠΟ ΤΗΝ ΑΙΣΘΗΤΙΚΗ. Η πλήρης στοίχιση ΧΩΡΙΣ
// συλλαβισμό δεν σπάει λέξη για να κλείσει τη γραμμή: τεντώνει τα κενά.
// Μετρημένο στις νομικές σελίδες σε 195 κενά, στα 1440: διάμεσο 5,5 · p90 14 ·
// μέγιστο 16,9, όταν το φυσικό κενό της Inter στα 15 είναι ~4,2. Δηλαδή χωρίς
// συλλαβισμό η «στοίχιση» παράγει ποτάμια λευκού μέσα στην παράγραφο —
// χειρότερα από τη ριγμένη άκρη που ήθελε να διορθώσει.
//
// ΚΑΙ ΤΟ `hyphens: auto` ΔΕΝ ΤΟ ΔΙΝΕΙ. Δοκιμάστηκε με `lang="el"` και έβγαλε
// ΙΔΙΑ ακριβώς νούμερα: ο περιηγητής θέλει λεξικό συλλαβισμού που για τα
// ελληνικά μπορεί να μην υπάρχει, ανάλογα με έκδοση και πλατφόρμα. Η στοίχιση
// του κειμένου μας θα ήταν λοταρία ανά συσκευή. Με δικά μας μαλακά ενωτικά ο
// περιηγητής σπάει ΜΟΝΟ εκεί που του δείξαμε, σε κάθε μηχανή και στο χαρτί.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Συλλαβίζει ΚΑΘΕ κείμενο μέσα σε ένα δέντρο React, μία φορά, στην απόδοση.
 *
 * ΔΙΑΣΧΙΖΕΙ ΤΟ ΔΕΝΤΡΟ, ΔΕΝ ΑΓΓΙΖΕΙ ΤΗ ΔΟΜΗ. Μόνο τα κείμενα αλλάζουν· τα
 * `<strong>` και οι σύνδεσμοι μένουν ό,τι ήταν, με τα κλειδιά τους.
 *
 * ΚΑΙ ΣΤΑΜΑΤΑ ΣΤΟΝ ΠΙΝΑΚΑ. Ο συλλαβισμός είναι εργαλείο της ΠΛΗΡΟΥΣ ΣΤΟΙΧΙΣΗΣ:
 * σε παράγραφο εξήντα ώς ογδόντα χαρακτήρων κλείνει τα κενά και η γραμμή στέκει
 * πέρα πέρα. Σε κελί πίνακα δεν υπάρχει τέτοια δουλειά να κάνει και το
 * αποτέλεσμα είναι το αντίθετο από καθαρό: μετρημένο στα 1.280, η στήλη του
 * τόπου είναι 168 εικονοστοιχεία και έβγαζε «Ευρωπαϊ-κή Ένωση», η στήλη της
 * περιγραφής «Ενερ-γοποιείται», «στοι-χεία», «ταξι-δεύει» — τέσσερα κομμένα
 * λεκτικά σε μία ματιά, σε πίνακα που διαβάζεται κάθετα. Το κελί τυλίγεται στα
 * κενά του και μένει ακέραιο.
 */
export function hy(node: ReactNode): ReactNode {
  if (typeof node === 'string') return hyphenate(node);
  if (Array.isArray(node)) return node.map((n, i) => <Fragment key={i}>{hy(n)}</Fragment>);
  if (isValidElement(node)) {
    if (node.type === 'table') return node;
    const kids = (node.props as { children?: ReactNode }).children;
    return kids === undefined ? node : cloneElement(node, undefined, hy(kids));
  }
  return node;
}
