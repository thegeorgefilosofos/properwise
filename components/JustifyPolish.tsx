'use client';

// ═══════════════════════════════════════════════════════════════════════════
// Ο ΛΕΙΑΝΤΗΣ ΤΗΣ ΠΛΗΡΟΥΣ ΣΤΟΙΧΙΣΗΣ
// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΜΕΤΡΗΘΗΚΕ. Στην αρχική στα 390, στην απάντηση «Πώς δουλεύει η σάρωση»,
// η πρώτη γραμμή είχε κενό 2,02em ανάμεσα σε δύο λέξεις (το κανονικό είναι
// 0,3em). Η γραμμή μαζί με το «ασφα-» έβγαινε 351,1 εικονοστοιχεία σε κουτί
// 350: έλειπε ΕΝΑ εικονοστοιχείο και ο περιηγητής, που σπάει γραμμή γραμμή,
// κατέβασε ολόκληρη τη λέξη και μοίρασε το κενό στα δύο διαστήματα.
//
// ΤΙ ΚΑΝΕΙ Η ΣΤΟΙΧΕΙΟΘΕΣΙΑ. Το InDesign και το TeX κλείνουν τέτοιες τρύπες
// σφίγγοντας ή ανοίγοντας ανεπαίσθητα την απόσταση των γραμμάτων στη
// συγκεκριμένη παράγραφο. Εδώ το ίδιο: μόνο σε παράγραφο πέρα πέρα που έχει
// κενό πάνω από LIMIT, δοκιμάζονται λίγες μικρές ρυθμίσεις (έως 0,03em στα
// γράμματα, δηλαδή μισό εικονοστοιχείο σε σώμα 15) και κρατιέται η καλύτερη,
// ΜΟΝΟ αν κλείνει την τρύπα χωρίς να προσθέσει γραμμή. Αλλιώς τίποτα.
//
// ΓΙΑΤΙ ΔΕΝ ΣΠΑΕΙ ΤΟ REACT. Γράφει μόνο `letter-spacing` και `word-spacing`
// στο inline style του στοιχείου και ένα data-attribute· το React δεν τα
// διαβάζει. Αν ξαναγραφτεί το κείμενο, η υπογραφή (πλάτος και μήκος) αλλάζει
// και η παράγραφος ξαναμετριέται.
// ═══════════════════════════════════════════════════════════════════════════
import { useEffect } from 'react';

export default function JustifyPolish() {
  useEffect(() => {
    // ΦΟΡΤΩΝΕΤΑΙ ΑΡΓΟΤΕΡΑ. Η λεία δεν αλλάζει τι λέει η σελίδα, μόνο πώς
    // κάθεται· δεν έχει θέση στο αρχικό πακέτο (docs/perf/budget.json).
    //
    // ΚΑΙ Ο ΣΤΟΙΧΕΙΟΘΕΤΗΣ ΣΕ ΚΑΘΕ ΔΗΜΟΣΙΑ ΣΕΛΙΔΑ. Στις δημόσιες σελίδες η πλήρης
    // στοίχιση έμπαινε με το χέρι (`po-just` και `hy()`), παράγραφο παράγραφο·
    // όποια ξεχνιόταν έμενε ριγμένη δεξιά. Ο ιδιοκτήτης φωτογράφισε δύο τέτοιες
    // στις 26.09.2026: το «Τι δεν περιλαμβάνει» του ΕΝΦΙΑ και τις απαντήσεις των
    // οδηγών. Ο ίδιος στοιχειοθέτης με την εφαρμογή (lib/ui/typeset.ts) κρίνει
    // τώρα κάθε μπλοκ του `main` με τους ίδιους κανόνες· ό,τι είναι ήδη
    // στοιχειοθετημένο μένει όπως ήταν.
    const stops: Array<() => void> = [];
    let dead = false;
    Promise.all([import('@/lib/ui/typeset'), import('@/lib/ui/justifyPolish')]).then(([t, j]) => {
      if (dead) return;
      stops.push(t.startTypesetter('main'), j.start());
    });
    return () => { dead = true; stops.forEach(s => s()); };
  }, []);
  return null;
}
