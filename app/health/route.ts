import { NextResponse } from 'next/server'

// ═══════════════════════════════════════════════════════════════════════════
// LIVENESS PROBE — ο δημόσιος έλεγχος «ζωής» για εξωτερική παρακολούθηση
// ─────────────────────────────────────────────────────────────────────────
// Ενα UptimeRobot (ή όποιος monitor) χτυπά αυτό το endpoint κάθε λίγα λεπτά και
// περιμένει 200. Επιστρέφει 200 όσο η εφαρμογή σερβίρει — τίποτα άλλο.
//
// ΓΙΑΤΙ ΖΕΙ ΕΞΩ ΑΠΟ ΤΟ /api/, ΕΠΙΤΗΔΕΣ. Ο διαμεσολαβητής εξαιρεί ρητά ολόκληρο
// το `/api/**` από τον έλεγχο συνεδρίας (proxy.ts)· κι επειδή δεν υπάρχει πια
// δίχτυ από πάνω, ο φύλακας `scripts/guard-api-auth.mjs` απαιτεί ΚΑΘΕ διαδρομή
// του `/api/**` να ζητά μόνη της ταυτότητα — συνεδρία, υπογραφή ή μυστικό
// χρονοδιαγράμματος. Μια liveness είναι εξ ορισμού δημόσια και ανώνυμη· αν την
// έβαζα κάτω από το `/api/` θα ήταν η μοναδική ανοιχτή πόρτα σε έναν κατάλογο
// που ο φύλακας κρατά ερμητικά κλειστό — και η σωστή απάντηση δεν είναι να
// τρυπήσω τον φύλακα, είναι να μη βάλω τη δημόσια πόρτα στον ιδιωτικό διάδρομο.
//
// Ζει λοιπόν στο `/health`, μαζί με τα άλλα endpoint που απευθύνονται σε
// μηχανές (robots.txt, sitemap.xml): εξαιρείται εντελώς από τον διαμεσολαβητή
// στο `proxy.ts`, ώστε να μην ξοδεύει εκτέλεση middleware ούτε κεφαλίδες
// ασφαλείας σε κάθε ping — ένας έλεγχος υγείας δεν χρειάζεται τίποτα από αυτά.
//
// ΔΕΝ ΑΓΓΙΖΕΙ ΤΗ ΒΑΣΗ, ΕΠΙΤΗΔΕΣ. Μια liveness που ρωτά τη βάση πέφτει σε κάθε
// στιγμιαίο της πρόβλημα και βγάζει ψεύτικο «Down» κάθε πέντε λεπτά. Ενας
// συναγερμός που κράζει χωρίς λόγο είναι χειρότερος από κανέναν, γιατί
// σταματάς να τον εμπιστεύεσαι — και τότε χάνεις και τον αληθινό. Ο βαθύς
// έλεγχος (βάση, τροφοδοσίες) ζει χωριστά, στη συνάρτηση `health-check`.
//
// force-dynamic + no-store: ένας cached έλεγχος υγείας λέει «ζωντανός» ακόμη
// κι όταν η εφαρμογή έχει πέσει — δηλαδή λέει ψέματα ακριβώς όταν μετράει.
// ═══════════════════════════════════════════════════════════════════════════

export const dynamic = 'force-dynamic'

export function GET(): NextResponse {
  return NextResponse.json(
    { ok: true, service: 'properwise', ts: new Date().toISOString() },
    { headers: { 'cache-control': 'no-store, max-age=0' } },
  )
}
