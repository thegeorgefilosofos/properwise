// Ο υπολογιστής απαντά «πόσο»· ο οδηγός «γιατί». Ο σύνδεσμος στέκει κάτω από
// την κάρτα, εκεί που γεννιέται η ερώτηση. Οι κάρτες των οδηγών στο τέλος
// της σελίδας (ToolGuides) μένουν όπως είναι. Ποιος οδηγός αντιστοιχεί σε
// ποιον υπολογιστή το λέει ο κατάλογος (lib/core/publicTools.ts, `meaning`).
//
// Δικό του αρχείο, χωρίς τίποτα άλλο: οι υπολογιστές χωρίς «Αποθήκευσε το
// ακίνητο» δεν κατεβάζουν ούτε το πρόχειρο ούτε τον έλεγχο της συνεδρίας.
// ═══════════════════════════════════════════════════════════════════════════
import Link from 'next/link';

export const MEANING_LABEL = 'Τι σημαίνει αυτό';

/** Ο σύνδεσμος μόνος του· μέσα στο επόμενο βήμα τον βάζει το app/ToolNextStep.tsx. */
export function ToolMeaningLink({ href }: { href: string }) {
  return <Link href={href} className="lp-link po-tap po-next-more">{MEANING_LABEL}</Link>;
}

/** Κάτω από την κάρτα του αποτελέσματος, όταν δεν υπάρχει επόμενο βήμα. */
export function ToolMeaning({ href }: { href?: string }) {
  return href ? <p className="po-noprint po-next-solo"><ToolMeaningLink href={href} /></p> : null;
}
