import { STR_INDIVIDUAL_MAX_PROPERTIES } from '@/lib/billing/greekTax';

/** Ουδέτερο γένος, γιατί συμφωνεί με το «ακίνητα». Εκτός καταλόγου γράφεται με ψηφία. */
const NEUTER_COUNT: Readonly<Record<number, string>> = { 1: 'ένα', 2: 'δύο', 3: 'τρία', 4: 'τέσσερα', 5: 'πέντε' };
const neuter = (n: number): string => NEUTER_COUNT[n] ?? String(n);

/** «έως δύο ακίνητα»: ό,τι επιτρέπεται στο φυσικό πρόσωπο χωρίς έναρξη. */
export const STR_MAX_PROPERTIES = `έως ${neuter(STR_INDIVIDUAL_MAX_PROPERTIES)} ακίνητα`;
/** «τρία ακίνητα και πάνω»: από εκεί το εισόδημα γίνεται επιχειρηματικό. */
export const STR_BUSINESS_PROPERTIES = `${neuter(STR_INDIVIDUAL_MAX_PROPERTIES + 1)} ακίνητα και πάνω`;
/** «τρία ή περισσότερα ακίνητα», για απαρίθμηση. */
export const STR_BUSINESS_PROPERTIES_OR_MORE = `${neuter(STR_INDIVIDUAL_MAX_PROPERTIES + 1)} ή περισσότερα ακίνητα`;
