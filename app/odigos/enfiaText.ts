// ΓΙΑΤΙ ΥΠΑΡΧΕΙ (20/10/2026, απόφαση ιδιοκτήτη). Ο οδηγός ΕΝΦΙΑ 2026 έγραφε
// «σε 12 μηνιαίες δόσεις» του νόμου, ο οδηγός προθεσμιών «έως δώδεκα» που
// «ανακοινώνονται κάθε χρόνο από την ΑΑΔΕ» και ο «Πώς υπολογίζεται» ότι το
// πλήθος «ορίζεται κάθε έτος». Τρεις διατυπώσεις για το ίδιο γεγονός. Και καμία
// δεν έλεγε ότι κάθε δόση είναι τουλάχιστον 10€ (lib/tools/enfiaSchedule.ts).
//
// Η μία διατύπωση: έως 12 μηνιαίες δόσεις, με την τελευταία το αργότερο τον
// Φεβρουάριο του επόμενου έτους, όπως ορίζει ο νόμος· καθεμία τουλάχιστον 10€·
// τις ακριβείς ημερομηνίες τις γράφει το εκκαθαριστικό. Οι ημερομηνίες και ο
// μήνας της τελευταίας βγαίνουν από το φορολογικό ημερολόγιο, με τη βεβαιότητά
// του: πριν από την έκδοση ο οδηγός δεν τις λέει «του νόμου».
//
// Χωρίς React και χωρίς 'use client'.
// ═══════════════════════════════════════════════════════════════════════════
import { greekPropertyTaxObligations } from '@/lib/tax/greekTaxCalendar';
import { ENFIA_INSTALMENTS, ENFIA_MIN_INSTALMENT, grDateLong } from '@/lib/tools/enfiaSchedule';
import { feWhole } from '@/lib/core/format';
import { monthAcc } from '@/lib/core/months';

/** Η πρώτη και η τελευταία δόση του εκκαθαριστικού της χρονιάς, από το ημερολόγιο. */
function ends(year: number) {
  const obl = greekPropertyTaxObligations(year, 'owner');
  const first = obl.find(o => o.kind === 'enfia-first')!;
  const last = obl.find(o => o.kind === 'enfia-last')!;
  return { first, last, issued: first.confidence === 'statutory' && last.confidence === 'statutory' };
}

/**
 * «έως 12 μηνιαίες δόσεις, με την τελευταία το αργότερο τον Φεβρουάριο του
 * επόμενου έτους, όπως ορίζει ο νόμος. Κάθε δόση πρέπει να είναι τουλάχιστον
 * 10€, οπότε για μικρό ποσό οι δόσεις λιγοστεύουν.» Μπαίνει μετά από «σε».
 */
export function enfiaInstalmentRule(year: number): string {
  const { last } = ends(year);
  return `έως ${ENFIA_INSTALMENTS} μηνιαίες δόσεις, με την τελευταία το αργότερο τον `
    + `${monthAcc(Number(last.date.slice(5, 7)) - 1)} του επόμενου έτους, όπως ορίζει ο νόμος. `
    + `Κάθε δόση πρέπει να είναι τουλάχιστον ${feWhole(ENFIA_MIN_INSTALMENT)}, οπότε για μικρό ποσό οι δόσεις λιγοστεύουν.`;
}

/**
 * «Τις ακριβείς ημερομηνίες τις γράφει το εκκαθαριστικό· για το 2026 είναι από
 * τις 31 Μαρτίου 2026 έως τις 26 Φεβρουαρίου 2027.» Πριν από την έκδοση λέει
 * ότι οι ημερομηνίες δεν έχουν ανακοινωθεί και δίνει το αναμενόμενο διάστημα.
 */
export function enfiaInstalmentDates(year: number): string {
  const { first, last, issued } = ends(year);
  return issued
    ? `Τις ακριβείς ημερομηνίες τις γράφει το εκκαθαριστικό· για το ${year} είναι από τις ${grDateLong(first.date)} έως τις ${grDateLong(last.date)}.`
    : `Τις ακριβείς ημερομηνίες τις γράφει το εκκαθαριστικό· για το ${year} δεν έχουν ανακοινωθεί ακόμη και, όπως τα τελευταία έτη, αναμένονται από τις ${grDateLong(first.date)} έως τις ${grDateLong(last.date)}.`;
}
