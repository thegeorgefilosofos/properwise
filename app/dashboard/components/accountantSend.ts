// ΤΙ ΗΤΑΝ ΧΑΛΑΣΜΕΝΟ. Ο σύνδεσμος για τον λογιστή ζούσε κρυμμένος πίσω από το
// «⋯» δίπλα στο «Φάκελος του ακινήτου». Η κάρτα «Νέο: πρόσβαση λογιστικού
// γραφείου» της Επισκόπησης έστελνε μόνο στην Πολιτική απορρήτου και η γραμμή
// «Πρόσβαση λογιστή» των Ρυθμίσεων έλεγε «ο σύνδεσμος βγαίνει από τη
// Λογιστική» χωρίς δρόμο ως εκεί.
//
// ΤΩΡΑ. Το κουμπί κάθεται ορατό στη Λογιστική. Η κάρτα και οι Ρυθμίσεις
// στέλνουν αυτό το γεγονός: η σελίδα ανοίγει τη Λογιστική και φέρνει το
// κουμπί στην οθόνη με εστίαση. Ο σύνδεσμος δεν εκδίδεται από μακριά: η
// πρόσβαση σε φάκελο δίνεται με ένα πάτημα εκεί όπου φαίνεται τι μοιράζεται.
// Ίδιο σχήμα με το «pos:myaade» (myaadeOpen.ts).
// ═══════════════════════════════════════════════════════════════════════════
export const ACCOUNTANT_SEND_EVENT = 'pos:send-accountant';
/** Το περίβλημα του κουμπιού στη Λογιστική (AccountantDossier). */
export const ACCOUNTANT_SEND_ID = 'acd-send-accountant';
// ΕΝΑ ΟΝΟΜΑ ΓΙΑ ΤΟΝ ΙΔΙΟ ΣΥΝΔΕΣΜΟ (αξιολόγηση σχεδίασης 3). Η κάρτα και οι
// Ρυθμίσεις έλεγαν «Στείλε στον λογιστή σου» και οδηγούσαν σε κουμπί με άλλο
// όνομα. Το κουμπί της Λογιστικής διαβάζει την ίδια σταθερά.
export const ACCOUNTANT_SEND_LABEL = 'Σύνδεσμος για τον λογιστή';

export const sendToAccountant = (): void => {
  window.dispatchEvent(new Event(ACCOUNTANT_SEND_EVENT));
};

/** Βρίσκει το κουμπί μόλις αποδοθεί η Λογιστική και του δίνει εστίαση. */
export const focusAccountantSend = (tries = 40): void => {
  const btn = document.getElementById(ACCOUNTANT_SEND_ID)?.querySelector<HTMLElement>('button, a');
  if (btn) { btn.scrollIntoView({ block: 'center' }); btn.focus({ preventScroll: true }); return; }
  if (tries > 0) setTimeout(() => focusAccountantSend(tries - 1), 50);
};
