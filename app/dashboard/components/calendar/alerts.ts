/** «10 ληξιπρόθεσμα · 1 λήγει», ή `null` όταν δεν υπάρχει τίποτα να πει. */
export function alertLine(overdue: number, expiring: number): string | null {
  const parts: string[] = [];
  if (overdue > 0) parts.push(`${overdue} ${overdue === 1 ? 'ληξιπρόθεσμο' : 'ληξιπρόθεσμα'}`);
  if (expiring > 0) parts.push(`${expiring} ${expiring === 1 ? 'λήγει' : 'λήγουν'}`);
  return parts.length ? parts.join(' · ') : null;
}

