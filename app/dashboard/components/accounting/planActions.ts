import { hasFeature, planAtLeast } from '@/lib/billing/entitlements'
import type { PlanId } from '@/lib/billing/plans'

export interface PlanActions {
  /** Ημερολόγιο άρθρων (διπλογραφικό). */
  journal: boolean
  /** Εισαγωγή κινήσεων τράπεζας από CSV, με αντιστοίχιση ενοικίων. */
  bankImport: boolean
  /** Σύνθεση αναφοράς για ολόκληρο το χαρτοφυλάκιο. */
  portfolioReport: boolean
  /** Κατανομή σε συνιδιοκτήτες. */
  ownerSplit: boolean
}

export function planActions(plan: PlanId): PlanActions {
  return {
    // `accounting_journal` από «Επαγγελματίας» και πάνω, όπως το γράφει και η
    // κάρτα του πακέτου.
    journal: hasFeature({ plan }, 'accounting_journal'),
    bankImport: hasFeature({ plan }, 'bank_import'),
    // Η σύνθεση αναφοράς κατεβάζει τη σύγκριση ΟΛΟΚΛΗΡΟΥ του χαρτοφυλακίου:
    // είναι η ίδια δυνατότητα με την καρτέλα «Χαρτοφυλάκιο», από άλλη πόρτα.
    portfolioReport: hasFeature({ plan }, 'portfolio'),
    // Η κατανομή σε συνιδιοκτήτες δεν πωλείται χωριστά και δεν έχει δική της
    // εγγραφή στο μητρώο δυνατοτήτων. Έρχεται ολόκληρη με το «Επαγγελματίας».
    ownerSplit: planAtLeast(plan, 'agency'),
  }
}
