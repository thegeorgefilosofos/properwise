// ΓΙΑΤΙ ΥΠΑΡΧΕΙ. Ο πίνακας των δεκαέξι γραμμών ζούσε ανοιχτός μέσα στις
// Ρυθμίσεις, κάτω από τον τιμοκατάλογο. Ο συνδρομητής που μπήκε για να αλλάξει
// τη διεύθυνση τιμολόγησής του κυλούσε από πάνω του κάθε φορά, για μια
// πληροφορία που διαβάζεται ΜΙΑ φορά στη ζωή του λογαριασμού.
//
// Και ήταν κλειδωμένος πίσω από τη σύνδεση. «Τι παίρνω με τι» είναι η πρώτη
// ερώτηση που κάνει και ο επισκέπτης που δεν έχει ακόμη λογαριασμό: η απάντηση
// δεν έπρεπε να χρειάζεται εγγραφή, ούτε να λείπει από τις μηχανές αναζήτησης.
//
// ΚΑΜΙΑ ΤΙΜΗ ΓΡΑΜΜΕΝΗ ΕΔΩ. Οι τιμές ζουν στο `lib/billing/plans` και ο πίνακας
// τις ΔΙΑΒΑΖΕΙ από εκεί, όπως και οι κάρτες της αρχικής: δύο σελίδες με τιμές
// που διαβάζουν την ίδια πηγή δεν μπορούν να διαφωνήσουν. Χωρίς τιμή και
// χωρίς κουμπί, η σελίδα απαντούσε «τι παίρνω» και έστελνε τον επισκέπτη
// αλλού για το «πόσο» και για το «πώς ξεκινώ».
// ═══════════════════════════════════════════════════════════════════════════
import { hy } from '@/components/Hyphen';
import type { Metadata } from 'next';
import { siteUrl } from '@/lib/core/site';
import { RECOMMENDED_PLAN } from '@/lib/billing/plans';
import { TRIAL_OFFER } from '@/lib/billing/trialOffer';
import { billingWords } from '@/lib/legal/billingWords';
import { PublicHeader, PublicFooter, JsonLd, WRAP, WRAP_PAD } from '../PublicChrome';
import { BackLink } from '../BackLink';
import { publicMetadata } from '../publicMetadata';
import { PlanMatrix } from '@/components/PlanMatrix';
import { ASSISTANT_TO } from '@/lib/assistant/identity';

const TITLE = 'Τι περιλαμβάνει κάθε πακέτο · PROPERWISE';
// Το «Χωρίς εγγραφή» ταίριαζε σε υπολογιστή, όχι σε σελίδα τιμών.
const DESC =
  'Τιμές και δυνατότητες κάθε πακέτου του PROPERWISE, γραμμή προς γραμμή: '
  + `ακίνητα, ερωτήσεις ${ASSISTANT_TO}, σάρωση εγγράφων, εξαγωγή Ε2, λογιστικό `
  + 'ημερολόγιο, χαρτοφυλάκιο. Τιμές με ΦΠΑ.';
const PATH = '/paketa';
const URL = siteUrl(PATH);

// Απόλυτος τίτλος (publicMetadata): το TITLE έχει ήδη το «· PROPERWISE», οπότε
// το πρότυπο της ρίζας (`%s · PROPERWISE`) θα το πρόσθετε δεύτερη φορά.
export const metadata: Metadata = publicMetadata({ title: TITLE, description: DESC, url: URL });

export default function Page() {
  return (
    // `pub-root`: η παλέτα της αρχικής και εδώ (globals.css). Ο επισκέπτης
    // φτάνει από το «Τιμές» της αρχικής και δεν πρέπει να αλλάζει χρώμα.
    <div className="pub-root min-h-dvh" data-mode="dark">
      <JsonLd data={{
        '@context': 'https://schema.org',
        '@type': 'WebPage',
        name: TITLE,
        description: DESC,
        url: URL,
      }} />
      <PublicHeader current="paketa" />
      {/* Ιδια δομή κεφαλίδας με τα δωρεάν εργαλεία: μάτι, τίτλος πρώτου
          επιπέδου, μία γραμμή υπόσχεσης. Δύο δημόσιες σελίδες με την ίδια
          δουλειά δεν επιτρέπεται να έχουν δύο διατάξεις. */}
      <main style={{ ...WRAP, padding: `clamp(28px,4vw,44px) ${WRAP_PAD} clamp(56px,7vw,88px)` }}>
        <BackLink />
        <div className="lp-eyebrow">Πακέτα</div>
        <h1 style={{ fontSize: 'clamp(28px,4.4vw,42px)', fontWeight: 680, letterSpacing: '-0.035em',
          lineHeight: 1.1, margin: '0 0 14px', textWrap: 'balance' }}>
          Τι περιλαμβάνει κάθε πακέτο
        </h1>
        {/* ═══ ΟΧΙ ΤΟ `ToolLede` ═════════════════════════════════════════════
            Το κοινό εισαγωγικό των ΔΩΡΕΑΝ ΕΡΓΑΛΕΙΩΝ κλείνει με «χωρίς εγγραφή
            και χωρίς email: ο υπολογισμός γίνεται στη συσκευή σου και μένει
            εκεί» και με υποσημείωση «οι ίδιοι υπολογισμοί που τρέχει το
            PROPERWISE». Εδώ δεν τρέχει κανένας υπολογισμός: είναι κατάλογος
            δυνατοτήτων. Η υπόσχεση θα ήταν άσχετη, άρα θόρυβος.

            Η ΔΕΥΤΕΡΗ ΠΡΟΤΑΣΗ ΕΡΧΕΤΑΙ ΑΠΟ ΜΙΑ ΠΗΓΗ. Το `billingWords().firstCharge`
            είναι η ίδια πηγή που τρέφει την αρχική: γυρίζει «δεν ζητείται κάρτα»
            όσο το ταμείο είναι κλειστό και «η κάρτα δηλώνεται στην αρχή, πρώτη
            χρέωση την 31η» μόλις ανοίξει — ώστε /paketa και αρχική να μη λένε
            ποτέ διαφορετικά πράγματα για το ίδιο πράγμα.

            ΤΟ ΜΕΤΡΟ ΞΑΝΑΜΠΗΚΕ. Το κείμενο δεν χωράει σε μία γραμμή σε καμία
            οθόνη, άρα είναι παράγραφος και παίρνει το μέτρο των 720. */}
        {/* ΑΡΙΣΤΕΡΗ ΣΤΟΙΧΙΣΗ ΣΕ ΜΕΤΡΟ ΠΑΡΑΓΡΑΦΟΥ, ΧΩΡΙΣ ΣΥΛΛΑΒΙΣΜΟ. Το σχόλιο
            που ήταν εδώ υποσχόταν «σε φαρδιά οθόνη μένει μία γραμμή»· στα 1440
            ήταν τρεις, με «ενεργοποί-ηση» και «θέ-λεις» κομμένα· στα 390
            τρία σπασίματα λέξης σε εννέα γραμμές. Τρεις σύντομες προτάσεις: η
            δοκιμή με το όριό της (TRIAL_OFFER, η ίδια πηγή με την αρχική), η
            κατάσταση της χρέωσης (billingWords) και ο ΦΠΑ. */}
        <p className="po-just" style={{ fontSize: 15, color: 'var(--text-secondary)', lineHeight: 1.6, margin: '0 0 6px' }}>{hy(<>
          {TRIAL_OFFER} {billingWords().firstCharge} Οι τιμές περιλαμβάνουν ΦΠΑ και σταματάς όποτε θέλεις.
        </>)}</p>
        {/* Η ΙΔΙΑ ΠΡΟΤΑΣΗ ΜΕ ΤΗΝ ΑΡΧΙΚΗ. Χωρίς προτεινόμενη στήλη ο πίνακας έδειχνε
            τέσσερα ίδια κύρια κουμπιά, ενώ η αρχική προτείνει ρητά ένα πακέτο.
            Οι κάρτες του κινητού κάθονται κάτω από τον <h1>, άρα είναι <h2>. */}
        <div style={{ marginTop: 'clamp(22px,3vw,34px)' }}><PlanMatrix recommended={RECOMMENDED_PLAN} headingLevel={2} /></div>
      </main>
      <PublicFooter />
    </div>
  );
}
