import { LockKeyhole } from 'lucide-react';
import { T } from '@/components/tokens';
import { billingWords } from '@/lib/legal/billingWords';

export function PaymentsBadge() {
  const { live, securedBy } = billingWords();
  if (!live || !securedBy) return null;
  return (
    <p style={{
      display: 'inline-flex', alignItems: 'center', gap: T.sp.sm,
      margin: `${T.sp.md}px 0 0`, padding: `${T.sp.xs}px ${T.sp.md}px`,
      border: '1px solid var(--border-subtle)', borderRadius: T.radius.pill,
      fontSize: 13, lineHeight: 1.4, color: 'var(--text-secondary)',
    }}>
      <LockKeyhole size={14} strokeWidth={2} style={{ flexShrink: 0 }} aria-hidden="true" />
      <span>{securedBy}</span>
    </p>
  );
}
