import { POLICY_VERSION } from '@/lib/legal/identity';

/** Το κλειδί του localStorage όπου γράφεται το «Το κατάλαβα». */
export const COOKIE_NOTICE_KEY = 'pos-cookie-consent';

/** Ισχύει μόνο εγγραφή της τρέχουσας έκδοσης· παλιά ή άκυρη ζητά ξανά ενημέρωση. */
export function acknowledged(raw: string | null): boolean {
  if (!raw) return false;
  try {
    const rec = JSON.parse(raw);
    return !!rec && rec.v === POLICY_VERSION;
  } catch { return false; }
}

/** Τρέχει στο <head> με το nonce του CSP. Ο ίδιος κανόνας με το `acknowledged`. */
export const cookieNoticeInitScript = `
(function() {
  try {
    var raw = localStorage.getItem(${JSON.stringify(COOKIE_NOTICE_KEY)});
    var rec = raw ? JSON.parse(raw) : null;
    if (rec && rec.v === ${JSON.stringify(POLICY_VERSION)}) document.documentElement.setAttribute('data-cookie-ok', '');
  } catch (e) {}
})();
`;
