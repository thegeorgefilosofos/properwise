'use client';

// Ενημέρωση cookies (GDPR/ePrivacy). Χρησιμοποιούμε ΜΟΝΟ απολύτως απαραίτητα
// cookies λειτουργίας (συνεδρία σύνδεσης, προτίμηση θέματος), για τα οποία ο
// νόμος δεν απαιτεί συγκατάθεση, απαιτεί όμως σαφή ενημέρωση. Η αναγνώριση του
// χρήστη καταγράφεται με έκδοση πολιτικής και χρονοσήμανση, ώστε να υπάρχει
// αποδεικτικό και να ζητείται εκ νέου όταν η πολιτική αλλάξει ουσιωδώς.
import { useEffect, useRef, useSyncExternalStore } from 'react';
import Link from 'next/link';
import { T, Btn } from '@/components/Theme';
// Η ΕΚΔΟΣΗ ΕΡΧΕΤΑΙ ΑΠΟ ΤΑ ΝΟΜΙΚΑ ΚΕΙΜΕΝΑ, ΟΧΙ ΑΠΟ ΕΔΩ. Ηταν «2026-08»
// γραμμένο με το χέρι, ενώ η Πολιτική είχε ήδη αλλάξει στις ενότητες για τα
// cookies: όποιος είχε δει την παλιά ενημέρωση δεν έβλεπε ποτέ τη νέα.
import { POLICY_VERSION } from '@/lib/legal/identity';

const KEY = 'pos-cookie-consent';

// ═══════════════════════════════════════════════════════════════════════════
// ΓΙΑΤΙ `useSyncExternalStore` ΚΑΙ ΟΧΙ `useEffect` ΜΕ `setState`
// ─────────────────────────────────────────────────────────────────────────
// Ο localStorage είναι εξωτερική πηγή δεδομένων, όχι κατάσταση της React. Το
// μοτίβο «ξεκινάω με ψέμα και το διορθώνω σε effect» κάνει ΔΥΟ αποδόσεις σε
// κάθε φόρτωση —μία με το πλαίσιο κρυμμένο και μία με αυτό ορατό— και ο
// μεταγλωττιστής της React το σημειώνει ως σφάλμα ακριβώς γι' αυτό.
//
// Εδώ ο διακομιστής απαντά «μην το δείξεις» και ο περιηγητής απαντά με την
// αλήθεια, σε ΜΙΑ απόδοση και χωρίς ασυμφωνία ενυδάτωσης. Και επειδή το
// `subscribe` ακούει το γεγονός `storage`, αν ο χρήστης το αποδεχτεί σε άλλη
// καρτέλα, το πλαίσιο κλείνει και εδώ.
// ═══════════════════════════════════════════════════════════════════════════

/** Άκυρη ή παλιότερης έκδοσης εγγραφή σημαίνει ότι ζητάμε ξανά αναγνώριση. */
function needsNotice(): boolean {
  try {
    const raw = localStorage.getItem(KEY);
    if (!raw) return true;
    const rec = JSON.parse(raw);
    return !rec || rec.v !== POLICY_VERSION;
  } catch { return true; }
}

const listeners = new Set<() => void>();
const notify = () => listeners.forEach(l => l());
function subscribe(l: () => void) {
  listeners.add(l);
  window.addEventListener('storage', l);
  return () => { listeners.delete(l); window.removeEventListener('storage', l); };
}

export default function CookieConsent() {
  const show = useSyncExternalStore(subscribe, needsNotice, () => false);
  const box = useRef<HTMLDivElement>(null);

  // ═══ ΤΟ ΠΛΑΙΣΙΟ ΣΚΕΠΑΖΕ ΤΟ ΚΟΥΜΠΙ ΤΗΣ ΣΥΝΔΕΣΗΣ, ΜΟΝΙΜΑ ══════════════════
  // ΜΕΤΡΗΜΕΝΟ ΣΕ CHROMIUM, 390×844 — το πιο κοινό τηλέφωνο. Το «Σύνδεση»
  // καθόταν στο 593 με ύψος 44 και το πλαίσιο άνοιγε στο 610: επικάλυψη 28
  // εικονοστοιχείων — και το `elementFromPoint` στο ΚΕΝΤΡΟ του κουμπιού
  // επέστρεφε το πλαίσιο, όχι το κουμπί. Δηλαδή ο αντίχειρας έπεφτε πάνω στην
  // ενημέρωση για cookies.
  //
  // ΚΑΙ ΔΕΝ ΥΠΗΡΧΕ ΔΙΕΞΟΔΟΣ. Η σελίδα σύνδεσης χωρά ολόκληρη στην οθόνη, άρα
  // δεν κυλάει: δεν μπορούσες να κατεβάσεις το κουμπί από κάτω του. Οποιος δεν
  // πατούσε πρώτα «Το κατάλαβα» δεν μπορούσε να συνδεθεί. Στα 360 και στα 820
  // δεν φαινόταν, γιατί εκεί η φόρμα πέφτει αλλού — γι' αυτό επέζησε.
  //
  // Η ΛΥΣΗ ΔΕΝ ΕΙΝΑΙ ΝΟΥΜΕΡΟ ΓΡΑΜΜΕΝΟ ΣΤΟ ΧΕΡΙ. Το ύψος του πλαισίου αλλάζει
  // με το πλάτος (66 στα 1440, 89 στα 390, 127 στα 360, γιατί το κείμενο
  // τυλίγει αλλιώς). Μετριέται και δημοσιεύεται ως `--cookie-h`· όποια
  // διάταξη κεντράρει περιεχόμενο σε ολόκληρη οθόνη κρατά τον χώρο του.
  // ΟΧΙ ΤΟ ΥΨΟΣ ΤΟΥ, Η ΖΩΝΗ ΠΟΥ ΠΙΑΝΕΙ. Το πλαίσιο αιωρείται πάνω από τον πάτο
  // κατά `--float-bottom`: με σκέτο ύψος, το κουτί της φόρμας τελείωνε ΜΕΣΑ στη
  // λωρίδα του κατά ακριβώς αυτή την απόσταση και ο σύνδεσμος «Πολιτική
  // απορρήτου» έμενε σκεπασμένος. Η απόσταση από τον πάτο του κάδρου ώς την
  // κορυφή του τα περιέχει και τα δύο, σε έναν αριθμό.
  //
  // ΚΑΙ ΜΟΝΟ `ResizeObserver`, ΧΩΡΙΣ ΑΚΡΟΑΤΗ `resize`. Το πλαίσιο είναι
  // αγκυρωμένο αριστερά και δεξιά: όταν αλλάζει το παράθυρο αλλάζει και το
  // ίδιο, οπότε ο παρατηρητής το πιάνει ήδη. Ο δεύτερος ακροατής ήταν
  // αντίγραφο — και έπιανε ΛΙΓΟΤΕΡΑ, γιατί δεν βλέπει την αναδίπλωση όταν
  // φορτώνει η γραμματοσειρά και το κείμενο ξαναμοιράζεται σε σειρές.
  useEffect(() => {
    const root = document.documentElement, el = box.current;
    const clear = () => root.style.setProperty('--cookie-h', '0px');
    if (!show || !el) { clear(); return; }
    const publish = () => root.style.setProperty('--cookie-h', `${Math.ceil(innerHeight - el.getBoundingClientRect().top)}px`);
    publish();
    const ro = new ResizeObserver(publish);
    ro.observe(el);
    return () => { ro.disconnect(); clear(); };
  }, [show]);

  if (!show) return null;
  const acknowledge = () => {
    try { localStorage.setItem(KEY, JSON.stringify({ v: POLICY_VERSION, ts: new Date().toISOString() })); } catch { /* ignore */ }
    notify();
  };

  return (
    // ΤΟ ΑΣΦΑΛΕΣ ΠΕΡΙΘΩΡΙΟ ΔΕΝ ΕΙΝΑΙ ΠΡΟΑΙΡΕΤΙΚΟ ΟΤΑΝ ΥΠΑΡΧΕΙ viewport-fit=cover.
    // Το layout.tsx δηλώνει `viewportFit: cover`, δηλαδή η σελίδα απλώνεται κάτω
    // από τη γραμμή του συστήματος. Με σκέτο `bottom: 12` τα κάτω 22 pixel του
    // πλαισίου κάθονταν μέσα στη ζώνη του home indicator του iPhone. Το
    // PwaProvider το έκανε ήδη σωστά· εδώ απλώς δεν είχε ακολουθήσει.
    //
    // ΔΕΝ ΕΙΝΑΙ ΔΙΑΛΟΓΟΣ ΠΟΥ ΔΕΣΜΕΥΕΙ. Δηλωνόταν `role="dialog"` χωρίς να
    // μετακινεί την εστίαση μέσα του και χωρίς να εμποδίζει τίποτα πίσω του —
    // δηλαδή υποσχόταν συμπεριφορά που δεν είχε και ο αναγνώστης οθόνης
    // ανακοίνωνε «διάλογος» για κάτι που ο χρήστης μπορεί απλώς να προσπεράσει.
    // Ενημερωτική περιοχή με όνομα: ούτε λιγότερο, ούτε ψέματα.
    // ── ΤΟ ΜΟΝΟ ΠΛΩΤΟ ΣΤΟΙΧΕΙΟ ΠΟΥ ΔΕΝ ΜΙΛΟΥΣΕ ΤΗ ΓΛΩΣΣΑ ΤΩΝ ΑΛΛΩΝ ──────────
    // ΤΙ ΕΣΠΑΣΕ, ΚΑΙ ΠΟΥ ΤΟ ΕΙΔΑ. Το πλαίσιο καθόταν σε `bottom: 12px` με
    // `zIndex: 2000`. Σε κινητό όμως υπάρχει σταθερή `.bottom-nav` στο
    // `bottom: 0` με `z-index: 900` — δηλαδή η ΚΥΡΙΑ ΠΛΟΗΓΗΣΗ. Το πλαίσιο
    // καθόταν ολόκληρο από πάνω της: ο επισκέπτης έβλεπε τις καρτέλες
    // «Λογαριασμοί», «Δαπάνες», «Ημερολόγιο», «Φάκελος Ακινήτου» κομμένες πίσω
    // από μια ενημέρωση για cookies, στο πρώτο δευτερόλεπτο της πρώτης του
    // επίσκεψης.
    //
    // Η ΣΥΜΒΑΣΗ ΥΠΗΡΧΕ ΗΔΗ. Το `--float-bottom` (globals.css) υπολογίζει
    // ακριβώς αυτό: ύψος πλοήγησης, συν τη μπάρα αφής του iPhone, συν το πλωτό
    // κουμπί του βοηθού. Το μιλούν ήδη τέσσερα στοιχεία — το toast, η μπάρα
    // μαζικών ενεργειών, η υπενθύμιση γνώμης κι ο βοηθός. Αυτό εδώ ήταν το
    // μόνο που είχε δικό του νούμερο γραμμένο στο χέρι — κι ήταν λάθος.
    //
    // Το `--float-z` (950) μπαίνει για τον ίδιο λόγο: το 2000 το έβαζε πάνω
    // ΚΑΙ από τα μηνύματα επιβεβαίωσης, δηλαδή μια ενημέρωση χωρίς επείγον
    // σκέπαζε ό,τι ο χρήστης μόλις ζήτησε.
    <div ref={box} role="region" aria-label="Ενημέρωση για cookies" className="po-noprint po-cookie" style={{ position: 'fixed', left: 12, right: 12, bottom: 'var(--float-bottom)', zIndex: 'var(--float-z)', maxWidth: 720, margin: '0 auto',
      background: 'var(--bg-elevated)', border: '1px solid var(--border-default)', borderRadius: T.radius.card, boxShadow: 'var(--elev-3)',
      padding: '14px 16px', display: 'flex', alignItems: 'center', gap: 14, flexWrap: 'wrap', fontFamily: T.font.sans }}>
      {/* ΓΙΑΤΙ ΤΟΣΟ ΣΥΝΤΟΜΟ: το κείμενο ήταν τέσσερις σειρές σε desktop και έξι σε
          κινητό, οπότε το πλαίσιο σκέπαζε το προϊόν ακριβώς στην πρώτη οθόνη —
          δηλαδή το πρώτο πράγμα που έβλεπε ένας υποψήφιος πελάτης ήταν νομικό
          κείμενο πάνω από αυτό που ήρθε να δει. Η ουσία χωράει σε μία γραμμή· οι
          λεπτομέρειες ανήκουν στην Πολιτική απορρήτου, όπου τις ψάχνει όποιος
          τις θέλει. Καμία πληροφορία δεν χάθηκε: η δήλωση «μόνο απαραίτητα, καμία
          παρακολούθηση» είναι ακριβώς το ουσιώδες περιεχόμενο της προηγούμενης.
          ΚΑΙ Η ΜΕΤΡΗΣΗ ΛΕΓΕΤΑΙ. Το «καμία παρακολούθηση» διαβαζόταν ως «δεν
          μετράται τίποτα», ενώ το layout φορτώνει ανώνυμη μέτρηση επισκέψεων
          χωρίς cookies, όπως τη γράφει η Πολιτική απορρήτου. */}
      <div style={{ flex: 1, minWidth: 200, fontSize: 13, color: 'var(--text-secondary)', lineHeight: 1.5, textWrap: 'pretty', textAlign: 'center' }}>
        Μόνο <strong style={{ color: 'var(--text-primary)' }}>απαραίτητα cookies</strong>. Ανώνυμη μέτρηση επισκέψεων χωρίς cookies, καμία διαφήμιση.{' '}
        {/* ΥΠΟΓΡΑΜΜΙΣΜΕΝΟΣ, ΓΙΑΤΙ ΤΟ ΧΡΩΜΑ ΜΟΝΟ ΤΟΥ ΔΕΝ ΕΙΝΑΙ ΣΥΝΔΕΣΜΟΣ. Με
            `textDecoration: none` το «Απόρρητο» ξεχώριζε ΜΟΝΟ από το χρώμα:
            όποιος δεν ξεχωρίζει το γαλάζιο από το γκρι —δαλτωνισμός, φως ήλιου
            στην οθόνη, ασπρόμαυρη εκτύπωση— διάβαζε έμφαση, όχι σύνδεσμο. Είναι
            ο μοναδικός δρόμος προς την πολιτική απορρήτου μέσα από αυτό το
            πλαίσιο. */}
        <Link href="/privacy" style={{ color: 'var(--accent)', textDecorationLine: 'underline', textUnderlineOffset: 2, fontWeight: 600 }}>Απόρρητο</Link>
      </div>
      <Btn variant="primary" onClick={acknowledge} className="po-cookie-cta">Το κατάλαβα</Btn>
    </div>
  );
}
