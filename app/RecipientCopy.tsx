// Η πύλη ενοικιαστή, το check-in, η απεγγραφή, η επιβεβαίωση διεύθυνσης και η
// επαλήθευση έχουν ΜΙΑ διεύθυνση για τις δύο γλώσσες (lib/i18n/locale.ts).
// Ενας πάροχος κάτω από το app/en, όπως στους υπολογιστές, θα κατέβαινε και
// στην ελληνική σελίδα: η διαδρομή είναι η ίδια, οπότε φορτώνεται ό,τι εισάγει
// το layout της. Εδώ το λεξικό ΔΕΝ εισάγεται· το δίνει ως τιμή το layout στον
// διακομιστή, μόνο όταν η γλώσσα του αιτήματος είναι αγγλικά, και ταξιδεύει
// μέσα στην απόκριση. Στα ελληνικά ο πάροχος δεν αποδίδεται καν.
// ═══════════════════════════════════════════════════════════════════════════
import type { ReactNode } from 'react';
import { ToolEnContext, type ToolEn } from '@/lib/i18n/toolEn';

export default function RecipientCopy({ value, children }: { value: ToolEn; children: ReactNode }) {
  return <ToolEnContext.Provider value={value}>{children}</ToolEnContext.Provider>;
}
