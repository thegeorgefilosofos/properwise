// Η σελίδα εγγραφής είναι `'use client'` — έχει φόρμα, κατάσταση και ελέγχους
// κωδικού. Ένα component πελάτη ΔΕΝ μπορεί να εξάγει `metadata`, οπότε η
// σελίδα κληρονομούσε τον τίτλο της ρίζας: ο επισκέπτης έβλεπε «PROPERWISE»
// σε καρτέλα και σε σελιδοδείκτη, χωρίς να ξεχωρίζει από την αρχική και η
// μηχανή αναζήτησης έβρισκε δύο σελίδες με τον ίδιο τίτλο και την ίδια
// περιγραφή — ενώ η εγγραφή είναι στον χάρτη με προτεραιότητα 0,8.
//
// Το layout είναι component διακομιστή, άρα εδώ τα μεταδεδομένα επιτρέπονται.
// Το μόνο περιτύλιγμα είναι ο πάροχος των όρων χρέωσης, χωρίς κανένα στοιχείο.
// ═══════════════════════════════════════════════════════════════════════════
import type { Metadata } from 'next';
import type { ReactNode } from 'react';
import { siteUrl } from '@/lib/core/site';
import { publicMetadata } from '../publicMetadata';
import { PLANS, TRIAL_DAYS } from '@/lib/billing/plans';
import { TRIAL_PLAN } from '@/lib/billing/entitlements';
import { billingWords } from '@/lib/legal/billingWords';
import { PlanTermsProvider } from './PlanTerms';

// ΤΟ «ΧΩΡΙΣ ΚΑΡΤΑ» ΕΦΥΓΕ ΓΙΑΤΙ ΕΠΑΨΕ ΝΑ ΙΣΧΥΕΙ. Μετά την επιβεβαίωση του email
// ο νέος λογαριασμός προσγειώνεται στο ταμείο και δίνει κάρτα. Η περιγραφή
// αυτή είναι ό,τι διαβάζει ο κόσμος στα αποτελέσματα αναζήτησης, δηλαδή η
// υπόσχεση ΠΡΙΝ από κάθε άλλη — και γι' αυτό δεν γράφεται με το χέρι: το
// `generateMetadata` τρέχει στον διακομιστή, όπου η αλήθεια για τη χρέωση
// είναι γνωστή. Στατικό `metadata` δεν θα μπορούσε να τη ρωτήσει.
export function generateMetadata(): Metadata {
  // ΔΙΚΗ ΤΗΣ ΚΑΡΤΑ ΚΟΙΝΟΠΟΙΗΣΗΣ. Χωρίς openGraph η σελίδα κληρονομούσε το
  // og:url της αρχικής: ο σύνδεσμος παραπομπής /signup?ref=… κοινοποιούνταν
  // ως η αρχική και η παραπομπή χανόταν.
  return publicMetadata({
    title: 'Εγγραφή · PROPERWISE',
    // ΠΡΩΤΑ ΤΟ ΔΩΡΕΑΝ ΠΑΚΕΤΟ, ΜΕΤΑ Η ΔΟΚΙΜΗ (έλεγχος κειμένων 06.10.2026). Ελεγε
    // σκέτο «ξεκίνα τη δοκιμή», ενώ τα «Ξεκίνα δωρεάν» της αρχικής φέρνουν εδώ
    // όποιον διαλέγει το δωρεάν πακέτο. Η δοκιμή ισχύει για κάθε νέο λογαριασμό
    // (`trialState`) και λέγεται με το πακέτο που δίνει, από τις πηγές τους.
    description: `Δημιούργησε λογαριασμό στο δωρεάν πακέτο «${PLANS.free.name}». Κάθε νέος λογαριασμός ξεκινά με δοκιμή ${TRIAL_DAYS} ημερών στο «${PLANS[TRIAL_PLAN].name}». ${billingWords().firstCharge}`,
    url: siteUrl('/signup'),
  });
}

// ΚΑΙ Η ΦΟΡΜΑ ΜΑΘΑΙΝΕΙ ΑΠΟ ΕΔΩ ΑΝ ΧΡΕΩΝΟΥΜΕ, για τον ίδιο λόγο (βλ. PlanTerms.tsx).
// Χωρίς αυτό η περιγραφή έλεγε «καμία χρέωση» και η σελίδα «Ετήσια χρέωση».
export default function SignupLayout({ children }: { children: ReactNode }) {
  const words = billingWords();
  return <PlanTermsProvider value={{ planTerms: words.signupPlanTerms, trialBadge: words.trialBadge }}>{children}</PlanTermsProvider>;
}
